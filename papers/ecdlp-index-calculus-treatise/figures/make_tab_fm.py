# ---------- ledger host ns per op ----------
def f(v):
    if v is None:
        return "--"
    x = v["median"]
    return f"{x:.0f}" if x >= 100 else (f"{x:.1f}" if x >= 10 else f"{x:.2f}")


def tab_regime(regs, cols, heads):
    rs = sorted((r for r in C["ledger_host"] if r["regime"] in regs), key=lambda r: (r["regime"], r["field_bits"]))
    s = ""
    for r in rs:
        name = {"prime": f"$\\FF_p$, {r['field_bits']} bits", "char2": f"random $\\FF_{{2^{{{r['field_bits']}}}}}$",
                "koblitz": f"{r['curve'].split(' /')[0].replace('_', '')} $\\FF_{{2^{{{r['field_bits']}}}}}$"}[r["regime"]]
        s += f"{name} & {r['log2_r']:.1f} & " + " & ".join(f(r["ns"].get(c)) for c in cols) + " \\\\\n"
    return s


cols_p = ["ns_per_add", "ns_per_double", "ns_per_inversion", "ns_per_sqrt", "ns_per_legendre", "ns_per_lookup", "ns_per_row_op", "ns_per_word_xor"]
cols_b = ["ns_per_add", "ns_per_double", "ns_per_as_solve", "ns_per_frobenius", "ns_per_s4_pair", "ns_per_lookup", "ns_per_row_op", "ns_per_word_xor"]
body = "\\begin{tabular}{@{}lrrrrrrrrr@{}}\n\\toprule\ninstance & $\\log_2 r$ & add & double & inv. & sqrt & Legendre & lookup & row op & word XOR \\\\\n\\midrule\n"
body += tab_regime(("prime",), cols_p, None)
body += "\\midrule\ninstance & $\\log_2 r$ & add & double & AS solve & Frobenius & $S_4$ pair & lookup & row op & word XOR \\\\\n\\midrule\n"
body += tab_regime(("char2", "koblitz"), cols_b, None)
body += "\\bottomrule\n\\end{tabular}\n"
w("tab-fm-ledgerhost.tex", body)

