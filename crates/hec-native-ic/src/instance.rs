//! The thread's curve families and instance rule (rounds seven and eight of
//! `research/notes/index-calculus/RESEARCH_HYPERELLIPTIC_IC_RHO.md`), so the
//! native engine runs on exactly the instances the BigUint engine ran on.

use std::collections::HashMap;

use crate::fp::Fp;
use crate::jac::{Curve, Div};
use crate::poly::Poly;

/// Genus 2: `y² = x⁵ + 3x³ + 2x² + x + c`.  Genus 3: `y² = x⁷ + x³ + cx + 1`.
/// Genus 4: `y² = x⁹ + x³ + cx + 1`.  `None` if `f` is not squarefree.
pub fn thread_curve(p: u64, c: u64, g: usize) -> Option<Curve> {
    let fp = Fp::new(p);
    let cs: Vec<u64> = match g {
        2 => vec![c % p, 1, 2, 3, 0, 1],
        3 => vec![1, c % p, 0, 1, 0, 0, 0, 1],
        4 => vec![1, c % p, 0, 1, 0, 0, 0, 0, 0, 1],
        _ => return None,
    };
    let f = Poly::from_coeffs(&cs);
    if Poly::gcd(&f, &f.deriv(&fp), &fp).deg() != 0 {
        return None;
    }
    Some(Curve::new(fp, f))
}

/// The BigUint engine's word-size Hasse–Weil interval, with its `f64`
/// rounding kept so instance selection does not move.
pub fn hasse_interval(p: u64, g: usize) -> (u64, u64) {
    let root = (p as f64).sqrt();
    let lo = (root - 1.0).powi(2 * g as i32).floor().max(1.0) as u64;
    let hi = (root + 1.0).powi(2 * g as i32).ceil() as u64;
    (lo, hi)
}

/// Degree-1 places `(x, y)` in increasing `x`, `y` the representative
/// `≤ (p−1)/2` of the `±` pair (`y = 0` included), as `build_factor_base`.
pub fn factor_base(curve: &Curve) -> Vec<(u64, u64)> {
    let fp = &curve.fp;
    let half = (fp.p - 1) / 2;
    let mut out = Vec::new();
    for x in 0..fp.p {
        if let Some(y) = fp.sqrt(curve.f.eval(x, fp)) {
            out.push((x, if y > half { fp.p - y } else { y }));
        }
    }
    out
}

pub fn prime_factors(mut n: u64) -> Vec<u64> {
    let mut out = Vec::new();
    let mut q = 2u64;
    while q * q <= n {
        if n % q == 0 {
            out.push(q);
            while n % q == 0 {
                n /= q;
            }
        }
        q += if q == 2 { 1 } else { 2 };
    }
    if n > 1 {
        out.push(n);
    }
    out
}

pub fn exact_order_from_multiple(curve: &Curve, d: &Div, m: u64) -> u64 {
    let mut ord = m;
    for q in prime_factors(m) {
        while ord % q == 0 && curve.is_zero(&curve.mul(d, ord / q)) {
            ord /= q;
        }
    }
    ord
}

/// Order of `d` by baby-step giant-step over the Hasse–Weil interval;
/// `None` if that needs more than `max_baby` baby steps.
pub fn order_bsgs(curve: &Curve, d: &Div, max_baby: usize) -> Option<u64> {
    let (lo, hi) = hasse_interval(curve.fp.p, curve.g);
    let width = (hi - lo).max(1);
    let steps = (width as f64).sqrt().ceil() as usize + 1;
    if steps > max_baby {
        return None;
    }
    let nd = curve.neg(d);
    let mut table: HashMap<Div, usize> = HashMap::with_capacity(steps);
    let mut acc = curve.zero();
    for j in 0..steps {
        table.entry(acc).or_insert(j);
        acc = curve.add(&acc, &nd);
    }
    let stride = curve.mul(d, steps as u64);
    let mut cur = curve.mul(d, lo);
    let giant_max = width as usize / steps + 2;
    for i in 0..=giant_max {
        if let Some(&j) = table.get(&cur) {
            let m = lo + (i * steps + j) as u64;
            if m != 0 && curve.is_zero(&curve.mul(d, m)) {
                return Some(exact_order_from_multiple(curve, d, m));
            }
        }
        cur = curve.add(&cur, &stride);
    }
    None
}

#[derive(Clone, Debug)]
pub struct Instance {
    pub genus: usize,
    pub p: u64,
    pub c: u64,
    pub curve: Curve,
    pub d1: Div,
    pub ell: u64,
}

/// Round seven's rule: the first `c` whose Jacobian has a prime subgroup
/// above 1000 carrying at least a quarter of the Hasse–Weil lower bound,
/// generated by a multiple of one of the first 8 factor-base places.
pub fn pick_instance(p: u64, genus: usize) -> Option<Instance> {
    for c in 1..p.min(60) {
        let Some(curve) = thread_curve(p, c, genus) else {
            continue;
        };
        let fb = factor_base(&curve);
        for &(x, y) in fb.iter().take(8) {
            let e = curve.place(x, y);
            let Some(order) = order_bsgs(&curve, &e, 200_000) else {
                continue;
            };
            let l = *prime_factors(order).last()?;
            let (lo, _) = hasse_interval(p, genus);
            if l < 1000 || (l as u128) * 4 < lo as u128 {
                continue;
            }
            let d1 = curve.mul(&e, order / l);
            if curve.is_zero(&d1) || !curve.is_zero(&curve.mul(&d1, l)) {
                continue;
            }
            return Some(Instance {
                genus,
                p,
                c,
                curve,
                d1,
                ell: l,
            });
        }
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    /// G3 (partial, fast rows): the native rule picks the subgroup order
    /// round eight's table reports.
    #[test]
    fn picks_round_eight_orders() {
        for &(g, p, n) in &[
            (2usize, 101u64, 4663u64),
            (2, 251, 61667),
            (3, 61, 124459),
            (4, 31, 239753),
        ] {
            let inst = pick_instance(p, g).expect("instance");
            assert_eq!(inst.ell, n, "g={g} p={p}");
        }
    }
}
