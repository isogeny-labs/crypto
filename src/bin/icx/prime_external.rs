//! Bounded external prime-field ECDLP input for the Semaev S3 driver.

use clap::Args;
use crypto_lib::cryptanalysis::ec_index_calculus::{
    ec_index_calculus_dlp_staged, pollard_rho_ecdlp,
};
use crypto_lib::ecc::{curve::CurveParams, field::FieldElement, point::Point};
use num_bigint::BigUint;
use serde_json::{json, Value};
use std::path::PathBuf;
use std::time::Instant;

#[path = "prime_route.rs"]
mod route;
pub use route::GenerateArgs as PrimeRouteGenerateArgs;

pub(super) fn generate_route(args: &PrimeRouteGenerateArgs) -> Result<Value, String> {
    route::generate(args)
}

#[derive(Args)]
pub struct PrimeArgs {
    /// Prime field modulus (5..=1000000).
    #[arg(long)]
    p: u64,
    /// Short-Weierstrass coefficient a.
    #[arg(long)]
    a: u64,
    /// Short-Weierstrass coefficient b.
    #[arg(long)]
    b: u64,
    /// Prime order of the subgroup generated by G.
    #[arg(long)]
    n: u64,
    #[arg(long)]
    gx: u64,
    #[arg(long)]
    gy: u64,
    #[arg(long)]
    qx: u64,
    #[arg(long)]
    qy: u64,
    #[arg(long, default_value_t = 8)]
    fb_size: usize,
    #[arg(long, default_value_t = 64)]
    extra_relations: usize,
    #[arg(long, default_value_t = 5000)]
    max_trials_per_relation: usize,
    #[arg(long, default_value_t = 64)]
    max_relation_attempts: usize,
    /// Maximum Pollard-rho steps on the same target; zero skips the reference.
    #[arg(long, default_value_t = 1_000_000)]
    rho_steps: usize,
    /// Certified isogeny_routes.json generated by isogeny_walk.
    #[arg(long, requires = "route_id")]
    route_file: Option<PathBuf>,
    /// IW1 route originating at the supplied curve's root node.
    #[arg(long, requires = "route_file")]
    route_id: Option<String>,
}

pub(super) fn prime(n: u64) -> bool {
    if n < 2 {
        return false;
    }
    if n.is_multiple_of(2) {
        return n == 2;
    }
    let mut d = 3;
    while d <= n / d {
        if n.is_multiple_of(d) {
            return false;
        }
        d += 2;
    }
    true
}

pub(super) fn count_curve_order(p: u64, a: u64, b: u64) -> u64 {
    let mut roots = vec![0u8; p as usize];
    for y in 0..p {
        roots[((y * y) % p) as usize] += 1;
    }
    let mut order = 1u64;
    for x in 0..p {
        let rhs = (((x * x) % p * x) % p + a * x + b) % p;
        order += u64::from(roots[rhs as usize]);
    }
    order
}

pub fn solve(args: &PrimeArgs) -> Result<Value, String> {
    if !(5..=1_000_000).contains(&args.p) || !prime(args.p) {
        return Err("p must be prime and in 5..=1000000".into());
    }
    if !(3..=4_000_000).contains(&args.n) || !prime(args.n) {
        return Err("n must be prime and in 3..=4000000".into());
    }
    if [args.a, args.b, args.gx, args.gy, args.qx, args.qy]
        .iter()
        .any(|&v| v >= args.p)
    {
        return Err("curve coefficients and point coordinates must be less than p".into());
    }
    if !(1..=1024).contains(&args.fb_size)
        || args.extra_relations > 4096
        || args.max_trials_per_relation == 0
        || args.max_relation_attempts == 0
    {
        return Err("invalid factor-base or relation-search budget".into());
    }
    let p = args.p as u128;
    let a = args.a as u128;
    let b = args.b as u128;
    if (4 * a * a * a + 27 * b * b).is_multiple_of(p) {
        return Err("singular curve: discriminant is zero modulo p".into());
    }
    let curve_order = count_curve_order(args.p, args.a, args.b);
    if !curve_order.is_multiple_of(args.n) {
        return Err("subgroup order does not divide the counted curve order".into());
    }
    let curve = CurveParams {
        name: "external-prime",
        p: BigUint::from(args.p),
        a: BigUint::from(args.a),
        b: BigUint::from(args.b),
        gx: BigUint::from(args.gx),
        gy: BigUint::from(args.gy),
        n: BigUint::from(args.n),
        h: (curve_order / args.n) as u32,
    };
    let point = |x, y| Point::Affine {
        x: FieldElement::new(BigUint::from(x), curve.p.clone()),
        y: FieldElement::new(BigUint::from(y), curve.p.clone()),
    };
    let g = point(args.gx, args.gy);
    let q = point(args.qx, args.qy);
    if !curve.is_on_curve(&g) || !curve.is_on_curve(&q) {
        return Err("G and Q must both lie on the specified curve".into());
    }
    let order = BigUint::from(args.n);
    let a_fe = curve.a_fe();
    if g.scalar_mul(&order, &a_fe) != Point::Infinity || g == Point::Infinity {
        return Err("G does not have the specified prime order".into());
    }
    if q.scalar_mul(&order, &a_fe) != Point::Infinity {
        return Err("Q is outside the subgroup generated by G".into());
    }
    // When n also divides the cofactor, E[n] may contain several order-n
    // subgroups. The order test alone does not establish membership in <G>.
    // In this case n^2 <= #E, so the bounded field range makes enumeration
    // of <G> small enough to validate the supplied target exactly.
    if (curve_order / args.n).is_multiple_of(args.n) {
        let mut multiple = Point::Infinity;
        let mut belongs = false;
        for _ in 0..args.n {
            if multiple == q {
                belongs = true;
                break;
            }
            multiple = multiple.add(&g, &a_fe);
        }
        if !belongs {
            return Err("Q is outside the subgroup generated by G".into());
        }
    }

    let transported = match (&args.route_file, &args.route_id) {
        (Some(path), Some(id)) => Some(route::transport(args, path, id)?),
        (None, None) => None,
        _ => return Err("--route-file and --route-id must be supplied together".into()),
    };
    let (work_curve, work_g, work_q) = transported
        .as_ref()
        .map(|t| (&t.curve, &t.generator, &t.target))
        .unwrap_or((&curve, &g, &q));
    let ic = ec_index_calculus_dlp_staged(
        work_curve,
        work_g,
        work_q,
        args.fb_size,
        args.extra_relations,
        args.max_trials_per_relation,
        args.max_relation_attempts,
    );
    let ic_verified = ic.as_ref().is_some_and(|(x, _)| {
        work_g.scalar_mul(x, &work_curve.a_fe()) == *work_q && g.scalar_mul(x, &a_fe) == q
    });
    let rho = if args.rho_steps == 0 {
        None
    } else {
        let started = Instant::now();
        let x = pollard_rho_ecdlp(&curve, &g, &q, args.rho_steps);
        let verified = x.as_ref().is_some_and(|x| g.scalar_mul(x, &a_fe) == q);
        Some(json!({
            "max_steps": args.rho_steps,
            "wall_ms": started.elapsed().as_secs_f64() * 1000.0,
            "verified": verified,
            "scalar": x.map(|v| v.to_string()),
        }))
    };
    Ok(json!({
        "schema_version": 1,
        "operation": "solve-prime",
        "status": if ic_verified { "complete" } else { "bounded_unknown" },
        "verified": ic_verified,
        "input": {
            "p": args.p, "a": args.a, "b": args.b, "n": args.n,
            "curve_order": curve_order, "cofactor": curve_order / args.n,
            "generator": [args.gx, args.gy], "target": [args.qx, args.qy],
        },
        "config": {
            "fb_size": args.fb_size,
            "extra_relations": args.extra_relations,
            "max_trials_per_relation": args.max_trials_per_relation,
            "max_relation_attempts": args.max_relation_attempts,
        },
        "ic": ic.map(|(x, stages)| json!({"scalar": x.to_string(), "stages": stages})),
        "isogeny_route": transported.map(|t| t.receipt),
        "rho": rho,
    }))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rejects_invalid_prime_and_target() {
        let mut args = PrimeArgs {
            p: 271,
            a: 1,
            b: 19,
            n: 281,
            gx: 3,
            gy: 7,
            qx: 231,
            qy: 54,
            fb_size: 8,
            extra_relations: 64,
            max_trials_per_relation: 5000,
            max_relation_attempts: 64,
            rho_steps: 0,
            route_file: None,
            route_id: None,
        };
        args.p = 272;
        assert!(solve(&args).unwrap_err().contains("prime"));
        args.p = 271;
        args.qy = 55;
        assert!(solve(&args).unwrap_err().contains("lie on"));
    }

    #[test]
    fn certified_isogeny_route_preserves_public_scalar() {
        let args = PrimeArgs {
            p: 271,
            a: 1,
            b: 19,
            n: 281,
            gx: 3,
            gy: 7,
            qx: 231,
            qy: 54,
            fb_size: 8,
            extra_relations: 64,
            max_trials_per_relation: 5000,
            max_relation_attempts: 64,
            rho_steps: 0,
            route_file: None,
            route_id: None,
        };
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("docs/ic/fixtures/prime271_isogeny_routes.json");
        let transported = route::transport(&args, &path, "IW1E11h1h1a619f4ab250").unwrap();
        assert_eq!(transported.receipt["hops"], 1);
        assert_eq!(
            transported
                .generator
                .scalar_mul(&BigUint::from(190u32), &transported.curve.a_fe()),
            transported.target
        );
        assert!(route::transport(&args, &path, "absent-route").is_err());
    }

    #[test]
    fn accepts_a_prime_subgroup_with_nontrivial_cofactor() {
        // Independently enumerated: #E(F_17) = 21, and [7](6,7) = O.
        let args = PrimeArgs {
            p: 17,
            a: 2,
            b: 8,
            n: 7,
            gx: 6,
            gy: 7,
            qx: 10,
            qy: 12,
            fb_size: 1,
            extra_relations: 0,
            max_trials_per_relation: 10,
            max_relation_attempts: 1,
            rho_steps: 0,
            route_file: None,
            route_id: None,
        };
        let report = solve(&args).unwrap();
        assert_eq!(report["input"]["curve_order"], 21);
        assert_eq!(report["input"]["cofactor"], 3);
    }

    #[test]
    fn rejects_other_order_three_subgroup_when_three_divides_cofactor() {
        // E/F_7: y^2 = x^3 + 2 has order 9 and independent 3-torsion.
        let mut args = PrimeArgs {
            p: 7,
            a: 0,
            b: 2,
            n: 3,
            gx: 0,
            gy: 3,
            qx: 3,
            qy: 1,
            fb_size: 2,
            extra_relations: 1,
            max_trials_per_relation: 100,
            max_relation_attempts: 1000,
            rho_steps: 0,
            route_file: None,
            route_id: None,
        };
        assert!(solve(&args).unwrap_err().contains("outside the subgroup"));
        args.qx = 0;
        args.qy = 4;
        assert!(solve(&args).is_ok());
    }
}
