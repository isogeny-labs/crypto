pub fn solve_file(args: &PrimeFileArgs) -> Result<Value, String> {
    let resolved = crypto_lib::store::resolve_path(&args.input)?;
    if fs::metadata(&resolved)
        .map_err(|e| format!("{}: {e}", args.input.display()))?
        .len()
        > 64 * 1024
    {
        return Err("prime target input exceeds 64 KiB".into());
    }
    let bytes =
        fs::read(&resolved).map_err(|e| format!("cannot read {}: {e}", args.input.display()))?;
    if bytes.len() > 64 * 1024 {
        return Err("prime target input exceeds 64 KiB".into());
    }
    let target: PrimeTargetInput =
        serde_json::from_slice(&bytes).map_err(|e| format!("invalid prime target JSON: {e}"))?;
    let solve_args = PrimeArgs {
        p: target.p,
        a: target.a,
        b: target.b,
        n: target.n,
        gx: target.gx,
        gy: target.gy,
        qx: target.qx,
        qy: target.qy,
        group_order: target.group_order,
        fb_size: args.fb_size,
        extra_relations: args.extra_relations,
        max_trials_per_relation: args.max_trials_per_relation,
        max_relation_attempts: args.max_relation_attempts,
        seed: args.seed,
        rho_steps: args.rho_steps,
        route_file: args.route_file.clone(),
        route_id: args.route_id.clone(),
        project_cofactor: args.project_cofactor,
        matched_rho_runs: args.matched_rho_runs,
    };
    let mut report = solve(&solve_args)?;
    report["operation"] = json!("solve-prime-file");
    report["input_artifact"] = json!({
        "reference": args.input.display().to_string(),
        "sha256": hex::encode(crypto_lib::hash::sha256::sha256(&bytes)),
        "bytes": bytes.len(),
    });
    Ok(report)
}

pub(super) fn prime(n: u64) -> bool {
    if n < 2 {
        return false;
    }
    if n.is_multiple_of(2) {
        return n == 2;
    }
    let mut d = 3;
    while d <= n / d {
        if n.is_multiple_of(d) {
            return false;
        }
        d += 2;
    }
    true
}

pub(super) fn count_curve_order(p: u64, a: u64, b: u64) -> u64 {
    let mut roots = vec![0u8; p as usize];
    for y in 0..p {
        roots[((y * y) % p) as usize] += 1;
    }
    let mut order = 1u64;
    for x in 0..p {
        let rhs = (((x * x) % p * x) % p + a * x + b) % p;
        order += u64::from(roots[rhs as usize]);
    }
    order
}

/// Largest prime field (and subgroup order) accepted: trial-division primality is about 2^25 steps here.
/// Largest factor base the command accepts (the pair-sum table holds 2F^2 entries and the
/// elimination is dense in F, so the cap bounds memory and time).
const MAX_FB_SIZE: usize = 16384;
const MAX_PRIME_FIELD: u64 = 1 << 50;
/// Largest field whose point count is done by brute force.
const COUNTABLE_FIELD: u64 = 40_000_000;

pub fn solve(args: &PrimeArgs) -> Result<Value, String> {
    // Trial-division primality bounds the sizes (about 2^25 steps at 2^50).
    if !(5..=MAX_PRIME_FIELD).contains(&args.p) || !prime(args.p) {
        return Err(format!("p must be prime and in 5..={MAX_PRIME_FIELD}"));
    }
    if !(3..=MAX_PRIME_FIELD).contains(&args.n) || !prime(args.n) {
        return Err(format!("n must be prime and in 3..={MAX_PRIME_FIELD}"));
    }
    if [args.a, args.b, args.gx, args.gy, args.qx, args.qy]
        .iter()
        .any(|&v| v >= args.p)
    {
        return Err("curve coefficients and point coordinates must be less than p".into());
    }
    if !(1..=MAX_FB_SIZE).contains(&args.fb_size)
        || args.extra_relations > 4096
        || args.max_trials_per_relation == 0
        || args.max_relation_attempts == 0
    {
        return Err("invalid factor-base or relation-search budget".into());
    }
    let p = args.p as u128;
    let a = args.a as u128;
    let b = args.b as u128;
    if (4 * a * a * a + 27 * b * b).is_multiple_of(p) {
        return Err("singular curve: discriminant is zero modulo p".into());
    }
    let curve_order = if args.p <= COUNTABLE_FIELD {
        let counted = count_curve_order(args.p, args.a, args.b);
        if let Some(given) = args.group_order {
            if given != counted {
                return Err(format!(
                    "group_order {given} differs from the counted order {counted}"
                ));
            }
        }
        counted
    } else {
        // Too large to count by brute force: the caller supplies the group order; only the
        // Hasse bound and divisibility are checked here.
        let given = args
            .group_order
            .ok_or("p above 40000000 needs group_order (the whole group's order)")?;
        let slack = 2 * (args.p as f64).sqrt() as u64 + 2;
        if given.abs_diff(args.p + 1) > slack {
            return Err(format!(
                "group_order {given} violates the Hasse bound for p = {}",
                args.p
            ));
        }
        given
    };
    if !curve_order.is_multiple_of(args.n) {
        return Err("subgroup order does not divide the curve order".into());
    }
    if curve_order / args.n > u64::from(u32::MAX) {
        return Err("cofactor does not fit u32".into());
    }
    let curve = CurveParams {
        name: "external-prime",
        p: BigUint::from(args.p),
        a: BigUint::from(args.a),
        b: BigUint::from(args.b),
        gx: BigUint::from(args.gx),
        gy: BigUint::from(args.gy),
        n: BigUint::from(args.n),
        h: (curve_order / args.n) as u32,
    };
    let point = |x, y| Point::Affine {
        x: FieldElement::new(BigUint::from(x), curve.p.clone()),
        y: FieldElement::new(BigUint::from(y), curve.p.clone()),
    };
    let g = point(args.gx, args.gy);
    let q = point(args.qx, args.qy);
    if !curve.is_on_curve(&g) || !curve.is_on_curve(&q) {
        return Err("G and Q must both lie on the specified curve".into());
    }
    let order = BigUint::from(args.n);
    let a_fe = curve.a_fe();
    if g.scalar_mul(&order, &a_fe) != Point::Infinity || g == Point::Infinity {
        return Err("G does not have the specified prime order".into());
    }
    if q.scalar_mul(&order, &a_fe) != Point::Infinity {
        return Err("Q is outside the subgroup generated by G".into());
    }
    // When n also divides the cofactor, E[n] may contain several order-n
    // subgroups. The order test alone does not establish membership in <G>.
    // In this case n^2 <= #E, so the bounded field range makes enumeration
    // of <G> small enough to validate the supplied target exactly.
    if (curve_order / args.n).is_multiple_of(args.n) {
        let mut multiple = Point::Infinity;
        let mut belongs = false;
        for _ in 0..args.n {
            if multiple == q {
                belongs = true;
                break;
            }
            multiple = multiple.add(&g, &a_fe);
        }
        if !belongs {
            return Err("Q is outside the subgroup generated by G".into());
        }
    }

    let transported = match (&args.route_file, &args.route_id) {
        (Some(path), Some(id)) => Some(route::transport(args, path, id)?),
        (None, None) => None,
        _ => return Err("--route-file and --route-id must be supplied together".into()),
    };
    let (work_curve, work_g, work_q) = transported
        .as_ref()
        .map(|t| (&t.curve, &t.generator, &t.target))
        .unwrap_or((&curve, &g, &q));
    let ic = match args.seed {
        Some(seed) if args.project_cofactor => ec_index_calculus_dlp_staged_seeded_projected(
            work_curve,
            work_g,
            work_q,
            args.fb_size,
            args.extra_relations,
            args.max_trials_per_relation,
            args.max_relation_attempts,
            seed,
        ),
        Some(seed) => ec_index_calculus_dlp_staged_seeded(
            work_curve,
            work_g,
            work_q,
            args.fb_size,
            args.extra_relations,
            args.max_trials_per_relation,
            args.max_relation_attempts,
            seed,
        ),
        None => ec_index_calculus_dlp_staged(
            work_curve,
            work_g,
            work_q,
            args.fb_size,
            args.extra_relations,
            args.max_trials_per_relation,
            args.max_relation_attempts,
        ),
    };
    let ic_verified = ic.as_ref().is_some_and(|(x, _)| {
        work_g.scalar_mul(x, &work_curve.a_fe()) == *work_q && g.scalar_mul(x, &a_fe) == q
    });
    let rho = if args.rho_steps == 0 {
        None
    } else {
        let started = Instant::now();
        let x = pollard_rho_ecdlp(&curve, &g, &q, args.rho_steps);
        let verified = x.as_ref().is_some_and(|x| g.scalar_mul(x, &a_fe) == q);
        Some(json!({
            "max_steps": args.rho_steps,
            "wall_ms": started.elapsed().as_secs_f64() * 1000.0,
            "verified": verified,
            "scalar": x.map(|v| v.to_string()),
        }))
    };
    Ok(json!({
        "schema_version": 1,
        "operation": "solve-prime",
        "status": if ic_verified { "complete" } else { "bounded_unknown" },
        "verified": ic_verified,
        "input": {
            "p": args.p, "a": args.a, "b": args.b, "n": args.n,
            "curve_order": curve_order, "cofactor": curve_order / args.n,
            "generator": [args.gx, args.gy], "target": [args.qx, args.qy],
        },
        "config": {
            "fb_size": args.fb_size,
            "extra_relations": args.extra_relations,
            "max_trials_per_relation": args.max_trials_per_relation,
            "max_relation_attempts": args.max_relation_attempts,
            "seed": args.seed,
        },
        "ic": ic.map(|(x, stages)| json!({"scalar": x.to_string(), "stages": stages})),
        "isogeny_route": transported.map(|t| t.receipt),
        "rho": rho,
        "matched_rho": if args.matched_rho_runs > 0 { Some(matched_rho(args)) } else { None },
    }))
}

/// The counted negation-map walk (the matched reference, A = 2) run `matched_rho_runs`
/// times on this instance with distinct walk seeds. Everything is in the unit of the
/// index-calculus arm: charged group additions and doublings (`gae` = adds + doubles) and
/// the walk's own unpriced counters, summed over the runs and per run.
fn matched_rho(args: &PrimeArgs) -> Value {
    let curve = PrimeCurve {
        p: args.p,
        a: args.a,
        b: args.b,
    };
    let g = PrimePoint::affine(args.gx, args.gy);
    let q = PrimePoint::affine(args.qx, args.qy);
    let cap = rho_cap(args.n, 64.0);
    let base = args.seed.unwrap_or(1);
    let k = args.matched_rho_runs;
    let mut gaes = Vec::with_capacity(k);
    let mut steps = Vec::with_capacity(k);
    let mut all_verified = true;
    let mut counters: std::collections::BTreeMap<String, u64> = Default::default();
    let mut method = String::new();
    for i in 0..k {
        let seed = base ^ (i as u64 + 1).wrapping_mul(0x9E37_79B9_7F4A_7C15);
        let res = rho_reference_walk(&curve, g, q, args.n, seed, cap, RhoWalk::negation());
        gaes.push(res.gae);
        steps.push(res.steps);
        all_verified &= res.verified;
        method = res.method.clone();
        for (name, v) in &res.counters {
            *counters.entry(name.clone()).or_insert(0) += v;
        }
    }
    let mean = |xs: &[f64]| xs.iter().sum::<f64>() / xs.len().max(1) as f64;
    let mut sorted = gaes.clone();
    sorted.sort_by(|x, y| x.partial_cmp(y).unwrap());
    let median = if sorted.is_empty() {
        0.0
    } else if sorted.len() % 2 == 1 {
        sorted[sorted.len() / 2]
    } else {
        (sorted[sorted.len() / 2 - 1] + sorted[sorted.len() / 2]) / 2.0
    };
    let per_run: std::collections::BTreeMap<String, f64> = counters
        .iter()
        .map(|(n, v)| (n.clone(), *v as f64 / k.max(1) as f64))
        .collect();
    // j = 0 or j = 1728 carry automorphisms beyond negation; then this walk is not the matched one.
    let eligible = if args.a == 0 || args.b == 0 {
        "NOT MATCHED: a = 0 or b = 0 (extra automorphisms)"
    } else {
        "negation only (A = 2): a and b are nonzero; no other automorphism checked"
    };
    json!({
        "method": method,
        "matched_rho_eligible": eligible,
        "runs": k,
        "cap": cap,
        "all_verified": all_verified,
        "mean_gae": mean(&gaes),
        "median_gae": median,
        "mean_steps": steps.iter().sum::<u64>() as f64 / k.max(1) as f64,
        "gae_per_run": gaes,
        "counters_summed": counters,
        "counters_per_run": per_run,
        "unit": "gae = group additions + doublings, as in ic rho",
    })
}

