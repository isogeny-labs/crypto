/// Walk length between fresh random starts (as `ic_control::RESTART_DEFAULT`).
pub const RESTART: u64 = 4096;

/// Where the relations are drawn from.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Source {
    /// Random elements of `⟨G', Z⟩` (all of `J` up to the index of `⟨Z⟩`).
    WholeJ,
    /// Only `⟨G'⟩`: the transferred-subgroup walk (`γ = 0`, `k = 0`), a
    /// positive control that must reproduce `ic_control`'s behaviour.
    Subgroup,
}

/// Result of one run.
#[derive(Clone, Debug, Default)]
pub struct FullResult {
    pub ic: IcResult,
    /// Smooth points / trials with a full degree-2 `u`.
    pub smooth_rate: f64,
}

#[derive(Clone, Copy, Debug)]
struct Rel {
    fb: [(u32, i8); 3],
    nfb: u8,
    lp: [(u32, i8); 2],
    nlp: u8,
    /// `−h b mod r`.
    tcoef: u64,
    /// `−k mod r`.
    zcoef: u64,
    /// `h a mod r`.
    rhs: u64,
}

impl Rel {
    fn endpoints(&self) -> (u32, i8, u32, i8) {
        match self.nlp {
            0 => (0, 0, 0, 0),
            1 => (0, 0, self.lp[0].0, self.lp[0].1),
            _ => (self.lp[0].0, self.lp[0].1, self.lp[1].0, self.lp[1].1),
        }
    }
}

/// `ic_control::build_rows` with the extra column `zcol` (the `ζ` unknown).
fn build_rows(
    rels: &[Rel],
    nverts: usize,
    tcol: u32,
    zcol: Option<u32>,
    r: u64,
    nat: &mut Nat,
) -> Vec<Row> {
    let neg = |e: i8| if e > 0 { 1u64 } else { r - 1 };
    let frow = |rel: &Rel| -> Vec<(u32, u64)> {
        let mut v: Vec<(u32, u64)> = rel.fb[..rel.nfb as usize]
            .iter()
            .map(|&(c, e)| (c, neg(e)))
            .collect();
        v.push((tcol, rel.tcoef));
        if let Some(zc) = zcol {
            if rel.zcoef != 0 {
                v.push((zc, rel.zcoef));
            }
        }
        v.sort_unstable_by_key(|x| x.0);
        v
    };
    let mut adj: Vec<Vec<u32>> = vec![Vec::new(); nverts];
    for (i, rel) in rels.iter().enumerate() {
        if rel.nlp > 0 {
            let (a, _, b, _) = rel.endpoints();
            adj[a as usize].push(i as u32);
            adj[b as usize].push(i as u32);
            nat.add += 2;
        }
    }
    let mut beta: Vec<Option<(Vec<(u32, u64)>, u64)>> = vec![None; nverts];
    beta[0] = Some((Vec::new(), 0));
    let mut is_tree = vec![false; rels.len()];
    let mut queue = std::collections::VecDeque::new();
    queue.push_back(0u32);
    while let Some(u) = queue.pop_front() {
        let edges = adj[u as usize].clone();
        for ei in edges {
            let rel = &rels[ei as usize];
            let (a, ea, b, eb) = rel.endpoints();
            let (v, ev, eu) = if a == u { (b, eb, ea) } else { (a, ea, eb) };
            if beta[v as usize].is_some() {
                continue;
            }
            is_tree[ei as usize] = true;
            let (bu, cu) = beta[u as usize].clone().expect("parent reached");
            let fv = frow(rel);
            let neg_f = ev > 0;
            let neg_u = (ev as i32) * (eu as i32) > 0;
            let terms = combine(&fv, neg_f, &bu, neg_u, r, nat);
            let mut c = if ev > 0 { rel.rhs } else { subm(0, rel.rhs, r) };
            let cu_term = if (ev as i32) * (eu as i32) > 0 {
                subm(0, cu, r)
            } else {
                cu
            };
            c = addm(c, cu_term, r);
            nat.add += 2;
            beta[v as usize] = Some((terms, c));
            queue.push_back(v);
        }
    }
    let mut rows = Vec::new();
    for (i, rel) in rels.iter().enumerate() {
        if is_tree[i] {
            continue;
        }
        let (a, ea, b, eb) = rel.endpoints();
        if rel.nlp > 0 && (beta[a as usize].is_none() || beta[b as usize].is_none()) {
            continue;
        }
        let mut terms = frow(rel);
        let mut rhs = rel.rhs;
        if rel.nlp > 0 {
            if a != 0 {
                let (ba, ca) = beta[a as usize].as_ref().expect("reached");
                terms = combine(&terms, false, ba, ea < 0, r, nat);
                rhs = if ea > 0 {
                    subm(rhs, *ca, r)
                } else {
                    addm(rhs, *ca, r)
                };
                nat.add += 1;
            }
            if b != 0 {
                let (bb, cb) = beta[b as usize].as_ref().expect("reached");
                terms = combine(&terms, false, bb, eb < 0, r, nat);
                rhs = if eb > 0 {
                    subm(rhs, *cb, r)
                } else {
                    addm(rhs, *cb, r)
                };
                nat.add += 1;
            }
        }
        rows.push((terms, rhs));
    }
    rows
}

/// A random `Z ∈ J` with `hZ ≠ 0` (so that `ζ ≠ 0`, which keeps the `ζ`
/// column determined).  `None` if none is found in 256 draws.
pub fn pick_z(curve: &H64Curve, h: u64, seed: u64) -> Option<H64Div> {
    let mut st = seed ^ 0x2545_F491_4F6C_DD1D;
    for _ in 0..256 {
        let z = curve.random_divisor(&mut st);
        if !z.is_identity() && !curve.mul_uncounted(z, h).is_identity() {
            return Some(z);
        }
    }
    None
}

/// Exact order of `d` in a group of order `n` (trial-division factoring).
pub fn point_order(curve: &H64Curve, d: H64Div, n: u64) -> u64 {
    let mut ord = n;
    let mut m = n;
    let mut q = 2u64;
    let mut primes = Vec::new();
    while q * q <= m {
        if m.is_multiple_of(q) {
            primes.push(q);
            while m.is_multiple_of(q) {
                m /= q;
            }
        }
        q += 1;
    }
    if m > 1 {
        primes.push(m);
    }
    for q in primes {
        while ord.is_multiple_of(q) && curve.mul_uncounted(d, ord / q).is_identity() {
            ord /= q;
        }
    }
    ord
}

/// One index-calculus run with relations from `source`.  `check_walk`
/// (tests): verify every relation against `Σ P_i = R` and `R = aG'+bT'+kZ`.
pub fn run_full_ic(
    inst: &Instance,
    z: H64Div,
    source: Source,
    prm: IcParams,
    check_walk: bool,
) -> FullResult {
    let start = std::time::Instant::now();
    let curve = &inst.curve;
    let (p, r, h) = (inst.p, inst.r, inst.h);
    let whole = source == Source::WholeJ;
    let mut rng = StdRng::seed_from_u64(prm.seed);
    let mut res = IcResult {
        arm: prm.arm.name(),
        p,
        ..Default::default()
    };
    let mut ops = GroupOps::default();
    let f = curve.f_coeffs();

    // ── factor base: every degree-1 place up to sign (or `nb` of them) ──
    let want = if prm.arm == Arm::Full {
        usize::MAX
    } else {
        prm.nb
    };
    let mut col = vec![u32::MAX; p as usize];
    let mut ncols = 0usize;
    {
        let half = (p - 1) / 2;
        for x in 0..p {
            if ncols >= want {
                break;
            }
            let mut fx = 0u64;
            for &cf in f.iter().rev() {
                fx = pm(p, fx, x, &mut res.rel);
                fx = pa(p, fx, cf, &mut res.rel);
            }
            if fx == 0 {
                continue;
            }
            if ppow(p, fx, half, &mut res.rel) == 1 {
                col[x as usize] = ncols as u32;
                ncols += 1;
            }
        }
    }
    res.fb_cols = ncols;
    let tcol = ncols as u32;
    let zcol = if whole { Some(tcol + 1) } else { None };
    let nunk = ncols + 1 + usize::from(whole);

    // ── walk set-up: 16 jumps α G' + β T' (+ γ Z) ──
    let short = r.min(1 << 12);
    let mut jumps: Vec<(H64Div, u64, u64, u64, u64)> = Vec::new();
    for _ in 0..16 {
        let a = rng.gen_range(1..short);
        let b = rng.gen_range(1..short);
        let ag = curve.mul(&mut ops, inst.g, a);
        let bt = curve.mul(&mut ops, inst.target, b);
        let mut m = curve.add(&mut ops, ag, bt);
        let mut gam = 0u64;
        if whole {
            gam = rng.gen_range(1..(1u64 << 12));
            let gz = curve.mul(&mut ops, z, gam);
            m = curve.add(&mut ops, m, gz);
        }
        jumps.push((m, a, b, gam % r, gam));
    }
    res.setup_ops = ops.adds + ops.doubles;

    let mut rels: Vec<Rel> = Vec::new();
    let mut vid: HashMap<u32, u32> = HashMap::new();
    let mut dsu = Dsu::new();
    let margin = |n: usize| 8 + n / 100;
    let mut cur = H64Div::IDENTITY;
    let (mut ca, mut cb, mut ck) = (0u64, 0u64, 0u64);
    // exact integer coefficients, tracked only when checking
    let (mut fa, mut fb_, mut fk) = (0u128, 0u128, 0u128);
    let mut since_restart = u64::MAX;
    let mut next_check = nunk as u64;
    let mut solved = false;
    let mut full_deg = 0u64;

    'outer: while !solved {
        while (rels.len() as u64) < next_check {
            if res.trials >= prm.max_trials {
                res.exhausted = true;
                break 'outer;
            }
            if since_restart >= RESTART {
                let a = rng.gen_range(1..r);
                let b = rng.gen_range(1..r);
                let ag = curve.mul(&mut ops, inst.g, a);
                let bt = curve.mul(&mut ops, inst.target, b);
                cur = curve.add(&mut ops, ag, bt);
                ca = a;
                cb = b;
                ck = 0;
                (fa, fb_, fk) = (a as u128, b as u128, 0);
                if whole {
                    let k = rng.gen_range(1..inst.order);
                    let kz = curve.mul(&mut ops, z, k);
                    cur = curve.add(&mut ops, cur, kz);
                    ck = k % r;
                    fk = k as u128;
                }
                since_restart = 0;
            } else {
                let j = (mix64(curve.key_of(&cur)) >> 24) as usize % 16;
                let (m, aj, bj, gj, gx) = jumps[j];
                cur = curve.add(&mut ops, cur, m);
                ca = addm(ca, aj, r);
                cb = addm(cb, bj, r);
                ck = addm(ck, gj, r);
                if check_walk {
                    fa += aj as u128;
                    fb_ += bj as u128;
                    if whole {
                        fk += gx as u128;
                    }
                }
                since_restart += 1;
            }
            res.trials += 1;
            if u32::from(cur.deg) != curve.genus() {
                continue;
            }
            full_deg += 1;
            let u: Poly = cur.u_coeffs();
            if !splits_completely(p, &u, &mut res.rel) {
                continue;
            }
            res.splits += 1;
            let Some(roots) = roots_of(p, &u, &mut rng, &mut res.rel) else {
                continue;
            };
            let vc = cur.v_coeffs();
            let mut rel = Rel {
                fb: [(0, 0); 3],
                nfb: 0,
                lp: [(0, 0); 2],
                nlp: 0,
                tcoef: 0,
                zcoef: 0,
                rhs: 0,
            };
            let mut lps: Vec<(u32, i8)> = Vec::new();
            let mut places: Vec<(u64, u64)> = Vec::new();
            for &x in &roots {
                let mut y = 0u64;
                for &cf in vc.iter().rev() {
                    y = pm(p, y, x, &mut res.rel);
                    y = pa(p, y, cf, &mut res.rel);
                }
                places.push((x, y));
                if y == 0 {
                    continue; // 2-torsion place: its log is 0 in the r-part
                }
                let eps: i8 = if y > (p - 1) / 2 { -1 } else { 1 };
                if col[x as usize] != u32::MAX {
                    rel.fb[rel.nfb as usize] = (col[x as usize], eps);
                    rel.nfb += 1;
                } else {
                    lps.push((x as u32, eps));
                }
            }
            if lps.len() > prm.arm.max_lp() {
                continue;
            }
            if rel.nfb == 0 && lps.is_empty() {
                continue;
            }
            res.rel.mul += 3;
            rel.rhs = mulmod(h % r, ca, r);
            rel.tcoef = subm(0, mulmod(h % r, cb, r), r);
            rel.zcoef = subm(0, ck, r);
            if prm.verify_relations || check_walk {
                let mut sum = H64Div::IDENTITY;
                for &(x, y) in &places {
                    let pt = curve.point(x, y).expect("a root of u lies on the curve");
                    sum = curve.cantor(sum, pt);
                }
                let mut want_pt = curve.mul_uncounted(inst.g, (fa % r as u128) as u64);
                want_pt = curve.cantor(
                    want_pt,
                    curve.mul_uncounted(inst.target, (fb_ % r as u128) as u64),
                );
                if whole {
                    want_pt = curve.cantor(want_pt, curve.mul_uncounted(z, fk as u64));
                }
                if sum != cur || (check_walk && want_pt != cur) {
                    res.bad_relations += 1;
                }
            }
            for (x, e) in lps {
                let id = *vid.entry(x).or_insert_with(|| dsu.add_vertex());
                rel.lp[rel.nlp as usize] = (id, e);
                rel.nlp += 1;
            }
            let (a, _, b, _) = rel.endpoints();
            dsu.edge(a, b);
            res.rels_by_lp[rel.nlp as usize] += 1;
            res.relations += 1;
            rels.push(rel);
        }

        // ── is a solve worth trying? ──
        res.cycles = dsu.cycles0();
        let nver = dsu.parent.len();
        if prm.arm != Arm::Full {
            let need = (nunk + margin(nunk)) as i64;
            if res.cycles < need {
                next_check = rels.len() as u64 + (need - res.cycles).max(1) as u64;
                continue;
            }
        } else {
            let mut scratch = Nat::default();
            let rows = build_rows(&rels, nver, tcol, zcol, r, &mut scratch);
            let (core, cc, _) = peel(&rows, nunk, tcol, &mut scratch);
            if core.len() < cc + margin(cc) {
                next_check = rels.len() as u64 + (nunk as u64 / 32).max(8);
                continue;
            }
        }

        // ── counted attempt ──
        res.attempts += 1;
        let mut g_nat = Nat::default();
        let rows = build_rows(&rels, nver, tcol, zcol, r, &mut g_nat);
        let mut p_nat = Nat::default();
        let (core, cc, ct) = peel(&rows, nunk, tcol, &mut p_nat);
        res.la_graph.merge(g_nat);
        res.la_peel.merge(p_nat);
        res.la.merge(g_nat);
        res.la.merge(p_nat);
        res.core_rows = core.len();
        res.core_cols = cc;
        if core.len() < cc + margin(cc) {
            next_check = rels.len() as u64 + (nunk as u64 / 20).max(8);
            continue;
        }
        let mut w_nat = Nat::default();
        let dense = res.attempts > 1;
        let sol = wiedemann(&core, cc, r, &mut rng, dense, &mut w_nat);
        res.la_wied.merge(w_nat);
        res.la.merge(w_nat);
        if let Some(x) = sol {
            let t = x[ct as usize];
            let v0 = ops.adds + ops.doubles;
            let chk = curve.mul(&mut ops, inst.g, t);
            res.verify_ops = ops.adds + ops.doubles - v0;
            let ok = chk == inst.target && curve.mul_rtl(inst.g, t) == inst.target;
            if ok {
                res.recovered = Some(t);
                res.certified = true;
                solved = true;
                continue;
            }
        }
        next_check = rels.len() as u64 + (nunk as u64 / 20).max(16);
    }
    res.la.add += dsu.ops;
    res.group = ops;
    res.walk_ops = (ops.adds + ops.doubles) - res.setup_ops - res.verify_ops;
    res.wall_ns = start.elapsed().as_nanos() as u64;
    let rate = if full_deg > 0 {
        res.splits as f64 / full_deg as f64
    } else {
        0.0
    };
    FullResult {
        ic: res,
        smooth_rate: rate,
    }
}

