//! # Open case O3: index calculus with relations from all of `J_C(F_p)`.
//!
//! Protocol: `research/full_jacobian_ic_20261113/PROTOCOL.md`.
//!
//! `research/chained_transfer_proof_20261112/PROOF.md` (T5, T7) shows that an
//! index calculus whose relations lie in the transferred subgroup
//! `S = c^*(E(F_p))` is a collision search on `E`.  Case O3 is the index
//! calculus of Gaudry's kind, which takes its relations from random elements
//! of the **whole** Jacobian.  This module is that algorithm for the
//! bielliptic covers of the chained-transfer experiments, with the walk
//! collection, double large primes and counted Wiedemann linear algebra of
//! [`super::ic_control`] (the unchanged `build_rows`-style graph reduction,
//! `peel` and `wiedemann`).
//!
//! ## The relation lattice and the projection to the `r`-part
//!
//! `#J = h r`, `r` prime, `r ∤ h` (curve selection rejects `r | #E2` and
//! `r² | #J`, which would make the `r`-part non-cyclic).  Hence the `r`-part
//! of `J(F_p)` is the cyclic group generated by `G' = φ^*G`, and `h·D ∈ ⟨G'⟩`
//! for every `D ∈ J`.  Let `Z` be a random element with `hZ ≠ 0` and
//! `ζ = log_{G'}(hZ)`.  A relation is a walk point
//!
//! ```text
//!   R = a G' + b T' + k Z  =  Σ ε_j P_j        (P_j degree-1 places)
//! ```
//!
//! with `T' = [t] G'`.  Multiplying by `h` projects to the `r`-part and gives
//! the row (unknowns `ℓ_j = log_{G'}(h P_j)`, `t`, `ζ`, all mod `r`)
//!
//! ```text
//!   Σ ε_j ℓ_j − (h b) t − k ζ = h a   (mod r).
//! ```
//!
//! The walk adds jumps `α G' + β T' + γ Z`, so `R` ranges over `⟨G', Z⟩`,
//! which is (a large part of) all of `J`; with `γ = 0` and `k = 0` it would be
//! the subgroup walk of `ic_control`.  Wiedemann solves the (peeled) system
//! mod `r`; `t` is certified by `[t]G' == T'` on `J_C` and `[t]G == T` on `E`.
//!
//! Nothing here is a transfer: the one-time cover and pull-back are in no
//! per-instance total.  Every figure is `[pcc:unverified]` until a validator
//! replays it.

