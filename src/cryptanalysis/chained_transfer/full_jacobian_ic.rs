    #[test]
    fn loglog_fit_recovers_an_exponent_and_rejects_bad_input() {
        let xs = [100.0, 200.0, 400.0, 800.0, 1600.0];
        let ys: Vec<f64> = xs.iter().map(|x: &f64| 3.0 * x.powf(0.5)).collect();
        let (s, a, se, ci) = fit_loglog(&xs, &ys).unwrap();
        assert!((s - 0.5).abs() < 1e-12 && (a - 3f64.ln()).abs() < 1e-12);
        assert!(se < 1e-9 && ci[0] <= 0.5 && ci[1] >= 0.5);
        assert!(fit_loglog(&xs[..2], &ys[..2]).is_none());
        assert!(fit_loglog(&xs, &[1.0, 2.0, 0.0, 4.0, 5.0]).is_none());
        assert!(t95(3) > t95(30) && t95(0).is_nan());
    }

    #[test]
    fn whole_j_ic_recovers_a_certified_log_in_all_arms_p211() {
        let ci = cover_select(211, 0).expect("cover");
        let inst0 = cover_instance(&ci, 0).expect("instance");
        // Z outside the transferred subgroup: its hZ is not 0 and Z has a
        // large order, so the walk leaves <G'>.
        assert!(inst0.z_order > inst0.inst.r);
        for (arm, nb) in [(Arm::Full, 0), (Arm::SingleLp, 30), (Arm::DoubleLp, 30)] {
            for seed in 1..4u64 {
                let out = run_full_ic(
                    &inst0.inst,
                    inst0.z,
                    Source::WholeJ,
                    params(arm, nb, seed),
                    false,
                );
                let rec = out.ic.recovered.expect("log recovered");
                assert!(out.ic.certified && !out.ic.exhausted, "{arm:?} {seed}");
                assert_eq!(out.ic.bad_relations, 0, "relation sums");
                assert_eq!(rec % inst0.inst.r, inst0.x);
                assert_eq!(certify_both(&ci, inst0.x, rec), (true, true));
                assert!(
                    out.smooth_rate > 0.2 && out.smooth_rate < 0.8,
                    "{}",
                    out.smooth_rate
                );
            }
        }
    }

