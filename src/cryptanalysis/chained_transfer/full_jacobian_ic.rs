/// One DLP instance on a selected cover, with every certificate input.
pub struct CoverInstance {
    pub inst: Instance,
    pub x: u64,
    pub seed: u64,
    pub z: H64Div,
    /// Order of `Z` in `J` (for the coverage statistic `ord(Z) / #J`).
    pub z_order: u64,
}

/// The `k`-th instance of a cover (`seed0 ^ k 0x1000`, as the recorded
/// cover_pushforward runs).  `Err` names why the instance is unusable.
pub fn cover_instance(ci: &CoverCurve, k: usize) -> Result<CoverInstance, String> {
    let b = &ci.b;
    let (r, e1) = (ci.r, b.e1);
    let seed = ci.seed0 ^ (k as u64 * 0x1000);
    let x = (seed.wrapping_mul(2_246_822_519).wrapping_add(7)) % r;
    let te = e1.mul(&ci.gen, x as u128);
    let dg = b.pull(Quotient::E1, &ci.gen);
    let dt = b.pull(Quotient::E1, &te);
    let hc = genus2_to_h64(&b.jac)?;
    let hg = convert_div(&hc, &dg).ok_or("G' does not convert")?;
    let ht = convert_div(&hc, &dt).ok_or("T' does not convert")?;
    let jac_order = e1.order() * b.e2.order();
    let inst = instance_for_rung(&hc, jac_order, r, hg, ht, x)?;
    let z = pick_z(&hc, inst.h, seed).ok_or("no Z with hZ != 0")?;
    let z_order = point_order(&hc, z, jac_order);
    Ok(CoverInstance {
        inst,
        x,
        seed,
        z,
        z_order,
    })
}

/// Independent certificates of a recovered log: `[k]G == T` on `E1` and
/// `[k]φ^*G == φ^*T` on `J_C`, both by the library's own arithmetic (not the
/// word Jacobian the solver used).
pub fn certify_both(ci: &CoverCurve, x_inst: u64, k: u64) -> (bool, bool) {
    let b = &ci.b;
    let te = b.e1.mul(&ci.gen, x_inst as u128);
    let on_e = b.e1.mul(&ci.gen, k as u128) == te;
    let dg = b.pull(Quotient::E1, &ci.gen);
    let dt = b.pull(Quotient::E1, &te);
    let on_j = b.jac.mul(&dg, k) == dt;
    (on_e, on_j)
}

/// Why each candidate before the selected one of [`cover_select`] was
/// skipped, by reason (the same checks, in the same order, as the selection).
pub fn selection_skips(p: u64, i: usize, selected: u64) -> std::collections::BTreeMap<String, u32> {
    use super::bielliptic::Bielliptic;
    use super::negation_remeasure::{candidate_coeffs, largest_cyclic_prime};
    let mut m = std::collections::BTreeMap::new();
    let _ = i;
    for s in 0..selected {
        let reason = match Bielliptic::new(p, candidate_coeffs(p, s)) {
            Err(_) => "bielliptic_rejected",
            Ok(b) => {
                let (n1, n2) = (b.e1.order(), b.e2.order());
                let r = largest_cyclic_prime(n1);
                if r < 50 {
                    "r_below_50"
                } else if n2.is_multiple_of(r) {
                    "r_divides_e2_order"
                } else if (n1 * n2).is_multiple_of(r * r) {
                    "r_squared_divides_jac_order"
                } else {
                    "other_hop_or_point_failure"
                }
            }
        };
        *m.entry(reason.to_string()).or_insert(0) += 1;
    }
    m
}

