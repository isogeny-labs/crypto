/// Two-sided 95% Student `t` quantile for `df` degrees of freedom
/// (`df = 1..=10` tabulated, then the normal 1.96 with the usual correction).
pub fn t95(df: usize) -> f64 {
    const T: [f64; 10] = [
        12.706, 4.303, 3.182, 2.776, 2.571, 2.447, 2.365, 2.306, 2.262, 2.228,
    ];
    if df == 0 {
        f64::NAN
    } else if df <= 10 {
        T[df - 1]
    } else {
        1.96 + 2.4 / df as f64
    }
}

/// OLS fit of `ln y = a + s ln x`: `(s, a, se(s), [lo, hi] 95%)`.
pub fn fit_loglog(xs: &[f64], ys: &[f64]) -> Option<(f64, f64, f64, [f64; 2])> {
    let n = xs.len();
    if n < 3
        || ys.len() != n
        || xs
            .iter()
            .chain(ys)
            .any(|v| v.partial_cmp(&0.0) != Some(std::cmp::Ordering::Greater))
    {
        return None;
    }
    let lx: Vec<f64> = xs.iter().map(|v| v.ln()).collect();
    let ly: Vec<f64> = ys.iter().map(|v| v.ln()).collect();
    let (mx, my) = (
        lx.iter().sum::<f64>() / n as f64,
        ly.iter().sum::<f64>() / n as f64,
    );
    let sxx: f64 = lx.iter().map(|v| (v - mx).powi(2)).sum();
    let sxy: f64 = lx.iter().zip(&ly).map(|(a, b)| (a - mx) * (b - my)).sum();
    let s = sxy / sxx;
    let a = my - s * mx;
    let sse: f64 = lx
        .iter()
        .zip(&ly)
        .map(|(x, y)| (y - a - s * x).powi(2))
        .sum();
    let se = (sse / (n as f64 - 2.0) / sxx).sqrt();
    let t = t95(n - 2);
    Some((s, a, se, [s - t * se, s + t * se]))
}

