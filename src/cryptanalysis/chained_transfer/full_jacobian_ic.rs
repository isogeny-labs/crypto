    #[test]
    fn rows_are_sound_against_brute_force_logs() {
        // Independent of the linear algebra: with every log computed by
        // table look-up in <G'> (r = 109 at p = 211), every collected
        // relation satisfies its row equation mod r.
        let ci = cover_select(211, 0).expect("cover");
        let c = cover_instance(&ci, 2).expect("instance");
        let (curve, r, h) = (&c.inst.curve, c.inst.r, c.inst.h);
        let mut table: HashMap<H64Div, u64> = HashMap::new();
        let mut acc = H64Div::IDENTITY;
        for j in 0..r {
            table.insert(acc, j);
            acc = curve.cantor(acc, c.inst.g);
        }
        let log = |d: H64Div| -> u64 { table[&curve.mul_uncounted(d, h)] };
        let zeta = log(c.z);
        assert!(zeta != 0);
        // walk by hand: R = aG' + bT' + kZ, a smooth R splits over places
        let mut st = 99u64;
        let mut checked = 0;
        let mut tries = 0;
        while checked < 40 && tries < 100_000 {
            tries += 1;
            st = mix64(st);
            let (a, b, k) = (st % r, (st >> 20) % r, (st >> 40) % 100_000);
            let rr = curve.cantor(
                curve.cantor(
                    curve.mul_uncounted(c.inst.g, a),
                    curve.mul_uncounted(c.inst.target, b),
                ),
                curve.mul_uncounted(c.z, k),
            );
            if u32::from(rr.deg) != curve.genus() {
                continue;
            }
            let mut nat = Nat::default();
            let u = rr.u_coeffs();
            if !splits_completely(211, &u, &mut nat) {
                continue;
            }
            let mut rng = StdRng::seed_from_u64(1);
            let roots = roots_of(211, &u, &mut rng, &mut nat).unwrap();
            let vc = rr.v_coeffs();
            let mut lhs = 0u64;
            let mut ok = true;
            for &x in &roots {
                let y = vc.iter().rev().fold(0u64, |s, &cf| (s * x + cf) % 211);
                let Some(pt) = curve.point(x, y) else {
                    ok = false;
                    break;
                };
                if y == 0 {
                    continue;
                }
                lhs = (lhs + log(pt)) % r;
            }
            if !ok {
                continue;
            }
            let rhs = (h % r * a + h % r * b % r * c.x + k % r * zeta) % r;
            assert_eq!(lhs, rhs % r, "row equation");
            checked += 1;
        }
        assert!(checked >= 40, "only {checked} smooth points");
    }

