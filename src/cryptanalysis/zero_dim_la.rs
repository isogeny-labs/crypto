//! **The linear stage after F4, from a Gröbner basis to the `F_p`-points:
//! transposed sparse FGLM with a rational univariate read-out.**
//!
//! Input: a monic grevlex Gröbner basis of a zero-dimensional ideal
//! `I ⊂ F_p[x_1..x_n]` (as `f4_fp` returns it), `n ≤ 8`, `p < 2^63`.
//! Output: every `F_p`-rational point of `I`, each checked against the input
//! system.
//!
//! The incumbent sparse stage (`jv_cover::linear_stage_from_basis`,
//! `LinMode::Sparse`) does three things. It builds `M = M_{x_n}`. It gets the
//! minimal polynomial from `u^T M^j v`: `2δ` matrix-vector products plus `2δ`
//! dot products of length `δ`. It then recovers each point by a corank-one
//! elimination over the shift chains, one per root.
//!
//! This stage builds the same `M` and changes the rest:
//!
//! * **One transposed Krylov pass serves every coordinate.** It computes
//!   `w_j = (M^T)^j u` for `j < 2δ`. Then `u^T M^j v = w_j · v` for every `v`.
//!   For `v = NF(1)` and `v = NF(x_i)`, which are unit vectors when `1` and
//!   `x_i` are standard, each term of every sequence is a read of one entry,
//!   with no dot products.
//! * **Minimal polynomial.** Berlekamp–Massey on the sequence of `v = NF(1)`
//!   gives the generator `f`. When `deg f = δ`, `f` is the characteristic
//!   polynomial of `M`, `x_n` separates the points, and `u` is cyclic.
//! * **Roots.** The roots of `f` in `F_p` come from `gcd(f, x^p − x)`. It is
//!   computed by squaring modulo `f` against a precomputed table of `x^k mod f`
//!   for `k = δ..2δ−2`, with lazy reduction.
//! * **Read-out, with no elimination.** Write
//!   `Ψ_a(T) = Σ_{j<δ} a_j Q_j(T)` with `Q_{δ−1} = 1` and
//!   `Q_j = f_{j+1} + T Q_{j+1}`, for a sequence `a` generated by `f`. If
//!   `u = Σ_ℓ α_ℓ ev_{P_ℓ}`, then `Ψ_{a(v)}(ξ_ℓ) = α_ℓ v(P_ℓ) f'(ξ_ℓ)`. So
//!   `x_i(P_ℓ) = Ψ_{a(x_i)}(ξ_ℓ) / Ψ_{a(1)}(ξ_ℓ)`. This is the rational
//!   univariate representation, at `O(n δ)` per root.
//!
//! The stage gives up (`None`) rather than guess:
//! * `deg f < δ` after four functionals `u`;
//! * a root where `Ψ_{a(1)}` vanishes (a multiple point);
//! * a candidate that fails the input.
//!
//! The caller then runs the incumbent's dense stage, which needs no
//! separating coordinate.
//!
//! All accumulation is lazy: products are summed in `u128` and reduced once
//! per output entry, or every `L = ⌊(2^128 − 1)/(p − 1)²⌋` terms when `p` is
//! large.

