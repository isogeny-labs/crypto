    fn naive_mul(p: u64, a: &[u32], b: &[u32]) -> Vec<u32> {
        let mut out = vec![0u64; a.len() + b.len() - 1];
        for (i, &x) in a.iter().enumerate() {
            for (j, &y) in b.iter().enumerate() {
                out[i + j] = (out[i + j] + x as u64 * y as u64 % p) % p;
            }
        }
        out.into_iter().map(|c| c as u32).collect()
    }

