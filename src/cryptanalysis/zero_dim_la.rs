/// `F_p` with lazy `u128` reduction.
#[derive(Clone, Copy)]
struct Fp {
    p: u64,
    /// Products of two reduced values that a `u128` holds.
    chunk: usize,
    /// `2^64 mod p`, for the fast reduction when `p < 2^32`.
    r64: u64,
    /// `2^32 mod p`.
    r32: u64,
    /// `⌊2^64 / p⌋`, for Barrett reduction of a `u64`.
    bm: u64,
    small: bool,
}

impl Fp {
    fn new(p: u64) -> Self {
        let pm = (p - 1) as u128;
        let chunk = if pm <= 1 {
            usize::MAX
        } else {
            (u128::MAX / (pm * pm)).min(usize::MAX as u128) as usize
        };
        let r64 = ((1u128 << 64) % p as u128) as u64;
        Fp {
            p,
            chunk: chunk.max(1),
            r64,
            r32: (1u64 << 32) % p,
            bm: (u128::from(u64::MAX) / u128::from(p)) as u64,
            small: p < (1u64 << 32),
        }
    }
    /// `x mod p` for any `u64`, by Barrett: `q = ⌊x·bm / 2^64⌋` is at most two
    /// short of `⌊x/p⌋`.
    #[inline(always)]
    fn bred(&self, x: u64) -> u64 {
        let q = ((x as u128 * self.bm as u128) >> 64) as u64;
        let mut r = x - q * self.p;
        if r >= self.p {
            r -= self.p;
        }
        if r >= self.p {
            r -= self.p;
        }
        r
    }
    #[inline(always)]
    fn red(&self, x: u128) -> u64 {
        if self.small {
            let hi = self.bred((x >> 64) as u64);
            let lo = self.bred(x as u64);
            // hi·r64 < p² < 2^64
            self.add(self.bred(hi * self.r64), lo)
        } else {
            (x % self.p as u128) as u64
        }
    }
    #[inline(always)]
    fn mul(&self, a: u64, b: u64) -> u64 {
        if self.small && a < self.p && b < self.p {
            self.bred(a * b)
        } else {
            self.red(a as u128 * b as u128)
        }
    }
    #[inline(always)]
    fn add(&self, a: u64, b: u64) -> u64 {
        let s = a + b;
        if s >= self.p {
            s - self.p
        } else {
            s
        }
    }
    #[inline(always)]
    fn sub(&self, a: u64, b: u64) -> u64 {
        if a >= b {
            a - b
        } else {
            a + self.p - b
        }
    }
    fn inv(&self, a: u64) -> u64 {
        inv_mod(a, self.p)
    }
}

// ── u32 kernels (p < 2^32) ─────────────────────────────────────────────
//
// Every reduced value fits a `u32` and every product a `u64`. A dot product
// keeps the low and the high 32 bits of its products in separate `u64` lanes,
// so nothing overflows for fewer than 2^32 terms. This is a loop LLVM
// vectorises (`vpmuludq`); the AVX2 copy is chosen at run time.

const LO: u64 = 0xFFFF_FFFF;

#[inline(always)]
fn dot_body(a: &[u32], b: &[u32]) -> (u64, u64) {
    let mut lo = [0u64; 8];
    let mut hi = [0u64; 8];
    let mut ca = a.chunks_exact(8);
    let mut cb = b.chunks_exact(8);
    for (x, y) in (&mut ca).zip(&mut cb) {
        for i in 0..8 {
            let pr = x[i] as u64 * y[i] as u64;
            lo[i] += pr & LO;
            hi[i] += pr >> 32;
        }
    }
    let (mut l, mut h) = (lo.iter().sum::<u64>(), hi.iter().sum::<u64>());
    for (x, y) in ca.remainder().iter().zip(cb.remainder()) {
        let pr = *x as u64 * *y as u64;
        l += pr & LO;
        h += pr >> 32;
    }
    (l, h)
}

// Explicit kernels. `vpmuludq` multiplies the low 32 bits of each 64-bit
// lane, so the even lanes of `x · y` come from `x`, `y` directly and the odd
// lanes from both shifted right by 32. Low and high halves of the products
// accumulate in separate 64-bit lanes, as in `dot_body`.

#[cfg(target_arch = "x86_64")]
#[target_feature(enable = "avx2")]
unsafe fn dot_avx2(a: &[u32], b: &[u32]) -> (u64, u64) {
    use std::arch::x86_64::*;
    let n = a.len();
    let mask = _mm256_set1_epi64x(LO as i64);
    let (mut lo, mut hi) = (_mm256_setzero_si256(), _mm256_setzero_si256());
    let mut i = 0;
    while i + 8 <= n {
        let x = _mm256_loadu_si256(a.as_ptr().add(i).cast());
        let y = _mm256_loadu_si256(b.as_ptr().add(i).cast());
        let pe = _mm256_mul_epu32(x, y);
        let po = _mm256_mul_epu32(_mm256_srli_epi64(x, 32), _mm256_srli_epi64(y, 32));
        lo = _mm256_add_epi64(
            lo,
            _mm256_add_epi64(_mm256_and_si256(pe, mask), _mm256_and_si256(po, mask)),
        );
        hi = _mm256_add_epi64(
            hi,
            _mm256_add_epi64(_mm256_srli_epi64(pe, 32), _mm256_srli_epi64(po, 32)),
        );
        i += 8;
    }
    let mut lv = [0u64; 4];
    let mut hv = [0u64; 4];
    _mm256_storeu_si256(lv.as_mut_ptr().cast(), lo);
    _mm256_storeu_si256(hv.as_mut_ptr().cast(), hi);
    let (mut l, mut h) = (lv.iter().sum::<u64>(), hv.iter().sum::<u64>());
    while i < n {
        let pr = a[i] as u64 * b[i] as u64;
        l += pr & LO;
        h += pr >> 32;
        i += 1;
    }
    (l, h)
}

/// Four dot products against one `w`, sharing its loads.
#[inline(always)]
fn dot4_body(r: [&[u32]; 4], w: &[u32]) -> [(u64, u64); 4] {
    let n = w.len();
    let mut lo = [[0u64; 8]; 4];
    let mut hi = [[0u64; 8]; 4];
    let full = n / 8 * 8;
    let mut i = 0;
    while i < full {
        let wc: &[u32; 8] = w[i..i + 8].try_into().unwrap();
        for k in 0..4 {
            let rc: &[u32; 8] = r[k][i..i + 8].try_into().unwrap();
            for j in 0..8 {
                let pr = rc[j] as u64 * wc[j] as u64;
                lo[k][j] += pr & LO;
                hi[k][j] += pr >> 32;
            }
        }
        i += 8;
    }
    let mut out = [(0u64, 0u64); 4];
    for k in 0..4 {
        let (mut l, mut h) = (lo[k].iter().sum::<u64>(), hi[k].iter().sum::<u64>());
        for j in full..n {
            let pr = r[k][j] as u64 * w[j] as u64;
            l += pr & LO;
            h += pr >> 32;
        }
        out[k] = (l, h);
    }
    out
}

#[cfg(target_arch = "x86_64")]
#[target_feature(enable = "avx512f")]
unsafe fn dot4_avx512(r: [&[u32]; 4], w: &[u32]) -> [(u64, u64); 4] {
    use std::arch::x86_64::*;
    let n = w.len();
    let mask = _mm512_set1_epi64(LO as i64);
    let mut lo = [_mm512_setzero_si512(); 4];
    let mut hi = [_mm512_setzero_si512(); 4];
    let mut i = 0;
    while i + 16 <= n {
        let y = _mm512_loadu_si512(w.as_ptr().add(i).cast());
        let yo = _mm512_srli_epi64(y, 32);
        for k in 0..4 {
            let x = _mm512_loadu_si512(r[k].as_ptr().add(i).cast());
            let pe = _mm512_mul_epu32(x, y);
            let po = _mm512_mul_epu32(_mm512_srli_epi64(x, 32), yo);
            lo[k] = _mm512_add_epi64(
                lo[k],
                _mm512_add_epi64(_mm512_and_si512(pe, mask), _mm512_and_si512(po, mask)),
            );
            hi[k] = _mm512_add_epi64(
                hi[k],
                _mm512_add_epi64(_mm512_srli_epi64(pe, 32), _mm512_srli_epi64(po, 32)),
            );
        }
        i += 16;
    }
    let mut out = [(0u64, 0u64); 4];
    for k in 0..4 {
        let (mut l, mut h) = (
            _mm512_reduce_add_epi64(lo[k]) as u64,
            _mm512_reduce_add_epi64(hi[k]) as u64,
        );
        for j in i..n {
            let pr = r[k][j] as u64 * w[j] as u64;
            l += pr & LO;
            h += pr >> 32;
        }
        out[k] = (l, h);
    }
    out
}

#[inline(always)]
fn axpy_body(lo: &mut [u64], hi: &mut [u64], c: u32, row: &[u32]) {
    let c = c as u64;
    for ((l, h), &x) in lo.iter_mut().zip(hi.iter_mut()).zip(row) {
        let pr = c * x as u64;
        *l += pr & LO;
        *h += pr >> 32;
    }
}

#[cfg(target_arch = "x86_64")]
#[target_feature(enable = "avx2")]
unsafe fn axpy_avx2(lo: &mut [u64], hi: &mut [u64], c: u32, row: &[u32]) {
    axpy_body(lo, hi, c, row)
}

#[cfg(target_arch = "x86_64")]
#[target_feature(enable = "avx512f")]
unsafe fn dot_avx512(a: &[u32], b: &[u32]) -> (u64, u64) {
    use std::arch::x86_64::*;
    let n = a.len();
    let mask = _mm512_set1_epi64(LO as i64);
    let (mut lo, mut hi) = (_mm512_setzero_si512(), _mm512_setzero_si512());
    let mut i = 0;
    while i + 16 <= n {
        let x = _mm512_loadu_si512(a.as_ptr().add(i).cast());
        let y = _mm512_loadu_si512(b.as_ptr().add(i).cast());
        let pe = _mm512_mul_epu32(x, y);
        let po = _mm512_mul_epu32(_mm512_srli_epi64(x, 32), _mm512_srli_epi64(y, 32));
        lo = _mm512_add_epi64(
            lo,
            _mm512_add_epi64(_mm512_and_si512(pe, mask), _mm512_and_si512(po, mask)),
        );
        hi = _mm512_add_epi64(
            hi,
            _mm512_add_epi64(_mm512_srli_epi64(pe, 32), _mm512_srli_epi64(po, 32)),
        );
        i += 16;
    }
    let (mut l, mut h) = (
        _mm512_reduce_add_epi64(lo) as u64,
        _mm512_reduce_add_epi64(hi) as u64,
    );
    while i < n {
        let pr = a[i] as u64 * b[i] as u64;
        l += pr & LO;
        h += pr >> 32;
        i += 1;
    }
    (l, h)
}

#[cfg(target_arch = "x86_64")]
#[target_feature(enable = "avx512f")]
unsafe fn axpy_avx512(lo: &mut [u64], hi: &mut [u64], c: u32, row: &[u32]) {
    use std::arch::x86_64::*;
    let n = row.len().min(lo.len()).min(hi.len());
    let mask = _mm512_set1_epi64(LO as i64);
    let cv = _mm512_set1_epi64(c as i64);
    let mut i = 0;
    while i + 8 <= n {
        let x = _mm512_cvtepu32_epi64(_mm256_loadu_si256(row.as_ptr().add(i).cast()));
        let pr = _mm512_mul_epu32(x, cv);
        let l = _mm512_loadu_si512(lo.as_ptr().add(i).cast());
        let h = _mm512_loadu_si512(hi.as_ptr().add(i).cast());
        _mm512_storeu_si512(
            lo.as_mut_ptr().add(i).cast(),
            _mm512_add_epi64(l, _mm512_and_si512(pr, mask)),
        );
        _mm512_storeu_si512(
            hi.as_mut_ptr().add(i).cast(),
            _mm512_add_epi64(h, _mm512_srli_epi64(pr, 32)),
        );
        i += 8;
    }
    axpy_body(&mut lo[i..n], &mut hi[i..n], c, &row[i..n]);
}

/// The widest vector unit to use: 2 = AVX-512, 1 = AVX2, 0 = portable.
/// `ZERO_DIM_LA_SIMD=avx2|portable` caps it (for the kernel ablation).
fn simd_level() -> u8 {
    static L: std::sync::OnceLock<u8> = std::sync::OnceLock::new();
    *L.get_or_init(|| {
        let cap = match std::env::var("ZERO_DIM_LA_SIMD").as_deref() {
            Ok("portable") => 0,
            Ok("avx2") => 1,
            _ => 2,
        };
        #[cfg(target_arch = "x86_64")]
        {
            let have = if std::is_x86_feature_detected!("avx512f") {
                2
            } else if std::is_x86_feature_detected!("avx2") {
                1
            } else {
                0
            };
            have.min(cap)
        }
        #[cfg(not(target_arch = "x86_64"))]
        {
            let _ = cap;
            0
        }
    })
}

/// Threads for the dense part of each Krylov step: `ZERO_DIM_LA_THREADS`
/// (default 1, the single-threaded comparison).
fn krylov_pool() -> Option<&'static rayon::ThreadPool> {
    static P: std::sync::OnceLock<Option<rayon::ThreadPool>> = std::sync::OnceLock::new();
    P.get_or_init(|| {
        let t: usize = std::env::var("ZERO_DIM_LA_THREADS")
            .ok()
            .and_then(|v| v.parse().ok())
            .unwrap_or(1);
        (t > 1).then(|| {
            rayon::ThreadPoolBuilder::new()
                .num_threads(t)
                .build()
                .expect("thread pool")
        })
    })
    .as_ref()
}

/// Threads the Krylov pass uses, for the records.
pub fn krylov_threads() -> usize {
    krylov_pool().map_or(1, |p| p.current_num_threads())
}

/// The kernel set in use, for the records.
pub fn simd_name() -> &'static str {
    match simd_level() {
        2 => "avx512f",
        1 => "avx2",
        _ => "portable",
    }
}

impl Fp {
    /// `(hi·2^32 + lo) mod p`.
    #[inline(always)]
    fn red_lohi(&self, lo: u64, hi: u64) -> u64 {
        let h = self.bred(self.bred(hi) * self.r32);
        self.add(h, self.bred(lo))
    }
    /// `Σ a_i b_i mod p`, `a, b` reduced, fewer than 2^32 terms.
    #[inline]
    fn dot(&self, a: &[u32], b: &[u32]) -> u64 {
        #[cfg(target_arch = "x86_64")]
        let (l, h) = match simd_level() {
            2 => unsafe { dot_avx512(a, b) },
            1 => unsafe { dot_avx2(a, b) },
            _ => dot_body(a, b),
        };
        #[cfg(not(target_arch = "x86_64"))]
        let (l, h) = dot_body(a, b);
        self.red_lohi(l, h)
    }
    /// Four dot products `r_k · w mod p`.
    #[inline]
    fn dot4(&self, r: [&[u32]; 4], w: &[u32]) -> [u64; 4] {
        #[cfg(target_arch = "x86_64")]
        let v = match simd_level() {
            2 => unsafe { dot4_avx512(r, w) },
            1 => unsafe {
                [
                    dot_avx2(r[0], w),
                    dot_avx2(r[1], w),
                    dot_avx2(r[2], w),
                    dot_avx2(r[3], w),
                ]
            },
            _ => dot4_body(r, w),
        };
        #[cfg(not(target_arch = "x86_64"))]
        let v = dot4_body(r, w);
        [
            self.red_lohi(v[0].0, v[0].1),
            self.red_lohi(v[1].0, v[1].1),
            self.red_lohi(v[2].0, v[2].1),
            self.red_lohi(v[3].0, v[3].1),
        ]
    }
    /// `(lo, hi) += c · row`, lane-wise.
    #[inline]
    fn axpy(&self, lo: &mut [u64], hi: &mut [u64], c: u32, row: &[u32]) {
        #[cfg(target_arch = "x86_64")]
        match simd_level() {
            2 => {
                unsafe { axpy_avx512(lo, hi, c, row) };
                return;
            }
            1 => {
                unsafe { axpy_avx2(lo, hi, c, row) };
                return;
            }
            _ => {}
        }
        axpy_body(lo, hi, c, row)
    }
}

// ── Polynomials over F_p, reduced u32 coefficients, low to high ──────────

const KARATSUBA_MIN: usize = 32;

/// `a · b` (lengths `la`, `lb` → `la + lb − 1`), reduced.
fn pmul(fp: &Fp, a: &[u32], b: &[u32], muls: &mut u64) -> Vec<u32> {
    if a.is_empty() || b.is_empty() {
        return Vec::new();
    }
    if a.len().min(b.len()) <= KARATSUBA_MIN || a.len() != b.len() {
        return pmul_school(fp, a, b, muls);
    }
    let n = a.len();
    let h = n / 2;
    let (a0, a1) = a.split_at(h);
    let (b0, b1) = b.split_at(h);
    // unequal halves when n is odd: pad the low halves to the high length
    let m = n - h;
    let pad = |x: &[u32]| -> Vec<u32> {
        let mut v = x.to_vec();
        v.resize(m, 0);
        v
    };
    let (a0p, b0p) = (pad(a0), pad(b0));
    let z0 = pmul(fp, &a0p, &b0p, muls);
    let z2 = pmul(fp, a1, b1, muls);
    let sa: Vec<u32> = a0p
        .iter()
        .zip(a1)
        .map(|(&x, &y)| fp.add(x as u64, y as u64) as u32)
        .collect();
    let sb: Vec<u32> = b0p
        .iter()
        .zip(b1)
        .map(|(&x, &y)| fp.add(x as u64, y as u64) as u32)
        .collect();
    let z1 = pmul(fp, &sa, &sb, muls);
    let mut out = vec![0u32; 2 * n - 1];
    for (i, &v) in z0.iter().enumerate() {
        out[i] = fp.add(out[i] as u64, v as u64) as u32;
    }
    for (i, &v) in z2.iter().enumerate() {
        out[i + 2 * h] = fp.add(out[i + 2 * h] as u64, v as u64) as u32;
    }
    for i in 0..z1.len() {
        let mid = fp.sub(
            fp.sub(z1[i] as u64, z0.get(i).copied().unwrap_or(0) as u64),
            z2.get(i).copied().unwrap_or(0) as u64,
        );
        if i + h < out.len() {
            out[i + h] = fp.add(out[i + h] as u64, mid) as u32;
        }
    }
    out
}

fn pmul_school(fp: &Fp, a: &[u32], b: &[u32], muls: &mut u64) -> Vec<u32> {
    let len = a.len() + b.len() - 1;
    let mut lo = vec![0u64; len];
    let mut hi = vec![0u64; len];
    let (s, l) = if a.len() <= b.len() { (a, b) } else { (b, a) };
    for (i, &c) in s.iter().enumerate() {
        if c != 0 {
            fp.axpy(&mut lo[i..i + l.len()], &mut hi[i..i + l.len()], c, l);
            *muls += l.len() as u64;
        }
    }
    lo.iter()
        .zip(&hi)
        .map(|(&l, &h)| fp.red_lohi(l, h) as u32)
        .collect()
}

/// Arithmetic modulo a monic `f` of degree `d ≥ 2` by Barrett: `finv` is
/// `rev(f)^{-1} mod x^{d−1}`.
struct ModF {
    d: usize,
    f: Vec<u32>,
    finv: Vec<u32>,
}

impl ModF {
    fn new(fp: &Fp, f: &[u64], muls: &mut u64) -> Self {
        let d = f.len() - 1;
        let fu: Vec<u32> = f.iter().map(|&c| c as u32).collect();
        // rev(f) = Σ f_{d−i} x^i has constant term 1; invert as a power series
        let k = d - 1;
        let rev: Vec<u64> = (0..=d).map(|i| f[d - i]).collect();
        let mut inv = vec![0u64; k.max(1)];
        inv[0] = 1;
        for i in 1..k {
            // inv_i = −Σ_{j=1..i} rev_j inv_{i−j}
            let mut lo = 0u64;
            let mut hi = 0u64;
            for j in 1..=i.min(d) {
                let pr = rev[j] * inv[i - j];
                lo += pr & LO;
                hi += pr >> 32;
            }
            *muls += i.min(d) as u64;
            inv[i] = (fp.p - fp.red_lohi(lo, hi)) % fp.p;
        }
        ModF {
            d,
            f: fu,
            finv: inv.iter().map(|&c| c as u32).collect(),
        }
    }
    /// `a mod f`, `a` of length `≤ 2d − 1`.
    fn reduce(&self, fp: &Fp, a: &[u32], muls: &mut u64) -> Vec<u32> {
        let d = self.d;
        if a.len() <= d {
            let mut r = a.to_vec();
            r.resize(d, 0);
            return r;
        }
        let k = d - 1;
        let mut a = a.to_vec();
        a.resize(2 * d - 1, 0);
        // quotient q (degree ≤ d − 2): rev(q) = rev(a)_{<k} · finv mod x^k
        let ra: Vec<u32> = a.iter().rev().take(k).copied().collect();
        let mut qr = pmul(fp, &ra, &self.finv, muls);
        qr.truncate(k);
        qr.resize(k, 0);
        let q: Vec<u32> = qr.iter().rev().copied().collect();
        // r = a − q·f, low d coefficients
        let qf = pmul_any(fp, &q, &self.f, muls);
        (0..d)
            .map(|i| fp.sub(a[i] as u64, qf.get(i).copied().unwrap_or(0) as u64) as u32)
            .collect()
    }
    /// Reference for the tests of [`Powering`].
    #[allow(dead_code)]
    fn sqrmod(&self, fp: &Fp, a: &[u32], muls: &mut u64) -> Vec<u32> {
        let sq = pmul(fp, a, a, muls);
        self.reduce(fp, &sq, muls)
    }
    /// `x · a mod f`.
    #[allow(dead_code)]
    fn mulx(&self, fp: &Fp, a: &[u32]) -> Vec<u32> {
        let d = self.d;
        let top = a[d - 1] as u64;
        let mut out = vec![0u32; d];
        out[1..d].copy_from_slice(&a[..d - 1]);
        if top != 0 {
            for i in 0..d {
                out[i] = fp.sub(out[i] as u64, fp.mul(top, self.f[i] as u64)) as u32;
            }
        }
        out
    }
}

/// Karatsuba on the common length, schoolbook on the rest.
fn pmul_any(fp: &Fp, a: &[u32], b: &[u32], muls: &mut u64) -> Vec<u32> {
    if a.is_empty() || b.is_empty() {
        return Vec::new();
    }
    let n = a.len().max(b.len());
    let mut ap = a.to_vec();
    ap.resize(n, 0);
    let mut bp = b.to_vec();
    bp.resize(n, 0);
    let mut out = pmul(fp, &ap, &bp, muls);
    out.truncate(a.len() + b.len() - 1);
    out
}

const GUARD: u64 = 0x8080_8080_8080_8080;

/// Standard monomials of the basis (grevlex leading monomials `lms`), or `None`
/// when some variable has no pure power among them, or there are more than
/// `limit` of them.
fn staircase(lms: &[Vec<u32>], n: usize, limit: usize) -> Option<Vec<Vec<u32>>> {
    let mut cap = vec![u32::MAX; n];
    for lm in lms {
        if let Some(k) = (0..n).find(|&k| lm[k] > 0 && (0..n).all(|i| i == k || lm[i] == 0)) {
            cap[k] = cap[k].min(lm[k]);
        }
    }
    if cap.contains(&u32::MAX) {
        return None;
    }
    fn walk(
        k: usize,
        mono: &mut Vec<u32>,
        cap: &[u32],
        lms: &[Vec<u32>],
        out: &mut Vec<Vec<u32>>,
        limit: usize,
    ) -> bool {
        if lms
            .iter()
            .any(|l| l.iter().zip(mono.iter()).all(|(a, b)| a <= b))
        {
            return true;
        }
        if k == cap.len() {
            out.push(mono.clone());
            return out.len() <= limit;
        }
        for e in 0..cap[k] {
            mono[k] = e;
            if !walk(k + 1, mono, cap, lms, out, limit) {
                mono[k] = 0;
                return false;
            }
        }
        mono[k] = 0;
        true
    }
    let mut out = Vec::new();
    let mut mono = vec![0u32; n];
    walk(0, &mut mono, &cap, lms, &mut out, limit).then_some(out)
}

/// The number of standard monomials of a grevlex basis (the degree δ of a
/// zero-dimensional ideal), or `None` if it is not zero-dimensional or has
/// more than `limit`.
pub fn staircase_size(basis: &[Poly], n: usize, limit: usize) -> Option<usize> {
    let lms: Vec<Vec<u32>> = basis.iter().map(|g| g[0].0.clone()).collect();
    staircase(&lms, n, limit).map(|v| v.len())
}

/// A normal form: a standard monomial, or a memoised dense row.
#[derive(Clone, Copy)]
enum Nf {
    Unit(usize),
    Row(usize),
}

struct NfTable<'a> {
    f: Fp,
    delta: usize,
    mask: u64,
    guard: u64,
    index: &'a FxMap<u64, usize>,
    /// (leading monomial, tail) of each basis element, packed, monic.
    bas: Vec<(u64, Vec<(u64, u64)>)>,
    memo: FxMap<u64, usize>,
    rows: Vec<Vec<u64>>,
    muls: u64,
}

impl NfTable<'_> {
    #[inline]
    fn divides(&self, a: u64, b: u64) -> bool {
        (((b & self.mask) | self.guard) - (a & self.mask)) & self.guard == self.guard
    }
    /// `NF(m)`, or `None` when no basis element reduces `m` (not a Gröbner
    /// basis of a zero-dimensional ideal).
    fn nf(&mut self, m: u64) -> Option<Nf> {
        if let Some(&k) = self.index.get(&m) {
            return Some(Nf::Unit(k));
        }
        if let Some(&r) = self.memo.get(&m) {
            return Some(Nf::Row(r));
        }
        let gi = self.bas.iter().position(|(lm, _)| self.divides(*lm, m))?;
        let cof = m - self.bas[gi].0;
        let tail_len = self.bas[gi].1.len();
        // the tail's normal forms first (recursion), then one lazy pass
        let mut parts: Vec<(u64, Nf)> = Vec::with_capacity(tail_len);
        for t in 0..tail_len {
            let (tm, c) = self.bas[gi].1[t];
            let sub = self.nf(tm + cof)?;
            parts.push((self.f.p - c, sub));
        }
        let delta = self.delta;
        let f = self.f;
        let mut acc = vec![0u128; delta];
        let mut out = vec![0u64; delta];
        // units are added directly; rows in chunks that a u128 holds
        let rows: Vec<(u64, usize)> = parts
            .iter()
            .filter_map(|&(c, s)| match s {
                Nf::Row(r) => Some((c, r)),
                Nf::Unit(_) => None,
            })
            .collect();
        for chunk in rows.chunks(f.chunk.min(1 << 20)) {
            for &(c, r) in chunk {
                let row = &self.rows[r];
                let c = c as u128;
                for (a, &x) in acc.iter_mut().zip(row.iter()) {
                    *a += c * x as u128;
                }
                self.muls += delta as u64;
            }
            if rows.len() > f.chunk {
                for (o, a) in out.iter_mut().zip(acc.iter_mut()) {
                    *o = f.add(*o, f.red(*a));
                    *a = 0;
                }
            }
        }
        if rows.len() <= f.chunk {
            for (o, a) in out.iter_mut().zip(acc.iter()) {
                *o = f.red(*a);
            }
        }
        for &(c, s) in &parts {
            if let Nf::Unit(k) = s {
                out[k] = f.add(out[k], c);
            }
        }
        let id = self.rows.len();
        self.rows.push(out);
        self.memo.insert(m, id);
        Some(Nf::Row(id))
    }
}

/// Berlekamp–Massey: the monic generator (low to high) of `seq`, degree = the
/// linear complexity. Values are reduced and below 2^32. The discrepancy
/// `Σ_{i=1}^{l} c_i s_{n−i}` is one vectorised dot product against `seq`
/// reversed.
fn berlekamp_massey(f: &Fp, seq: &[u64], muls: &mut u64) -> Vec<u64> {
    let len = seq.len();
    // rev[len − 1 − k] = s_k, so s_{n−i} for i = 1..l is rev[len − n .. len − n + l]
    let rev: Vec<u32> = seq.iter().rev().map(|&x| x as u32).collect();
    let mut c: Vec<u32> = vec![1];
    let mut b: Vec<u32> = vec![1];
    let mut l = 0usize;
    let mut m = 1usize;
    // the inverse of the last nonzero discrepancy, kept with `b`
    let mut bd_inv = 1u64;
    for n in 0..len {
        let top = l.min(c.len() - 1);
        let d = if top == 0 {
            seq[n]
        } else {
            let start = len - n;
            f.add(seq[n], f.dot(&c[1..=top], &rev[start..start + top]))
        };
        *muls += top as u64;
        if d == 0 {
            m += 1;
            continue;
        }
        let coef = f.mul(d, bd_inv);
        let t = if 2 * l <= n { Some(c.clone()) } else { None };
        if c.len() < b.len() + m {
            c.resize(b.len() + m, 0);
        }
        for (i, &bi) in b.iter().enumerate() {
            c[i + m] = f.sub(c[i + m] as u64, f.mul(coef, bi as u64)) as u32;
        }
        *muls += b.len() as u64 + 1;
        if let Some(t) = t {
            l = n + 1 - l;
            b = t;
            bd_inv = f.inv(d);
            m = 1;
        } else {
            m += 1;
        }
    }
    c.resize(l + 1, 0);
    c.reverse();
    c.into_iter().map(|x| x as u64).collect()
}

// ── Allocation-free Karatsuba and Barrett for the powering ───────────────

/// Below this length the product is schoolbook. `ZERO_DIM_LA_KARA` overrides
/// it (tuning only).
fn kara_threshold() -> usize {
    static T: std::sync::OnceLock<usize> = std::sync::OnceLock::new();
    *T.get_or_init(|| {
        std::env::var("ZERO_DIM_LA_KARA")
            .ok()
            .and_then(|v| v.parse().ok())
            .unwrap_or(256)
            .clamp(4, 512)
    })
}

thread_local! {
    /// Products the polynomial kernels below execute, one per nonzero
    /// coefficient times the row it scales (`school_into`, `square_into`,
    /// `mul_low`, and through them `kmul`); the powering charges its
    /// difference, so `FastStats` counts what ran, not a formula.
    static KMULS: std::cell::Cell<u64> = const { std::cell::Cell::new(0) };
}

fn kcount(k: usize) {
    KMULS.with(|c| c.set(c.get() + k as u64));
}

fn kmuls() -> u64 {
    KMULS.with(|c| c.get())
}

/// `out[..la + lb − 1] = a · b` by schoolbook, lazily (one reduction per output).
fn school_into(fp: &Fp, a: &[u32], b: &[u32], out: &mut [u32], lo: &mut [u64], hi: &mut [u64]) {
    let len = a.len() + b.len() - 1;
    let (lo, hi) = (&mut lo[..len], &mut hi[..len]);
    lo.fill(0);
    hi.fill(0);
    let (s, l) = if a.len() <= b.len() { (a, b) } else { (b, a) };
    for (i, &c) in s.iter().enumerate() {
        if c != 0 {
            fp.axpy(&mut lo[i..i + l.len()], &mut hi[i..i + l.len()], c, l);
            kcount(l.len());
        }
    }
    for i in 0..len {
        out[i] = fp.red_lohi(lo[i], hi[i]) as u32;
    }
}

/// `out[..lim] = (a · b) mod x^lim`, schoolbook below the threshold.
fn mul_low(fp: &Fp, a: &[u32], b: &[u32], lim: usize, out: &mut [u32], ks: &mut KScratch) {
    let n = a.len();
    if n > kara_threshold() || b.len() != n {
        let mut full = vec![0u32; a.len() + b.len() - 1];
        if b.len() == n {
            kmul(fp, a, b, &mut full, &mut ks.w, &mut ks.lo, &mut ks.hi);
        } else {
            school_into(fp, a, b, &mut full, &mut ks.lo, &mut ks.hi);
        }
        out[..lim].copy_from_slice(&full[..lim]);
        return;
    }
    let (lo, hi) = (&mut ks.lo[..lim], &mut ks.hi[..lim]);
    lo.fill(0);
    hi.fill(0);
    for (i, &c) in a.iter().enumerate().take(lim) {
        if c != 0 {
            let len = b.len().min(lim - i);
            fp.axpy(&mut lo[i..i + len], &mut hi[i..i + len], c, &b[..len]);
            kcount(len);
        }
    }
    for i in 0..lim {
        out[i] = fp.red_lohi(lo[i], hi[i]) as u32;
    }
}

/// `out[..2n − 1] = a²`, schoolbook with the symmetric half below the
/// threshold.
fn square_into(fp: &Fp, a: &[u32], out: &mut [u32], ks: &mut KScratch) {
    let n = a.len();
    if n > kara_threshold() {
        kmul(fp, a, a, out, &mut ks.w, &mut ks.lo, &mut ks.hi);
        return;
    }
    let len = 2 * n - 1;
    let (lo, hi) = (&mut ks.lo[..len], &mut ks.hi[..len]);
    lo.fill(0);
    hi.fill(0);
    // off-diagonal Σ_{i<j} a_i a_j x^{i+j}, doubled below
    for i in 0..n.saturating_sub(1) {
        let c = a[i];
        if c != 0 {
            let row = &a[i + 1..];
            fp.axpy(
                &mut lo[2 * i + 1..2 * i + 1 + row.len()],
                &mut hi[2 * i + 1..2 * i + 1 + row.len()],
                c,
                row,
            );
            kcount(row.len());
        }
    }
    for i in 0..len {
        // a lane is below 2^32·n, so doubling it stays far from 2^64
        let (mut l, mut h) = (2 * lo[i], 2 * hi[i]);
        if i % 2 == 0 {
            kcount(1);
            let pr = a[i / 2] as u64 * a[i / 2] as u64;
            l += pr & LO;
            h += pr >> 32;
        }
        out[i] = fp.red_lohi(l, h) as u32;
    }
}

/// Scratch for [`kmul`]: about `6n` words and two `2n` lane buffers.
struct KScratch {
    w: Vec<u32>,
    lo: Vec<u64>,
    hi: Vec<u64>,
}

impl KScratch {
    fn new(n: usize) -> Self {
        KScratch {
            w: vec![0; 8 * n + 64],
            lo: vec![0; 2 * n + 2],
            hi: vec![0; 2 * n + 2],
        }
    }
}

/// `out[..2n − 1] = a · b` for `a, b` of the same length `n`.
fn kmul(
    fp: &Fp,
    a: &[u32],
    b: &[u32],
    out: &mut [u32],
    w: &mut [u32],
    lo: &mut [u64],
    hi: &mut [u64],
) {
    let n = a.len();
    debug_assert_eq!(b.len(), n);
    if n == 0 {
        return;
    }
    if n <= kara_threshold() {
        school_into(fp, a, b, out, lo, hi);
        return;
    }
    let h = n / 2;
    let m = n - h;
    let (a0, a1) = a.split_at(h);
    let (b0, b1) = b.split_at(h);
    // z0 = a0·b0 at out[0..2h−1], z2 = a1·b1 at out[2h..2n−1], out[2h−1] = 0
    {
        let (o0, o2) = out.split_at_mut(2 * h);
        if h > 0 {
            kmul(fp, a0, b0, &mut o0[..2 * h - 1], w, lo, hi);
            o0[2 * h - 1] = 0;
        }
        kmul(fp, a1, b1, &mut o2[..2 * m - 1], w, lo, hi);
    }
    // z1 = (a0 + a1)(b0 + b1) in scratch, the low halves padded to m
    let (sa, rest) = w.split_at_mut(m);
    let (sb, rest) = rest.split_at_mut(m);
    let (z1, rest) = rest.split_at_mut(2 * m - 1);
    for i in 0..m {
        let x0 = if i < h { a0[i] as u64 } else { 0 };
        let y0 = if i < h { b0[i] as u64 } else { 0 };
        sa[i] = fp.add(x0, a1[i] as u64) as u32;
        sb[i] = fp.add(y0, b1[i] as u64) as u32;
    }
    kmul(fp, sa, sb, z1, rest, lo, hi);
    // z1 − z0 − z2 first (it reads `out`), then out[h + i] += it
    for i in 0..2 * m - 1 {
        let z0 = if i < 2 * h - 1 { out[i] as u64 } else { 0 };
        let z2 = out[2 * h + i] as u64;
        z1[i] = fp.sub(fp.sub(z1[i] as u64, z0), z2) as u32;
    }
    for i in 0..2 * m - 1 {
        out[h + i] = fp.add(out[h + i] as u64, z1[i] as u64) as u32;
    }
}

/// Squaring and Barrett reduction modulo a monic `f` (degree `d ≥ 3`), with
/// every buffer preallocated: the powering allocates nothing per step.
struct Powering {
    d: usize,
    /// `f` padded to `d + 1`, `finv = rev(f)^{-1} mod x^{d−1}` padded to `d − 1`.
    f: Vec<u32>,
    finv: Vec<u32>,
    prod: Vec<u32>,
    ra: Vec<u32>,
    qr: Vec<u32>,
    q: Vec<u32>,
    qf: Vec<u32>,
    ks: KScratch,
}

impl Powering {
    fn new(mf: &ModF) -> Self {
        let d = mf.d;
        let mut finv = mf.finv.clone();
        finv.resize(d - 1, 0);
        Powering {
            d,
            f: mf.f.clone(),
            finv,
            prod: vec![0; 2 * d + 1],
            ra: vec![0; d - 1],
            qr: vec![0; 2 * d],
            q: vec![0; d + 1],
            qf: vec![0; 2 * d + 2],
            ks: KScratch::new(d + 1),
        }
    }
    /// `acc ← acc² mod f` in place (`acc` has length `d`).
    fn square(&mut self, fp: &Fp, acc: &mut [u32], muls: &mut u64) {
        let d = self.d;
        let k = d - 1;
        let before = kmuls();
        square_into(fp, acc, &mut self.prod[..2 * d - 1], &mut self.ks);
        // rev(q) = rev(prod)_{<k} · finv mod x^k
        for i in 0..k {
            self.ra[i] = self.prod[2 * d - 2 - i];
        }
        mul_low(fp, &self.ra, &self.finv, k, &mut self.qr, &mut self.ks);
        // q (degree ≤ d − 2) padded to d + 1, times f; keep the low d
        for i in 0..k {
            self.q[i] = self.qr[k - 1 - i];
        }
        self.q[k] = 0;
        self.q[k + 1] = 0;
        mul_low(fp, &self.q, &self.f, d, &mut self.qf, &mut self.ks);
        for i in 0..d {
            acc[i] = fp.sub(self.prod[i] as u64, self.qf[i] as u64) as u32;
        }
        *muls += kmuls() - before;
    }
    /// `acc ← x · acc mod f`.
    fn times_x(&self, fp: &Fp, acc: &mut [u32], muls: &mut u64) {
        let d = self.d;
        let top = acc[d - 1] as u64;
        for i in (1..d).rev() {
            acc[i] = acc[i - 1];
        }
        acc[0] = 0;
        if top != 0 {
            for i in 0..d {
                acc[i] = fp.sub(acc[i] as u64, fp.mul(top, self.f[i] as u64)) as u32;
            }
            *muls += d as u64;
        }
    }
}

/// `x^p mod f` by left-to-right binary powering (square, then times `x`).
fn x_pow_p(fp: &Fp, mf: &ModF, muls: &mut u64) -> Vec<u32> {
    let mut pw = Powering::new(mf);
    let mut acc = vec![0u32; mf.d];
    acc[0] = 1;
    let e = fp.p;
    for bit in (0..64 - e.leading_zeros()).rev() {
        pw.square(fp, &mut acc, muls);
        if (e >> bit) & 1 == 1 {
            pw.times_x(fp, &mut acc, muls);
        }
    }
    acc
}

/// The distinct roots of the monic `f` (degree `≥ 1`) in `F_p`.
fn roots_in_fp(fp: &Fp, f: &[u64], rng: &mut StdRng, muls: &mut u64) -> Vec<u64> {
    let d = f.len() - 1;
    let ring = PolyRing::new(fp.p);
    if d <= 2 {
        let r = ring.roots(&UPoly(f.to_vec()), rng);
        *muls += ring.muls.get();
        return r;
    }
    let mf = ModF::new(fp, f, muls);
    let mut xp: Vec<u64> = x_pow_p(fp, &mf, muls).iter().map(|&c| c as u64).collect();
    // x^p − x
    xp[1] = fp.sub(xp[1], 1);
    while xp.last() == Some(&0) {
        xp.pop();
    }
    let g = poly_gcd(fp, f, &xp, muls);
    if g.len() <= 1 {
        return Vec::new();
    }
    // g has small degree (the number of roots): split it with the ring
    let r = ring.roots(&UPoly(g), rng);
    *muls += ring.muls.get();
    r
}

/// Monic gcd of two polynomials (low to high, trimmed).
fn poly_gcd(fp: &Fp, a: &[u64], b: &[u64], muls: &mut u64) -> Vec<u64> {
    let mut a = a.to_vec();
    let mut b = b.to_vec();
    while !b.is_empty() {
        // a mod b
        let lb = fp.inv(*b.last().unwrap());
        while a.len() >= b.len() && !a.is_empty() {
            let q = fp.mul(*a.last().unwrap(), lb);
            let s = a.len() - b.len();
            for (i, &bc) in b.iter().enumerate() {
                a[s + i] = fp.sub(a[s + i], fp.mul(q, bc));
            }
            *muls += b.len() as u64 + 1;
            while a.last() == Some(&0) {
                a.pop();
            }
        }
        std::mem::swap(&mut a, &mut b);
    }
    if let Some(&l) = a.last() {
        let li = fp.inv(l);
        for c in a.iter_mut() {
            *c = fp.mul(*c, li);
        }
    }
    a
}

/// The fast linear stage. `None` when it gives up (see the module notes);
/// the caller then runs a stage that needs no separating `x_n`.
pub fn fast_stage(
    basis: &[Poly],
    input: &[Poly],
    n: usize,
    p: u64,
    rng: &mut StdRng,
    st: &mut FastStats,
) -> Option<Vec<Vec<u64>>> {
    let t0 = Instant::now();
    let out = fast_inner(basis, input, n, p, rng, st);
    st.total_ms = t0.elapsed().as_secs_f64() * 1e3;
    out
}

fn fast_inner(
    basis: &[Poly],
    input: &[Poly],
    n: usize,
    p: u64,
    rng: &mut StdRng,
    st: &mut FastStats,
) -> Option<Vec<Vec<u64>>> {
    if !(2..=8).contains(&n) || !(3..(1u64 << 32)).contains(&p) {
        st.gave_up = Some("shape");
        return None;
    }
    let fp = Fp::new(p);
    let mut lrng = StdRng::seed_from_u64(rng.gen());
    let t = Instant::now();
    let lms: Vec<Vec<u32>> = basis.iter().map(|g| g[0].0.clone()).collect();
    if lms.iter().any(|l| l.iter().any(|&e| e >= 120)) {
        st.gave_up = Some("exponent");
        return None;
    }
    let Some(std_mons) = staircase(&lms, n, 1 << 16) else {
        st.gave_up = Some("not zero-dimensional");
        return None;
    };
    let delta = std_mons.len();
    st.delta = delta;
    if delta == 0 {
        return Some(Vec::new());
    }
    let pack = |e: &[u32]| -> u64 {
        e.iter()
            .enumerate()
            .fold(0u64, |a, (k, &x)| a | ((x as u64) << (8 * k)))
    };
    let mask: u64 = if n >= 8 {
        u64::MAX
    } else {
        (1u64 << (8 * n)) - 1
    };
    let index: FxMap<u64, usize> = std_mons
        .iter()
        .enumerate()
        .map(|(i, m)| (pack(m), i))
        .collect();
    let mut tab = NfTable {
        f: fp,
        delta,
        mask,
        guard: GUARD & mask,
        index: &index,
        bas: basis
            .iter()
            .map(|g| {
                let lc_inv = fp.inv(g[0].1);
                (
                    pack(&g[0].0),
                    g[1..]
                        .iter()
                        .map(|(e, c)| (pack(e), fp.mul(*c, lc_inv)))
                        .collect(),
                )
            })
            .collect(),
        memo: FxMap::default(),
        rows: Vec::new(),
        muls: 0,
    };
    // the columns of M = M_{x_n}: a shift target, or a sparse normal form
    let xn = n - 1;
    let unit = 1u64 << (8 * xn);
    // shift columns as (position, source); dense columns as rows of `dmat`
    let mut shifts: Vec<(u32, u32)> = Vec::with_capacity(delta);
    let mut dense_pos: Vec<usize> = Vec::new();
    let mut dmat: Vec<u32> = Vec::new();
    // columns at most a quarter full stay sparse: (position, [(row, coef)])
    let mut sparse_cols: Vec<(usize, Vec<(u32, u32)>)> = Vec::new();
    for (j, b) in std_mons.iter().enumerate() {
        match tab.nf(pack(b) + unit) {
            None => {
                st.gave_up = Some("not a Gröbner basis");
                return None;
            }
            Some(Nf::Unit(k)) => shifts.push((j as u32, k as u32)),
            Some(Nf::Row(r)) => {
                let row = &tab.rows[r];
                let nz = row.iter().filter(|&&c| c != 0).count();
                st.dense_cols += 1;
                st.nnz += nz;
                if 4 * nz > delta {
                    dense_pos.push(j);
                    dmat.extend(row.iter().map(|&c| c as u32));
                } else {
                    sparse_cols.push((
                        j,
                        row.iter()
                            .enumerate()
                            .filter(|(_, &c)| c != 0)
                            .map(|(k, &c)| (k as u32, c as u32))
                            .collect(),
                    ));
                }
            }
        }
    }
    // the functionals read: NF(1) and NF(x_i), i < n − 1, as sparse vectors
    let mut reads: Vec<Vec<(usize, u64)>> = Vec::with_capacity(n);
    for i in 0..=xn {
        let m = if i == xn { 0 } else { 1u64 << (8 * i) };
        let v = match tab.nf(m) {
            None => {
                st.gave_up = Some("not a Gröbner basis");
                return None;
            }
            Some(Nf::Unit(k)) => vec![(k, 1u64)],
            Some(Nf::Row(r)) => tab.rows[r]
                .iter()
                .enumerate()
                .filter(|(_, &c)| c != 0)
                .map(|(k, &c)| (k, c))
                .collect(),
        };
        reads.push(v);
    }
    // reads[xn] is NF(1); reads[i] is NF(x_i) for i < xn
    st.nf_rows = tab.rows.len();
    st.nf_muls = tab.muls;
    drop(tab);
    st.nf_ms = t.elapsed().as_secs_f64() * 1e3;

    let mut seqs: Vec<Vec<u64>> = Vec::new();
    let mut fpoly: Vec<u64> = Vec::new();
    for _try in 0..4 {
        st.functionals_tried += 1;
        let t = Instant::now();
        let mut w: Vec<u32> = (0..delta).map(|_| lrng.gen_range(0..p) as u32).collect();
        let mut y = vec![0u32; delta];
        let pool = krylov_pool();
        let mut dvals = vec![0u32; dense_pos.len()];
        seqs = vec![Vec::with_capacity(2 * delta); n];
        for j in 0..2 * delta {
            for (s, v) in seqs.iter_mut().zip(reads.iter()) {
                let x = if v.len() == 1 && v[0].1 == 1 {
                    w[v[0].0] as u64
                } else {
                    let mut acc = 0u128;
                    for &(k, c) in v {
                        acc += c as u128 * w[k] as u128;
                    }
                    st.krylov_muls += v.len() as u64;
                    fp.red(acc)
                };
                s.push(x);
            }
            if j + 1 == 2 * delta {
                break;
            }
            // y = M^T w: entry j is column j of M against w
            for &(pos, k) in &shifts {
                y[pos as usize] = w[k as usize];
            }
            match pool {
                Some(pool) if dense_pos.len() * delta >= 1 << 15 => {
                    use rayon::prelude::*;
                    let wr = &w;
                    pool.install(|| {
                        dvals
                            .par_iter_mut()
                            .enumerate()
                            .with_min_len(4)
                            .for_each(|(c, v)| {
                                *v = fp.dot(&dmat[c * delta..(c + 1) * delta], wr) as u32;
                            })
                    });
                    for (&pos, &v) in dense_pos.iter().zip(&dvals) {
                        y[pos] = v;
                    }
                }
                _ => {
                    let nd = dense_pos.len();
                    let row = |c: usize| &dmat[c * delta..(c + 1) * delta];
                    let mut c = 0;
                    while c + 4 <= nd {
                        let v = fp.dot4([row(c), row(c + 1), row(c + 2), row(c + 3)], &w);
                        for k in 0..4 {
                            y[dense_pos[c + k]] = v[k] as u32;
                        }
                        c += 4;
                    }
                    while c < nd {
                        y[dense_pos[c]] = fp.dot(row(c), &w) as u32;
                        c += 1;
                    }
                }
            }
            for (pos, nz) in &sparse_cols {
                let (mut lo, mut hi) = (0u64, 0u64);
                for &(k, c) in nz {
                    let pr = c as u64 * w[k as usize] as u64;
                    lo += pr & LO;
                    hi += pr >> 32;
                }
                y[*pos] = fp.red_lohi(lo, hi) as u32;
            }
            st.krylov_muls += (dense_pos.len() * delta
                + sparse_cols.iter().map(|c| c.1.len()).sum::<usize>())
                as u64;
            std::mem::swap(&mut w, &mut y);
        }
        st.krylov_ms += t.elapsed().as_secs_f64() * 1e3;
        let t = Instant::now();
        fpoly = berlekamp_massey(&fp, &seqs[xn], &mut st.bm_muls);
        st.bm_ms += t.elapsed().as_secs_f64() * 1e3;
        if fpoly.len() == delta + 1 {
            break;
        }
    }
    if fpoly.len() != delta + 1 {
        st.gave_up = Some("minimal polynomial short of delta");
        return None;
    }
    let t = Instant::now();
    let roots = roots_in_fp(&fp, &fpoly, &mut lrng, &mut st.roots_muls);
    st.roots = roots.len();
    st.roots_ms = t.elapsed().as_secs_f64() * 1e3;
    let t = Instant::now();
    let mut sols: Vec<Vec<u64>> = Vec::with_capacity(roots.len());
    let mut q = vec![0u64; delta];
    for xi in roots {
        // Q_{δ−1} = 1, Q_j = f_{j+1} + ξ Q_{j+1}
        q[delta - 1] = 1;
        for j in (0..delta - 1).rev() {
            q[j] = fp.add(fpoly[j + 1], fp.mul(xi, q[j + 1]));
        }
        st.readout_muls += delta as u64;
        let psi = |a: &[u64]| -> u64 {
            let mut res = 0u64;
            for (ach, qch) in a[..delta].chunks(fp.chunk).zip(q.chunks(fp.chunk)) {
                let mut acc = 0u128;
                for (&x, &y) in ach.iter().zip(qch) {
                    acc += x as u128 * y as u128;
                }
                res = fp.add(res, fp.red(acc));
            }
            res
        };
        let den = psi(&seqs[xn]);
        if den == 0 {
            st.gave_up = Some("multiple point");
            return None;
        }
        let di = fp.inv(den);
        let mut sol = vec![0u64; n];
        for i in 0..xn {
            sol[i] = fp.mul(psi(&seqs[i]), di);
        }
        sol[xn] = xi;
        st.readout_muls += (n * delta) as u64;
        if !input.iter().all(|f| f4_fp::eval(f, &sol, p) == 0) {
            st.gave_up = Some("candidate fails the input");
            return None;
        }
        sols.push(sol);
    }
    st.readout_ms = t.elapsed().as_secs_f64() * 1e3;
    sols.sort();
    sols.dedup();
    Some(sols)
}

