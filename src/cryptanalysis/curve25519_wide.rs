//! **The real Curve25519 group over `F_p`, `p = 2^255 − 19`.**
//!
//! The one-word engine stops at `p < 2^62`; the Curve25519-family miniatures
//! (`curve25519_family_instance`) keep Curve25519's structure at 20–32 bits
//! so the existing pipeline can measure them.  This module is the next layer
//! up: the actual 255-bit curve as an affine group over the generic
//! [`Fp256`] backend, with every operation charged to [`GroupOps`].
//!
//! What is here:
//!
//! - [`Curve25519Wide`] — the Montgomery curve `y² = x³ + A x² + x` with
//!   `A = 486662`, in short Weierstrass form (`a = (3 − A²)/3`,
//!   `b = (2A³ − 9A)/27`), so the affine formulas are the framework's own.
//! - Group law, scalar multiplication by a [`BigUint`] (the subgroup order
//!   is 252 bits), point keys, and the standard order checks.
//! - [`smoke`] — a bounded, counted factor-base/probe scan at 255 bits.  It
//!   is a *measurement of the arithmetic and the scan*, not a relation
//!   collection: with a base of `N` points and `T` probes the expected hits
//!   are `T·N/r`, so a toy scan reports zero and that is the honest result.
//!
//! What is **not** here yet: the index-calculus pipeline itself.  Its
//! [`InstanceCtx`](crate::cryptanalysis::ic_framework::stages::InstanceCtx)
//! carries `r`, `cofactor` and `group_order` as `u64`, and
//! [`CountedGroup::mul`](crate::cryptanalysis::ic_boundary::CountedGroup::mul)
//! takes a `u64` scalar; both must widen to a 256-bit scalar before
//! `run_pipeline` can run on this curve.  This module makes the group side of
//! that extension real and testable in the meantime.

use std::collections::{BTreeMap, HashMap};

use num_bigint::BigUint;
use num_traits::{One, ToPrimitive, Zero};
use serde_json::{json, Value};

use crate::cryptanalysis::fp_backend::{Fp256, PrimeField};
use crate::cryptanalysis::ic_boundary::GroupOps;

/// `p = 2^255 − 19`.
pub const P25519: &str =
    "57896044618658097711785492504343953926634992332820282019728792003956564819949";
/// `ℓ = 2^252 + 27742317777372353535851937790883648493`, the prime order of
/// the subgroup generated by `u = 9`.
pub const L25519: &str =
    "7237005577332262213973186563042994240857116359379907606001950938285454250989";
/// The Montgomery coefficient `A = 486662`.
pub const A25519: u64 = 486_662;
/// The base point's `u` coordinate (`u = 9`).
pub const U25519: u64 = 9;
/// `#E / ℓ = 8`.
pub const COFACTOR25519: u64 = 8;

/// A point in affine short Weierstrass coordinates, or the identity.
pub type WidePoint = Option<(Fp256Elem, Fp256Elem)>;

/// The element type of [`Fp256`].
pub type Fp256Elem = <Fp256 as PrimeField>::Elem;

/// Curve25519 over `F_p`, in short Weierstrass form.
#[derive(Clone, Debug)]
pub struct Curve25519Wide {
    pub field: Fp256,
    /// Short Weierstrass `a = (3 − A²)/3`.
    pub a: Fp256Elem,
    /// Short Weierstrass `b = (2A³ − 9A)/27`.
    pub b: Fp256Elem,
    /// `ℓ`, the prime subgroup order.
    pub r: BigUint,
    /// `#E / ℓ`.
    pub cofactor: u64,
    /// The generator (`u = 9`, even-`y` root).
    pub generator: WidePoint,
}

impl Curve25519Wide {
    /// Build the curve and its generator.  The generator check (`[ℓ]G = O`)
    /// is left to [`Curve25519Wide::order_checks`] so construction cannot
    /// silently hide a wrong constant.
    pub fn new() -> Self {
        let field = Fp256::new(&P25519.parse().expect("a decimal prime"));
        let a_mont = field.from_u64(A25519);
        let three = field.from_u64(3);
        let a = field.mul(
            field.sub(three, field.sqr(a_mont)),
            field.inv(three).expect("3 is invertible"),
        );
        let a3 = field.mul(field.sqr(a_mont), a_mont);
        let b = field.mul(
            field.sub(field.double(a3), field.mul(field.from_u64(9), a_mont)),
            field.inv(field.from_u64(27)).expect("27 is invertible"),
        );
        let u = field.from_u64(U25519);
        let rhs = field.mul(
            u,
            field.add(field.add(field.sqr(u), field.mul(a_mont, u)), field.one()),
        );
        let y = field.sqrt(rhs).expect("u = 9 is on the curve");
        // Deterministic sign: the smaller of y and −y.
        let y = if field.to_biguint(y) < field.to_biguint(field.neg(y)) {
            y
        } else {
            field.neg(y)
        };
        let x = field.add(u, field.mul(a_mont, field.inv(three).expect("3")));
        Self {
            field,
            a,
            b,
            r: L25519.parse().expect("a decimal order"),
            cofactor: COFACTOR25519,
            generator: Some((x, y)),
        }
    }

    pub fn identity(&self) -> WidePoint {
        None
    }

    pub fn is_identity(&self, p: &WidePoint) -> bool {
        p.is_none()
    }

    pub fn rhs(&self, x: Fp256Elem) -> Fp256Elem {
        let f = &self.field;
        f.add(f.add(f.mul(f.sqr(x), x), f.mul(self.a, x)), self.b)
    }

    pub fn on_curve(&self, p: WidePoint) -> bool {
        match p {
            None => true,
            Some((x, y)) => self.field.sqr(y) == self.rhs(x),
        }
    }

    pub fn neg(&self, p: WidePoint) -> WidePoint {
        p.map(|(x, y)| (x, self.field.neg(y)))
    }

    /// Affine addition, charging the same field tallies the one-word
    /// [`PrimeCurve`](crate::cryptanalysis::ic_boundary::PrimeCurve) charges:
    /// one inversion, two multiplications and one squaring for distinct
    /// points; one inversion, five multiplications and two squarings for a
    /// doubling.
    pub fn add(&self, ops: &mut GroupOps, p: WidePoint, q: WidePoint) -> WidePoint {
        let f = &self.field;
        match (p, q) {
            (None, t) | (t, None) => t,
            (Some((x1, y1)), Some((x2, y2))) => {
                if x1 == x2 {
                    if f.is_zero(f.add(y1, y2)) {
                        return None;
                    }
                    return self.double(ops, Some((x1, y1)));
                }
                ops.adds += 1;
                ops.field_ops.muls += 2;
                ops.field_ops.sqrs += 1;
                ops.field_ops.invs += 1;
                let lam = f.mul(
                    f.sub(y2, y1),
                    f.inv(f.sub(x2, x1)).expect("distinct abscissae"),
                );
                let x3 = f.sub(f.sub(f.sqr(lam), x1), x2);
                let y3 = f.sub(f.mul(lam, f.sub(x1, x3)), y1);
                Some((x3, y3))
            }
        }
    }

    pub fn double(&self, ops: &mut GroupOps, p: WidePoint) -> WidePoint {
        let f = &self.field;
        let Some((x, y)) = p else { return None };
        if f.is_zero(y) {
            return None;
        }
        ops.doubles += 1;
        ops.field_ops.muls += 5;
        ops.field_ops.sqrs += 2;
        ops.field_ops.invs += 1;
        let lam = f.mul(
            f.add(f.mul(f.from_u64(3), f.sqr(x)), self.a),
            f.inv(f.double(y)).expect("y ≠ 0"),
        );
        let x3 = f.sub(f.sqr(lam), f.double(x));
        let y3 = f.sub(f.mul(lam, f.sub(x, x3)), y);
        Some((x3, y3))
    }

    /// `[k]P` for a wide scalar.
    pub fn mul_biguint(&self, ops: &mut GroupOps, p: WidePoint, k: &BigUint) -> WidePoint {
        ops.scalar_mults += 1;
        if k.is_zero() || p.is_none() {
            return None;
        }
        let bits = k.bits();
        let mut acc = p;
        for i in (0..bits - 1).rev() {
            acc = self.double(ops, acc);
            if k.bit(i) {
                acc = self.add(ops, acc, p);
            }
        }
        acc
    }

    pub fn mul_u64(&self, ops: &mut GroupOps, p: WidePoint, k: u64) -> WidePoint {
        self.mul_biguint(ops, p, &BigUint::from(k))
    }

    /// A 64-bit fingerprint of a point; equal points hash equally.
    pub fn key(&self, p: &WidePoint) -> u64 {
        let Some((x, y)) = *p else { return 0 };
        let mut h = 0xcbf2_9ce4_8422_2325u64;
        for limb in self
            .field
            .to_biguint(x)
            .to_u64_digits()
            .into_iter()
            .chain(self.field.to_biguint(y).to_u64_digits())
        {
            h ^= limb;
            h = h.wrapping_mul(0x100_0000_01b3);
            h ^= h >> 29;
        }
        h | 1
    }

    /// The three constants a wrong curve or generator would fail:
    /// `G` on the curve, `[ℓ]G = O`, and `[ℓ+1]G = G`.
    pub fn order_checks(&self, ops: &mut GroupOps) -> Value {
        let g = self.generator;
        let r = &self.r;
        let r_plus_one = r + BigUint::one();
        let at_r = self.mul_biguint(ops, g, r);
        let at_r_plus_one = self.mul_biguint(ops, g, &r_plus_one);
        json!({
            "generator_on_curve": self.on_curve(g),
            "r_bits": r.bits(),
            "r_plus_one_equals_generator": at_r_plus_one == g,
            "r_times_generator_is_identity": at_r.is_none(),
        })
    }
}

impl Default for Curve25519Wide {
    fn default() -> Self {
        Self::new()
    }
}

/// The widened instance context: the fields `ic_framework::InstanceCtx`
/// carries as `u64`, here as `BigUint` where the subgroup order needs it.
///
/// A future wide pipeline reads this instead of `InstanceCtx`; it exists now
/// so the three scalar paths (`r`, `cofactor`, `group_order`) have a typed
/// 255-bit home, alongside [`Curve25519Wide::mul_biguint`] and
/// [`WideGauss`] for the relation matrix.
#[derive(Clone, Debug)]
pub struct WideInstanceCtx<'a> {
    pub group: &'a Curve25519Wide,
    pub generator: WidePoint,
    pub target: WidePoint,
    pub r: BigUint,
    pub cofactor: u64,
    pub group_order: BigUint,
    pub name: String,
}

impl<'a> WideInstanceCtx<'a> {
    pub fn curve25519(group: &'a Curve25519Wide) -> Self {
        let cofactor = BigUint::from(group.cofactor);
        Self {
            group,
            generator: group.generator,
            target: group.generator,
            r: group.r.clone(),
            cofactor: group.cofactor,
            group_order: &group.r * cofactor,
            name: "curve25519".into(),
        }
    }

    /// `⌈log₂ r⌉`, the integer the projection/objective columns report.
    pub fn log2_r(&self) -> f64 {
        self.r.to_f64().expect("r fits f64").log2()
    }
}

/// Relation-matrix elimination modulo `ℓ`, the 252-bit subgroup order.
///
/// `ic_framework::linalg` works modulo a `u64`; this is the same
/// incremental-Gauss shape over [`Fp256`] instantiated at `ℓ`, so a relation
/// row whose coefficients are 252-bit field elements can be eliminated.
/// It is a standalone, tested component until a wide `run_pipeline` uses it.
#[derive(Clone, Debug)]
pub struct WideGauss {
    field: Fp256,
    cols: usize,
    /// Pivot column → (row, right-hand side), in increasing pivot order.
    rows: BTreeMap<usize, (Vec<Fp256Elem>, Fp256Elem)>,
    inconsistent: bool,
}

impl WideGauss {
    pub fn new(cols: usize) -> Self {
        Self {
            field: Fp256::new(&L25519.parse().expect("a decimal prime")),
            cols,
            rows: BTreeMap::new(),
            inconsistent: false,
        }
    }

    pub fn rank(&self) -> usize {
        self.rows.len()
    }

    pub fn inconsistent(&self) -> bool {
        self.inconsistent
    }

    /// Add one row `a·x = b` (mod `ℓ`); returns whether the rank grew.
    pub fn add_row(&mut self, coeffs: &[BigUint], rhs: &BigUint) -> bool {
        let f = &self.field;
        let mut row: Vec<Fp256Elem> = (0..self.cols)
            .map(|i| {
                coeffs
                    .get(i)
                    .map_or_else(|| f.zero(), |c| f.from_biguint(c))
            })
            .collect();
        let mut b = f.from_biguint(rhs);
        for (&col, (prow, pb)) in &self.rows {
            if f.is_zero(row[col]) {
                continue;
            }
            let factor = row[col];
            for j in col..self.cols {
                row[j] = f.sub(row[j], f.mul(factor, prow[j]));
            }
            b = f.sub(b, f.mul(factor, *pb));
        }
        let Some(pivot) = (0..self.cols).find(|&j| !f.is_zero(row[j])) else {
            if !f.is_zero(b) {
                self.inconsistent = true;
            }
            return false;
        };
        let inv = f.inv(row[pivot]).expect("pivot is nonzero");
        for x in row.iter_mut().skip(pivot) {
            *x = f.mul(*x, inv);
        }
        b = f.mul(b, inv);
        self.rows.insert(pivot, (row, b));
        true
    }

    /// The unique solution when the rank is full; `None` otherwise.
    pub fn solve(&self) -> Option<Vec<BigUint>> {
        if self.inconsistent || self.rows.len() < self.cols {
            return None;
        }
        let f = &self.field;
        let mut x = vec![f.zero(); self.cols];
        // Back substitution from the highest pivot; rows are echelon.
        for (&col, (row, b)) in self.rows.iter().rev() {
            let mut acc = *b;
            for j in col + 1..self.cols {
                acc = f.sub(acc, f.mul(row[j], x[j]));
            }
            x[col] = f.mul(acc, f.inv(row[col]).expect("normalized pivot"));
        }
        Some(x.into_iter().map(|v| f.to_biguint(v)).collect())
    }
}

/// One `ic bench`-shaped row for a bounded scan on the real 255-bit curve.
///
/// This is what lets the ordinary sweeper (`ic bench` / `ic sweep`) run a
/// configuration at `--bits 255 --family curve25519`: the relation phase
/// executes and charges its work, and the row is marked `exhausted` because
/// no relation can be found at `T·N/ℓ ≈ 0`.  The scorer treats that as a
/// failed measurement, which is the honest classification.
pub fn scan_row(base: usize, max_trials: u64, seed: u64) -> Value {
    let curve = Curve25519Wide::new();
    let mut checks = GroupOps::default();
    let order_checks = curve.order_checks(&mut checks);
    let mut ops = GroupOps::default();
    let started = std::time::Instant::now();

    let g = curve.generator;
    let mut base_index: HashMap<Fp256Elem, usize> = HashMap::new();
    let mut p = g;
    for i in 1..=base.max(1) {
        if let Some((x, _)) = p {
            base_index.entry(x).or_insert(i);
        }
        p = curve.add(&mut ops, p, g);
    }
    let planted = (seed.wrapping_mul(0x9E37_79B9) | 1) % 1_000_000 + 1;
    let q = curve.mul_u64(&mut ops, g, planted);

    let mut hits = 0u64;
    let mut r = q;
    let mut tried = 0u64;
    while tried < max_trials {
        if let Some((x, _)) = r {
            if base_index.contains_key(&x) {
                hits += 1;
                break;
            }
        }
        r = curve.add(&mut ops, r, g);
        tried += 1;
    }
    let wall_seconds = started.elapsed().as_secs_f64();
    let gae = (ops.adds + ops.doubles) as f64;
    let r_f64 = curve.r.to_f64().expect("r fits f64");
    let log2_r = r_f64.log2();
    let n = base.max(1);
    json!({
        "instance": "curve25519-wide",
        "log2_r": log2_r,
        "r": r_f64,
        "group_order": r_f64 * curve.cofactor as f64,
        "label": "curve25519-255",
        "factor_base": {"columns": n, "signed_points": n},
        "decomposition": {
            "targets_tried": tried.max(1),
            "hit_rate": hits as f64 / tried.max(1) as f64,
            "solver": Value::Null,
        },
        "linear_algebra": {},
        "verify": {
            "group_ops": {
                "adds": ops.adds,
                "doubles": ops.doubles,
                "scalar_mults": ops.scalar_mults,
            },
            "native": {},
            "wall_ns": (wall_seconds * 1e9) as u64,
        },
        "order_checks": order_checks,
        "planted_log": planted,
        "hits": hits,
        "recovered": Value::Null,
        "verified": false,
        "total_gae": gae,
        "s": gae / 2f64.powf(log2_r / 2.0),
        "exhausted": true,
        "wall_seconds": wall_seconds,
    })
}

/// A bounded, counted scan on the real 255-bit curve.
///
/// Builds `F = {[1]G, …, [N]G}`, plants `Q = [k]G` for a fixed `k`, and
/// probes `R_t = Q + [t]G` for `t = 1..T`, looking up `x(R_t)` in `F`.  The
/// expected number of hits is `T·N/ℓ`; at any feasible `T` and `N` it is
/// effectively zero, and the report says so rather than implying a
/// relation was found.  Every group and field operation is counted.
pub fn smoke(base: usize, trials: u64, seed: u64) -> Value {
    let curve = Curve25519Wide::new();
    let mut ops = GroupOps::default();
    let mut checks = GroupOps::default();
    let order_checks = curve.order_checks(&mut checks);

    let g = curve.generator;
    let start = std::time::Instant::now();

    // Factor base: repeated addition.
    let mut base_index: HashMap<Fp256Elem, usize> = HashMap::new();
    let mut p = g;
    for i in 1..=base.max(1) {
        if let Some((x, _)) = p {
            base_index.entry(x).or_insert(i);
        }
        p = curve.add(&mut ops, p, g);
    }

    // A planted target the arithmetic can check exactly.
    let planted = (seed.wrapping_mul(0x9E37_79B9) | 1) % 1_000_000 + 1;
    let q = curve.mul_u64(&mut ops, g, planted);

    // Probe stream: R_0 = Q, R_t = R_{t-1} + G.
    let mut hits = 0u64;
    let mut r = q;
    for _ in 0..trials {
        if let Some((x, _)) = r {
            if base_index.contains_key(&x) {
                hits += 1;
            }
        }
        r = curve.add(&mut ops, r, g);
    }
    let elapsed = start.elapsed().as_secs_f64();

    let gae = (ops.adds + ops.doubles) as f64;
    // `bits()` rounds up to 253; the cost unit uses log2 ℓ itself.
    let log2_r = curve.r.to_f64().expect("r fits f64").log2();
    json!({
        "schema": "curve25519-wide/v1",
        "p": P25519,
        "p_bits": curve.field.bits(),
        "r": L25519,
        "log2_r": log2_r,
        "cofactor": curve.cofactor,
        "planted_log": planted,
        "order_checks": order_checks,
        "factor_base": base.max(1),
        "trials": trials,
        "hits": hits,
        "expected_hits": (trials as f64) * (base.max(1) as f64) / 2f64.powf(log2_r),
        "ops": {
            "adds": ops.adds,
            "doubles": ops.doubles,
            "scalar_mults": ops.scalar_mults,
            "field_muls": ops.field_ops.muls,
            "field_sqrs": ops.field_ops.sqrs,
            "field_invs": ops.field_ops.invs,
        },
        "counted_gae": gae,
        "wall_seconds": elapsed,
        "note": "Bounded arithmetic and probe scan only. A real relation collection has T·N/ℓ hits, which is zero at any feasible N and T; no index-calculus result is claimed."
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generator_is_on_the_curve_and_has_prime_order() {
        let curve = Curve25519Wide::new();
        assert!(curve.on_curve(curve.generator));
        assert_eq!(curve.r.bits(), 253);
        let mut ops = GroupOps::default();
        assert!(
            curve
                .mul_biguint(&mut ops, curve.generator, &curve.r)
                .is_none(),
            "[r]G must be the identity"
        );
        let rp1 = &curve.r + BigUint::one();
        assert_eq!(
            curve.mul_biguint(&mut ops, curve.generator, &rp1),
            curve.generator,
            "[r+1]G must be G"
        );
    }

    #[test]
    fn group_law_is_associative_on_small_multiples() {
        let curve = Curve25519Wide::new();
        let mut ops = GroupOps::default();
        let g = curve.generator;
        let two = curve.double(&mut ops, g);
        let three = curve.add(&mut ops, two, g);
        let five = curve.add(&mut ops, three, two);
        assert_eq!(five, curve.mul_u64(&mut ops, g, 5));
        assert_eq!(curve.add(&mut ops, three, curve.neg(three)), None);
        for p in [g, two, three, five] {
            assert!(curve.on_curve(p));
        }
    }

    #[test]
    fn cofactor_clears_to_the_prime_subgroup() {
        let curve = Curve25519Wide::new();
        let mut ops = GroupOps::default();
        let g8 = curve.mul_u64(&mut ops, curve.generator, curve.cofactor);
        assert!(curve.mul_biguint(&mut ops, g8, &curve.r).is_none());
    }

    #[test]
    fn wide_matrix_solves_a_full_rank_system_mod_ell() {
        let n = 8usize;
        let f = Fp256::new(&L25519.parse().unwrap());
        let x: Vec<BigUint> = (0..n)
            .map(|i| BigUint::from(1_234_567u64 + 98_765 * i as u64))
            .collect();
        let mut g = WideGauss::new(n);
        for r in 0..n {
            // Vandermonde rows: powers of the distinct bases 1, 2, …, n.
            let base = f.from_u64((r + 1) as u64);
            let coeffs: Vec<BigUint> = (0..n)
                .map(|c| f.to_biguint(f.pow_u64(base, (c + 1) as u64)))
                .collect();
            let mut rhs = f.zero();
            for c in 0..n {
                rhs = f.add(
                    rhs,
                    f.mul(f.from_biguint(&coeffs[c]), f.from_biguint(&x[c])),
                );
            }
            assert!(g.add_row(&coeffs, &f.to_biguint(rhs)));
        }
        assert_eq!(g.rank(), n);
        assert_eq!(g.solve().expect("full rank"), x);
    }

    #[test]
    fn wide_matrix_reports_an_inconsistent_row() {
        let mut g = WideGauss::new(2);
        assert!(g.add_row(
            &[BigUint::from(1u32), BigUint::from(0u32)],
            &BigUint::from(1u32)
        ));
        assert!(!g.add_row(
            &[BigUint::from(1u32), BigUint::from(0u32)],
            &BigUint::from(2u32)
        ));
        assert!(g.inconsistent());
        assert_eq!(g.solve(), None);
    }

    #[test]
    fn wide_context_carries_the_252_bit_order() {
        let curve = Curve25519Wide::new();
        let ctx = WideInstanceCtx::curve25519(&curve);
        assert_eq!(ctx.r, curve.r);
        assert_eq!(ctx.group_order, &curve.r * BigUint::from(8u32));
        assert_eq!(ctx.cofactor, 8);
        assert!((ctx.log2_r() - 252.0).abs() < 0.01);
    }

    #[test]
    fn smoke_reports_zero_hits_and_counts_work() {
        let report = smoke(64, 1_000, 20261104);
        assert_eq!(report["hits"], 0);
        assert_eq!(
            report["order_checks"]["r_times_generator_is_identity"],
            true
        );
        assert!(report["counted_gae"].as_f64().unwrap() > 1_000.0);
    }
}
