//! Fixed decision rule (PROTOCOL.md section 8) applied to the TSV rows of one run directory.
//! Writes summary.md, summary.tsv and fig_overlap_vs_m.svg. No judgement is left to the analyst.

use crate::rng::{hash_str, Rng};
use std::collections::BTreeMap;
use std::fmt::Write as _;

struct Table {
    cols: Vec<String>,
    rows: Vec<Vec<String>>,
}

impl Table {
    fn read(path: &str) -> Result<Table, String> {
        let txt = std::fs::read_to_string(path).map_err(|e| format!("{path}: {e}"))?;
        let mut lines = txt.lines();
        let cols: Vec<String> = lines.next().ok_or("empty file")?.split('\t').map(|s| s.to_string()).collect();
        let rows = lines.filter(|l| !l.is_empty()).map(|l| l.split('\t').map(|s| s.to_string()).collect()).collect();
        Ok(Table { cols, rows })
    }
    fn idx(&self, c: &str) -> usize {
        self.cols.iter().position(|x| x == c).unwrap_or_else(|| panic!("missing column {c}"))
    }
    fn s(&self, r: usize, c: &str) -> &str {
        &self.rows[r][self.idx(c)]
    }
    fn f(&self, r: usize, c: &str) -> f64 {
        self.s(r, c).parse::<f64>().unwrap_or(f64::NAN)
    }
}

fn files(dir: &str, prefix: &str) -> Vec<String> {
    let mut v: Vec<String> = std::fs::read_dir(dir)
        .map(|rd| {
            rd.filter_map(|e| e.ok())
                .map(|e| e.file_name().to_string_lossy().to_string())
                .filter(|n| n.starts_with(prefix) && n.ends_with(".tsv"))
                .collect()
        })
        .unwrap_or_default();
    v.sort();
    v.into_iter().map(|n| format!("{dir}/{n}")).collect()
}

fn pct(v: &mut Vec<f64>, q: f64) -> f64 {
    v.retain(|x| x.is_finite());
    if v.is_empty() {
        return f64::NAN;
    }
    v.sort_by(|a, b| a.partial_cmp(b).unwrap());
    v[((v.len() - 1) as f64 * q).round() as usize]
}

/// Percentile bootstrap (2000 resamples over bases) of a ratio of sums num/den (indices into the arrays).
fn boot_ratio(num: &[f64], den: &[f64], seed: u64) -> (f64, f64, f64) {
    let n = num.len();
    let point = num.iter().sum::<f64>() / den.iter().sum::<f64>();
    if n < 2 {
        return (point, f64::NAN, f64::NAN);
    }
    let mut rng = Rng::new(seed);
    let mut vals = Vec::with_capacity(2000);
    for _ in 0..2000 {
        let (mut a, mut b) = (0.0, 0.0);
        for _ in 0..n {
            let i = rng.below(n as u64) as usize;
            a += num[i];
            b += den[i];
        }
        vals.push(a / b);
    }
    (point, pct(&mut vals.clone(), 0.025), pct(&mut vals, 0.975))
}

fn boot_mean(x: &[f64], seed: u64) -> (f64, f64, f64) {
    let x: Vec<f64> = x.iter().cloned().filter(|v| v.is_finite()).collect();
    let n = x.len();
    if n == 0 {
        return (f64::NAN, f64::NAN, f64::NAN);
    }
    let point = x.iter().sum::<f64>() / n as f64;
    if n < 2 {
        return (point, f64::NAN, f64::NAN);
    }
    let mut rng = Rng::new(seed);
    let mut vals = Vec::with_capacity(2000);
    for _ in 0..2000 {
        let mut a = 0.0;
        for _ in 0..n {
            a += x[rng.below(n as u64) as usize];
        }
        vals.push(a / n as f64);
    }
    (point, pct(&mut vals.clone(), 0.025), pct(&mut vals, 0.975))
}

fn fmt3(t: (f64, f64, f64)) -> String {
    format!("{:.3} [{:.3}, {:.3}]", t.0, t.1, t.2)
}

pub fn classify(lo: f64, hi: f64, delta: f64) -> &'static str {
    if !lo.is_finite() || !hi.is_finite() {
        return "UNRESOLVED";
    }
    if lo > 1.0 + delta {
        "E-EXTRA"
    } else if hi < 1.0 / (1.0 + delta) {
        "E-DEFICIT"
    } else if lo >= 1.0 / (1.0 + delta) && hi <= 1.0 + delta {
        "E-OVERLAP"
    } else {
        "UNRESOLVED"
    }
}

/// Least-squares slope of y on x with a bootstrap-free standard formula (used inside the outer bootstrap).
fn slope(x: &[f64], y: &[f64]) -> f64 {
    let n = x.len() as f64;
    let mx = x.iter().sum::<f64>() / n;
    let my = y.iter().sum::<f64>() / n;
    let sxy: f64 = x.iter().zip(y).map(|(a, b)| (a - mx) * (b - my)).sum();
    let sxx: f64 = x.iter().map(|a| (a - mx) * (a - mx)).sum();
    sxy / sxx
}

struct OvRow {
    a: u32,
    n: u32,
    m: usize,
    l: u32,
    arm: String,
    half: String,
    nx: f64,
    nsol: f64,
    nu: f64,
    uf: f64,
    un: f64,
    up: f64,
    cf: f64,
    cn: f64,
    ceq: f64,
    hb: f64,
    cpb: f64,
    cnb: f64,
    lbb: f64,
    clos: f64,
    closp: f64,
    status: String,
    jn: f64,
}

pub fn analyze(dir: &str) -> Result<(), String> {
    let mut md = String::new();
    let mut tsv = String::from("kind\tcell\tarm\tstat\tvalue\tlo\thi\tclass\n");
    writeln!(md, "# G5 summary (generated by `g5census analyze`; decision rule frozen in PROTOCOL.md section 8)\n").unwrap();
    writeln!(md, "Run directory: `{dir}`\n").unwrap();
    let mut voids: Vec<String> = vec![];

    // ---------------- Proposition T ----------------
    let pfiles = files(dir, "propt_");
    if !pfiles.is_empty() {
        writeln!(md, "## A. Proposition T, instance by instance\n").unwrap();
        writeln!(md, "| n | m | arm | trials | assigns | trials failing identity | Boolean-recombination fails | singular M_j | planted (bad) | conj. solution fails / n | domain fails | neg. disagree | verdict |").unwrap();
        writeln!(md, "|---|---|---|---|---|---|---|---|---|---|---|---|---|").unwrap();
        let mut agg: BTreeMap<(u32, usize, String), Vec<f64>> = BTreeMap::new();
        for p in &pfiles {
            let t = Table::read(p)?;
            for r in 0..t.rows.len() {
                let key = (t.f(r, "n") as u32, t.f(r, "m") as usize, t.s(r, "arm").to_string());
                let e = agg.entry(key).or_insert_with(|| vec![0.0; 16]);
                let cols = [
                    "trials", "assigns", "trials_eq_fail", "trials_bool_fail", "rec_singular", "planted", "plant_bad",
                    "conj_member_n", "conj_member_fail", "dom_n", "dom_fail", "neg_n", "neg_disagree", "stable_n",
                    "stable_cob_fail", "assigns_eq_fail",
                ];
                for (i, c) in cols.iter().enumerate() {
                    e[i] += t.f(r, c);
                }
            }
        }
        for ((n, m, arm), e) in agg.iter() {
            let (trials, assigns, eqf, bf, sing, planted, pbad, cmn, cmf, domn, domf, _negn, negd, _sn, scf) =
                (e[0], e[1], e[2], e[3], e[4], e[5], e[6], e[7], e[8], e[9], e[10], e[11], e[12], e[13], e[14]);
            let verdict = match arm.as_str() {
                "koblitz" | "stable" => {
                    if eqf == 0.0 && bf == 0.0 && sing == 0.0 && pbad == 0.0 && cmf == 0.0 && domf == 0.0 && negd == 0.0 && scf == 0.0 && planted > 0.0 {
                        format!("HOLDS (violation rate < {:.1e}, rule of three)", 3.0 / trials)
                    } else {
                        voids.push(format!("propt n={n} m={m} {arm}: violation (instrument first)"));
                        "VIOLATION: PROP_T_FALSIFIED_OR_INSTRUMENT_FAIL".to_string()
                    }
                }
                _ => {
                    let det = eqf / trials;
                    let ok = det >= 0.99 && (arm != "ordinary" || cmn == 0.0 || cmf / cmn >= 0.95) && (arm != "wrongdir" || domn == 0.0 || domf / domn >= 0.9);
                    if !ok {
                        voids.push(format!("propt n={n} m={m} {arm}: control did not detect"));
                    }
                    format!("{} (detection {:.4})", if ok { "CONTROL DETECTS" } else { "CONTROL_FAIL" }, det)
                }
            };
            writeln!(
                md,
                "| {n} | {m} | {arm} | {trials} | {assigns} | {eqf} | {bf} | {sing} | {planted} ({pbad}) | {cmf}/{cmn} | {domf} | {negd} | {verdict} |"
            )
            .unwrap();
            writeln!(tsv, "propt\tn{n}_m{m}\t{arm}\ttrials_eq_fail\t{eqf}\t\t\t{verdict}").unwrap();
        }
        writeln!(md).unwrap();
    }

    // ---------------- overlap census ----------------
    let ofiles = files(dir, "overlap_");
    let mut rows: Vec<OvRow> = vec![];
    for p in &ofiles {
        let t = Table::read(p)?;
        for r in 0..t.rows.len() {
            let st = t.s(r, "status").to_string();
            let g = |c: &str| if st == "OK" { t.f(r, c) } else { f64::NAN };
            rows.push(OvRow {
                a: t.f(r, "a") as u32,
                n: t.f(r, "n") as u32,
                m: t.f(r, "m") as usize,
                l: t.f(r, "l") as u32,
                arm: t.s(r, "arm").to_string(),
                half: t.s(r, "half").to_string(),
                nx: t.f(r, "nx"),
                nsol: g("nsol"),
                nu: g("nu"),
                uf: g("u_frob"),
                un: g("u_null"),
                up: g("u_pred"),
                cf: g("corr_frob"),
                cn: g("corr_null"),
                ceq: g("count_equal_frob"),
                hb: g("halving_bad"),
                cpb: g("chain_pos_bad"),
                cnb: g("chain_neg_bad"),
                lbb: g("lb_bad"),
                clos: g("clos_closed"),
                closp: g("clos_pairs"),
                status: st,
                jn: ((t.f(r, "n") - 1.0) / 2.0).floor(),
            });
        }
    }
    let mut cells: BTreeMap<(u32, u32, usize, u32), Vec<usize>> = BTreeMap::new();
    for (i, r) in rows.iter().enumerate() {
        cells.entry((r.a, r.n, r.m, r.l)).or_default().push(i);
    }
    if !rows.is_empty() {
        writeln!(md, "## B. Same-instance overlap census (Lemma A2-prime), decision table\n").unwrap();
        writeln!(md, "U = shared (tuple, conjugate-pair) triples; model = independence prediction from the measured K(S) sizes; null = same bases, random multipliers. D = U_frob / U_null (paired, same enumeration). delta = max(0.05, half-width of the A/A ratio of D between the main and aa halves).\n").unwrap();
        writeln!(md, "| cell (a,n,m,l) | arm | bases | mean nx | mean nu | U_frob/model [95%] | U_null/model [95%] | D = frob/null [95%] | delta | class | gates |").unwrap();
        writeln!(md, "|---|---|---|---|---|---|---|---|---|---|---|").unwrap();
        for (cell, idxs) in cells.iter() {
            let mut arms: BTreeMap<String, Vec<usize>> = BTreeMap::new();
            for &i in idxs {
                arms.entry(rows[i].arm.clone()).or_default().push(i);
            }
            for (arm, ai) in arms.iter() {
                let ok: Vec<usize> = ai.iter().cloned().filter(|&i| rows[i].status == "OK").collect();
                let skipped = ai.len() - ok.len();
                if ok.is_empty() {
                    writeln!(md, "| {:?} | {arm} | 0 ({skipped} skipped) | | | | | | | NOT_MEASURED | |", cell).unwrap();
                    continue;
                }
                let main: Vec<usize> = ok.iter().cloned().filter(|&i| rows[i].half == "main").collect();
                let aa: Vec<usize> = ok.iter().cloned().filter(|&i| rows[i].half == "aa").collect();
                let seed = hash_str(&format!("{:?}{arm}", cell));
                let v = |idx: &[usize], f: &dyn Fn(&OvRow) -> f64| -> Vec<f64> { idx.iter().map(|&i| f(&rows[i])).collect() };
                let uf = v(&main, &|r| r.uf);
                let un = v(&main, &|r| r.un);
                let up = v(&main, &|r| r.up);
                let rf = boot_ratio(&uf, &up, seed);
                let rn = boot_ratio(&un, &up, seed ^ 1);
                let d = boot_ratio(&uf, &un, seed ^ 2);
                let mut delta = 0.05;
                if aa.len() >= 2 && main.len() >= 2 {
                    // A/A: ratio of D between the halves via bootstrap of each half
                    let da = boot_ratio(&v(&aa, &|r| r.uf), &v(&aa, &|r| r.un), seed ^ 3);
                    let mut rs: Vec<f64> = vec![];
                    let mut rng = Rng::new(seed ^ 4);
                    let (m_n, a_n) = (main.len(), aa.len());
                    let (mu, mn_, au, an_) = (&uf, &un, v(&aa, &|r| r.uf), v(&aa, &|r| r.un));
                    for _ in 0..1000 {
                        let (mut s1, mut s2, mut s3, mut s4) = (0.0, 0.0, 0.0, 0.0);
                        for _ in 0..m_n {
                            let i = rng.below(m_n as u64) as usize;
                            s1 += mu[i];
                            s2 += mn_[i];
                        }
                        for _ in 0..a_n {
                            let i = rng.below(a_n as u64) as usize;
                            s3 += au[i];
                            s4 += an_[i];
                        }
                        rs.push((s1 / s2) / (s3 / s4));
                    }
                    let (lo, hi) = (pct(&mut rs.clone(), 0.025), pct(&mut rs, 0.975));
                    if lo.is_finite() && hi.is_finite() {
                        delta = f64::max(0.05, (hi - lo) / 2.0);
                    }
                    let _ = da;
                }
                let gates_bad: f64 = ok.iter().map(|&i| rows[i].hb + rows[i].cpb + rows[i].cnb + rows[i].lbb).sum();
                let mut gate = if gates_bad == 0.0 { "pass".to_string() } else { "INSTRUMENT_FAIL".to_string() };
                if gates_bad != 0.0 {
                    voids.push(format!("overlap cell {:?} arm {arm}: gate failures {gates_bad}", cell));
                }
                // stable positive control
                if arm == "stable" {
                    let all_eq = ok.iter().all(|&i| (rows[i].ceq - 1.0).abs() < 1e-12);
                    if !all_eq {
                        voids.push(format!("overlap cell {:?} stable base not exactly equivariant", cell));
                        gate = "CONTROL_FAIL(stable equivariance)".into();
                    } else {
                        gate.push_str("; stable |Sol| equivariance = 1.000 exactly");
                    }
                }
                let cal = rn.1 <= 1.0 && 1.0 <= rn.2;
                gate.push_str(if cal { "; null calibrates the model" } else { "; NULL_MISCALIBRATED (model column not used)" });
                let censored = skipped as f64 / ai.len() as f64 > 0.05;
                let class = if gates_bad != 0.0 {
                    "VOID"
                } else if censored {
                    "CENSORED"
                } else {
                    classify(d.1, d.2, delta)
                };
                let mnx = main.iter().map(|&i| rows[i].nx).sum::<f64>() / main.len() as f64;
                let mnu = main.iter().map(|&i| rows[i].nu).sum::<f64>() / main.len() as f64;
                writeln!(
                    md,
                    "| {:?} | {arm} | {} (skipped {skipped}) | {:.1} | {:.2} | {} | {} | {} | {:.3} | {class} | {gate} |",
                    cell,
                    main.len(),
                    mnx,
                    mnu,
                    fmt3(rf),
                    fmt3(rn),
                    fmt3(d),
                    delta
                )
                .unwrap();
                writeln!(tsv, "overlap\t{:?}\t{arm}\tD\t{:.5}\t{:.5}\t{:.5}\t{class}", cell, d.0, d.1, d.2).unwrap();
                writeln!(tsv, "overlap\t{:?}\t{arm}\tU_frob_over_model\t{:.5}\t{:.5}\t{:.5}\t", cell, rf.0, rf.1, rf.2).unwrap();
                writeln!(tsv, "overlap\t{:?}\t{arm}\tU_null_over_model\t{:.5}\t{:.5}\t{:.5}\t", cell, rn.0, rn.1, rn.2).unwrap();
            }
        }
        writeln!(md).unwrap();

        // indicator correlation
        writeln!(md, "### B2. Indicator autocorrelation along the orbit (mean over lags), Frobenius minus null\n").unwrap();
        writeln!(md, "| cell | arm | mean corr_frob - corr_null [95%] | mean corr_frob |").unwrap();
        writeln!(md, "|---|---|---|---|").unwrap();
        for (cell, idxs) in cells.iter() {
            let mut arms: BTreeMap<String, Vec<f64>> = BTreeMap::new();
            let mut armf: BTreeMap<String, Vec<f64>> = BTreeMap::new();
            for &i in idxs {
                let r = &rows[i];
                if r.status == "OK" && r.half == "main" {
                    arms.entry(r.arm.clone()).or_default().push(r.cf - r.cn);
                    armf.entry(r.arm.clone()).or_default().push(r.cf);
                }
            }
            for (arm, x) in arms.iter() {
                let b = boot_mean(x, hash_str(&format!("{:?}{arm}corr", cell)));
                let mf = armf[arm].iter().filter(|v| v.is_finite()).sum::<f64>() / armf[arm].iter().filter(|v| v.is_finite()).count().max(1) as f64;
                writeln!(md, "| {:?} | {arm} | {} | {:.4} |", cell, fmt3(b), mf).unwrap();
            }
        }
        writeln!(md).unwrap();

        // m trend on the yield-matched arm
        writeln!(md, "### B3. Per-solution, per-lag overlap rate vs m (arm `tuned`, nu matched near 4), log2 slope\n").unwrap();
        writeln!(md, "Model: rate_pred = U_pred / (nsol * J). Observed: U_frob / (nsol * J). Prediction of the ledger: about +1 in log2 per unit m (2^m - 2 signed sub-sums, probability 1/r each) until 2^m approaches r.\n").unwrap();
        writeln!(md, "| curve (a,n) | m | rate_obs | rate_null | rate_pred | obs/pred |").unwrap();
        writeln!(md, "|---|---|---|---|---|---|").unwrap();
        let mut curves: BTreeMap<(u32, u32), BTreeMap<usize, (f64, f64, f64, f64)>> = BTreeMap::new();
        for (cell, idxs) in cells.iter() {
            let tn: Vec<&OvRow> = idxs.iter().map(|&i| &rows[i]).filter(|r| r.arm == "tuned" && r.status == "OK" && r.half == "main").collect();
            if tn.is_empty() {
                continue;
            }
            let den: f64 = tn.iter().map(|r| r.nsol * r.jn).sum();
            let (o, nl, pr) = (
                tn.iter().map(|r| r.uf).sum::<f64>() / den,
                tn.iter().map(|r| r.un).sum::<f64>() / den,
                tn.iter().map(|r| r.up).sum::<f64>() / den,
            );
            // keep the first l per (curve, m) (tuned does not depend on l)
            curves.entry((cell.0, cell.1)).or_default().entry(cell.2).or_insert((o, nl, pr, den));
        }
        let mut svg_series: Vec<(String, Vec<(f64, f64)>, Vec<(f64, f64)>)> = vec![];
        for (cv, ms) in curves.iter() {
            let mut obs = vec![];
            let mut prd = vec![];
            for (m, (o, nl, pr, _)) in ms.iter() {
                writeln!(md, "| {:?} | {m} | {:.3e} | {:.3e} | {:.3e} | {:.3} |", cv, o, nl, pr, o / pr).unwrap();
                if *o > 0.0 {
                    obs.push((*m as f64, o.log2()));
                }
                prd.push((*m as f64, pr.log2()));
            }
            if obs.len() >= 3 {
                let (x, y): (Vec<f64>, Vec<f64>) = (obs.iter().map(|p| p.0).collect(), obs.iter().map(|p| p.1).collect());
                let (xp, yp): (Vec<f64>, Vec<f64>) = (prd.iter().map(|p| p.0).collect(), prd.iter().map(|p| p.1).collect());
                writeln!(md, "| {:?} | slope(log2 rate_obs on m) = {:.3}; slope(log2 rate_pred on m) = {:.3} | | | | |", cv, slope(&x, &y), slope(&xp, &yp)).unwrap();
                writeln!(tsv, "overlap\t{:?}\ttuned\tslope_obs\t{:.4}\t\t\t", cv, slope(&x, &y)).unwrap();
                writeln!(tsv, "overlap\t{:?}\ttuned\tslope_pred\t{:.4}\t\t\t", cv, slope(&xp, &yp)).unwrap();
            }
            svg_series.push((format!("a={} n={}", cv.0, cv.1), obs, prd));
        }
        writeln!(md).unwrap();
        let _ = std::fs::write(format!("{dir}/fig_overlap_vs_m.svg"), svg(&svg_series));

        // stratified by number of distinct sigma-orbits among the legs
        writeln!(md, "### B5. Overlap by number of distinct sigma-orbits among the legs (pooled over bases, main half)\n").unwrap();
        writeln!(md, "Prediction (derived in PROTOCOL.md section 3, unverified): a tuple whose legs all lie in ONE orbit has small-height sums in Z[tau]; a coincidence there needs an exact identity in Z[tau], which a valuation argument forbids, so D < 1 in stratum 1 whenever heights stay below sqrt(r). Strata 2 and 3 follow the independence model (D = 1).\n").unwrap();
        writeln!(md, "| cell | arm | stratum | subsets | solution pairs | U_frob | U_null | D = frob/null [95%] |").unwrap();
        writeln!(md, "|---|---|---|---|---|---|---|---|").unwrap();
        for p in &ofiles {
            let t = Table::read(p)?;
            let mut by: BTreeMap<(String, String), Vec<usize>> = BTreeMap::new();
            for r in 0..t.rows.len() {
                if t.s(r, "status") == "OK" && t.s(r, "half") == "main" {
                    by.entry((format!("a{}_n{}_m{}_l{}", t.s(r, "a"), t.s(r, "n"), t.s(r, "m"), t.s(r, "l")), t.s(r, "arm").to_string())).or_default().push(r);
                }
            }
            for ((cell, arm), ri) in by.iter() {
                for sx in 1..=3 {
                    let g = |c: &str| -> Vec<f64> { ri.iter().map(|&r| t.f(r, &format!("s{sx}_{c}"))).collect() };
                    let (ns, nl, uf, un) = (g("nsub"), g("nsol"), g("uf"), g("un"));
                    let tot_n: f64 = ns.iter().sum();
                    if tot_n == 0.0 {
                        continue;
                    }
                    let d = boot_ratio(&uf, &un, hash_str(&format!("{cell}{arm}{sx}")));
                    writeln!(md, "| {cell} | {arm} | {sx} | {} | {} | {} | {} | {} |", tot_n, nl.iter().sum::<f64>(), uf.iter().sum::<f64>(), un.iter().sum::<f64>(), fmt3(d)).unwrap();
                    writeln!(tsv, "overlap\t{cell}\t{arm}\tD_stratum{sx}\t{:.5}\t{:.5}\t{:.5}\t", d.0, d.1, d.2).unwrap();
                }
            }
        }
        writeln!(md).unwrap();

        // Proposition Sigma closure
        let (mut cp, mut cc) = (0.0, 0.0);
        for r in rows.iter().filter(|r| r.status == "OK") {
            if r.closp.is_finite() {
                cp += r.closp;
                cc += r.clos;
            }
        }
        writeln!(md, "### B4. Proposition Sigma (setwise closure of Sol(R,V) under sigma^j)\n").unwrap();
        writeln!(md, "(target, lag) pairs checked: {cp}; closed: {cc}. Predicted exactly 0 (proved for prime n); a nonzero count is an instrument error or a headline.\n").unwrap();
        if cc != 0.0 {
            voids.push(format!("Proposition Sigma closure count {cc} != 0"));
        }
    }

    // ---------------- rank ----------------
    let rfiles = files(dir, "rank_");
    if !rfiles.is_empty() {
        writeln!(md, "## C. Rank of conjugate relations (plain vs orbit basis)\n").unwrap();
        writeln!(md, "| cell | arm | bases | rank_orbit(N) | rank_orbit(nN) == rank_orbit(N) in all bases | non-proportional conjugate rows | rows failing identity | wrong-lambda control grows (frac) | independent-target control grows (frac) | mean rank_plain(nN)/rank_plain(N) |").unwrap();
        writeln!(md, "|---|---|---|---|---|---|---|---|---|---|").unwrap();
        for p in &rfiles {
            let t = Table::read(p)?;
            let mut by: BTreeMap<String, Vec<usize>> = BTreeMap::new();
            for r in 0..t.rows.len() {
                if t.s(r, "n_rel") != "NA" && t.f(r, "n_rel") > 0.0 {
                    by.entry(t.s(r, "arm").to_string()).or_default().push(r);
                }
            }
            for (arm, ri) in by.iter() {
                let eq = ri.iter().all(|&r| t.f(r, "rank_orbit_n") == t.f(r, "rank_orbit_1"));
                let np: f64 = ri.iter().map(|&r| t.f(r, "nonproportional")).sum();
                let rb: f64 = ri.iter().map(|&r| t.f(r, "rows_bad") + t.f(r, "incons")).sum();
                let wg = ri.iter().filter(|&&r| t.f(r, "rank_orbit_wrong") > t.f(r, "rank_orbit_n")).count() as f64 / ri.len() as f64;
                let ig = ri.iter().filter(|&&r| t.f(r, "rank_orbit_indep") > t.f(r, "rank_orbit_1")).count() as f64 / ri.len() as f64;
                let pl: f64 = ri.iter().map(|&r| t.f(r, "rank_plain_n") / t.f(r, "rank_plain_1").max(1.0)).sum::<f64>() / ri.len() as f64;
                let mo: f64 = ri.iter().map(|&r| t.f(r, "rank_orbit_1")).sum::<f64>() / ri.len() as f64;
                let cell = format!("a{}_n{}_m{}_l{}", t.s(ri[0], "a"), t.s(ri[0], "n"), t.s(ri[0], "m"), t.s(ri[0], "l"));
                let informative = wg > 0.0 || ig > 0.0;
                let verdict = if eq && np == 0.0 && rb == 0.0 {
                    if informative {
                        "yes"
                    } else {
                        "yes, NOT_INFORMATIVE (no control grew)"
                    }
                } else {
                    "NO"
                };
                if verdict.starts_with("NO") {
                    voids.push(format!("rank cell {cell} {arm}: orbit-basis equality failed"));
                }
                writeln!(md, "| {cell} | {arm} | {} | {:.1} | {verdict} | {np} | {rb} | {:.2} | {:.2} | {:.2} |", ri.len(), mo, wg, ig, pl).unwrap();
            }
        }
        writeln!(md).unwrap();
    }

    writeln!(md, "## Voids and failures\n").unwrap();
    if voids.is_empty() {
        writeln!(md, "None.\n").unwrap();
    } else {
        for v in &voids {
            writeln!(md, "- {v}").unwrap();
        }
        writeln!(md).unwrap();
    }
    writeln!(md, "## What this does not establish\n").unwrap();
    writeln!(md, "- No solver, no cost per relation, no wall-time comparison, no comparison with Pollard rho, no statement about ECC2K-130 beyond the arithmetic in PROTOCOL.md section 9. Nothing here is an improvement over the index-calculus baseline.").unwrap();
    writeln!(md, "- The overlap census is exact on toy groups (r between 991 and 262543) where 2^m approaches or exceeds r; the ratio-to-model at m close to n is a saturation statement, not an asymptotic one.").unwrap();
    writeln!(md, "- The factor base is the set of x-coordinates of points of the prime-order subgroup G with x in V; legs outside G (cosets of the 2-torsion) and twist legs are excluded in every arm.").unwrap();
    std::fs::write(format!("{dir}/summary.md"), md).map_err(|e| e.to_string())?;
    std::fs::write(format!("{dir}/summary.tsv"), tsv).map_err(|e| e.to_string())?;
    Ok(())
}

fn svg(series: &[(String, Vec<(f64, f64)>, Vec<(f64, f64)>)]) -> String {
    let (w, h, ml, mb, mt, mr) = (720.0, 420.0, 70.0, 50.0, 30.0, 150.0);
    let mut xs: Vec<f64> = vec![];
    let mut ys: Vec<f64> = vec![];
    for (_, o, p) in series {
        for q in o.iter().chain(p.iter()) {
            xs.push(q.0);
            ys.push(q.1);
        }
    }
    if xs.is_empty() {
        return "<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"10\" height=\"10\"/>".into();
    }
    let (x0, x1) = (xs.iter().cloned().fold(f64::MAX, f64::min), xs.iter().cloned().fold(f64::MIN, f64::max));
    let (y0, y1) = (ys.iter().cloned().fold(f64::MAX, f64::min) - 0.5, ys.iter().cloned().fold(f64::MIN, f64::max) + 0.5);
    let px = |x: f64| ml + (x - x0) / (x1 - x0).max(1e-9) * (w - ml - mr);
    let py = |y: f64| h - mb - (y - y0) / (y1 - y0).max(1e-9) * (h - mb - mt);
    let colors = ["#1f77b4", "#d95f02", "#1b9e77", "#7570b3", "#e7298a"];
    let mut s = String::new();
    write!(s, "<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"{w}\" height=\"{h}\" font-family=\"sans-serif\" font-size=\"12\">").unwrap();
    write!(s, "<rect width=\"{w}\" height=\"{h}\" fill=\"#ffffff\"/>").unwrap();
    write!(s, "<text x=\"{ml}\" y=\"18\" font-size=\"14\">log2 of overlap rate per solution per lag vs m (circles observed, dashed model)</text>").unwrap();
    write!(s, "<line x1=\"{ml}\" y1=\"{}\" x2=\"{}\" y2=\"{}\" stroke=\"#333\"/>", h - mb, w - mr, h - mb).unwrap();
    write!(s, "<line x1=\"{ml}\" y1=\"{mt}\" x2=\"{ml}\" y2=\"{}\" stroke=\"#333\"/>", h - mb).unwrap();
    let mut m = x0.ceil();
    while m <= x1 {
        write!(s, "<text x=\"{}\" y=\"{}\" text-anchor=\"middle\">{}</text>", px(m), h - mb + 16.0, m).unwrap();
        m += 1.0;
    }
    write!(s, "<text x=\"{}\" y=\"{}\" text-anchor=\"middle\">m</text>", (ml + w - mr) / 2.0, h - 10.0).unwrap();
    let mut y = y0.ceil();
    while y <= y1 {
        write!(s, "<text x=\"{}\" y=\"{}\" text-anchor=\"end\">{}</text>", ml - 6.0, py(y) + 4.0, y).unwrap();
        write!(s, "<line x1=\"{ml}\" y1=\"{}\" x2=\"{}\" y2=\"{}\" stroke=\"#ddd\"/>", py(y), w - mr, py(y)).unwrap();
        y += 2.0;
    }
    for (i, (name, obs, prd)) in series.iter().enumerate() {
        let c = colors[i % colors.len()];
        let pts: Vec<String> = prd.iter().map(|p| format!("{},{}", px(p.0), py(p.1))).collect();
        write!(s, "<polyline fill=\"none\" stroke=\"{c}\" stroke-dasharray=\"5 4\" points=\"{}\"/>", pts.join(" ")).unwrap();
        for p in obs {
            write!(s, "<circle cx=\"{}\" cy=\"{}\" r=\"4\" fill=\"{c}\"/>", px(p.0), py(p.1)).unwrap();
        }
        write!(s, "<rect x=\"{}\" y=\"{}\" width=\"10\" height=\"10\" fill=\"{c}\"/><text x=\"{}\" y=\"{}\">{}</text>", w - mr + 10.0, mt + 16.0 * i as f64, w - mr + 26.0, mt + 9.0 + 16.0 * i as f64, name).unwrap();
    }
    s.push_str("</svg>");
    s
}
