#!/usr/bin/env python3
"""Render tables.md and summary.json from remeasure.json (old vs new distance).

Usage: python3 render_tables.py [remeasure.json] [tables.md] [summary.json]
Every number is [pcc:unverified]; this script only reads remeasure.json.
"""
import json
import sys

src = sys.argv[1] if len(sys.argv) > 1 else "remeasure.json"
out_md = sys.argv[2] if len(sys.argv) > 2 else "tables.md"
out_js = sys.argv[3] if len(sys.argv) > 3 else "summary.json"
d = json.load(open(src))


def f(x, n=3):
    if x is None:
        return "n/a"
    if abs(x) >= 1000:
        return f"{x:,.0f}"
    if abs(x) >= 100:
        return f"{x:.0f}"
    if abs(x) >= 10:
        return f"{x:.1f}"
    return f"{x:.{n}g}"


def tri(v):
    return " / ".join(f(x) for x in v)


md = []
summ = {"rows": [], "counts": {}}
cls_count = {}
below_any = []

for tname, t in d["targets"].items():
    md.append(f"\n## {tname}\n")
    rows = t["rows"]
    md.append("### matched rho, in process (mean over seeds), group ops and native counters\n")
    md.append("| p | r | neg total | neg walk | canon | part. hash | DP lookup | DP insert | word | native/step | plain total | plain native/step | old plain rho | aut |")
    md.append("|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--|")
    for r in rows:
        n, pl = r["rho"]["negation"], r["rho"]["plain"]
        old = r.get("old_plain_rho_ops", r.get("old_plain_rho_ops_mean"))
        aut = r["rho"]["automorphism_fold"]["automorphism_beyond_negation"] or "none (j=%d)" % r["rho"]["automorphism_fold"]["j_invariant"]
        md.append(f"| {r['p']} | {f(r.get('r', r.get('r_mean')))} | {f(n['total_ops'])} | {f(n['walk_ops'])} | {f(n['canonicalisations'])} | {f(n['partition_hashes'])} | {f(n['dp_lookups'])} | {f(n['dp_inserts'])} | {f(n['word_ops'])} | {f(n['native_per_step'])} | {f(pl['total_ops'])} | {f(pl['native_per_step'])} | {f(old)} | {aut} |")
    md.append("")
    md.append("### calibration (best-of-N, ns per operation; w_cal = class time / group-add time)\n")
    md.append("| p | mul_p | mul_r | inv_r | canon | hash | lookup | insert | draw | word | t_add (ns) |")
    md.append("|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--|")
    for r in rows:
        c = r["class_times_ns"]
        md.append(f"| {r['p']} | " + " | ".join(f(c[k]) for k in ["mul_p", "mul_r", "inv_r", "canon", "hash", "lookup", "insert", "draw", "word"]) + " | " + ", ".join(f"{k} {f(v)}" for k, v in r["t_add_ns"].items()) + " |")
    md.append("")
    arms = []
    for r in rows:
        for a in r["arms"]:
            if a not in arms:
                arms.append(a)
    md.append("### distance to the negation rho (arm total / rho total) at the band 0 / 0.1 / 1, and the calibrated reading 0 / w_cal / 10 w_cal\n")
    md.append("| p | arm | group ops | native (by class) | band ratio vs negation | class | calibrated ratio | class (cal) | ranked at cal. price | vs best of neg/plain (band) | lower bound | old (recorded) ratio / class |")
    md.append("|--:|--|--:|--|--|--|--|--|--|--|--|--|")
    for r in rows:
        for a in arms:
            e = r["arms"].get(a)
            if not e:
                continue
            nat = ", ".join(f"{k} {f(v)}" for k, v in e["native"].items()) or "none emitted"
            rec = e.get("recorded_ratio_to_old_plain_rho") or e.get("recorded_ratio_to_old_plain_rho_la_priced") or e.get("recorded_median_ratio_to_old_plain_rho")
            rc = e.get("recorded_class")
            recs = f"{tri(rec)} / {rc}" if rec else ""
            md.append(f"| {r['p']} | {a} | {f(e['group_ops'])} | {nat} | {tri(e['ratio_neg_band'])} | {e['class_neg_band']} | {tri(e['ratio_neg_cal'])} | {e['class_neg_cal']} | {'yes' if e['ranked_at_calibrated_price'] else 'no'} | {tri(e['ratio_best_band'])} | {'yes' if e['lower_bound'] else 'no'} | {recs} |")
            cls_count[(tname, e["class_neg_band"])] = cls_count.get((tname, e["class_neg_band"]), 0) + 1
            if e["class_neg_band"] == "below":
                below_any.append((tname, r["p"], a))
            summ["rows"].append({"target": tname, "p": r["p"], "arm": a, "ratio_neg_band": e["ratio_neg_band"], "class_neg_band": e["class_neg_band"], "ratio_neg_cal": e["ratio_neg_cal"], "class_neg_cal": e["class_neg_cal"], "recorded_ratio": rec, "recorded_class": rc, "lower_bound": e["lower_bound"]})
    md.append("")

summ["counts"] = {f"{k[0]}:{k[1]}": v for k, v in cls_count.items()}
summ["below_any"] = below_any
open(out_md, "w").write("# Tables (generated by render_tables.py from remeasure.json) [pcc:unverified]\n" + "\n".join(md) + "\n")
json.dump(summ, open(out_js, "w"), indent=1)
print("wrote", out_md, out_js, "arm-rows:", len(summ["rows"]), "below:", below_any)
