// Evaluate the registered L1 tests of PROTOCOL.md section 3 from the recorded sessions.
//   node evaluate.mjs <ecbench binary> <sessions dir> <out dir>
// It computes nothing the harness does not: ratios, intervals and band means come from `ecbench compare` and
// `ecbench band`; this file only picks the strictest incumbent per weight, applies the registered thresholds
// and lays the numbers out.  Output: <out>/results.json and <out>/results.md.
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync, readFileSync } from "node:fs";

const [bin, sess, out] = process.argv.slice(2);
mkdirSync(out, { recursive: true });
const W = [0, 0.1, 1];
import { ROWS } from "../curves.mjs";
const run = (args) => execFileSync(bin, args, { encoding: "utf8", maxBuffer: 1 << 28 });
const json = (args) => JSON.parse(run([...args, "--json"]));
const dirs = (b) => [1, 2, 3].map((r) => `${sess}/B${b}-r${r}`);
const bandOf = (ds) => {
  const f = `${out}/.band.json`;
  run(["band", "--dir", ...ds, "--json", f]);
  const rows = JSON.parse(readFileSync(f, "utf8")).rows;
  return Object.fromEntries(rows.map((r) => [r.arm, r]));
};
const cmp = (ds, a, b, w) => {
  const j = json(["compare", "--dir", ...ds, "--a", a, "--b", b, "--weight", String(w), "--resamples", "4000", "--seed", "20261002"]);
  const o = j.ops ?? j; // one session nests the result under `ops`; pooled sessions print it flat
  const ci = o.ci95, cb = o.ci95_bootstrap;
  return { ratio: o.ratio_b_over_a, ci95: ci, ci95_bootstrap: cb, upper: Math.max(ci?.[1] ?? NaN, cb?.[1] ?? NaN),
    pairs: o.workloads, status: o.status, method: o.ci_method, boot_method: o.ci_bootstrap_method };
};

const results = { schema: "ic_tableb_ksum.evaluation/v1", rows: [] };
for (const row of ROWS) {
  const ds = dirs(row.bits);
  const perSession = ds.map((d) => bandOf([d]));
  const pooledBand = bandOf(ds);
  const incs = Object.keys(pooledBand).filter((n) => n.startsWith("inc-"));
  const meanS = (arm, wi) => pooledBand[arm].mean_s[wi];
  const r = { ...row, incumbents: incs, weights: {} };
  const cheapest = (band, wi) => incs.reduce((x, y) => (band[y].mean_s[wi] < band[x].mean_s[wi] ? y : x));
  W.forEach((w, wi) => {
    const best = cheapest(pooledBand, wi);
    const bestRep = perSession.map((b) => cheapest(b, wi));            // per-replicate strictest incumbent
    const o = { incumbent: best, incumbent_per_replicate: bestRep,
      S: Object.fromEntries(["rho-neg", "bsgs-neg", ...incs, "ksum4", "ksum5"].map((a) => [a, pooledBand[a].mean_s[wi]])) };
    for (const cand of ["ksum5", "ksum4"]) {
      o[cand] = { over_incumbent: cmp(ds, best, cand, w),
        per_replicate: ds.map((d, i) => cmp([d], bestRep[i], cand, w)), over_bsgs: cmp(ds, "bsgs-neg", cand, w),
        gap_to_rho: pooledBand[cand].mean_s[wi] / pooledBand["rho-neg"].mean_s[wi] };
    }
    o.inc_tb_over_incumbent = pooledBand["inc-tb"].mean_s[wi] / pooledBand[best].mean_s[wi];
    r.weights[w] = o;
  });
  // A/A noise floor: same arm, same curve, different seeds, across the three replicate sessions (w = 0 mean S).
  const spread = {};
  for (const a of ["inc-tb", "rho-neg", "ksum5", "ksum4"]) {
    const v = perSession.map((b) => b[a].mean_s[0]);
    spread[a] = Math.max(...v) / Math.min(...v);
  }
  r.replicate_spread = spread;
  r.delta = Math.max(...Object.values(spread));
  for (const cand of ["ksum5", "ksum4"]) {
    const upper = Math.max(...W.map((w) => r.weights[w][cand].over_incumbent.upper));
    const repsUpper = Math.max(...W.flatMap((w) => r.weights[w][cand].per_replicate.map((x) => x.upper)));
    r[cand] = { max_upper_pooled: upper, max_upper_replicate: repsUpper, holds: upper < 1 && repsUpper < 1 && 1 - upper > r.delta - 1 };
  }
  results.rows.push(r);
}
const primary = results.rows.filter((r) => r.role === "primary");
for (const cand of ["ksum5", "ksum4"]) {
  results[`${cand}_l1_holds_on_a_primary_row`] = primary.some((r) => r[cand].holds);
  results[`${cand}_l1_falsified`] = primary.every((r) => W.some((w) => r.weights[w][cand].over_incumbent.upper >= 1));
}
writeFileSync(`${out}/results.json`, JSON.stringify(results, null, 1) + "\n");
const f = (x, d = 3) => (typeof x === "number" ? x.toFixed(d) : String(x));
let md = `# L1 evaluation (generated by evaluate.mjs from the recorded sessions) [pcc:unverified]\n\n`;
for (const cand of ["ksum5", "ksum4"]) {
  md += `## candidate ${cand}\n\n| row | role | w | strictest incumbent (pooled) | S incumbent | S inc-tb | S ${cand} | S rho-neg | ${cand} / incumbent [95%] | max upper (both intervals) | per-replicate ratios (own strictest) | ${cand} / rho-neg | ${cand} / bsgs-neg |\n|:--|:--|--:|:--|--:|--:|--:|--:|:--|--:|:--|--:|--:|\n`;
  for (const r of results.rows) for (const w of W) {
    const x = r.weights[w], c = x[cand], p = c.over_incumbent;
    md += `| ${r.slug} | ${r.role} | ${w} | ${x.incumbent} | ${f(x.S[x.incumbent], 2)} | ${f(x.S["inc-tb"], 2)} | ${f(x.S[cand], 2)} | ${f(x.S["rho-neg"], 3)} | ${f(p.ratio)} [${f(p.ci95?.[0])}, ${f(p.ci95?.[1])}] | ${f(p.upper)} | ${c.per_replicate.map((q) => f(q.ratio)).join(" / ")} | ${f(c.gap_to_rho, 2)} | ${f(c.over_bsgs.ratio, 2)}x |\n`;
  }
  md += `\n| row | role | replicate spread inc-tb / rho-neg / ksum5 / ksum4 (max/min of mean S, w = 0) | delta | max upper pooled | max upper any replicate | L1 holds (${cand}) |\n|:--|:--|:--|--:|--:|--:|:--|\n`;
  for (const r of results.rows)
    md += `| ${r.slug} | ${r.role} | ${["inc-tb", "rho-neg", "ksum5", "ksum4"].map((a) => f(r.replicate_spread[a], 4)).join(" / ")} | ${f(r.delta, 4)} | ${f(r[cand].max_upper_pooled)} | ${f(r[cand].max_upper_replicate)} | ${r[cand].holds} |\n`;
  md += `\nL1 (${cand}) holds on a primary row: **${results[`${cand}_l1_holds_on_a_primary_row`]}**; falsified (all primary rows at or above 1 at some weight): **${results[`${cand}_l1_falsified`]}**.\n\n`;
}
writeFileSync(`${out}/results.md`, md);
console.log(md);
