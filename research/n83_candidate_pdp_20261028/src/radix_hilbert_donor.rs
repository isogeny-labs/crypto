//! Exact original-top Hilbert certificates. See HILBERT_DESIGN.md for proof scope.
use serde_json::{json, Value};
use sha2::{Digest, Sha256};
use std::{fs, path::Path};
const P: u128 = 4835703278761981908090881;
fn sha(b: &[u8]) -> String {
    format!("{:x}", Sha256::digest(b))
}
fn read(p: &Path) -> Value {
    serde_json::from_slice(&fs::read(p).unwrap()).unwrap()
}
fn save(p: &Path, v: &Value) {
    fs::write(p, serde_json::to_string_pretty(v).unwrap() + "\n").unwrap();
}
fn binom(n: usize, k: usize) -> u64 {
    if k > n {
        return 0;
    }
    let mut v = 1u128;
    for j in 0..k.min(n - k) {
        v = v.checked_mul((n - j) as u128).unwrap() / (j + 1) as u128;
    }
    v.try_into().unwrap()
}
fn mulmod(mut a: u128, mut b: u128, p: u128) -> u128 {
    assert!(p > 1 && p < (1u128 << 127));
    a %= p;
    let mut r = 0;
    while b != 0 {
        if b & 1 != 0 {
            r = (r + a) % p;
        }
        a = (a + a) % p;
        b >>= 1;
    }
    r
}
fn powmod(mut a: u128, mut b: u128, p: u128) -> u128 {
    let mut r = 1;
    while b != 0 {
        if b & 1 != 0 {
            r = mulmod(r, a, p);
        }
        a = mulmod(a, a, p);
        b >>= 1;
    }
    r
}
fn small_prime(p: u128) -> bool {
    if p < 2 {
        return false;
    }
    let mut d = 2;
    while d * d <= p {
        if p % d == 0 {
            return false;
        }
        d += 1;
    }
    true
}
fn prime_certificate() -> Value {
    let mut remaining = P - 1;
    let mut factors = vec![];
    let mut product = 1u128;
    for q in [2u128, 5, 677, 13999, 23203] {
        assert!(small_prime(q));
        let mut e = 0;
        while remaining % q == 0 {
            remaining /= q;
            product = product.checked_mul(q).unwrap();
            e += 1;
        }
        assert!(e > 0);
        factors.push((q, e));
    }
    assert_eq!(remaining, 1);
    assert_eq!(product, P - 1);
    let witness = (2..1000)
        .find(|a| {
            powmod(*a, P - 1, P) == 1
                && factors.iter().all(|(q, _)| powmod(*a, (P - 1) / q, P) != 1)
        })
        .unwrap();
    json!({"modulus":P.to_string(),"method":"Lucas full n-1 factorization and element of order n-1; all factor primes proven by trial division","factors":factors.iter().map(|(q,e)|json!({"prime":q.to_string(),"exponent":e,"proper_power_residue":powmod(witness,(P-1)/q,P).to_string()})).collect::<Vec<_>>(),"witness":witness.to_string(),"fermat_residue":powmod(witness,P-1,P).to_string(),"verified":true})
}
fn rank_certificate(n: usize, i: usize, p: u128) -> Value {
    assert!(n <= 27 && i <= n && p >= 2);
    let target = binom(n, i);
    let source = if i >= 2 { binom(n, i - 2) } else { 0 };
    if i < 2 {
        return json!({"degree":i,"source_dimension":source,"target_dimension":target,"rank":0,"diagonals":[]});
    }
    let complemented = i - 2 > n - i;
    let (t, k) = if complemented {
        (n - i, n - i + 2)
    } else {
        (i - 2, i)
    };
    assert!(t <= k && k <= n - t);
    let mut rank = 0u64;
    let mut diagonal = vec![];
    for j in 0..=t {
        let value = 2 * binom(k - j, 2);
        let multiplicity = binom(n, j) - if j > 0 { binom(n, j - 1) } else { 0 };
        let nonzero = (value as u128) % p != 0;
        if nonzero {
            rank += multiplicity;
        }
        diagonal
            .push(json!({"j":j,"entry":value,"multiplicity":multiplicity,"nonzero_mod_p":nonzero}));
    }
    assert!(rank <= source.min(target));
    if p > n as u128 {
        assert_eq!(rank, source.min(target), "Lefschetz cross-check");
    }
    json!({"degree":i,"source_dimension":source,"target_dimension":target,"complement_transpose":complemented,"t":t,"k":k,"rank":rank,"diagonals":diagonal})
}
fn series(n: usize, p: u128) -> Value {
    assert!(n <= 27);
    let ranks: Vec<_> = (0..=n).map(|i| rank_certificate(n, i, p)).collect();
    let r: Vec<_> = ranks.iter().map(|x| x["rank"].as_u64().unwrap()).collect();
    let mut h = vec![0u64; 2 * n + 2];
    let mut bigraded = vec![];
    for i in 0..=n {
        for j in 0..=n {
            let dim = binom(n, i) * binom(n, j);
            let rank = r[i] * r[j];
            assert!(rank <= dim);
            let value = dim - rank;
            h[i + j] += value;
            bigraded.push(json!({"i":i,"j":j,"ambient_dimension":dim,"image_rank":rank,"hilbert_dimension":value}));
        }
    }
    let last = h.iter().rposition(|x| *x > 0).unwrap();
    assert!(h[..=last].iter().all(|x| *x > 0));
    assert!(h[last + 1..].iter().all(|x| *x == 0));
    json!({"ell":n,"characteristic":p.to_string(),"rank_certificates":ranks,"bigraded":bigraded,"hilbert_function":h,"last_nonzero_degree":last,"dreg_exact":last+1,"total_dimension":h.iter().sum::<u64>(),"definition":"First degree d with (R/H)_d=0, H generated by original highest homogeneous forms; not a solving degree or LFD"})
}
fn s3(x: &str, y: &str, z: &str, a: &str, b: &str) -> String {
    format!("(({x})-({y}))^2*({z})^2-2*((({x})+({y}))*(({x})*({y})+{a})+2*{b})*({z})+(({x})*({y})-{a})^2-4*{b}*(({x})+({y}))")
}
fn witness_suffix(input: &Value) -> String {
    if input["target_kind"] == "natural" {
        assert!(input["witness"].is_null());
        return String::new();
    }
    assert_eq!(input["target_kind"], "planted");
    let w = input["witness"].as_array().unwrap();
    assert_eq!(w.len(), 54);
    let bits: Vec<_> = w
        .iter()
        .map(|x| {
            let b = x.as_str().unwrap();
            assert!(b == "0" || b == "1");
            b
        })
        .collect();
    format!("map witness=r,{};\nif(size(witness(I))!=0){{print(\"WITNESS_FAILED\");exit;}} print(\"WITNESS_OK\");\n", bits.join(","))
}
fn validate_source(input: &Value, text: &str, arm: &str) -> Value {
    assert_eq!(input["family"], "prime");
    assert_eq!(input["m"], 2);
    assert_eq!(input["n"], 83);
    assert_eq!(input["ell"], 27);
    assert_eq!(input["n_vars"], 54);
    assert_eq!(input["input_equations"], 55);
    assert_eq!(input["field_modulus"], P.to_string());
    assert_eq!(input["curve_a"], "2");
    assert_eq!(input["curve_b"], "3");
    assert_eq!(input["source_sha256"], sha(text.as_bytes()));
    assert!(["original", "baseline", "spike40"].contains(&arm));
    let pos: Vec<_> = (0..27)
        .map(|j| if arm == "spike40" && j == 26 { 40 } else { j })
        .collect();
    if arm != "original" {
        assert_eq!(input["coordinate_bit_positions"], json!(pos));
        assert_eq!(input["arm"], arm);
    }
    let manifest = if arm == "spike40" {
        "78f21fdb94cd84163c8054258f9a4de914df8f82c24897555cb4c15ffe5b4324"
    } else {
        "199d1b214c78650b2e2e2b539f458eae2688296b9bc51985830951b1cac5aaa5"
    };
    assert_eq!(input["factor_base_manifest_sha256"], manifest);
    let mut expected = format!("ring r=(integer,{P}),(v(1..54)),dp;\nideal I;\n");
    let mut weights = vec![];
    for i in 0..2 {
        expected += &format!(
            "poly x{i}={};\n",
            (0..27)
                .map(|j| format!("{}*v({})", 1u128 << pos[j], i * 27 + j + 1))
                .collect::<Vec<_>>()
                .join("+")
        );
        for j in 0..27 {
            let w = 1u128 << pos[j];
            let inverse = powmod(w, P - 2, P);
            assert_eq!(mulmod(w, inverse, P), 1);
            weights.push(json!({"variable_zero_based":i*27+j,"weight":w.to_string(),"inverse":inverse.to_string()}));
        }
    }
    let z = input["target_x"].as_str().unwrap();
    assert!(z.parse::<u128>().unwrap() < P);
    expected += &format!("I[1]={};\n", s3("x0", "x1", z, "2", "3"));
    for i in 0..54 {
        expected += &format!("I[{}]=v({})^2-v({});\n", i + 2, i + 1, i + 1);
    }
    expected += &witness_suffix(input);
    assert_eq!(
        text, expected,
        "complete source bytes must match the admitted presentation"
    );
    json!({"source_sha256":sha(text.as_bytes()),"full_source_template_verified":true,"normalized_top_ideal":"(all54 variable squares, (sum first27 variables)^2 * (sum last27 variables)^2)","normalization":"Set a_i=weight_i*v_i; invertible diagonal change preserves the ideal of variable squares","weights":weights})
}
fn masks(n: usize, k: usize) -> Vec<usize> {
    (0..(1usize << n))
        .filter(|x| x.count_ones() as usize == k)
        .collect()
}
fn gaussian(mut a: Vec<Vec<u64>>, cols: usize, p: u64) -> usize {
    let mut rank = 0;
    for col in 0..cols {
        if let Some(pivot) = (rank..a.len()).find(|i| a[*i][col] != 0) {
            a.swap(rank, pivot);
            let inv = powmod(a[rank][col] as u128, (p - 2) as u128, p as u128) as u64;
            for j in col..cols {
                a[rank][j] = a[rank][j] * inv % p;
            }
            for i in rank + 1..a.len() {
                let q = a[i][col];
                for j in col..cols {
                    a[i][j] = (a[i][j] + p - q * a[rank][j] % p) % p;
                }
            }
            rank += 1;
            if rank == a.len() {
                break;
            }
        }
    }
    rank
}
fn explicit_rank(n: usize, i: usize, p: u64) -> usize {
    if i < 2 {
        return 0;
    }
    let source = masks(n, i - 2);
    let target = masks(n, i);
    let a = target
        .iter()
        .map(|y| {
            source
                .iter()
                .map(|x| if x & y == *x { 2 % p } else { 0 })
                .collect()
        })
        .collect();
    gaussian(a, source.len(), p)
}
fn explicit_product(n: usize, d: usize, p: u64) -> u64 {
    let target = masks(2 * n, d);
    if d < 4 {
        return target.len() as u64;
    }
    let source = masks(2 * n, d - 4);
    let low = (1usize << n) - 1;
    let a = target
        .iter()
        .map(|y| {
            source
                .iter()
                .map(|x| {
                    let diff = y ^ x;
                    if x & y == *x
                        && (diff & low).count_ones() == 2
                        && (diff >> n).count_ones() == 2
                    {
                        4 % p
                    } else {
                        0
                    }
                })
                .collect()
        })
        .collect();
    target.len() as u64 - gaussian(a, source.len(), p) as u64
}
fn controls() -> Value {
    let mut ranks = vec![];
    let mut products = vec![];
    let mut deficiencies = 0;
    for n in 2..=8 {
        for p in [2u64, 3, 5, 101] {
            for i in 0..=n {
                let c = rank_certificate(n, i, p as u128);
                let actual = explicit_rank(n, i, p) as u64;
                assert_eq!(actual, c["rank"].as_u64().unwrap());
                if actual
                    < c["source_dimension"]
                        .as_u64()
                        .unwrap()
                        .min(c["target_dimension"].as_u64().unwrap())
                {
                    deficiencies += 1;
                }
                ranks.push(
                    json!({"n":n,"p":p,"degree":i,"explicit_rank":actual,"formula_rank":c["rank"]}),
                );
            }
        }
    }
    for n in 2..=4 {
        for p in [2u64, 3, 101] {
            let formula = series(n, p as u128);
            for d in 0..=2 * n {
                let actual = explicit_product(n, d, p);
                assert_eq!(actual, formula["hilbert_function"][d].as_u64().unwrap());
                products.push(json!({"n":n,"p":p,"degree":d,"explicit_hilbert_dimension":actual}));
            }
        }
    }
    assert!(deficiencies > 0);
    json!({"schema":"n83.hilbert-controls/v1","rank_checks":ranks,"product_checks":products,"nonmaximal_rank_controls":deficiencies,"all_passed":true})
}
fn run(root: &Path, out: &Path, replay: bool) {
    let protocol = read(&root.join("protocol-hilbert-v2.json"));
    let cases = protocol["extensions"]["cases"].as_array().unwrap();
    assert_eq!(cases.len(), 6);
    if !replay {
        fs::create_dir(out).unwrap();
    }
    let pc = prime_certificate();
    assert!(P > 27);
    let ctl = controls();
    let hf = series(27, P);
    for name in ["primality", "controls", "hilbert"] {
        let v = match name {
            "primality" => &pc,
            "controls" => &ctl,
            _ => &hf,
        };
        let path = out.join(format!("{name}.json"));
        if replay {
            assert_eq!(read(&path), *v);
        } else {
            save(&path, v);
        }
    }
    let mut rows = vec![];
    for case in cases {
        let key = case["key"].as_str().unwrap();
        let p = root.join("inputs").join(key);
        let input = read(&p.join("input.json"));
        assert_eq!(
            sha(&fs::read(p.join("input.json")).unwrap()),
            case["input_sha256"].as_str().unwrap()
        );
        let text = fs::read_to_string(p.join("system.sing")).unwrap();
        assert_eq!(
            sha(text.as_bytes()),
            case["source_sha256"].as_str().unwrap()
        );
        let source = validate_source(&input, &text, case["arm"].as_str().unwrap());
        let cert = json!({"schema":"n83.prime-m2-hilbert-certificate/v1","key":key,"input":input,"source":source,"hilbert_sha256":sha(&fs::read(out.join("hilbert.json")).unwrap()),"primality_sha256":sha(&fs::read(out.join("primality.json")).unwrap()),"dreg_exact":hf["dreg_exact"],"method":"Wilson diagonal rank certificate, complement transpose, bidegree tensor image; six exact retained presentations"});
        let path = out.join(format!("{key}.json"));
        if replay {
            assert_eq!(read(&path), cert);
        } else {
            save(&path, &cert);
        }
        rows.push(json!({"key":key,"arm":case["arm"],"id":input["id"],"family":"prime","m":2,"ell":27,"target_kind":input["target_kind"],"source_sha256":input["source_sha256"],"factor_base_manifest_sha256":input["factor_base_manifest_sha256"],"dreg_exact":hf["dreg_exact"],"last_nonzero_degree":hf["last_nonzero_degree"],"total_dimension":hf["total_dimension"],"certificate":format!("{key}.json"),"status":"exact","verified":true}));
        println!("{} {}", if replay { "replayed" } else { "certified" }, key);
    }
    let summary = json!({"schema":"n83.prime-m2-hilbert-summary/v1","rows":rows,"controls_passed":true,"primality_verified":true,"formalization":"Finite Hilbert arithmetic only; matrix-rank theorem and polynomial-quotient bridge not formalized"});
    if replay {
        assert_eq!(read(&out.join("summary.json")), summary);
        save(
            &root.join("replay.json"),
            &json!({"schema":"n83.hilbert-replay/v1","cases":6,"all_passed":true,"summary_sha256":sha(&fs::read(out.join("summary.json")).unwrap())}),
        );
    } else {
        save(&out.join("summary.json"), &summary);
    }
}
fn main() {
    let a: Vec<_> = std::env::args().collect();
    match a[1].as_str() {
        "controls" => save(Path::new(&a[2]), &controls()),
        "run" | "replay" => run(Path::new(&a[2]), Path::new(&a[3]), a[1] == "replay"),
        _ => panic!("controls OUT | run ROOT OUT | replay ROOT OUT"),
    }
}
