# SVG plot: log10 gm T vs k and gm mem vs k per arm
arms = ['U','U2','U4','UAA','AF1','AF2','AF4','AF8','AS2','AS4','AS8','G','S']
col = ['#000000','#888888','#444444','#bbbbbb','#999900','#1f77b4','#17becf','#9467bd','#2ca02c','#98df8a','#006400','#d62728','#ff7f0e']
data = {(r['arm'], int(r['k'])): r for r in rows}
W, H = 980, 420
s = ['<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" font-family="sans-serif" font-size="11">' % (W, H), '<rect width="100%" height="100%" fill="white"/>']
def panel(x0, title, key):
    pw, ph, y0 = 330, 300, 50
    vals = [float(data[(a,k)][key]) for a in arms for k in (8,10,12,14)]
    lo, hi = math.log10(min(vals)), math.log10(max(vals))
    s.append('<text x="%d" y="30" font-size="13">%s (log10 geometric mean, 12 curves)</text>' % (x0, title))
    s.append('<rect x="%d" y="%d" width="%d" height="%d" fill="none" stroke="#333"/>' % (x0, y0, pw, ph))
    for i, k in enumerate((8,10,12,14)):
        x = x0 + 30 + i * (pw - 60) / 3
        s.append('<text x="%.0f" y="%d" text-anchor="middle">k=%d</text>' % (x, y0 + ph + 16, k))
    for t in range(int(math.floor(lo)), int(math.ceil(hi)) + 1):
        y = y0 + ph - (t - lo) / (hi - lo) * ph
        if y0 <= y <= y0 + ph:
            s.append('<line x1="%d" x2="%d" y1="%.0f" y2="%.0f" stroke="#ddd"/><text x="%d" y="%.0f" text-anchor="end">1e%d</text>' % (x0, x0+pw, y, y, x0-3, y+4, t))
    for a, c in zip(arms, col):
        pts = []
        for i, k in enumerate((8,10,12,14)):
            x = x0 + 30 + i * (pw - 60) / 3
            y = y0 + ph - (math.log10(float(data[(a,k)][key])) - lo) / (hi - lo) * ph
            pts.append("%.1f,%.1f" % (x, y))
        s.append('<polyline points="%s" fill="none" stroke="%s" stroke-width="1.5"/>' % (" ".join(pts), c))
panel(40, 'T (line trials)', 'gm_T')
panel(400, 'mem_total (records)', 'gm_mem')
for i, (a, c) in enumerate(zip(arms, col)):
    s.append('<rect x="780" y="%d" width="10" height="10" fill="%s"/><text x="796" y="%d">%s</text>' % (55 + i*20, c, 64 + i*20, a))
s.append('<text x="40" y="%d">Counts only, [pcc:unverified]. Cells with exhausted runs plot consumed supply (see n_exh in RESULTS.md).</text>' % (H-12))
s.append('</svg>')
open('plot.svg', 'w').write("\n".join(s))
