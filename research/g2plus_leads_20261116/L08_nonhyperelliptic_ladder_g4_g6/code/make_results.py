#!/usr/bin/env python3
"""Formats raw/analysis*.json, raw/analysis*.tsv, raw/gate_*.jsonl, raw/run_*.jsonl into RESULTS.md and plot.svg. Numbers only."""
import json, glob, math, collections
def L(f): return [json.loads(l) for l in open(f) if l.strip()]
def fmt(x):
    if x is None: return "n/a"
    if isinstance(x, float): return f"{x:.4g}"
    return str(x)
out = []
w = out.append
w("# L08 RESULTS (numbers only; all `[pcc:unverified]`)\n")
w("Generated by `code/make_results.py` from `raw/`. Cost unit FPM = mult + 10 x inv (instrumented). IC figures are partial (enumeration + relation collection + modelled LA `3*cols*W`); no descent, no Pic^0 arithmetic, no logarithm. Not a benchmark. " + open("raw/python_version.txt").read().strip() + ".\n")
w("## 1. Gates\n")
w("Selftest (`raw/selftest.txt`): " + open("raw/selftest.txt").read().strip().splitlines()[-1] + " (17 tests).\n")
w("Gate stage (G1, G2 on FB relations; G3 Weil reciprocity; G3-PC; G4 reported; G5 union-find formula):\n")
w("| d | p | curve | n_quads | g3_pass | g3pc_fail | g1_fail | g2_fail | split_frac | |diff| vs C(p,n)/p^n | g4 | g5 total / E / rank | g5_pass | all_pass |")
w("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
for f in ["raw/gate_d5.jsonl", "raw/gate_d4.jsonl"]:
    for r in L(f):
        g5 = "n/a" if r["g5_total"] is None else f"{r['g5_total']} / {r['g5_E']} / {r['g5_rank']}"
        w(f"| {r['d']} | {r['p']} | {r['c']} | {r['n_quads']} | {r['g3_pass']} | {r['g3pc_fail']} | {r['g1_fail']} | {r['g2_fail']} | {fmt(r['split_frac'])} | {fmt(r['g4_absdiff'])} | {r['g4']} | {g5} | {fmt(r['g5_pass'])} | {r['all_pass']} |")
w("\nG4 is `n/a` in the gate stage by SPEC 6 (evaluated only for p >= 1031 and eligible >= 20000); the split fraction and difference are reported anyway.\n")
rows = [r for f in sorted(glob.glob("raw/run_d*.jsonl")) for r in L(f)]
rows6 = [r for f in sorted(glob.glob("raw/opt_d6*.jsonl")) for r in L(f)]
allr = rows + rows6
w("Main-run verification counters (all rows, stage 1 and 2): rows = %d, sum g1_fail = %d, sum g2_fail = %d.\n" % (len(allr), sum(r['g1_fail'] for r in allr), sum(r['g2_fail'] for r in allr)))
c4 = collections.Counter(r["g4"] for r in allr)
w("G4 in main runs: " + ", ".join(f"{k}: {v}" for k, v in sorted(c4.items())) + ".\n")
w("G4 `fail` rows (|diff| > 0.01 with eligible >= 20000 and p >= 1031):\n")
w("| d | m | p | arm | cF | curve | eligible | split_frac | expected | abs diff |"); w("|---|---|---|---|---|---|---|---|---|---|")
for r in allr:
    if r["g4"] == "fail":
        w(f"| {r['d']} | {r['m']} | {r['p']} | {r['arm']} | {r['cF']} | {r['curve_index']} | {r['eligible']} | {fmt(r['split_frac'])} | {fmt(r['g4_expected'])} | {fmt(r['g4_absdiff'])} |")
w("")
for tag, an in [("Stage 1 (primary: d=5,m=2 genus 4; control d=4,m=0 genus 3)", "raw/analysis.json"), ("Stage 2 optional (d=6)", "raw/analysis_opt.json")]:
    a = json.load(open(an))
    w(f"## {tag}\n")
    w(f"Analyzer verdict field (`{an}`): `{json.dumps(a['verdict'], sort_keys=True)}`\n")
    for k, g in a["groups"].items():
        w(f"### {k} (genus {g['g']})\n")
        w("A_2LP series (min over valid cF of the 4-curve mean fpm_total), with ratio to rho references (rho_393 / rho_8900 = sqrt(pi p^g/2) x 393 / 8900), and share of enumeration in the chosen cell:\n")
        w("| p | argmin cF | A_2LP mean fpm_total | IC/rho_393 | IC/rho_8900 | IC/rho_393 Weil band | IC/rho_8900 Weil band | enum share |"); w("|---|---|---|---|---|---|---|---|")
        for p in sorted(g["A_2LP"], key=int):
            v = g["A_2LP"][p]; rt = g["ratios_A_2LP"][p]
            w(f"| {p} | {v['argmin_cF']} | {fmt(v['value'])} | {fmt(rt['ratio_393'])} | {fmt(rt['ratio_8900'])} | [{fmt(rt['ratio_393_band'][0])}, {fmt(rt['ratio_393_band'][1])}] | [{fmt(rt['ratio_8900_band'][0])}, {fmt(rt['ratio_8900_band'][1])}] | {fmt(g['enum_share'][p])} |")
        w("")
        b = g["bootstrap"]
        w(f"Slopes (OLS ln cost on ln p): A_2LP all primes = {fmt(g['slope_A_all'])}; A_2LP 4 largest = {fmt(g['slope_A_largest4'])}; FB all = {fmt(g['slope_FB_all'])}; FB 4 largest = {fmt(g['slope_FB_largest4'])}; bootstrap of A_2LP all-prime slope (2000 reps, curve resampling per p) 2.5/97.5 = {fmt(b['lo']) if b else 'n/a'} / {fmt(b['hi']) if b else 'n/a'}.\n")
        w("Per-cF slopes (rep 1, valid primes only): " + "; ".join(f"cF={c}: {fmt(v['slope'])} over primes {v['primes']}" for c, v in g["slope_per_cF"].items()) + ".\n")
        aa = g["AA"]
        w(f"A/A (cF=2): slope rep1 = {fmt(aa['slope_rep1'])}, rep2 = {fmt(aa['slope_rep2'])}, |diff| = {fmt(aa['absdiff'])} over primes {aa['primes']}.\n")
    if "d5_m2" in a["groups"]:
        w("Instrument checks and decision-rule inputs (PROTOCOL 8): " + json.dumps(a["verdict"], sort_keys=True) + "\n")
# full cell table
w("## 2. All cells (means over the curves in the cell)\n")
w("Columns: n_valid = rows not exhausted and with g1=g2=0; exh = rows exhausted. Means are over all present rows of the cell. Full table with every column: `raw/analysis.tsv`, `raw/analysis_opt.tsv`.\n")
for tsv in ["raw/analysis.tsv", "raw/analysis_opt.tsv"]:
    lines = open(tsv).read().strip().splitlines()
    hdr = lines[0].split("\t")
    idx = {h: i for i, h in enumerate(hdr)}
    w(f"### {tsv}\n")
    w("| d | m | arm | cF | rep | p | n_valid | exh | mean_fpm_total | mean_fpm_enum | mean_fpm_rel | mean_la_fpm | mean_lines_tried | mean_useful | mean_needed | mat_rows | mat_cols | mat_weight | split_frac | ratio_393 | ratio_8900 |")
    w("|" + "---|" * 21)
    for ln in lines[1:]:
        c = ln.split("\t")
        def g_(h):
            v = c[idx[h]]
            try:
                return fmt(float(v)) if "." in v or "e" in v else v
            except Exception:
                return v
        w("| " + " | ".join([c[0], c[1], c[2], c[3], c[4], c[5], c[6], c[idx['n_exhausted']]] + [g_(h) for h in ["mean_fpm_total", "mean_fpm_enum", "mean_fpm_rel", "mean_la_fpm", "mean_lines_tried", "mean_useful", "mean_needed", "mean_mat_rows", "mean_mat_cols", "mean_mat_weight", "mean_split_frac", "ratio_393", "ratio_8900"]]) + " |")
    w("")
w("## 3. Curve admission (genus test rejections before the admitted seeds)\n")
w("| d | m | p | admitted seeds (curves 0..3) | rejection counts before curve 0 / seeds tried for the last curve |"); w("|---|---|---|---|---|")
rj = collections.defaultdict(dict)
for r in allr:
    rj[(r['d'], r['m'], r['p'])][r['curve_index']] = (r['curve_seed'], r['seeds_tried'], r['reject_counts'])
for k in sorted(rj):
    cs = rj[k]
    last = cs[max(cs)]
    w(f"| {k[0]} | {k[1]} | {k[2]} | {[cs[i][0] for i in sorted(cs)]} | last curve seeds_tried = {last[1]}, rejects = {json.dumps(last[2], sort_keys=True)} |")
w("")
w("## 4. Exhausted runs (all 4 curves counted per cell)\n")
ex = collections.Counter((r['d'], r['m'], r['arm'], r['cF'], r['rep'], r['p']) for r in allr if r['exhausted'])
w("| d | m | arm | cF | rep | p | exhausted rows (of 4) |"); w("|---|---|---|---|---|---|---|")
for k, v in sorted(ex.items()):
    w("| " + " | ".join(map(str, k)) + f" | {v} |")
w("")
w("Rows with the duplicate-line diagnostic (`rel_dup_lines`: relations whose line was already produced by another pair of factor-base points; SPEC does not deduplicate) for curve 0, FB arm:\n")
w("| d | p | rel_dup_lines | useful |"); w("|---|---|---|---|")
for r in sorted([r for r in allr if r['arm'] == 'FB' and r['curve_index'] == 0], key=lambda r: (r['d'], r['m'], r['p'])):
    w(f"| {r['d']} | {r['p']} | {r['rel_dup_lines']} | {r['useful']} |")
w("")
w("## 5. Sensitivity (reported, not used in a verdict)\n")
w("Mean `fpm_total_kappa` (= enum + rel + g^2 x LA) of the A_2LP argmin cells, by p, stage 1:\n")
a = json.load(open("raw/analysis.json"))
cells = collections.defaultdict(list)
for r in rows: cells[(r['d'], r['m'], r['arm'], r['cF'], r['rep'], r['p'])].append(r)
w("| d | p | argmin cF | mean fpm_total | mean fpm_total_kappa |"); w("|---|---|---|---|---|")
for k, g in a["groups"].items():
    for p, v in sorted(g["A_2LP"].items(), key=lambda kv: int(kv[0])):
        rs = cells[(g['d'], g['m'], '2LP', v['argmin_cF'], 1, int(p))]
        w(f"| {g['d']} | {p} | {v['argmin_cF']} | {fmt(sum(r['fpm_total'] for r in rs)/len(rs))} | {fmt(sum(r['fpm_total_kappa'] for r in rs)/len(rs))} |")
w("\nPlot: `plot.svg` (A_2LP and FB mean fpm_total versus p, log-log, d=4 control, d=5, and d=6 optional).")
open("RESULTS_body.md", "w").write("\n".join(out) + "\n")

# SVG plot, log-log
series = {}
for gk in ["raw/analysis.json", "raw/analysis_opt.json"]:
    a = json.load(open(gk))
    for k, g in a["groups"].items():
        series[f"{k} A_2LP"] = {int(p): v["value"] for p, v in g["A_2LP"].items()}
        series[f"{k} FB"] = {int(p): v for p, v in g["FB_values"].items()}
W, H, ml, mb, mt, mr = 760, 520, 70, 60, 30, 190
xs = [math.log(p) for s in series.values() for p in s]
ys = [math.log10(v) for s in series.values() for v in s.values()]
x0, x1 = min(xs), max(xs); y0, y1 = math.floor(min(ys)), math.ceil(max(ys))
def X(p): return ml + (math.log(p) - x0) / (x1 - x0) * (W - ml - mr)
def Y(v): return H - mb - (math.log10(v) - y0) / (y1 - y0) * (H - mb - mt)
cols = ["#1f77b4", "#1f77b4", "#d62728", "#d62728", "#2ca02c", "#2ca02c", "#9467bd", "#9467bd"]
svg = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" font-family="sans-serif" font-size="12"><rect width="100%" height="100%" fill="white"/>']
svg.append(f'<text x="{ml}" y="18" font-size="14">L08: mean fpm_total (enum + relations + LA model) vs p, log-log [pcc:unverified]</text>')
for e in range(y0, y1 + 1):
    svg.append(f'<line x1="{ml}" x2="{W-mr}" y1="{Y(10**e)}" y2="{Y(10**e)}" stroke="#ddd"/><text x="{ml-8}" y="{Y(10**e)+4}" text-anchor="end">1e{e}</text>')
for p in [131, 257, 521, 1031, 2053, 4099, 8209]:
    svg.append(f'<line y1="{mt}" y2="{H-mb}" x1="{X(p)}" x2="{X(p)}" stroke="#eee"/><text x="{X(p)}" y="{H-mb+16}" text-anchor="middle">{p}</text>')
svg.append(f'<text x="{(ml+W-mr)/2}" y="{H-12}" text-anchor="middle">p</text><text x="14" y="{H/2}" transform="rotate(-90 14 {H/2})" text-anchor="middle">FPM</text>')
for i, (name, s) in enumerate(sorted(series.items())):
    c = cols[i % len(cols)]; dash = ' stroke-dasharray="5,4"' if "FB" in name else ""
    pts = " ".join(f"{X(p):.1f},{Y(v):.1f}" for p, v in sorted(s.items()))
    svg.append(f'<polyline fill="none" stroke="{c}" stroke-width="2"{dash} points="{pts}"/>')
    for p, v in s.items():
        svg.append(f'<circle cx="{X(p):.1f}" cy="{Y(v):.1f}" r="3" fill="{c}"/>')
    svg.append(f'<line x1="{W-mr+10}" x2="{W-mr+34}" y1="{40+i*20}" y2="{40+i*20}" stroke="{c}" stroke-width="2"{dash}/><text x="{W-mr+40}" y="{44+i*20}">{name}</text>')
svg.append("</svg>")
open("plot.svg", "w").write("\n".join(svg))
