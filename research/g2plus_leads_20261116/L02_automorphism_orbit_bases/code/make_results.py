import json, os, sys, glob, collections
os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
A = json.load(open("raw/analysis.json"))
def f(x, n=4):
    if x is None: return "NA"
    if abs(x) >= 1e5: return "%.4g" % x
    return ("%." + str(n) + "g") % x
def cellkey(k): fam, b = k.split("|"); return (fam, int(b))
cells = sorted(A["cells"], key=cellkey)
L = []
w = L.append
w("# L02 RESULTS: automorphism-orbit factor bases on `y^2 = x^q + a`\n")
w("All numbers are `[pcc:unverified]`: one session, shared 4-core container, Python instrument, no independent replay. Exact counts, seeds from `SPEC.md` section 2. This file states measured values and gate outcomes; it contains no interpretation. Source: `raw/analysis.json`, `raw/summary.tsv`, `raw/*.jsonl`; commands and file hashes: `raw/COMMANDS.log`, `raw/data.sha256`. Generated by `code/make_results.py` from `raw/analysis.json`.\n")
w("FPM = field multiplications + I x inversions (+ kappa x mod-r work for IC). Primary reading `I10_kg2` is (I, kappa) = (10, g^2). Other readings: `I1_k1` = (1, 1), `I30_kg2` = (30, g^2). IC_A, IC_B are full-base IC arms A (one column per abscissa) and B (one column per rho-orbit of abscissae); R_neg, R_aut are rho on classes of size 2 and 2q. D1 = IC_A/IC_B, rho_gain = R_neg/R_aut, N = D1/rho_gain, gap_A = IC_A/R_aut, gap_B = IC_B/R_aut (definitions as PROTOCOL section 5). CIs: 95% percentile, hierarchical bootstrap, 2000 replicates, seed 20261116.\n")
g = A["gates"]
w("## 1. Gate outcomes\n")
w("| gate | outcome |\n|---|---|")
w("| G0 selftest (`raw/selftest.txt`) | 15 of 15 tests PASS (see DEVIATIONS.md items 1-2 for two test-harness departures) |")
w("| G1/G2 failing curves | %s (48 curves checked: 15 F5, 9 F7, 15 C5, 9 C7) |" % (g["G1_G2_failing_curves"] or "none"))
w("| G3 void cells (>5%% uncertified) | %s; uncertified runs: 0 of 360 IC runs, 0 of 1224 rho runs |" % (g["G3_void_cells"] or "none"))
w("| G4 paired-stream digests (A0, A, B) | failures: %d |" % len(g["G4_failures"]))
w("| G5 orbit identity (`ncols_B q + delta0 = ncols_A`, `ncols_A0 = 2 ncols_A`) | failures: %d |" % len(g["G5_failures"]))
w("| G6 A/A on controls (B = A, Raut = Rneg, every counter) | failures: %d |" % len(g["G6_failures"]))
w("| G7 positive control (mean relations_A0 / relations_A in [1.8, 2.2]) | %s |" % ("all 8 cells inside" if g["G7_pass"] else "FAILED in some cell"))
w("\nG7 cell values: " + ", ".join("%s: %s" % (k, f(v["mean_pos_ratio"])) for k, v in sorted(g["G7"].items(), key=lambda kv: cellkey(kv[0]))) + "\n")
w("Solver status over all runs: every IC run `ok` and certified; every rho run `ok` (cap not reached) and certified. No `trial_cap`, no `la_fail`.\n")
w("## 2. Pooled statistic (decision cells named in PROTOCOL section 6)\n")
w("Pooled = geometric mean over cells. F5: k = 12, 13, 14. F7: k = 9, 10.\n")
w("| family | reading | pooled D1 [95% CI] | pooled rho_gain | pooled N [95% CI] |\n|---|---|---|---|---|")
for fam in ("F5", "F7"):
    p = A["pooled"][fam]
    for r in ("I1_k1", "I10_kg2", "I30_kg2"):
        d = p[r]
        w("| %s | %s | %s [%s, %s] | %s | %s [%s, %s] |" % (fam, r, f(d["D1"]), f(d["D1_lo"]), f(d["D1_hi"]), f(d["rho_gain"]), f(d["N"]), f(d["N_lo"]), f(d["N_hi"])))
w("\nThe pre-registered threshold in PROTOCOL section 6 is 2.0 on the pooled N interval; the mechanical outcome of the frozen rule for each reading is in `raw/analysis.json` under `pooled.<family>.verdict_by_reading` and is not restated or interpreted here.\n")
w("## 3. Per-cell FPM and ratios, primary reading (10, g^2)\n")
w("| family | k | curves | IC_A | IC_B | R_neg | R_aut | D1 [CI] | rho_gain | N [CI] | gap_A | gap_B |\n|---|---|---|---|---|---|---|---|---|---|---|---|")
for k in cells:
    fam, b = cellkey(k); c = A["cells"][k]; d = c["readings"]["I10_kg2"]
    w("| %s | %d | %d | %s | %s | %s | %s | %s [%s, %s] | %s | %s [%s, %s] | %s | %s |" % (fam, b, c["n_curves"], f(d["IC_A"]), f(d["IC_B"]), f(d["R_neg"]), f(d["R_aut"]), f(d["D1"]), f(d["D1_lo"]), f(d["D1_hi"]), f(d["rho_gain"]), f(d["N"]), f(d["N_lo"]), f(d["N_hi"]), f(d["gap_A"]), f(d["gap_B"])))
w("\n## 4. Per-cell D1, N and gaps at the other two readings\n")
w("| family | k | reading | IC_A | IC_B | R_neg | R_aut | D1 | N [CI] | gap_B |\n|---|---|---|---|---|---|---|---|---|---|")
for k in cells:
    fam, b = cellkey(k)
    if fam not in ("F5", "F7"): continue
    for r in ("I1_k1", "I30_kg2"):
        d = A["cells"][k]["readings"][r]
        w("| %s | %d | %s | %s | %s | %s | %s | %s | %s [%s, %s] | %s |" % (fam, b, r, f(d["IC_A"]), f(d["IC_B"]), f(d["R_neg"]), f(d["R_aut"]), f(d["D1"]), f(d["N"]), f(d["N_lo"]), f(d["N_hi"]), f(d["gap_B"])))
w("\n## 5. IC counts per cell (means over curves and seeds; 3 curves x 3 seeds)\n")
w("| family | k | arm | relations | trials | group additions | rel_mul | rel_inv | la_mul (mod r) | la_inv | dim | nnz | max_fill | LA_model 2 dim nnz | LA attempts |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
for k in cells:
    fam, b = cellkey(k)
    for arm in ("A0", "A", "B"):
        la = A["cells"][k]["la"].get(arm)
        if la: w("| %s | %d | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (fam, b, arm, f(la["relations"]), f(la["trials"]), f(la["grp_ops"]), f(la["rel_mul"]), f(la["rel_inv"]), f(la["la_mul"]), f(la["la_inv"]), f(la["dim"]), f(la["nnz"]), la["max_fill"], f(la["LA_model_2dim_nnz"]), f(la["la_attempts"])))
w("\n## 6. Prediction-check quantities (reported only)\n")
w("| family | k | rel_ratio (A/B) | rel_pred (nA+10)/(nB+10) | within 5% | pos_ratio (A0/A) | rho_gain | in [0.75 sqrt q, 1.15 sqrt q] |\n|---|---|---|---|---|---|---|---|")
for k in cells:
    fam, b = cellkey(k)
    if fam not in ("F5", "F7"): continue
    c = A["cells"][k]
    w("| %s | %d | %s | %s | %s | %s | %s | %s |" % (fam, b, f(c["rel_ratio"], 5), f(c["rel_pred"], 5), c["rel_ratio_within_5pct_of_pred"], f(c["pos_ratio"]), f(c["readings"]["I10_kg2"]["rho_gain"]), c["rho_gain_in_band_[0.75sqrtq,1.15sqrtq]"]))
w("\n## 7. Rho counts per cell (means over runs)\n")
w("| family | k | arm | runs | steps | mul | inv | look-ahead extra | walks started | DPs stored | abandoned steps / steps | mod-r bookkeeping mults (excluded from FPM) |\n|---|---|---|---|---|---|---|---|---|---|---|---|")
for k in cells:
    fam, b = cellkey(k)
    for arm in ("Rneg", "Raut"):
        r = A["cells"][k]["rho"][arm]
        w("| %s | %d | %s | %d | %s | %s | %s | %s | %s | %s | %s | %s |" % (fam, b, arm, r["n_runs"], f(r["steps"]), f(r["mul"]), f(r["inv"]), f(r["lookahead_extra"]), f(r["walks_started"]), f(r["dps_stored"]), f(r["abandon_frac"]), f(r["rmul_bookkeeping"])))
w("\n## 8. Instances (admitted by rule; `raw/instances_*.jsonl`)\n")
w("| curve_id | k | p | #J | h | r | lambda | nA | delta0 | nB |\n|---|---|---|---|---|---|---|---|---|---|")
for fam in ("F5", "F7", "C5", "C7"):
    for l in open("raw/instances_%s.jsonl" % fam):
        d = json.loads(l)
        if d.get("rejected"): continue
        w("| %s | %d | %d | %d | %d | %d | %s | %d | %d | %d |" % (d["curve_id"], d["bits"], d["p"], d["N"], d["h"], d["r"], d["lam"] if fam[0] == "F" else "NA", d["nA"], d["delta0"], d["nB"]))
rej = collections.Counter()
for fam in ("F5", "F7", "C5", "C7"):
    for l in open("raw/instances_%s.jsonl" % fam):
        d = json.loads(l)
        if d.get("rejected"): rej[(fam, d["reason"])] += 1
w("\nRejected candidates (count by reason): " + ", ".join("%s %s: %d" % (a, b, n) for (a, b), n in sorted(rej.items())) + ".\n")
w("## 9. Deviations\n\nSee `DEVIATIONS.md`. Plot: `plot.svg` (primary-reading mean FPM per arm and cell).\n")
open("RESULTS.md", "w").write("\n".join(L) + "\n")
