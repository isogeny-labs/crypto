#!/usr/bin/env python3
"""Phase A selection rule of PROTOCOL.md, applied to the train sessions.

    python3 select.py

Prices every train record with `ecbench work` (bitop/v1). Per curve size and
arm family (`pair`, `rf3`), the winner is the candidate with the smallest mean
bitops among candidates whose runs all verified and are all completely
priced. A winner at either end of the grid tried so far needs an extension
(one step of 2^(1/2) beyond it, not below 8; at most three a curve and arm).

Writes `select/SELECTION.md` and `select/selection.json` every time. When no
extension is needed it also writes `params.json`; otherwise it prints one
`make_specs.py ext …` command per needed extension and exits 3.
"""
import json
import math
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
BIN = HERE.parent.parent / "target" / "release" / "ecbench"
MAX_EXT = 3


def main():
    dirs = sorted(p for p in (HERE / "sessions").glob("train-P*") if p.is_dir())
    if not dirs:
        sys.exit("no train sessions")
    out = subprocess.run([str(BIN), "work", *map(str, dirs)], check=True,
                         capture_output=True, text=True).stdout
    # (bits, family) -> size -> list of (status, complete, bitops)
    runs = defaultdict(lambda: defaultdict(list))
    exts = defaultdict(int)
    for d in dirs:
        name = d.name
        if "-ext" in name:
            b_s, fam, _ = name.split("-P")[1].split("-")
            b = int(b_s)
            exts[(b, fam)] += 1
    for line in out.splitlines():
        r = json.loads(line)
        if r["warmup"] or r["arm"] == "rho-neg":
            continue
        fam, size = r["arm"].split("-N")
        b = round(r["log2_r"])
        w = r["work"].get("Ok") or {}
        runs[(b, fam)][int(size)].append(
            (r["status"], bool(w.get("complete")), int(w["bitops"]) if w.get("bitops") else None))

    rows, params, needed = [], {"pair": {}, "rf3": {}}, []
    for (b, fam) in sorted(runs):
        cands = runs[(b, fam)]
        sizes = sorted(cands)
        ok = {}
        for s in sizes:
            rs = cands[s]
            good = all(st == "verified" and c and x is not None for st, c, x in rs)
            mean = sum(x for _, _, x in rs if x is not None) / len(rs) if good else None
            ok[s] = mean
            rows.append((b, fam, s, len(rs), sum(st == "verified" for st, _, _ in rs), mean))
        elig = [s for s in sizes if ok[s] is not None]
        if not elig:
            params[fam][str(b)] = None
            continue
        win = min(elig, key=lambda s: ok[s])
        params[fam][str(b)] = win
        edge = None
        if win == sizes[0] and win > 8:
            edge = max(8, round(win / 2 ** 0.5))
        elif win == sizes[-1]:
            edge = round(win * 2 ** 0.5)
        if edge is not None and edge not in cands and exts[(b, fam)] < MAX_EXT:
            needed.append((b, fam, edge, exts[(b, fam)] + 1))

    sel = HERE / "select"
    sel.mkdir(exist_ok=True)
    md = ["# Phase A selection (bitop/v1, train panel)", "",
          "Generated by `select.py` from `sessions/train-P*` (PROTOCOL.md, Phase A).", "",
          "| bits | arm | base | runs | verified | mean bitops | log2 | selected |",
          "|--:|:--|--:|--:|--:|--:|--:|:--|"]
    for b, fam, s, n, v, mean in rows:
        mark = "**yes**" if params[fam].get(str(b)) == s else ""
        md.append(f"| {b} | {fam} | {s} | {n} | {v} | "
                  f"{'—' if mean is None else f'{mean:.4g}'} | "
                  f"{'—' if mean is None else f'{math.log2(mean):.3f}'} | {mark} |")
    (sel / "SELECTION.md").write_text("\n".join(md) + "\n")
    (sel / "selection.json").write_text(json.dumps(
        {"rows": rows, "selected": params, "extensions_needed": needed}, indent=1) + "\n")
    if needed:
        for b, fam, edge, n in needed:
            print(f"python3 make_specs.py ext {b} {fam} {edge} {n}")
        sys.exit(3)
    params["_comment"] = ("Frozen by select.py from the train panel (PROTOCOL.md Phase A): "
                          "per size, the base with the smallest mean bitop/v1 cost among "
                          "candidates verified and completely priced on every train target.")
    (HERE / "params.json").write_text(json.dumps(params, indent=1, sort_keys=True) + "\n")
    print("params.json written")


if __name__ == "__main__":
    main()
