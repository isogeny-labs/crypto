#!/usr/bin/env python3
"""Readings Q1-Q4 and Qcal of PROTOCOL section 3, gates of section 4,
statistics of section 5. Written after the run was launched and before any of
its data was read; it implements the frozen definitions only."""
import json
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))
PREV = os.path.join(HERE, "..", "genus4_positive_control_20261116", "run.jsonl")
B = 2000
WS = [("0", 0.0), ("0.1", 0.1), ("1", 1.0)]
rows = [json.loads(l) for l in open(os.path.join(HERE, "run.jsonl"))]
prev = [json.loads(l) for l in open(PREV)]


def key(r):
    return (r["curve_seed"], r.get("target_seed", r["curve_seed"]), r["seed"])


def arm(rs, name):
    return {key(r): r for r in rs if r.get("kind") == "run" and r.get("g") == 4 and r["p"] == 8209 and r["arm"] == name}


W = arm(rows, "C_double_lp+pre+coord+unitT")
R = arm(rows, "R_rho_neg")
P = arm(rows, "R_rho_plain")
Wold = arm(prev, "C_double_lp+pre+coord+unitT")
Rold = arm(prev, "R_rho_neg")
cal = [r for r in rows if r.get("kind") == "calibration"]

gates = {"G1": [], "G2": []}
for new, old, fields in [(W, Wold, ["group_ops", "rel_mul", "la_mul", "trials", "relations"]),
                         (R, Rold, ["group_ops", "native", "steps"])]:
    for k, o in old.items():
        if k[2] > 2:
            continue
        n = new.get(k)
        if n is None:
            gates["G1"].append(f"{k} missing")
            continue
        for f in fields:
            if n[f] != o[f]:
                gates["G1"].append(f"{k} {f}: {n[f]} != {o[f]}")
for d in (W, R, P):
    for k, r in d.items():
        if not (r.get("certified") and r.get("ok")):
            gates["G2"].append(f"{r['arm']} {k}")
gate_ok = {g: not v for g, v in gates.items()}

# calibrated weights (mean over curves): relation phase priced mod p, LA mod r
wm_p = sum(c["w_cal_mul_p"] for c in cal) / len(cal)
wa_p = sum(c["w_cal_add_p"] for c in cal) / len(cal)
wm_r = sum(c["w_cal_mul_r"] for c in cal) / len(cal)


def ic_cost(r, reading, w):
    G, M, A = r["group_ops"], r["rel_mul"] + r["la_mul"], r["rel_add"] + r["la_add"]
    if reading == "Q1":
        return G + w * M
    if reading == "Qcal":
        return G + wm_p * r["rel_mul"] + wm_r * r["la_mul"] + wa_p * A
    return G + w * (M + A)


def rho_cost(r, reading, w):
    G, C = r["group_ops"], r["native"]
    K, H, D = r["compares_uncharged"], r["hash_uncharged"], r["coef_adds_uncharged"]
    if reading in ("Q1", "Q2"):
        return G + w * C
    if reading == "Q3":
        return G + w * (C + K)
    if reading == "Q4":
        return G + w * (C + K + H + D)
    return G  # Qcal: rho's native work is timed inside the Cantor step


def mean(v):
    return sum(v) / len(v)


def boot_vs_cheapest(reading, w, keys, seed=20261120):
    """Ratio of mean IC cost to the cheaper of mean R / mean P cost; bootstrap
    over targets, then seeds (protocol §5)."""
    rnd = random.Random(seed)
    targets = sorted({(k[0], k[1]) for k in keys})
    by_t = {t: [k for k in keys if (k[0], k[1]) == t] for t in targets}

    def stat(ks):
        ic = mean([ic_cost(W[k], reading, w) for k in ks])
        rr = mean([rho_cost(R[k], reading, w) for k in ks])
        pp = mean([rho_cost(P[k], reading, w) for k in ks])
        return ic / min(rr, pp), ("R" if rr <= pp else "P"), pp / rr

    est, which, pr = stat(keys)
    bs = []
    for _ in range(B):
        ks = []
        for t in [rnd.choice(targets) for _ in targets]:
            ks += [rnd.choice(by_t[t]) for _ in by_t[t]]
        bs.append(stat(ks)[0])
    bs.sort()
    return {"ratio": est, "lo": bs[int(0.025 * B)], "hi": bs[int(0.975 * B) - 1], "cheapest": which, "P_over_R": pr}


keys = sorted(W)
out = {"gates": gate_ok, "gate_failures": {g: v[:20] for g, v in gates.items()},
       "calibration": {"w_cal_mul_p": wm_p, "w_cal_add_p": wa_p, "w_cal_mul_r": wm_r, "records": cal},
       "readings": {}, "loo": {}, "claims": "[pcc:unverified]"}
for reading in ["Q1", "Q2", "Q3", "Q4"]:
    out["readings"][reading] = {name: boot_vs_cheapest(reading, w, keys) for name, w in WS}
out["readings"]["Qcal"] = {"cal": boot_vs_cheapest("Qcal", 0.0, keys)}
curves = sorted({k[0] for k in keys})
for reading in ["Q1", "Q2", "Q3", "Q4"]:
    out["loo"][reading] = {str(c): boot_vs_cheapest(reading, 1.0, [k for k in keys if k[0] != c]) for c in curves}
verdict = {}
for reading, cells in out["readings"].items():
    verdict[reading] = all(v["hi"] < 1 for v in cells.values())
out["below_cheapest_rho_at_every_price"] = verdict
json.dump(out, open(os.path.join(HERE, "analysis.json"), "w"), indent=1)

f3 = lambda v: f"{v['ratio']:.3f} [{v['lo']:.3f}, {v['hi']:.3f}] ({v['cheapest']})"
L = ["# Tables (generated by analyze.py; every number [pcc:unverified])", "",
     "Gates: " + ", ".join(f"{g} {'pass' if ok else 'FAIL'}" for g, ok in gate_ok.items()),
     f"Runs: w {len(W)}, R {len(R)}, P {len(P)}; targets {len({(k[0], k[1]) for k in keys})}", "",
     f"Calibration (mean of {len(cal)} curves; ns ratios to one Cantor addition): "
     f"mul mod p {wm_p:.5f}, add mod p {wa_p:.5f}, mul mod r {wm_r:.5f}", "",
     "## Arm w against the cheapest rho (R = negation, P = plain), per reading", "",
     "| reading | w = 0 | w = 0.1 | w = 1 | below at every price |", "|--|--|--|--|--|"]
for reading in ["Q1", "Q2", "Q3", "Q4"]:
    c = out["readings"][reading]
    L.append(f"| {reading} | {f3(c['0'])} | {f3(c['0.1'])} | {f3(c['1'])} | {verdict[reading]} |")
L.append(f"| Qcal | – | {f3(out['readings']['Qcal']['cal'])} | – | {verdict['Qcal']} |")
L += ["", "P/R (plain over negation rho cost) at w = 1: "
      + ", ".join(f"{q} {out['readings'][q]['1']['P_over_R']:.3f}" for q in ["Q1", "Q2", "Q3", "Q4"])
      + f"; at w = 0: {out['readings']['Q1']['0']['P_over_R']:.3f}",
      "", "## Leave one curve out, w = 1", "", "| reading | " + " | ".join(f"without {c}" for c in curves) + " |",
      "|--|" + "--|" * len(curves)]
for reading in ["Q1", "Q2", "Q3", "Q4"]:
    L.append(f"| {reading} | " + " | ".join(f3(out["loo"][reading][str(c)]) for c in curves) + " |")
open(os.path.join(HERE, "tables.md"), "w").write("\n".join(L) + "\n")

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.backends.backend_pdf import PdfPages

fig, ax = plt.subplots(figsize=(8, 4.6))
xs = []
for i, reading in enumerate(["Q1", "Q2", "Q3", "Q4"]):
    for j, (name, _) in enumerate(WS):
        v = out["readings"][reading][name]
        x = i * 4 + j
        ax.errorbar([x], [v["ratio"]], yerr=[[v["ratio"] - v["lo"]], [v["hi"] - v["ratio"]]], fmt="o",
                    color=["#1f77b4", "#ff7f0e", "#d62728"][j], capsize=3, label=f"w = {name}" if i == 0 else None)
    xs.append(i * 4 + 1)
v = out["readings"]["Qcal"]["cal"]
ax.errorbar([16], [v["ratio"]], yerr=[[v["ratio"] - v["lo"]], [v["hi"] - v["ratio"]]], fmt="s", color="k",
            capsize=3, label="calibrated")
ax.set_xticks(xs + [16], ["Q1", "Q2", "Q3", "Q4", "Qcal"])
ax.axhline(1, color="k", lw=0.8, ls="--")
ax.set(yscale="log", ylabel="arm w / cheapest rho", title="Genus 4, p = 8209, 9 targets: pricing readings  [pcc:unverified]")
ax.legend()
fig.tight_layout()
fig.savefig(os.path.join(HERE, "figure.svg"))
fig.savefig(os.path.join(HERE, "figure.png"), dpi=150)
with PdfPages(os.path.join(HERE, "REPORT.pdf")) as pdf:
    pdf.savefig(fig)
    for src in ["RESULTS.md", "tables.md"]:
        pth = os.path.join(HERE, src)
        if os.path.exists(pth):
            t = plt.figure(figsize=(11, 8.5))
            t.text(0.03, 0.97, open(pth).read()[:7000], va="top", family="monospace", fontsize=5.6)
            pdf.savefig(t)
print("\n".join(L))
