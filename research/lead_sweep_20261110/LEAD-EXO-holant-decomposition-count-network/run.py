#!/usr/bin/env python3
"""Preregistered toy: digit-QTT flattening rank of the Semaev-2 count matrix under x / random / DL labelling.
stdlib only, deterministic seeds. See PROTOCOL.md."""
import json, random, sys, time

def is_prime(n):
    return n > 1 and all(n % d for d in range(2, int(n ** .5) + 1))

def add(P, Q, a, p):
    if P is None: return Q
    if Q is None: return P
    x1, y1 = P; x2, y2 = Q
    if x1 == x2:
        if (y1 + y2) % p == 0: return None
        l = (3 * x1 * x1 + a) * pow(2 * y1, -1, p) % p
    else:
        l = (y2 - y1) * pow(x2 - x1, -1, p) % p
    x3 = (l * l - x1 - x2) % p
    return (x3, (l * (x1 - x3) - y1) % p)

def cyclic_curve(p, rng):
    """Return xs[k]=x(kG) (None for k=0), N, curve with cyclic E(F_p) generated by G."""
    sq = {}
    for y in range(p): sq.setdefault(y * y % p, []).append(y)
    for _ in range(2000):
        a, b = rng.randrange(p), rng.randrange(p)
        if (4 * a ** 3 + 27 * b * b) % p == 0: continue
        pts = [(x, y) for x in range(p) for y in sq.get((x ** 3 + a * x + b) % p, [])]
        N = len(pts) + 1
        if N < 16: continue
        for _t in range(6):
            G = rng.choice(pts); xs = [None]; Q = G
            while Q is not None and len(xs) <= N:
                xs.append(Q[0]); Q = add(Q, G, a, p)
            if len(xs) == N and Q is None:
                return xs, N, (a, b)
    raise RuntimeError("no cyclic curve")

def gf2_rank(rows):
    basis = {}  # leading bit -> row
    r = 0
    for v in rows:
        while v:
            h = v.bit_length()
            if h in basis: v ^= basis[h]
            else: basis[h] = v; r += 1; break
    return r

def flat_rank(ones, n, k):
    """GF(2) rank of the bond-k flattening of a 2^n x 2^n 0/1 matrix given as (i,j) list."""
    m = (1 << (n - k)) - 1; rows = {}
    for i, j in ones:
        r = ((i >> (n - k)) << k) | (j >> (n - k))
        c = ((i & m) << (n - k)) | (j & m)
        rows[r] = rows.get(r, 0) | (1 << c)
    return gf2_rank(rows.values())

def cuts(n): return sorted({max(1, n // 2 - 1), n // 2, min(n - 1, n // 2 + 1)})

def stat(ones, n, npts):
    npts = len(ones)
    out = {}
    for k in cuts(n):
        ceil = min(4 ** k, 4 ** (n - k), npts)
        out[k] = (flat_rank(ones, n, k), ceil)
    return out

def norm(s):  # max over cuts of rank/ceiling
    return max(r / c for r, c in s.values())

def run_p(p, seed, nrand):
    rng = random.Random(seed * 1000003 + p)
    xs, N, ab = cyclic_curve(p, rng)
    fb = set(range(p // 4))
    kx = {}
    for k in range(1, N): kx.setdefault(xs[k], k)
    X = sorted(kx); n = (p - 1).bit_length()
    inFB = [False] * N
    for k in range(1, N): inFB[k] = xs[k] in fb
    pairs = []
    for x1 in X:
        k1 = kx[x1]
        for x2 in X:
            k2 = kx[x2]
            if inFB[(k1 + k2) % N] or inFB[(k1 - k2) % N]: pairs.append((x1, x2))
    res = {"p": p, "N": N, "curve_ab": ab, "n_bits": n, "npts_x": len(X), "ones": len(pairs)}
    lab = {x: x for x in X}
    res["x"] = stat(pairs, n, len(X))
    rn = []
    for t in range(nrand):
        r2 = random.Random(seed * 7919 + p * 31 + t)
        perm = r2.sample(range(1 << n), len(X)); lab = dict(zip(X, perm))
        rn.append(stat([(lab[a], lab[b]) for a, b in pairs], n, len(X)))
    res["random"] = rn
    lab = {x: min(kx[x], N - kx[x]) for x in X}
    res["dl"] = stat([(lab[a], lab[b]) for a, b in pairs], n, len(X))
    res["x_norm"] = norm(res["x"]); res["rand_norm"] = [norm(s) for s in rn]
    res["dl_norm"] = norm(res["dl"])
    return res

def positive_control(n=8):
    s = 1 << n
    ones = [(i, j) for i in range(s) for j in range(s) if ((i >> (n - 1)) ^ (j >> (n - 1)) ^ ((i ^ j) & 1)) & 1]
    low = stat(ones, n, s)
    r = random.Random(5); perm = r.sample(range(s), s)
    rel = stat([(perm[i], perm[j]) for i, j in ones], n, s)
    return {"structured": low, "relabelled": rel,
            "pass": max(rr for rr, _ in low.values()) <= 4 and min(rr for rr, _ in rel.values()) >= 3 * max(rr for rr, _ in low.values())}

def main():
    smoke = "--smoke" in sys.argv
    t0 = time.time(); seed = 20261110
    ps = [61] if smoke else [127, 251, 509, 1021]
    nrand = 2 if smoke else 4
    rows = [run_p(p, seed, nrand) for p in ps]
    pc = positive_control(6 if smoke else 8)
    aa = []; dev = []
    for r in rows:
        mean = sum(r["rand_norm"]) / len(r["rand_norm"])
        dev.append(abs(r["x_norm"] - mean))
        aa.append(max(r["rand_norm"]) - min(r["rand_norm"]))
    big = rows[-1]
    x_high = all(r["x_norm"] >= 0.85 for r in rows[1:]) if not smoke else True
    x_match = all(d <= 0.03 for d in dev[1:]) if not smoke else True
    aa_ok = all(a <= 0.03 for a in aa[1:]) if not smoke else True
    dl_low = big["dl_norm"] <= 0.35 * min(1.0, big["x_norm"]) if not smoke else True
    if not pc["pass"] or not aa_ok: verdict = "inconclusive"
    elif any(r["x_norm"] <= 0.8 * sum(r["rand_norm"]) / len(r["rand_norm"]) for r in rows[1:]) and not smoke: verdict = "falsified"
    elif x_high and x_match and dl_low: verdict = "consistent_with_prediction"
    else: verdict = "inconclusive"
    print(json.dumps({"lead": "LEAD-EXO-holant-decomposition-count-network", "smoke": smoke, "seed": seed,
        "primes": ps, "n_random_relabels": nrand, "fb_rule": "x < p//4", "field": "GF(2) rank, cuts near middle",
        "rows": rows, "positive_control": pc, "x_vs_randmean_abs_dev": dev, "aa_spread": aa,
        "checks": {"x_high": x_high, "x_match": x_match, "aa_ok": aa_ok, "dl_low": dl_low, "pos_ctrl": pc["pass"]},
        "elapsed_s": round(time.time() - t0, 2), "verdict": verdict}, default=str))
    return 0

if __name__ == "__main__":
    sys.exit(main())
