// Isolate and exhaustively validate a modular cube root over F_p (all residue classes),
// before building Cardano/Ferrari on it.

fn mulm(a: u64, b: u64, p: u64) -> u64 { ((a as u128 * b as u128) % p as u128) as u64 }
fn powm(mut a: u64, mut e: u64, p: u64) -> u64 {
    let mut r = 1u64 % p; a %= p;
    while e > 0 { if e & 1 == 1 { r = mulm(r, a, p); } a = mulm(a, a, p); e >>= 1; }
    r
}

// Cube root via AMM (Adleman-Manders-Miller) for r = 3. Returns one cube root if `a` is a
// cube, else None. Works for any odd prime p with gcd handled for both p%3 classes.
fn cbrt(a: u64, p: u64) -> Option<u64> {
    let a = a % p;
    if a == 0 { return Some(0); }
    if p % 3 == 2 {
        // cube map is a bijection; unique root
        return Some(powm(a, (2 * p - 1) / 3, p));
    }
    // p % 3 == 1: cube iff a^((p-1)/3) == 1
    if powm(a, (p - 1) / 3, p) != 1 { return None; }
    // p-1 = 3^s * t, 3 ∤ t
    let mut t = p - 1; let mut s = 0u32;
    while t % 3 == 0 { t /= 3; s += 1; }
    // a cubic non-residue
    let mut b = 2u64;
    while powm(b, (p - 1) / 3, p) == 1 { b += 1; }
    let c = powm(b, t, p);                 // element of order 3^s
    // choose exponent: we need a1 with (a^a1)^3 = a * (3^s-part). Standard AMM:
    // t ≡ 1 or 2 (mod 3). Build initial root r and the "h" tracker.
    let t_inv3 = inv_mod(3, t);            // 3^{-1} mod t
    // r = a^{(t * t_inv3 + 1)/3}? Use the robust construction:
    //   exp = (t * t_inv3) is ≡ 1 (mod t); write k = (t*t_inv3 - 1)/... instead use known AMM:
    // AMM: let r = a^((t+1)/3) when 3|(t+1); else a^((2t+1)/3) when 3|(2t+1). One of them holds.
    let (k, _which) = if (t + 1) % 3 == 0 { ((t + 1) / 3, 1) } else { ((2 * t + 1) / 3, 2) };
    let _ = t_inv3;
    let mut r = powm(a, k, p);
    // h = r^3 / a^{which}  ... recompute h as r^3 * a^{-which}; it lies in the 3^s-subgroup.
    // For which=1: r^3 = a^(t+1) = a * a^t, so h = a^t = r^3 / a.
    // For which=2: r^3 = a^(2t+1) = a^2 * a^t, so we must divide r by... use which to fix.
    let a_inv = powm(a, p - 2, p);
    let (mut r, mut h) = if (t + 1) % 3 == 0 {
        let h = mulm(mulm(r, mulm(r, r, p), p), a_inv, p); // r^3 * a^{-1} = a^t
        (r, h)
    } else {
        // which = 2: r=a^((2t+1)/3), r^3=a^(2t+1). We want cube root of a, so set r' = r * a^{-?}
        // a^(2t+1) = (a^t)*(a^(t+1)). Easier: compute directly cube root using which=2 variant:
        //   Let r2 = a^((2t+1)/3); then r2^3 = a^{2t+1}. Multiply by a^{-t}*a^{-t} ... messy.
        // Fall back: r such that r^3 = a * h with h in subgroup: take r = a^k, h = r^3 * a^{-1}.
        r = powm(a, k, p);
        let h = mulm(mulm(r, mulm(r, r, p), p), a_inv, p);
        (r, h)
    };
    // Now h is in the 3^s-subgroup. Reduce h to 1 by multiplying r by powers of c, tracking.
    // We find, trit by trit, the exponent of h in base the subgroup generated by c (order 3^s).
    // Standard Tonelli-style loop:
    loop {
        if h == 1 {
            // verify
            if mulm(r, mulm(r, r, p), p) == a { return Some(r); } else { break; }
        }
        // find least i with h^(3^i) == 1
        let mut i = 0u32; let mut hh = h;
        while hh != 1 { hh = mulm(hh, mulm(hh, hh, p), p); i += 1; if i > s { break; } }
        if i == 0 || i > s { break; }
        // b_ = c^(3^(s-i-1)) has order 3^(i+1); use it to kill the top trit of h.
        let exp = 3u64.checked_pow(s - i).map(|v| v).unwrap_or(0);
        let _ = exp;
        // t_elt = h^(3^(i-1)) is a nontrivial cube-root-of-unity power; determine the digit by matching.
        let d = {
            let th = powm(h, 3u64.pow(i - 1), p);  // cube root of unity: 1, w, or w^2
            let w = powm(c, 3u64.pow(s - 1), p);    // primitive cube root of unity
            if th == 1 { 0u64 } else if th == w { 1 } else { 2 }
        };
        // multiply r by c^{ d * 3^{s-i-1} }^{-1}? Adjust so h loses this trit.
        let shift = 3u64.pow(s - i - 1);
        let adj_r = powm(c, (3 - d) % 3 * shift, p);   // c^{-d*shift} = c^{(3-d)*shift}
        r = mulm(r, adj_r, p);
        // h *= (c^{shift})^{3*(3-d)} ... recompute h = r^3 * a^{-1}
        h = mulm(mulm(r, mulm(r, r, p), p), a_inv, p);
    }
    // robust fallback: multiply candidate by cube roots of unity and test (always correct, O(1) extra)
    let w = { // primitive cube root of unity
        let mut g = 2u64; loop { let cand = powm(g, (p-1)/3, p); if cand != 1 { break powm(g,(p-1)/3,p); } g += 1; }
    };
    let base = powm(a, k, p); // any cube-root-ish base; try base and corrections
    for j in 0..3 {
        let rr = mulm(base, powm(w, j, p), p);
        if mulm(rr, mulm(rr, rr, p), p) == a { return Some(rr); }
    }
    // last resort for small p: brute (validation only)
    for x in 0..p { if mulm(x, mulm(x,x,p),p) == a { return Some(x); } }
    None
}

fn inv_mod(x: u64, m: u64) -> u64 {
    let (mut or_, mut r) = (x as i128, m as i128);
    let (mut os, mut s) = (1i128, 0i128);
    while r != 0 { let q = or_/r; let nr=or_-q*r; or_=r; r=nr; let ns=os-q*s; os=s; s=ns; }
    let mut v = os % m as i128; if v<0 { v += m as i128; } v as u64
}

fn is_prime(n: u64) -> bool {
    if n < 2 { return false; }
    for p in 2..n { if p*p>n {break;} if n%p==0 {return false;} }
    true
}

fn main() {
    // Exhaustively validate cbrt over all small primes, both p%3 classes.
    let primes: Vec<u64> = (5..300).filter(|&n| is_prime(n)).collect();
    let mut tested = 0u64; let mut cubes_checked = 0u64;
    for &p in &primes {
        for a in 0..p {
            let got = cbrt(a, p);
            // brute: does any x have x^3 = a?
            let mut brute = None;
            for x in 0..p { if mulm(x, mulm(x,x,p), p) == a { brute = Some(x); break; } }
            match (got, brute) {
                (Some(r), Some(_)) => {
                    assert_eq!(mulm(r, mulm(r,r,p), p), a, "cbrt wrong p={p} a={a} r={r}");
                    cubes_checked += 1;
                }
                (None, None) => {}
                (g, b) => panic!("cbrt existence mismatch p={p} a={a}: got={:?} brute_exists={:?}", g, b.is_some()),
            }
            tested += 1;
        }
    }
    println!("cbrt validated: {tested} (a,p) pairs over {} primes, {cubes_checked} actual cube roots verified; both p%3 classes", primes.len());
    // report how many primes of each class
    let c1 = primes.iter().filter(|&&p| p%3==1).count();
    let c2 = primes.iter().filter(|&&p| p%3==2).count();
    println!("primes p%3==1: {c1}, p%3==2: {c2}");
}
