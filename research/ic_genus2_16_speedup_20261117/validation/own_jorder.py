#!/usr/bin/env python3
"""Check 2, second stage: pin #J(F_p) with the validator's own code for
instances where check_orders.py left more than one own candidate.

Method (own arithmetic; PARI's #J is used only as a hint to find element
orders, every order is re-verified by own Cantor arithmetic):
  1. own candidates C = {N in the Hasse-Weil window, consistent with own exact
     a_1..a_K (+ Weil bounds), with own Hasse-Witt L(1) mod p, and divisible
     by e' = lcm of own-verified element orders}  (as in check_orders.py);
  2. M = lcm(C) kills J(F_p) (the true #J is in C);
  3. for every prime l | M: the l-Sylow subgroup S_l is generated by
     [M / l^v] D_i for T random D_i; |S_l| by explicit closure (small l) or,
     when l^2 exceeds the window top, |S_l| = l iff some projection != 0;
  4. #J_own = prod |S_l|  (the order of a subgroup, so it divides #J; equal
     to #J unless the T random elements fail to generate an l-Sylow).
Then #J_own is compared with PARI's #J and must lie in C.

usage: venv/bin/python own_jorder.py p,g,cs [p,g,cs ...]
"""
import math
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from check_orders import ENUM_LIMIT, hw_window, instances, own_candidates, pari_charpoly  # noqa: E402
from hyperell import (HCurve, charpoly_mod_p, count_points_ext, element_order, factor,  # noqa: E402
                      hasse_witt, lpoly_from_counts)

T = 40


def key(D):
    return (tuple(D[0]), tuple(D[1]))


def subgroup_order(C, gens, cap):
    H = {key(C.zero): C.zero}
    for x in gens:
        if key(x) in H:
            continue
        # m = smallest k > 0 with k x in H
        cosets = [list(H.values())]
        kx = x
        while key(kx) not in H:
            cosets.append([C.add(h, kx) for h in cosets[0]])
            kx = C.add(kx, x)
            if sum(len(c) for c in cosets) > cap:
                raise RuntimeError("subgroup exceeds cap")
        H = {key(e): e for c in cosets for e in c}
    return len(H)


def main():
    inst, _, _ = instances()
    for arg in sys.argv[1:]:
        p, g, cs = (int(x) for x in arg.split(","))
        rec = inst[(p, g, cs)]
        f = rec["f"]
        rng = random.Random(1000 * p + 10 * g + cs)
        C = HCurve(f, p)
        chi = pari_charpoly(f, p)
        J_pari = sum(chi)
        N = []
        k = 1
        while k <= g and p ** k <= ENUM_LIMIT:
            N.append(count_points_ext(f, p, k, rng=random.Random(k)))
            k += 1
        a_own, _ = lpoly_from_counts(N, p, g)
        cp = charpoly_mod_p(hasse_witt(f, p, g), p)
        hw_a = [cp[g - i] % p for i in range(1, g + 1)]
        Jf = list(factor(J_pari))
        rand = [C.random_element(rng, parts=4) for _ in range(T)]
        eprime = 1
        for D in rand[:16]:
            o = element_order(C, D, J_pari, Jf)  # asserts [J_pari] D = 0
            eprime = eprime * o // math.gcd(eprime, o)
        lo, hi, cands = own_candidates(p, g, a_own, hw_a, eprime)
        assert 0 < len(cands) <= 50
        M = 1
        for n in cands:
            M = M * n // math.gcd(M, n)
        sizes = {}
        for ell, v in sorted(factor(M).items()):
            cof = M // ell ** v
            proj = [C.mul(cof, D) for D in rand]
            if ell * ell > hi:
                sizes[ell] = ell if any(not C.is_zero(x) for x in proj) else 1
            else:
                sizes[ell] = subgroup_order(C, proj, cap=10 ** 6)
        J_own = math.prod(sizes.values())
        print(f"p={p} g={g} curve={cs}: own candidates={len(cands)} {cands}; e'={eprime}; "
              f"Sylow sizes={ {l: s for l, s in sizes.items() if s > 1} }; #J_own={J_own}; #J_pari={J_pari}; "
              f"own in candidates={J_own in cands}; equal={J_own == J_pari}; record order={rec['order']} r={rec['r']} "
              f"r|#J_own={J_own % rec['r'] == 0}", flush=True)


if __name__ == "__main__":
    main()
