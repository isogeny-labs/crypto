#!/usr/bin/env python3
"""See PROTOCOL.md. Stdlib only. Run: python3 -I descent_class.py"""
import json, random, sys

K = 20
def is_prime(n):
    if n < 2: return False
    for q in (2, 3, 5, 7, 11, 13):
        if n % q == 0: return n == q
    d, s = n - 1, 0
    while d % 2 == 0: d //= 2; s += 1
    for a in (2, 3, 5, 7, 11, 13, 17):
        x = pow(a, d, n)
        if x in (1, n - 1): continue
        for _ in range(s - 1):
            x = x * x % n
            if x == n - 1: break
        else: return False
    return True

p = (1 << K) - 1
while not (p % 8 == 5 and is_prime(p)): p -= 1
chi = bytearray(p)                       # chi[v] = 0 (v=0), 1 (square), 2 (nonsquare)
for y in range(1, p): chi[y * y % p] = 1
for v in range(1, p):
    if chi[v] == 0: chi[v] = 2
def leg(v):
    v %= p
    return 0 if v == 0 else (1 if chi[v] == 1 else -1)

def order(A):                            # #E(F_p) for y^2 = x^3 + A x^2 + x
    s = p + 1
    for x in range(p):
        s += leg(x * x % p * x + A * x * x + x)
    return s

A = 6
while True:
    if leg(A * A - 4) == -1:
        n = order(A); nt = 2 * p + 2 - n
        if n % 8 == 0 and nt % 4 == 0 and is_prime(n // 8) and is_prime(nt // 4) and n // 8 > (1 << (K - 3)):
            break
    A += 4
r = n // 8
print("p=%d A=%d n=%d r=%d" % (p, A, n, r))

# Montgomery arithmetic on y^2 = x^3 + A x^2 + x (affine, B = 1); None = infinity
inv = lambda v: pow(v, p - 2, p)
def add(P, Q):
    if P is None: return Q
    if Q is None: return P
    x1, y1 = P; x2, y2 = Q
    if x1 == x2:
        if (y1 + y2) % p == 0: return None
        lam = (3 * x1 * x1 + 2 * A * x1 + 1) * inv(2 * y1) % p
    else:
        lam = (y2 - y1) * inv(x2 - x1) % p
    x3 = (lam * lam - A - x1 - x2) % p
    return (x3, (lam * (x1 - x3) - y1) % p)
def neg(P): return None if P is None else (P[0], (-P[1]) % p)
def mul(P, k):
    R = None
    while k:
        if k & 1: R = add(R, P)
        P = add(P, P); k >>= 1
    return R
def sqrt(v):                             # p = 5 mod 8
    v %= p
    if v == 0: return 0
    if leg(v) != 1: return None
    y = pow(v, (p + 3) // 8, p)
    return y if y * y % p == v else y * pow(2, (p - 1) // 4, p) % p
def rhs(x): return (x * x * x + A * x * x + x) % p
def point(x):
    y = sqrt(rhs(x)); return None if y is None else (x, y)
def delta(P):                            # x_M mod squares; (0,0) -> class of the other factor
    if P is None: return 1
    return leg(P[0]) if P[0] != 0 else leg(A * A - 4)

rnd = random.Random(20261111)
# 1. construction
order2 = [x for x in range(p) if rhs(x) == 0]
print("rational 2-torsion abscissae:", order2)
while True:
    x = rnd.randrange(1, p); P = point(x)
    if P and mul(P, n) is None and mul(mul(P, 8), r) is None: break
cof = mul(P, r)                          # in E[8]
G = mul(P, 8)                            # order r (or 1)
assert G is not None and mul(G, r) is None
e8 = [mul(cof, i) for i in range(8)]
# generator of E[8]: find point of order exactly 8
while True:
    x = rnd.randrange(1, p); Q = point(x)
    if Q:
        T = mul(Q, r)
        if T and mul(mul(T, 4), 1) is not None and mul(T, 8) is None: break
E8 = [mul(T, i) for i in range(8)]
print("cyclic E[8] generated by a point of order 8:", len({str(t) for t in E8}) == 8)
# 2. homomorphism
bad = 0
for _ in range(2000):
    A1 = point(rnd.randrange(1, p)); B1 = point(rnd.randrange(1, p))
    if A1 and B1 and delta(add(A1, B1)) != delta(A1) * delta(B1): bad += 1
print("homomorphism violations in 2000 pairs:", bad)
print("delta on E[8] generator:", delta(T), "; delta(G)=", delta(G))
shift = A * inv(3) % p                   # x_W = x_M + A/3
res = {"p": p, "A": A, "r": r, "hom_violations": bad}
TS = tuple(int(a) for a in sys.argv[1].split(",")) if len(sys.argv) > 1 else (5, 6)
OUT = sys.argv[2] if len(sys.argv) > 2 else "results.json"
for t in TS:
    base = []
    for xw in range(1 << t):
        xm = (xw - shift) % p
        P = point(xm)
        if P: base.append(P)             # one abscissa per +-P pair
    cls = [delta(P) for P in base]
    plus, minus = cls.count(1), cls.count(-1)
    print("t=%d base abscissae=%d delta=+1:%d delta=-1:%d" % (t, len(base), plus, minus))
    # 4. exact pair hits
    signed = []
    for P in base: signed += [P, neg(P)]
    pair = {}
    for i, a in enumerate(signed):
        for b in signed[i:]:
            pair.setdefault(add(a, b), []).append((a, b))
    hits = {1: 0, -1: 0}; viol = 0; lifts_hit = {1: 0, -1: 0}
    pc = {1: 0, -1: 0}
    for (key, lst) in pair.items():
        for (a, b) in lst:
            pc[delta(add(a, b))] = pc.get(delta(add(a, b)), 0) + 1
    ntar = 200
    for _ in range(ntar):
        R = mul(G, rnd.randrange(1, r))
        for K8 in E8:
            RK = add(R, K8)
            for (a, b) in pair.get(RK, []):
                if delta(add(a, b)) != delta(RK): viol += 1
                hits[delta(RK)] += 1
    # all lifts of a target: 4 with delta +1, 4 with -1
    print("t=%d hits over %d targets x 8 lifts: delta(R+K)=+1:%d  delta(R+K)=-1:%d ; identity violations: %d"
          % (t, ntar, hits[1], hits[-1], viol))
    print("t=%d pair sums by delta: +1:%d  -1:%d" % (t, pc[1], pc[-1]))
    res["t%d" % t] = {"base": len(base), "plus": plus, "minus": minus, "hits_plus": hits[1],
                      "hits_minus": hits[-1], "violations": viol, "pair_sums_plus": pc[1], "pair_sums_minus": pc[-1]}
json.dump(res, open(OUT, "w"), indent=1, sort_keys=True)
