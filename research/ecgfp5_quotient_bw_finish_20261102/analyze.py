#!/usr/bin/env python3
"""Frozen analysis (PROTOCOL.md §7): reads results/m5_p*/ and W0's merged analysis.json only.

Writes analysis.json, analysis.md and figures/bw_finish.{svg,png}.
"""
import json
import math
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
W0 = json.loads((HERE.parent / "ecgfp5_quotient_solve_20261101" / "analysis.json").read_text())
PRIMES = [4111, 262231, 33554371]
CLOCK = 2.8e9
CLOSE, PROMOTE = 46.0, 38.0
PRED = {4111: (11500, 3900, 15500), 262231: (14100, 3900, 18100), 33554371: (16400, 7400, 23900)}


def lg(cpu):
    return math.log2(cpu * CLOCK)


def g1(c):
    lo, hi = lg(c / 4), lg(4 * c)
    point = "CLOSE" if lg(c) >= CLOSE else ("PROMOTE" if lg(c) <= PROMOTE else "not_measured")
    if lo >= CLOSE:
        band = "CLOSE"
    elif hi <= PROMOTE:
        band = "PROMOTE"
    elif lo > PROMOTE and hi < CLOSE:
        band = "not_measured"
    else:
        band = "straddling"
    return point, band, lo, hi


def hnf_cpu(log):
    tot = 0.0
    for ph in ("parse_gb", "staircase", "dump_P"):
        m = re.search(rf"\[hnfsolve\] {ph}: [\d.]+ s wall, ([\d.]+) s cpu", log)
        if not m:
            raise SystemExit(f"dump.log lacks {ph}")
        tot += float(m.group(1))
    st = re.search(r"stab_fail=(\d+) maxchain=(\d+)", log)
    return tot, int(st.group(1)), int(st.group(2))


cells = []
for p in PRIMES:
    d = HERE / "results" / f"m5_p{p}"
    ex = dict(l.split("=", 1) for l in (d / "exit_codes.txt").read_text().split())
    ms = json.loads((d / "msolve.run.json").read_text())
    bw = json.loads((d / "bw.json").read_text())
    hcpu, stab_fail, maxchain = hnf_cpu((d / "dump.log").read_text())
    ms_cpu = ms["user_seconds"] + ms["sys_seconds"]
    fin = bw["total_cpu_s"]
    c_new = ms_cpu + hcpu + fin
    w0 = W0["phase_split"][f"m5_p{p}"]
    gates = {
        "exits_zero": all(ex[k] == "0" for k in ("msolve_exit", "hnfsolve_exit", "bwfinish_exit")),
        "a_eliminant_equals_w0": ex.get("eliminant_equals_w0") == "true",
        "b_planted_recovered": bw["planted"] == "recovered",
        "c_D_and_stability": bw["D"] == 65536 and bw["elim_degree"] == 65536 and stab_fail == 0,
        "no_cap_stop": not (ms["killed_by_rss_cap"] or ms["killed_by_wall_cap"]),
    }
    valid = all(gates.values())
    bar = w0["solve_cpu_s"] / 1.5
    point, band, lo, hi = g1(c_new)
    aa = (ms_cpu - w0["f4_cpu_s"]) / w0["f4_cpu_s"]
    pm, pf, pc = PRED[p]
    cells.append({
        "p": p, "valid": valid, "gates": gates,
        "t": bw["t"], "D": bw["D"], "b": bw["b"], "limbs": bw["limbs"], "L": bw["L"],
        "max_chain": maxchain, "rational_roots": bw["rational_roots"],
        "msolve_cpu_s": round(ms_cpu, 1), "msolve_wall_s": ms["wall_seconds"],
        "msolve_maxrss_gib": round(ms["maxrss_kib"] / 2**20, 2),
        "hnfsolve_cpu_s": round(hcpu, 1),
        "finish_cpu_s": round(fin, 1), "finish_maxrss_gib": round(bw["maxrss_kib"] / 2**20, 2),
        "finish_phases_cpu_s": {k: v["cpu_s"] for k, v in bw["phases"].items()},
        "c_new_cpu_s": round(c_new, 1), "log2_c_cyc": round(lg(c_new), 3),
        "W0_solve_cpu_s": w0["solve_cpu_s"], "W0_f4_cpu_s": w0["f4_cpu_s"],
        "W0_log2_c_cyc": round(lg(w0["solve_cpu_s"]), 3),
        "W0_finish_cpu_s": round(w0["solve_cpu_s"] - w0["f4_cpu_s"], 1),
        "speedup_vs_W0": round(w0["solve_cpu_s"] / c_new, 3),
        "finish_speedup_vs_W0_change_of_order": round((w0["solve_cpu_s"] - w0["f4_cpu_s"]) / (hcpu + fin + ms_cpu - w0["f4_cpu_s"]), 3),
        "bar_cpu_s": round(bar, 1), "improvement": valid and c_new <= bar,
        "aa_msolve_vs_W0_f4": round(aa, 4), "aa_flag_host_drift": abs(aa) > 0.25,
        "g1_point": point, "g1_band": band, "band_log2": [round(lo, 2), round(hi, 2)],
        "distance_to_promote_bits": round(lg(c_new) - PROMOTE, 3),
        "pred_c_new": pc, "pred_finish": pf,
        "finish_vs_pred": round(fin / pf - 1, 4), "finish_prediction_failure": abs(fin / pf - 1) > 0.30,
    })

out = {
    "unit": "CPU-s; c_cyc = CPU-s x 2.8e9",
    "thresholds_log2_c_cyc": {"CLOSE": CLOSE, "PROMOTE": PROMOTE},
    "cells": cells,
    "pipeline_improvement": all(c["improvement"] for c in cells),
}
(HERE / "analysis.json").write_text(json.dumps(out, indent=1) + "\n")

L = ["# Analysis (generated by analyze.py; do not edit)", "",
     "| p | valid | msolve CPU-s | hnfsolve | finish | c_new | log2 c_cyc | W0 | speed-up | bar | improvement | G1 (band) | A/A | finish vs pred |",
     "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---|---|---:|---:|"]
for c in cells:
    L.append(f"| {c['p']} | {c['valid']} | {c['msolve_cpu_s']:,.0f} | {c['hnfsolve_cpu_s']:,.0f} | {c['finish_cpu_s']:,.0f} | "
             f"{c['c_new_cpu_s']:,.0f} | {c['log2_c_cyc']:.2f} | {c['W0_solve_cpu_s']:,.0f} | {c['speedup_vs_W0']:.2f}x | "
             f"{c['bar_cpu_s']:,.0f} | {c['improvement']} | {c['g1_point']} ({c['g1_band']}) | "
             f"{100*c['aa_msolve_vs_W0_f4']:+.1f}% | {100*c['finish_vs_pred']:+.1f}% |")
L += ["", f"Pipeline improvement (all three primes): {out['pipeline_improvement']}", ""]
(HERE / "analysis.md").write_text("\n".join(L))

# Figure
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

FIG = HERE / "figures"
FIG.mkdir(exist_ok=True)
fig, (a, b) = plt.subplots(1, 2, figsize=(13, 5.2))
x = range(len(cells))
lab = [f"p = {c['p']}" for c in cells]
w = 0.36
a.bar([i - w / 2 for i in x], [c["W0_f4_cpu_s"] for c in cells], w, color="#9ecae1", label="W0: F4")
a.bar([i - w / 2 for i in x], [c["W0_finish_cpu_s"] for c in cells], w, bottom=[c["W0_f4_cpu_s"] for c in cells],
      color="#3182bd", label="W0: change of order + RUR")
a.bar([i + w / 2 for i in x], [c["msolve_cpu_s"] for c in cells], w, color="#fdae6b", label="new: F4 + basis print")
a.bar([i + w / 2 for i in x], [c["hnfsolve_cpu_s"] + c["finish_cpu_s"] for c in cells], w,
      bottom=[c["msolve_cpu_s"] for c in cells], color="#e6550d", label="new: chain dump + block Wiedemann")
for i, c in enumerate(cells):
    a.plot([i - 0.45, i + 0.45], [c["bar_cpu_s"]] * 2, "k--", lw=1, label="improvement bar (W0/1.5)" if i == 0 else None)
    a.text(i + w / 2, c["c_new_cpu_s"] * 1.01, f"{c['speedup_vs_W0']:.2f}x", ha="center", va="bottom", fontsize=8)
a.set_xticks(list(x), lab)
a.set_ylabel("whole-solve CPU-s (4 threads)")
a.set_title("(a) whole-solve CPU-s, W0 vs block-Wiedemann finish", fontsize=10)
a.legend(fontsize=7, frameon=False, loc="upper left")

for i, c in enumerate(cells):
    lo, hi = c["band_log2"]
    b.plot([i, i], [lo, hi], color="#e6550d", lw=6, alpha=0.35)
    b.plot(i, c["log2_c_cyc"], "o", color="#e6550d", label="new c_cyc [c/4, 4c]" if i == 0 else None)
    b.plot(i, c["W0_log2_c_cyc"], "s", color="#3182bd", mfc="white", label="W0 c_cyc" if i == 0 else None)
b.axhline(CLOSE, color="k", lw=1)
b.axhline(PROMOTE, color="k", lw=1, ls=":")
b.text(len(cells) - 0.5, CLOSE + 0.1, "CLOSE 2^46", fontsize=8, ha="right")
b.text(len(cells) - 0.5, PROMOTE + 0.1, "PROMOTE 2^38", fontsize=8, ha="right")
b.set_xticks(list(x), lab)
b.set_xlim(-0.5, len(cells) - 0.5)
b.set_ylabel("log2 c_cyc")
b.set_title("(b) G1 position and distance to the PROMOTE bar", fontsize=10)
b.legend(fontsize=7, frameon=False, loc="center left")
fig.suptitle("EcGFp5 m = 5 quotient: block-Wiedemann finish on the BNS22 chain matrix (frozen cells)", fontsize=11)
fig.tight_layout()
fig.savefig(FIG / "bw_finish.svg")
fig.savefig(FIG / "bw_finish.png", dpi=150)
print((HERE / "analysis.md").read_text())
