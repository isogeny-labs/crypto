// Evaluate the registered tests of PROTOCOL.md section 3 from the recorded sessions.
//   node analysis/evaluate.mjs <ecbench binary> <sessions dir> <out dir>      (cwd = study directory)
// Ratios, intervals and band means come from `ecbench compare` and `ecbench band`; this script only selects and tabulates.
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync, readFileSync } from "node:fs";
import { ROWS } from "../rows.mjs";

const [bin, sess, out] = process.argv.slice(2);
mkdirSync(out, { recursive: true });
const W = [0, 0.1, 1], K = [5, 4], CAND = ["ps", "pr", "psr"];
const run = (args) => execFileSync(bin, args, { encoding: "utf8", maxBuffer: 1 << 28 });
const json = (args) => JSON.parse(run([...args, "--json"]));
const dirs = (id) => [1, 2, 3].map((r) => `${sess}/${id}-r${r}`);
const bandOf = (ds) => { const f = `${out}/.band.json`; run(["band", "--dir", ...ds, "--json", f]);
  return Object.fromEntries(JSON.parse(readFileSync(f, "utf8")).rows.map((r) => [r.arm, r])); };
// ratio = cost(b)/cost(a), paired by target and round.
const cmp = (ds, a, b, w) => {
  const j = json(["compare", "--dir", ...ds, "--a", a, "--b", b, "--weight", String(w), "--resamples", "4000", "--seed", "20261118"]);
  const o = j.ops ?? j, ci = o.ci95, cb = o.ci95_bootstrap;
  return { ratio: o.ratio_b_over_a, ci95: ci, ci95_bootstrap: cb, upper: Math.max(ci?.[1] ?? NaN, cb?.[1] ?? NaN), pairs: o.workloads, status: o.status };
};
const results = { schema: "ic_ksum_split.evaluation/v1", rows: [] };
for (const row of ROWS) {
  const ds = dirs(row.id), pooled = bandOf(ds);
  const r = { ...row, weights: {} };
  W.forEach((w, wi) => {
    const S = Object.fromEntries(Object.keys(pooled).map((a) => [a, pooled[a].mean_s[wi]]));
    const o = { S, aa: cmp(ds, "rho-neg", "rho-neg-aa", w), gap_to_rho: {} };
    for (const a of Object.keys(S)) if (a.startsWith("ksum")) o.gap_to_rho[a] = S[a] / S["rho-neg"];
    for (const k of K) for (const c of CAND) {
      const inc = `ksum${k}-p`, x = `ksum${k}-${c}`;
      o[x] = { ratio: cmp(ds, inc, x, w), per_replicate: ds.map((d) => cmp([d], inc, x, w)) };
    }
    for (const k of K) o[`ksum${k}-psr_over_pr`] = cmp(ds, `ksum${k}-pr`, `ksum${k}-psr`, w);
    // best against best: the cheaper incumbent and the cheaper combined arm by mean S at this weight.
    const inc = S["ksum4-p"] <= S["ksum5-p"] ? "ksum4-p" : "ksum5-p", cand = S["ksum4-psr"] <= S["ksum5-psr"] ? "ksum4-psr" : "ksum5-psr";
    o.best = { incumbent: inc, candidate: cand, ratio: cmp(ds, inc, cand, w), gap_incumbent: S[inc] / S["rho-neg"], gap_candidate: S[cand] / S["rho-neg"] };
    r.weights[w] = o;
  });
  const aaDev = Math.max(...W.map((w) => Math.abs(r.weights[w].aa.ratio - 1)));
  for (const k of K) for (const c of ["ps", "psr"]) {
    const x = `ksum${k}-${c}`;
    const upper = Math.max(...W.map((w) => r.weights[w][x].ratio.upper));
    const repUpper = Math.max(...W.flatMap((w) => r.weights[w][x].per_replicate.map((q) => q.upper)));
    r[x] = { max_upper_pooled: upper, max_upper_replicate: repUpper, aa_max_abs_dev: aaDev, holds: upper < 1 && repUpper < 1 && 1 - upper > aaDev };
  }
  results.rows.push(r);
}
for (const [tag, c] of [["split", "ps"], ["combined", "psr"]]) for (const k of K) {
  const x = `ksum${k}-${c}`;
  results[`${tag}${k}_holds_rows`] = results.rows.filter((r) => r[x].holds).map((r) => r.id);
  results[`${tag}${k}_holds_all_rows`] = results.rows.every((r) => r[x].holds);
}
writeFileSync(`${out}/results.json`, JSON.stringify(results, null, 1) + "\n");
const f = (x, d = 3) => (typeof x === "number" ? x.toFixed(d) : String(x));
const ci = (p) => `${f(p.ratio, 4)} [${f(p.ci95?.[0], 4)}, ${f(p.ci95?.[1], 4)}]`;
let md = `# split / stride-renew evaluation (generated by analysis/evaluate.mjs from the recorded sessions) [pcc:unverified]\n\nRatios cost(X)/cost(ksum<k>-p), paired by target and round, \`ecbench compare\` (4,000 resamples, seed 20261118), 95 % interval.\n\n`;
for (const k of K) {
  md += `## k = ${k}\n\n| row | w | S ksum${k}-p | S -ps | S -pr | S -psr | -ps / -p | -pr / -p | -psr / -p | -psr per replicate | -psr / rho-neg | -p / rho-neg |\n|:--|--:|--:|--:|--:|--:|:--|:--|:--|:--|--:|--:|\n`;
  for (const r of results.rows) for (const w of W) { const x = r.weights[w], b = `ksum${k}`;
    md += `| ${w === 0 ? r.id : ""} | ${w} | ${f(x.S[b + "-p"])} | ${f(x.S[b + "-ps"])} | ${f(x.S[b + "-pr"])} | ${f(x.S[b + "-psr"])} | ${ci(x[b + "-ps"].ratio)} | ${ci(x[b + "-pr"].ratio)} | **${ci(x[b + "-psr"].ratio)}** | ${x[b + "-psr"].per_replicate.map((q) => f(q.ratio, 4)).join(" / ")} | ${f(x.gap_to_rho[b + "-psr"], 2)} | ${f(x.gap_to_rho[b + "-p"], 2)} |\n`; }
  md += `\n| row | -ps max upper (pooled / replicate) | -ps holds | -psr max upper (pooled / replicate) | -psr holds | A/A max dev |\n|:--|:--|:--|:--|:--|--:|\n`;
  for (const r of results.rows) { const a = r[`ksum${k}-ps`], b = r[`ksum${k}-psr`];
    md += `| ${r.id} | ${f(a.max_upper_pooled, 4)} / ${f(a.max_upper_replicate, 4)} | ${a.holds} | ${f(b.max_upper_pooled, 4)} / ${f(b.max_upper_replicate, 4)} | ${b.holds} | ${f(a.aa_max_abs_dev, 4)} |\n`; }
  md += `\n`;
}
md += `## Best against best (cheaper of k = 4, 5 by mean S at each weight)\n\n| row | w | incumbent | candidate | candidate / incumbent [95%] | gap to rho: incumbent | gap to rho: candidate |\n|:--|--:|:--|:--|:--|--:|--:|\n`;
for (const r of results.rows) for (const w of W) { const b = r.weights[w].best;
  md += `| ${w === 0 ? r.id : ""} | ${w} | ${b.incumbent} | ${b.candidate} | **${ci(b.ratio)}** | ${f(b.gap_incumbent, 2)} | ${f(b.gap_candidate, 2)} |\n`; }
writeFileSync(`${out}/results.md`, md); console.log(md);
