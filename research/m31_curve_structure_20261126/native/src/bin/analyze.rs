//! analyze <evidence_dir>: paired ratio-of-means with percentile bootstrap (10,000 resamples,
//! SplitMix64 seed 20261126), per protocol. Writes summary.json, summary.md and ../figures/ratios.svg.
use m31_structure_rho::splitmix;
use std::collections::BTreeMap;

fn field<'a>(line: &'a str, k: &str) -> &'a str {
    let pat = format!("\"{}\":", k);
    let i = line.find(&pat).unwrap_or_else(|| panic!("missing {}", k)) + pat.len();
    let rest = &line[i..];
    let end = rest.find(|c| c == ',' || c == '}').unwrap();
    rest[..end].trim_matches('"')
}
fn num(line: &str, k: &str) -> f64 {
    field(line, k).parse().unwrap()
}

#[derive(Clone, Default)]
struct Row {
    steps: f64,
    walk_mul: f64,
    total_mul: f64,
    wall: f64,
    walk_wall: f64,
    unpriced: f64, // canonicalisations + cycle checks + DP-table ops
    escapes: f64,
    rejects: f64,
}

type Key = (String, usize, String); // curve, W, arm

fn metric(r: &Row, m: &str, band: f64) -> f64 {
    match m {
        "steps" => r.steps + band * r.unpriced,
        "walk_mul" => r.walk_mul,
        "total_mul" => r.total_mul,
        "wall" => r.wall,
        "walk_wall" => r.walk_wall,
        _ => unreachable!(),
    }
}

fn ratio_ci(a: &[Row], b: &[Row], m: &str, band: f64, paired: bool) -> (f64, f64, f64) {
    let n = a.len().min(b.len());
    let mean = |v: &[Row], idx: &[usize]| idx.iter().map(|&i| metric(&v[i], m, band)).sum::<f64>() / idx.len() as f64;
    let all: Vec<usize> = (0..n).collect();
    let point = mean(a, &all) / mean(b, &all);
    let mut s = 20261126u64;
    let mut rs = Vec::with_capacity(10000);
    for _ in 0..10000 {
        let ia: Vec<usize> = (0..n).map(|_| (splitmix(&mut s) % n as u64) as usize).collect();
        let ib: Vec<usize> = if paired { ia.clone() } else { (0..n).map(|_| (splitmix(&mut s) % n as u64) as usize).collect() };
        rs.push(mean(a, &ia) / mean(b, &ib));
    }
    rs.sort_by(|x, y| x.partial_cmp(y).unwrap());
    (point, rs[249], rs[9749])
}

fn main() {
    let dir = std::env::args().nth(1).unwrap();
    let text = std::fs::read_to_string(format!("{}/panel.jsonl", dir)).unwrap();
    let mut cells: BTreeMap<Key, Vec<(usize, Row)>> = BTreeMap::new();
    let (mut nver, mut nall) = (0, 0);
    for line in text.lines() {
        nall += 1;
        if field(line, "verified") == "true"
            && field(line, "verify_jacobian_dG_eq_Q") == "true"
            && field(line, "verify_eq_evaluator_log") == "true"
        {
            nver += 1;
        }
        let arm = field(line, "arm_label").to_string();
        let canon = if field(line, "arm") == "plain" { 0.0 } else { num(line, "steps") + num(line, "accepted_steps") };
        let r = Row {
            steps: num(line, "steps"),
            walk_mul: num(line, "walk_mul") + num(line, "restart_mul"),
            total_mul: num(line, "total_mul"),
            wall: num(line, "wall_ms"),
            walk_wall: num(line, "walk_wall_ms"),
            unpriced: canon + num(line, "distinguished_points"),
            escapes: num(line, "cycle_escapes") + num(line, "restarts_cycle"),
            rejects: num(line, "lookahead_rejects"),
        };
        let key = (field(line, "curve").to_string(), num(line, "W") as usize, arm);
        cells.entry(key).or_default().push((num(line, "trial") as usize, r));
    }
    assert_eq!(nver, nall, "every row must verify");
    let get = |c: &str, w: usize, a: &str| -> Vec<Row> {
        let mut v = cells.get(&(c.to_string(), w, a.to_string())).unwrap().clone();
        v.sort_by_key(|x| x.0);
        v.into_iter().map(|x| x.1).collect()
    };
    // cell means
    let mut md = String::from("# Panel summary (generated by native/src/bin/analyze.rs)\n\n");
    md += &format!("Rows: {} (all verified three ways: engine affine check, independent Jacobian d*G == Q, evaluator log).\n\n", nall);
    md += "| curve | W, dp | arm | trials | mean steps | S = steps/sqrt(n) | walk mults/solve | total mults/solve | wall ms | fruitless escapes/solve | look-ahead rejects/solve |\n|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|\n";
    let order_n = |c: &str| match c {
        "B677" => 2147446831f64,
        "M31_minus3_21" => 2147487637f64,
        _ => 165188041f64,
    };
    let mut js_cells = vec![];
    for ((c, w, a), v) in &cells {
        let k = v.len() as f64;
        let m = |f: &dyn Fn(&Row) -> f64| v.iter().map(|x| f(&x.1)).sum::<f64>() / k;
        let st = m(&|r| r.steps);
        md += &format!(
            "| {} | {}, {} | {} | {} | {:.0} | {:.3} | {:.0} | {:.0} | {:.2} | {:.2} | {:.1} |\n",
            c, w, if *w == 64 { 5 } else { 3 }, a, v.len(), st, st / order_n(c).sqrt(), m(&|r| r.walk_mul), m(&|r| r.total_mul), m(&|r| r.wall), m(&|r| r.escapes), m(&|r| r.rejects)
        );
        js_cells.push(format!(
            "{{\"curve\":\"{}\",\"W\":{},\"arm\":\"{}\",\"trials\":{},\"mean_steps\":{:.1},\"S\":{:.4},\"mean_walk_mul\":{:.1},\"mean_total_mul\":{:.1},\"mean_wall_ms\":{:.3}}}",
            c, w, a, v.len(), st, st / order_n(c).sqrt(), m(&|r| r.walk_mul), m(&|r| r.total_mul), m(&|r| r.wall)
        ));
    }
    // comparisons: (label, curve, W, arm_a, arm_b, prediction)
    let comps: &[(&str, &str, usize, &str, &str, f64)] = &[
        ("B677 neg / plain", "B677", 64, "neg", "plain", 0.7071),
        ("B677 A/A neg_aa / neg", "B677", 64, "neg_aa", "neg", 1.0),
        ("M31(-3,21) neg / plain", "M31_minus3_21", 64, "neg", "plain", 0.7071),
        ("M31(-3,21) A/A", "M31_minus3_21", 64, "neg_aa", "neg", 1.0),
        ("j=0 neg / plain", "J0_b5_r", 64, "neg", "plain", 0.7071),
        ("j=0 A/A", "J0_b5_r", 64, "neg_aa", "neg", 1.0),
        ("j=0 aut6 / neg (W64)", "J0_b5_r", 64, "aut6", "neg", 0.5774),
        ("j=0 aut6 / plain (W64)", "J0_b5_r", 64, "aut6", "plain", 0.4082),
        ("j=0 aut6 / neg (W16, dp3)", "J0_b5_r", 16, "aut6", "neg", 0.5774),
    ];
    md += "\n## Paired ratios of means, 95% percentile bootstrap (10,000 resamples, paired by trial index)\n\n";
    md += "| comparison | prediction | group ops | band 0.1 GAE | band 1 GAE | walk field mults | total mults incl. setup | walk wall (indicative) | wall incl. setup (indicative) |\n|---|---:|---|---|---|---|---|---|---|\n";
    let mut js = vec![];
    let mut fig = vec![];
    for &(lab, c, w, a, b, pred) in comps {
        let (va, vb) = (get(c, w, a), get(c, w, b));
        let f = |m: &str, band: f64| ratio_ci(&va, &vb, m, band, true);
        let r = [f("steps", 0.0), f("steps", 0.1), f("steps", 1.0), f("walk_mul", 0.0), f("total_mul", 0.0), f("walk_wall", 0.0), f("wall", 0.0)];
        let s = |x: (f64, f64, f64)| format!("{:.3} [{:.3}, {:.3}]", x.0, x.1, x.2);
        md += &format!("| {} | {:.3} | {} | {} | {} | {} | {} | {} | {} |\n", lab, pred, s(r[0]), s(r[1]), s(r[2]), s(r[3]), s(r[4]), s(r[5]), s(r[6]));
        let names = ["steps", "steps_band_0.1", "steps_band_1", "walk_mul", "total_mul", "walk_wall_ms", "wall_ms"];
        let parts: Vec<String> = names.iter().zip(r.iter()).map(|(n, x)| format!("\"{}\":[{:.4},{:.4},{:.4}]", n, x.0, x.1, x.2)).collect();
        js.push(format!("{{\"comparison\":\"{}\",\"prediction\":{},\"pairs\":{},{}}}", lab, pred, va.len().min(vb.len()), parts.join(",")));
        fig.push((lab.to_string(), pred, r[0], r[3]));
    }
    // cross-curve, unpaired: best structural arm on the j=0 class vs negation rho on B677
    let cross = ratio_ci(&get("J0_b5_r", 64, "aut6"), &get("B677", 64, "neg"), "walk_mul", 0.0, false);
    let cross_s = ratio_ci(&get("J0_b5_r", 64, "aut6"), &get("B677", 64, "neg"), "steps", 0.0, false);
    md += &format!(
        "\nCross-curve (unpaired, different groups): j=0 aut6 (r = 165188041) / B677 neg: steps {:.3} [{:.3}, {:.3}], walk mults {:.3} [{:.3}, {:.3}]. This mixes the order-6 automorphism factor with the 13x smaller prime subgroup; it is not a B677 speedup.\n",
        cross_s.0, cross_s.1, cross_s.2, cross.0, cross.1, cross.2
    );
    std::fs::write(format!("{}/summary.md", dir), md).unwrap();
    std::fs::write(
        format!("{}/summary.json", dir),
        format!(
            "{{\"rows\":{},\"verified\":{},\"cells\":[{}],\"comparisons\":[{}],\"cross_curve_j0_aut6_over_B677_neg\":{{\"steps\":[{:.4},{:.4},{:.4}],\"walk_mul\":[{:.4},{:.4},{:.4}]}}}}\n",
            nall, nver, js_cells.join(","), js.join(","), cross_s.0, cross_s.1, cross_s.2, cross.0, cross.1, cross.2
        ),
    )
    .unwrap();
    // figure: horizontal dot-and-interval chart, two metrics, log-free linear axis 0..1.3
    let (w, rowh, left, top) = (860.0, 34.0, 250.0, 60.0);
    let h = top + rowh * fig.len() as f64 + 70.0;
    let x = |v: f64| left + (v / 1.3) * (w - left - 30.0);
    let mut svg = format!(
        "<svg xmlns='http://www.w3.org/2000/svg' width='{w}' height='{h}' viewBox='0 0 {w} {h}' font-family='Helvetica,Arial,sans-serif' font-size='12'>\n<rect width='100%' height='100%' fill='white'/>\n<text x='{}' y='22' font-size='15' font-weight='bold'>Single-target rho over GF(2^31-1): paired ratios, 95% bootstrap CI (2000 pairs each)</text>\n<text x='{}' y='40' fill='#555'>dot = group operations; square = walk field multiplications; open triangle = heuristic prediction</text>\n",
        20, 20
    );
    for t in [0.0, 0.25, 0.5, 0.75, 1.0, 1.25] {
        svg += &format!("<line x1='{0}' x2='{0}' y1='{1}' y2='{2}' stroke='{3}'/><text x='{0}' y='{4}' text-anchor='middle' fill='#333'>{5:.2}</text>\n", x(t), top - 8.0, h - 50.0, if t == 1.0 { "#888" } else { "#e3e3e3" }, h - 34.0, t);
    }
    for (i, (lab, pred, st, wm)) in fig.iter().enumerate() {
        let y = top + rowh * i as f64 + 12.0;
        svg += &format!("<text x='{}' y='{}' text-anchor='end'>{}</text>\n", left - 10.0, y + 4.0, lab.replace('&', "&amp;").replace('<', "&lt;"));
        svg += &format!("<path d='M{} {} l-5 -8 l10 0 z' fill='none' stroke='#b05' />\n", x(*pred), y - 3.0);
        svg += &format!("<line x1='{}' x2='{}' y1='{}' y2='{}' stroke='#1f5fa8' stroke-width='2'/><circle cx='{}' cy='{}' r='4' fill='#1f5fa8'/>\n", x(st.1), x(st.2), y, y, x(st.0), y);
        svg += &format!("<line x1='{}' x2='{}' y1='{}' y2='{}' stroke='#d07a00' stroke-width='2'/><rect x='{}' y='{}' width='7' height='7' fill='#d07a00'/>\n", x(wm.1), x(wm.2), y + 8.0, y + 8.0, x(wm.0) - 3.5, y + 4.5);
    }
    svg += &format!("<text x='{}' y='{}' text-anchor='middle' fill='#333'>ratio of means (arm A / arm B); &lt; 1 means arm A is cheaper</text>\n</svg>\n", (left + w) / 2.0, h - 14.0);
    std::fs::write(format!("{}/../figures/ratios.svg", dir), svg).unwrap();
    println!("{}", std::fs::read_to_string(format!("{}/summary.md", dir)).unwrap());
}
