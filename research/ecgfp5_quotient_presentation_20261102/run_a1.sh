#!/usr/bin/env bash
# Amendment A1 cells (PROTOCOL.md §9, A1).   sh run_a1.sh <cell> [<cell> ...]
#   cells: U3_<p>  U1F_<p>  A0_<p>  U2_4111  U1P_4111      (p in 4111 262231 33554371)
# Outputs go to results/A1/<cell>/; a present cell directory aborts that cell.
set -u
H="$(cd "$(dirname "$0")" && pwd)"
W0="$H/../ecgfp5_quotient_solve_20261101"
BW="$H/../ecgfp5_quotient_bw_finish_20261102"
RUN() { OMP_WAIT_POLICY=PASSIVE "$W0/bin/qsolve" run --rss-cap-gib 12 --wall-cap-s 14400 --record "$O/msolve.run.json" -- "$@"; }

gen() { # p -> $G (u-ring system and planted point at seed 1)
  if [ "$1" = 4111 ]; then G="$H/results/U1/gen"; else
    G="$O/gen"; "$H/bin/qsolve" generate --m 5 --p "$1" --seed 1 --arms uring --out "$G" > "$O/gen.json" 2> "$O/gen.log"
    echo "generate_exit=$?" >> "$O/exit_codes.txt"; fi
}

f4only() { # sys
  RUN msolve -v 2 -t 4 -g 1 -f "$1" -o "$O/lm.out" > "$O/msolve.log" 2>&1
  echo "msolve_exit=$?" >> "$O/exit_codes.txt"
}

for CELL in "$@"; do
  O="$H/results/A1/$CELL"
  [ -e "$O" ] && { echo "$CELL: present, skipped"; continue; }
  mkdir -p "$O"; date -u +%FT%TZ > "$O/started_at.txt"
  ARM="${CELL%_*}"; P="${CELL#*_}"
  case "$ARM" in
    A0)  cp "$W0/results/m5_p${P}_planted/quot.ms" "$O/sys.ms"
         sha256sum "$O/sys.ms" /usr/bin/msolve > "$O/inputs.sha256"
         f4only "$O/sys.ms"; rm -f "$O/sys.ms" ;;
    U1F) gen "$P"; sha256sum "$G/uring.ms" /usr/bin/msolve > "$O/inputs.sha256"
         f4only "$G/uring.ms" ;;
    U2)  gen "$P"; python3 "$H/src/subst_s5.py" "$G/uring.ms" "$G/uring.planted" "$O/u2.ms" "$O/u2.planted" > "$O/subst.json"
         echo "subst_exit=$?" >> "$O/exit_codes.txt"
         sha256sum "$O/u2.ms" /usr/bin/msolve > "$O/inputs.sha256"
         f4only "$O/u2.ms" ;;
    U1P) gen "$P"; sha256sum "$G/uring.ms" /usr/bin/msolve > "$O/inputs.sha256"
         RUN msolve -v 2 -t 4 -P 1 -f "$G/uring.ms" -o "$O/u1p.out" > "$O/msolve.log" 2>&1
         echo "msolve_exit=$?" >> "$O/exit_codes.txt"
         if [ -s "$O/u1p.out" ]; then
           "$W0/bin/qsolve" check --msolve-out "$O/u1p.out" --planted "$G/uring.planted" --msolve-log "$O/msolve.log" > "$O/check.json" 2>&1
           echo "check_exit=$?" >> "$O/exit_codes.txt"; fi ;;
    U3)  gen "$P"; python3 "$H/src/shear_w.py" "$G/uring.ms" "$G/uring.planted" 1 "$O/u3.ms" "$O/u3.planted" > "$O/shear.json"
         echo "shear_exit=$?" >> "$O/exit_codes.txt"
         sha256sum "$O/u3.ms" /usr/bin/msolve "$BW/bin/hnfsolve" "$BW/bin/bwfinish" > "$O/inputs.sha256"
         rm -f "$O/gb.fifo"; mkfifo "$O/gb.fifo"
         "$BW/bin/hnfsolve" --gb "$O/gb.fifo" --dump-P "$O/P.bin" > "$O/dump.json" 2> "$O/dump.log" &
         HP=$!
         RUN msolve -v 2 -t 4 -g 2 -f "$O/u3.ms" -o "$O/gb.fifo" > "$O/msolve.log" 2>&1
         echo "msolve_exit=$?" >> "$O/exit_codes.txt"
         wait $HP; echo "hnfsolve_exit=$?" >> "$O/exit_codes.txt"
         rm -f "$O/gb.fifo"
         if [ -s "$O/P.bin" ]; then
           "$BW/bin/bwfinish" --P "$O/P.bin" --b 128 --threads 4 --seed 1 \
             --planted "$O/u3.planted" --elim-out "$O/bw.elim" > "$O/bw.json" 2> "$O/bw.log"
           echo "bwfinish_exit=$?" >> "$O/exit_codes.txt"
           sha256sum "$O/P.bin" > "$O/outputs.sha256"; rm -f "$O/P.bin"
         fi
         rm -f "$O/u3.ms" ;;   # regenerated by shear_w.py from gen/ (hash in inputs.sha256)
    *) echo "unknown cell $CELL"; continue ;;
  esac
  date -u +%FT%TZ > "$O/finished_at.txt"
  echo "$CELL: $(tr '\n' ' ' < "$O/exit_codes.txt")"
done
