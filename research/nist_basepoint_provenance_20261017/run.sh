#!/usr/bin/env bash
# Re-run every search of this note in a scratch copy and leave the new records
# there for comparison with out/. Never writes into the committed directory.
# Needs: gcc, libgmp-dev, PARI/GP >= 2.15, python3 with gmpy2 and fpylll.
# The invocations are the ones in each record's "done:" line. Wall times were
# not recorded; T1, T2, T6, T7 and T13 are the long ones. Run a subset with
#   ./run.sh <step> ...      steps: targets t1 t2 t3 t4 t5 t6 t7 t8 t9 t10 t11 t12 t13 t14 disc
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
work="${WORK:-$(mktemp -d)}"
mkdir -p "$work/src" "$work/lib"
cp "$here"/src/*.* "$work/src/"; cp "$here"/lib/*.py "$work/lib/"
cd "$work/src"
echo "work dir: $work/src"
cc() { gcc -O2 -o "$1" "$1.c" "${@:2}" -lgmp; }
steps=("$@"); [ ${#steps[@]} -eq 0 ] && steps=(targets t1 t2 t3 t4 t5 t6 t7 t8 t9 t10 t11 t12 t13 t14 disc)
for s in "${steps[@]}"; do case "$s" in
  targets) : > bin_targets.txt; : > k_targets.txt   # regenerated by the two GP scripts
           gp -q gnb.gp > gnb.out; gp -q gnb_k2.gp > gnb_k.log ;;
  t1)  cc freelip_brute; ./freelip_brute 4194304 > freelip_brute.out
       cc freelip_brute2; ./freelip_brute2 16777216 4194305 > freelip_brute_ext.out ;;
  t2)  cc freelip_brute3 -DOFFMAX=64; ./freelip_brute3 915148800 852076800 > freelip_ts.out
       cc freelip_brute4 -DOFFMAX=64; ./freelip_brute4 852076799 631152000 > freelip_ts9096.out ;;
  t3)  python3 freelip_widths.py > freelip_widths.out; python3 fl384w62.py > fl384w62.out ;;
  t4)  python3 samerun_bp.py > samerun_bp.out ;;
  t5)  python3 unreduce_scan.py > unreduce_scan.out ;;
  t6)  cc gmp_bp; ./gmp_bp > gmp_bp.out 2> gmp_bp.err ;;
  t7)  cc miracl_bp; ./miracl_bp > miracl_bp.out 2> miracl_bp.err ;;
  t8)  python3 libs_bp.py > libs_bp.out ;;
  t9)  python3 hash_bp.py > hash_bp.out ;;
  t10) gp -q smallk.gp > smallk.out ;;
  t11) python3 scan_bin.py > scan_bin.out; python3 scan_k.py > scan_k.out ;;
  t12) python3 libs_bin.py > libs_bin.out ;;
  t13) cc b163_brute; ./b163_brute > b163_brute.out 2> b163_brute.err ;;
  t14) python3 b163_edit.py > b163_edit.out ;;
  disc) gp -q disc.gp > disc.out ;;
  *) echo "unknown step $s" >&2; exit 2 ;;
esac; done
