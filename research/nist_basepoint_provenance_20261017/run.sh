#!/usr/bin/env bash
# Re-run the native (C and PARI/GP) searches of this note in a scratch copy and
# leave the new records there for comparison with out/. Never writes into the
# committed directory. The Python searches are a frozen evidence snapshot
# (snapshot/, AGENTS.md "Implementation language: no Python") and are not run.
# Needs: gcc, libgmp-dev, PARI/GP >= 2.15.
# The invocations are the ones in each record's "done:" line. Wall times were
# not recorded; T1, T2, T6, T7 and T13 are the long ones. Run a subset with
#   ./run.sh <step> ...      steps: targets t1 t2 t2d t6 t7 t10 t13 disc
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
work="${WORK:-$(mktemp -d)}"
mkdir -p "$work/src"
cp "$here"/src/*.* "$work/src/"
cd "$work/src"
echo "work dir: $work/src"
cc() { gcc -O2 -o "$1" "$1.c" "${@:2}" -lgmp; }
steps=("$@"); [ ${#steps[@]} -eq 0 ] && steps=(targets t1 t2 t2d t6 t7 t10 t13 disc)
for s in "${steps[@]}"; do case "$s" in
  targets) : > bin_targets.txt; : > k_targets.txt   # regenerated by the two GP scripts
           gp -q gnb.gp > gnb.out; gp -q gnb_k2.gp > gnb_k.log ;;
  t1)  cc freelip_brute; ./freelip_brute 4194304 > freelip_brute.out
       cc freelip_brute2; ./freelip_brute2 16777216 4194305 > freelip_brute_ext.out ;;
  t2)  cc freelip_brute3 -DOFFMAX=64; ./freelip_brute3 915148800 852076800 > freelip_ts.out
       cc freelip_brute4 -DOFFMAX=64; ./freelip_brute4 852076799 631152000 > freelip_ts9096.out ;;
  t2d) cc fl_list; ./fl_list date_seeds.txt > fl_list.out ;;
  t6)  cc gmp_bp; ./gmp_bp > gmp_bp.out 2> gmp_bp.err ;;
  t7)  cc miracl_bp; ./miracl_bp > miracl_bp.out 2> miracl_bp.err ;;
  t10) gp -q smallk.gp > smallk.out ;;
  t13) cc b163_brute; ./b163_brute > b163_brute.out 2> b163_brute.err ;;
  disc) gp -q disc.gp > disc.out ;;
  *) echo "unknown step $s" >&2; exit 2 ;;
esac; done
