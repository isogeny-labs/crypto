#!/usr/bin/env python3
"""Post hoc mechanism test for the b = 0 (j = 1728) deficit, k = 2, d = 1.

For each non-degenerate line V and curve, the subgroup of E(F_p) generated by the trace image
S = {Tr(Q)}; report its index in E(F_p). Run: python3 -I subgroup_index_b0.py
"""
import importlib.util, os, random
from collections import Counter
here = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("tz", os.path.join(here, "tracezero.py"))
tz = importlib.util.module_from_spec(spec); spec.loader.exec_module(tz)

def gen_subgroup(curve, S):
    H = {0}; frontier = [0]
    S = list(S)
    while frontier:
        h = frontier.pop()
        for s in S:
            n = curve.T[h][s]
            if n not in H: H.add(n); frontier.append(n)
    return len(H)

def run(p, ncurves, cls):
    F = tz.Field(p, 2)
    lines = [c0 + p for c0 in range(p)]
    lines = [g for g in lines if F.frob(g) not in (g, F.neg(g))]   # drop pure lines (rational excluded by construction)
    res = Counter(); idx_by = {}
    curves = [(a, 0) for a in range(1, p)] if cls == "b0" else [(a, b) for a, b in tz.curves_for(p, 2, 120) if b != 0 and a != 0]
    for a, b in curves[:ncurves]:
        curve = tz.Curve(p, a, b)
        for g in lines:
            V = sorted({F.mul(t, g) if t else 0 for t in range(p)})
            n0, tr = tz.lifts_trace(F, curve, V, a, b)
            S = {t for t in tr if t}
            if not S: res["empty"] += 1; continue
            H = gen_subgroup(curve, S)
            res[curve.n // H] += 1
    return res

for p in (23, 37, 53):
    for cls in ("b0", "generic"):
        r = run(p, 40, cls)
        tot = sum(r.values())
        print("p=%d %-7s index distribution %s (n=%d)" % (p, cls, dict(sorted(r.items(), key=str)), tot))

# Which lines give index 2? Test the square class of the norm N(g) = g^(p+1) in F_p (well defined per line).
def class_test(p, ncurves=40):
    F = tz.Field(p, 2)
    lines = [c0 + p for c0 in range(p) if F.frob(c0 + p) not in (c0 + p, F.neg(c0 + p))]
    tab = Counter()
    for a in range(1, p)[:ncurves]:
        curve = tz.Curve(p, a, 0)
        for g in lines:
            N = F.mul(g, F.frob(g))                       # in F_p, as an int < p
            sq = pow(N, (p - 1) // 2, p) == 1
            V = sorted({F.mul(t, g) if t else 0 for t in range(p)})
            n0, tr = tz.lifts_trace(F, curve, V, a, 0)
            S = {t for t in tr if t}
            if S: tab[(("N square" if sq else "N nonsquare"), curve.n // gen_subgroup(curve, S))] += 1
    return dict(sorted(tab.items()))
for p in (23, 37, 53):
    print("p=%d" % p, class_test(p))
