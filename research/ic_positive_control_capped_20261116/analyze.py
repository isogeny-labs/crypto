#!/usr/bin/env python3
"""Gates, tables, figure and PDF for arm W (PROTOCOL sections 4-7).

W rows: run_w.json (this study). S and R rows: the unit-T study's run.json,
reused by determinism; G1 checks that run_sr.json (this run, p <= 8209)
reproduces them. Writes analysis.json, tables.md, figure.svg/png, REPORT.pdf.
"""
import json
import math
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))
PREV = os.path.join(HERE, "..", "ic_positive_control_unit_t_20261116", "run.json")
B = 2000
PRICES = [("total_w0", "0"), ("total_w01", "0.1"), ("total_w1", "1")]


def key(r):
    return (r["p"], r["curve_idx"], r["seed"])


def index(rows, arm):
    return {key(r): r for r in rows if r["arm"] == arm}


w_rows = json.load(open(os.path.join(HERE, "run_w.json")))["rows"]
sr_rows = json.load(open(os.path.join(HERE, "run_sr.json")))["rows"]
prev = json.load(open(PREV))["rows"]
W = index(w_rows, "C_unit_t_capped_fast")
S = index(prev, "C_coord_square")
R = index(prev, "R_rho_negation")

# ── gates ──
gates = {"G1": [], "G2": []}
for arm, fields in [("C_coord_square", ["group_ops", "rel_mul", "la_mul", "trials", "relations", "certified"]),
                    ("R_rho_negation", ["group_ops", "native_mul", "certified"])]:
    old = index(prev, arm)
    new = index(sr_rows, arm)
    if not new:
        gates["G1"].append(f"{arm}: no reproduction rows")
    for k, r in new.items():
        o = old.get(k)
        if o is None:
            gates["G1"].append(f"{arm} {k}: no earlier row")
            continue
        for f in fields:
            if r[f] != o[f]:
                gates["G1"].append(f"{arm} {k} {f}: {r[f]} != {o[f]}")
for k, r in W.items():
    if not r["certified"]:
        gates["G2"].append(f"W {k} not certified")
missing = [k for k in W if k not in S or k not in R]
if missing:
    gates["G2"].append(f"W rows without S/R partner: {missing[:5]}")
gate_ok = {g: not v for g, v in gates.items()}


def mean(v):
    return sum(v) / len(v)


def boot(num, den, p, fn_num, fn_den=None, seed=20261118):
    fn_den = fn_den or fn_num
    rnd = random.Random(seed)
    gn, gd = {}, {}
    for k, r in num.items():
        if k[0] == p:
            gn.setdefault(k[1], []).append(fn_num(r))
    for k, r in den.items():
        if k[0] == p:
            gd.setdefault(k[1], []).append(fn_den(r))
    curves = sorted(gn)
    est = mean(sum(gn.values(), [])) / mean(sum(gd.values(), []))
    bs = []
    for _ in range(B):
        cs = [rnd.choice(curves) for _ in curves]
        n, d = [], []
        for c in cs:
            n += [rnd.choice(gn[c]) for _ in gn[c]]
            d += [rnd.choice(gd[c]) for _ in gd[c]]
        bs.append(mean(n) / mean(d))
    bs.sort()
    return est, bs[int(0.025 * B)], bs[int(0.975 * B) - 1]


f = lambda name: (lambda r: r[name])
per_trial = lambda r: r["rel_mul"] / r["trials"]
ps = sorted({k[0] for k in W})
out = {"gates": gate_ok, "gate_failures": {g: v[:20] for g, v in gates.items()}, "per_p": [],
       "claims": "[pcc:unverified]"}
for p in ps:
    e = {"p": p, "runs": sum(1 for k in W if k[0] == p),
         "W_fallbacks": sum(r["la_fallbacks"] for k, r in W.items() if k[0] == p),
         "W_over_S_la_mul": boot(W, S, p, f("la_mul")),
         "W_over_S_native_all": boot(W, S, p, f("native_all")),
         "W_over_S_rel_per_trial": boot(W, S, p, per_trial)}
    for col, w in PRICES:
        e[f"W_over_R_w{w}"] = boot(W, R, p, f(col))
        e[f"S_over_R_w{w}"] = boot(S, R, p, f(col))
        e[f"W_over_S_w{w}"] = boot(W, S, p, f(col))
    out["per_p"].append(e)

big = [e for e in out["per_p"] if e["p"] >= 4099]
out["advances_every_p_ge_4099"] = all(e["W_over_S_w0.1"][0] < 1 and e["W_over_S_w1"][0] < 1 for e in big)
out["W_w01_interval_below_1"] = [e["p"] for e in out["per_p"] if e["W_over_R_w0.1"][2] < 1]
out["W_below_rho_all_prices"] = [e["p"] for e in out["per_p"] if all(e[f"W_over_R_w{w}"][2] < 1 for _, w in PRICES)]
pts = [(math.log(e["p"]), math.log(e["W_over_R_w0.1"][0])) for e in big]
mx = mean([a for a, _ in pts]); my = mean([b for _, b in pts])
out["slope_lnWR_w01"] = sum((a - mx) * (b - my) for a, b in pts) / sum((a - mx) ** 2 for a, _ in pts)
json.dump(out, open(os.path.join(HERE, "analysis.json"), "w"), indent=1)

f3 = lambda t: f"{t[0]:.3f} [{t[1]:.3f}, {t[2]:.3f}]"
f2 = lambda t: f"{t[0]:.2f} [{t[1]:.2f}, {t[2]:.2f}]"
L = ["# Tables (generated by analyze.py; every number [pcc:unverified])", "",
     f"Gates: {', '.join(f'{g} {chr(10003) if ok else 'FAIL'}' for g, ok in gate_ok.items())}", "",
     "## W against S (paired on p, curve, seed)", "",
     "| p | runs | W fallbacks | LA mult. W/S | LA incl. additions W/S | relation mult. per trial W/S | total W/S w=0.1 | total W/S w=1 |",
     "|--:|--:|--:|--|--|--|--|--|"]
for e in out["per_p"]:
    L.append(f"| {e['p']} | {e['runs']} | {e['W_fallbacks']} | {f3(e['W_over_S_la_mul'])} | {f3(e['W_over_S_native_all'])} | "
             f"{f3(e['W_over_S_rel_per_trial'])} | {f3(e['W_over_S_w0.1'])} | {f3(e['W_over_S_w1'])} |")
L += ["", "## Distance to the matched negation rho (arm total / R total)", "",
      "| p | S w=0.1 | W w=0 | W w=0.1 | S w=1 | W w=1 |", "|--:|--|--|--|--|--|"]
for e in out["per_p"]:
    L.append(f"| {e['p']} | {f2(e['S_over_R_w0.1'])} | {f2(e['W_over_R_w0'])} | {f2(e['W_over_R_w0.1'])} | "
             f"{f2(e['S_over_R_w1'])} | {f2(e['W_over_R_w1'])} |")
L += ["", f"W advances on S at every p >= 4099 (w = 0.1 and w = 1): {out['advances_every_p_ge_4099']}",
      f"p where W's w = 0.1 interval lies below 1: {out['W_w01_interval_below_1']}",
      f"p where W is below rho at all three prices (§5a): {out['W_below_rho_all_prices']}",
      f"slope of ln(W/R, w = 0.1) on ln p, p >= 4099: {out['slope_lnWR_w01']:.3f}"]
open(os.path.join(HERE, "tables.md"), "w").write("\n".join(L) + "\n")

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.backends.backend_pdf import PdfPages

fig, ax = plt.subplots(1, 2, figsize=(12, 4.6))
x = [e["p"] for e in out["per_p"]]
for k, w in enumerate(["0.1", "1"]):
    for arm, col in [("S", "#6b6b6b"), ("W", "#d62728")]:
        v = [e[f"{arm}_over_R_w{w}"] for e in out["per_p"]]
        ax[k].errorbar(x, [t[0] for t in v], yerr=[[t[0] - t[1] for t in v], [t[2] - t[0] for t in v]],
                       fmt="o-", color=col, label=arm, capsize=2)
    ax[k].axhline(1, color="k", lw=0.8, ls="--")
    ax[k].set(xscale="log", yscale="log", xlabel="p", ylabel="arm / matched rho",
              title=f"distance to rho at w = {w} GAE per native mult")
    ax[k].legend()
fig.suptitle("Genus-3 positive control: arm W (capped unit-T + fallback roots) vs S  [pcc:unverified]")
fig.tight_layout()
fig.savefig(os.path.join(HERE, "figure.svg"))
fig.savefig(os.path.join(HERE, "figure.png"), dpi=150)
with PdfPages(os.path.join(HERE, "REPORT.pdf")) as pdf:
    pdf.savefig(fig)
    for src in ["RESULTS.md", "tables.md"]:
        pth = os.path.join(HERE, src)
        if os.path.exists(pth):
            t = plt.figure(figsize=(11, 8.5))
            t.text(0.03, 0.97, open(pth).read()[:7000], va="top", family="monospace", fontsize=5.6)
            pdf.savefig(t)
print("\n".join(L))
