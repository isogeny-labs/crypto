// Evaluate the registered tests of PROTOCOL.md section 3 from the recorded sessions.
//   node analysis/evaluate.mjs <ecbench binary> <sessions dir> <out dir>      (cwd = study directory)
// Computes nothing the harness does not: ratios, intervals and band means come from `ecbench compare` and `ecbench band`.
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync, readFileSync } from "node:fs";
import { ROWS } from "../rows.mjs";

const [bin, sess, out] = process.argv.slice(2);
mkdirSync(out, { recursive: true });
const W = [0, 0.1, 1], K = [5, 4];
const run = (args) => execFileSync(bin, args, { encoding: "utf8", maxBuffer: 1 << 28 });
const json = (args) => JSON.parse(run([...args, "--json"]));
const dirs = (id) => [1, 2, 3].map((r) => `${sess}/${id}-r${r}`);
const bandOf = (ds) => { const f = `${out}/.band.json`; run(["band", "--dir", ...ds, "--json", f]);
  return Object.fromEntries(JSON.parse(readFileSync(f, "utf8")).rows.map((r) => [r.arm, r])); };
// ratio = cost(b)/cost(a), paired by target and round.
const cmp = (ds, a, b, w) => {
  const j = json(["compare", "--dir", ...ds, "--a", a, "--b", b, "--weight", String(w), "--resamples", "4000", "--seed", "20261002"]);
  const o = j.ops ?? j, ci = o.ci95, cb = o.ci95_bootstrap;
  return { ratio: o.ratio_b_over_a, ci95: ci, ci95_bootstrap: cb, upper: Math.max(ci?.[1] ?? NaN, cb?.[1] ?? NaN), pairs: o.workloads, status: o.status };
};
const results = { schema: "ic_ksum_prune.evaluation/v1", rows: [] };
for (const row of ROWS) {
  const ds = dirs(row.id), perSession = ds.map((d) => bandOf([d])), pooled = bandOf(ds);
  const r = { ...row, weights: {}, spread: {} };
  W.forEach((w, wi) => {
    const o = { S: Object.fromEntries(Object.keys(pooled).map((a) => [a, pooled[a].mean_s[wi]])),
      aa: cmp(ds, "rho-neg", "rho-neg-aa", w) };
    for (const k of K) {
      const u = `ksum${k}`, p = `ksum${k}-p`;
      o[u] = { ratio_p_over_u: cmp(ds, u, p, w), per_replicate: ds.map((d) => cmp([d], u, p, w)),
        gap_to_rho_unpruned: pooled[u].mean_s[wi] / pooled["rho-neg"].mean_s[wi], gap_to_rho_pruned: pooled[p].mean_s[wi] / pooled["rho-neg"].mean_s[wi] };
    }
    r.weights[w] = o;
  });
  // replicate spread (sibling definition): max/min over the 3 sessions of one arm's mean S at w = 0.
  for (const a of ["rho-neg", "ksum5", "ksum5-p", "ksum4", "ksum4-p"]) { const v = perSession.map((b) => b[a].mean_s[0]); r.spread[a] = Math.max(...v) / Math.min(...v); }
  for (const k of K) {
    const u = `ksum${k}`, p = `${u}-p`;
    const upper = Math.max(...W.map((w) => r.weights[w][u].ratio_p_over_u.upper));
    const repUpper = Math.max(...W.flatMap((w) => r.weights[w][u].per_replicate.map((x) => x.upper)));
    const aaDev = Math.max(...W.map((w) => Math.abs(r.weights[w].aa.ratio - 1)));
    const delta = Math.max(r.spread["rho-neg"], r.spread[u], r.spread[p]);
    const gain = 1 - upper;
    r[u] = { max_upper_pooled: upper, max_upper_replicate: repUpper, aa_max_abs_dev: aaDev, delta_sibling: delta, gain_lower_bound: gain,
      holds: upper < 1 && repUpper < 1 && gain > aaDev, holds_sibling_delta: upper < 1 && repUpper < 1 && gain > delta - 1 };
  }
  results.rows.push(r);
}
for (const k of K) { const u = `ksum${k}`;
  results[`${u}_p_holds_rows`] = results.rows.filter((r) => r[u].holds).map((r) => r.id);
  results[`${u}_p_holds_all_rows`] = results.rows.every((r) => r[u].holds);
  results[`${u}_p_holds_sibling_delta_rows`] = results.rows.filter((r) => r[u].holds_sibling_delta).map((r) => r.id); }
writeFileSync(`${out}/results.json`, JSON.stringify(results, null, 1) + "\n");
const f = (x, d = 3) => (typeof x === "number" ? x.toFixed(d) : String(x));
let md = `# prune=1 evaluation (generated by evaluate.mjs from the recorded sessions) [pcc:unverified]\n\n`;
for (const k of K) { const u = `ksum${k}`;
  md += `## ${u}-p / ${u}\n\n| row | w | S ${u} | S ${u}-p | ${u}-p / ${u} [95%] | max upper | per-replicate | A/A rho-neg-aa/rho-neg | S rho-neg | ${u}-p / rho-neg |\n|:--|--:|--:|--:|:--|--:|:--|--:|--:|--:|\n`;
  for (const r of results.rows) for (const w of W) { const x = r.weights[w], c = x[u], p = c.ratio_p_over_u;
    md += `| ${r.id} | ${w} | ${f(x.S[u], 3)} | ${f(x.S[u + "-p"], 3)} | ${f(p.ratio, 4)} [${f(p.ci95?.[0], 4)}, ${f(p.ci95?.[1], 4)}] | ${f(p.upper, 4)} | ${c.per_replicate.map((q) => f(q.ratio, 4)).join(" / ")} | ${f(x.aa.ratio, 4)} | ${f(x.S["rho-neg"], 3)} | ${f(c.gap_to_rho_pruned, 2)} |\n`; }
  md += `\n| row | max upper pooled | max upper replicate | A/A max dev | delta (sibling) | holds (paired A/A gate) | holds (sibling delta gate) |\n|:--|--:|--:|--:|--:|:--|:--|\n`;
  for (const r of results.rows) md += `| ${r.id} | ${f(r[u].max_upper_pooled, 4)} | ${f(r[u].max_upper_replicate, 4)} | ${f(r[u].aa_max_abs_dev, 4)} | ${f(r[u].delta_sibling, 4)} | ${r[u].holds} | ${r[u].holds_sibling_delta} |\n`;
  md += `\n`; }
writeFileSync(`${out}/results.md`, md); console.log(md);
