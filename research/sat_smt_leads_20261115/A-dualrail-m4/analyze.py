#!/usr/bin/env python3
"""Tables, decision and figure from raw rows.  Usage: analyze.py [raw files ...] (default raw/*.jsonl).
With the default input it rewrites results.json, tables.md, ratio_vs_l.svg/.png."""
import sys, os, json, glob, math, statistics as st
HERE = os.path.dirname(os.path.abspath(__file__))
files = sys.argv[1:] or sorted(glob.glob(os.path.join(HERE, "raw", "*.jsonl")))
default = not sys.argv[1:]
rows = [json.loads(x) for f in files for x in open(f)]
if default:
    json.dump(rows, open(os.path.join(HERE, "results.json"), "w"))
out = []
P = out.append
Ls = sorted(set(r["l"] for r in rows))
half = lambda l: (1 << (2 * l)) // 2
ok = [r for r in rows if r["status"] == "OK"]
notrun = [r for r in rows if r["status"] != "OK"]


def sel(arm, l, dec=False):
    return [r for r in ok if r["arm"] == arm and r["l"] == l and r["decomposable"] == dec]


def ratio(r):
    return (r["leaves"] + r["conflicts"]) / half(r["l"])


def fmt(x):
    if x is None:
        return "not run"
    return "%.3g" % x if x < 100 else "%.0f" % x


def cell(arm, l, dec=False):
    """(mean ratio, n, censored count) or None"""
    rs = sel(arm, l, dec)
    if not rs:
        return None
    return st.mean(ratio(r) for r in rs), len(rs), sum(1 for r in rs if r.get("censored"))


def trend(vals):
    pts = [(l, math.log2(v)) for l, v in vals if v]
    pts = pts[-3:]
    if len(pts) < 3:
        return None
    mx, my = st.mean(p[0] for p in pts), st.mean(p[1] for p in pts)
    return sum((x - mx) * (y - my) for x, y in pts) / sum((x - mx) ** 2 for x, y in pts)


P("# Tables (generated by analyze.py; every number [pcc:unverified])\n")
P("Rows: %d total, %d OK, %d NOT_RUN. Files: %s\n" % (len(rows), len(ok), len(notrun),
                                                    ", ".join(os.path.basename(f) for f in files)))
P("## Cells and baseline counts\n")
P("| l | n | B | factor base (points up to sign) | pair scan 2^(2l)/2 leaf solves | leaves the budget-0 DFS visits | meet in the middle: time and memory 2^(2l) | 3-scan enumeration 2^(3l)/24 |")
P("|---|---|---|---|---|---|---|---|")
for l in Ls:
    r = next(r for r in rows if r["l"] == l)
    P("| %d | %d | %d | %d | %d | %d | %d and %d | %.0f |" % (l, r["n"], r["B"], r["base_points"], half(l),
      (1 << l) * ((1 << l) - 1) // 2, 1 << (2 * l), 1 << (2 * l), (1 << (3 * l)) / 24))

P("\n## Part 1: conflicts per leaf with (x1, x2) assigned, non-decomposable targets [pcc:unverified]\n")
P("Warm = leaf calls of the budget-0 keep DFS (one incremental solver, every leaf). Cold = fresh solver per leaf, sampled leaves, cap 20 000.\n")
P("| l | warm dual: mean | zero-conflict leaves | largest leaf | warm dual2: mean | largest | cold dual: mean | median | max | capped | cold dual2: mean | median | capped |")
P("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
part1 = {}
for l in Ls:
    w, w2 = sel("keep-B0", l), sel("keep-B0-d2", l)
    c, c2 = sel("cold-dual", l), sel("cold-dual2", l)
    f = lambda rs: sum(r["leaf_conflicts"] for r in rs) / max(1, sum(r["leaves"] for r in rs))
    cl = [x for r in c for x in r["per_leaf"]]
    cl2 = [x for r in c2 for x in r["per_leaf"]]
    part1[l] = (f(w) if w else None, st.mean(cl) if cl else None)
    P("| %d | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
        l, fmt(f(w)) if w else "not run",
        ("%.0f %%" % (100 * sum(r["leaf_zero"] for r in w) / sum(r["leaves"] for r in w))) if w else "",
        max(r["leaf_max"] for r in w) if w else "",
        fmt(f(w2)) if w2 else "not run", max(r["leaf_max"] for r in w2) if w2 else "",
        (">= " if any(r["censored"] for r in c) else "") + fmt(st.mean(cl)) if cl else "not run",
        fmt(st.median(cl)) if cl else "", max(cl) if cl else "",
        ("%d of %d" % (sum(r["censored"] for r in c), len(cl))) if cl else "",
        (">= " if any(r["censored"] for r in c2) else "") + fmt(st.mean(cl2)) if cl2 else "not run",
        fmt(st.median(cl2)) if cl2 else "",
        ("%d of %d" % (sum(r["censored"] for r in c2), len(cl2))) if cl2 else ""))

ARMS = ["keep-B0", "keep-B3", "keep-B10", "keep-B100", "core", "free", "keep-B0-blk", "keep-B10-blk",
        "keep-B0-d2", "keep-B10-d2", "free-d2", "free-plain"]
LEARN = [a for a in ARMS if a not in ("keep-B0", "keep-B0-blk", "keep-B0-d2")]
DISC = ["disc-B0", "disc-B3", "disc-B10", "disc-B100"]


def table(arms, dec, title):
    P("\n" + title + "\n")
    P("| arm | " + " | ".join("l=%d" % l for l in Ls) + " | trend, bits per l (3 largest sizes) | targets at largest l | capped runs at largest l |")
    P("|---|" + "---|" * (len(Ls) + 3))
    res = {}
    for a in arms:
        cs = [cell(a, l, dec) for l in Ls]
        tr = trend([(l, c[0]) for l, c in zip(Ls, cs) if c])
        res[a] = (cs, tr)
        P("| %s | %s | %s | %s | %s |" % (a, " | ".join(
            ((">= " if c[2] else "") + fmt(c[0])) if c else "not run" for c in cs),
            ("%+.2f" % tr) if tr is not None else "n/a", cs[-1][1] if cs[-1] else 0, cs[-1][2] if cs[-1] else ""))
    return res


res = table(ARMS, False, "## Part 2: ratio = (leaf calls + conflicts) / (2^(2l)/2), mean over non-decomposable targets; 1 = the pair scan count [pcc:unverified]")
P("\nSame arms divided by the keep-B0 arm of the same size (the solver's own scan):\n")
P("| arm | " + " | ".join("l=%d" % l for l in Ls) + " |")
P("|---|" + "---|" * len(Ls))
for a in ARMS[1:]:
    cs = res[a][0]
    P("| %s | %s |" % (a, " | ".join(fmt(c[0] / res["keep-B0"][0][i][0]) if c and res["keep-B0"][0][i] else "not run" for i, c in enumerate(cs))))

dres = table(DISC, False, "## Discard control: fresh solver per solver call (full DFS) [pcc:unverified]")
P("\nSampled discard estimate, 1 + mean cold conflicts per leaf (stands in for the discard control where the full DFS was not run):\n")
P("| l | " + " | ".join(str(l) for l in Ls) + " |")
P("|---|" + "---|" * len(Ls))
est = {l: (1 + part1[l][1]) if part1[l][1] is not None else None for l in Ls}
P("| estimate | " + " | ".join(fmt(est[l]) for l in Ls) + " |")

P("\n## Detail at each size: leaves visited, conflicts, wall time (means, non-decomposable) [pcc:unverified]\n")
P("| arm | l | leaves visited | conflicts | of which at leaf calls | seconds | runs with fewer leaves+conflicts than 2^(2l)/2 |")
P("|---|---|---|---|---|---|---|")
for a in ARMS[:6]:
    for l in Ls:
        rs = sel(a, l)
        if rs:
            P("| %s | %d | %.1f | %.0f | %s | %.2f | %d of %d |" % (
                a, l, st.mean(r["leaves"] for r in rs), st.mean(r["conflicts"] for r in rs),
                ("%.0f" % st.mean(r["leaf_conflicts"] for r in rs)) if "leaf_conflicts" in rs[0] else "",
                st.mean(r["time"] for r in rs), sum(1 for r in rs if ratio(r) < 1 and not r.get("censored")), len(rs)))
P("\nPer-target ratios at the largest size:\n")
L = Ls[-1]
for a in ARMS:
    rs = sorted(sel(a, L), key=lambda r: r["idx"])
    if rs:
        P("- %s: %s" % (a, ", ".join(("%s%.3g" % (">= " if r.get("censored") else "", ratio(r))) for r in rs)))
cs = sel("core", L)
if cs:
    P("\nCore arm at l = %d: mean nogoods %.0f, mean core length %.2f of %d literals, shortest core %d, mean leaves covered without a solve %.1f." % (
        L, st.mean(r["nogoods"] for r in cs), sum(r["core_len_sum"] for r in cs) / max(1, sum(r["nogoods"] for r in cs)),
        2 * L, min(r["core_len_min"] for r in cs), st.mean(r["covered"] for r in cs)))
for a in ("keep-B3", "keep-B10", "keep-B100"):
    rs = sel(a, L)
    if rs:
        D = 2 * L
        P("- %s at l = %d, mean refutations by depth 0..%d: %s; mean conflicts by depth: %s" % (
            a, L, D, " ".join("%.1f" % st.mean(r["prune_depth"][k] for r in rs) for k in range(D + 1)),
            " ".join("%.0f" % st.mean(r["confl_depth"][k] for r in rs) for k in range(D + 1))))

table(ARMS[:6], True, "## Planted (decomposable) targets, reported separately; search stops at the first model [pcc:unverified]")

# ---- decision
P("\n## Decision per the pre-registered rule\n")
lastv = {a: res[a][0][-1] for a in ARMS}
alive, kill, lines = [], True, []
for a in ARMS:
    c = lastv[a]
    if c is None:
        lines.append("- %s: not run at l = %d" % (a, L))
        kill = False
        continue
    if c[0] < 1.0:
        kill = False
    if a in LEARN:
        ctl = dres.get("disc-B0", ([None],))[0][-1]
        ctlv = ctl[0] if ctl else est[L]
        tr = res[a][1]
        is_alive = c[0] < 0.7 and not c[2] and tr is not None and tr < 0 and ctlv is not None and c[0] < ctlv
        if is_alive:
            alive.append(a)
    lines.append("- %s: ratio %s%s at l = %d, trend %s" % (a, ">= " if c[2] else "", fmt(c[0]), L,
                 ("%+.2f" % res[a][1]) if res[a][1] is not None else "n/a"))
decision = "ALIVE (%s)" % ", ".join(alive) if alive else ("KILL" if kill else "INCONCLUSIVE")
P("**%s** [pcc:unverified]\n" % decision)
out.extend(lines)
P("\nDiscard control used at l = %d: %s." % (L, "full disc-B0 DFS" if dres.get("disc-B0", ([None],))[0][-1] else
  "sampled cold-leaf estimate %s" % fmt(est[L])))

text = "\n".join(out) + "\n"
print(text)
if default:
    open(os.path.join(HERE, "tables.md"), "w").write(text)
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    INK, MUTE, SURF = "#0b0b0b", "#52514e", "#fcfcfb"
    series = [("keep-B0", "#2a78d6", "o", "budget 0 (scan done by the solver)"), ("keep-B3", "#eb6834", "s", "budget 3"),
              ("keep-B10", "#1baf7a", "^", "budget 10"), ("keep-B100", "#eda100", "D", "budget 100"),
              ("core", "#e87ba4", "v", "core nogoods over (x1, x2)"), ("free", "#008300", "P", "free CDCL (lower bound where capped)"),
              ("ctl", "#6250d6", "X", "discard control (fresh solver per call)")]
    fig, ax = plt.subplots(figsize=(9, 5.6), facecolor=SURF)
    ax.set_facecolor(SURF)
    ends = []
    for a, col, mk, lab in series:
        if a == "ctl":
            pts = []
            for i, l in enumerate(Ls):
                c = dres["disc-B0"][0][i]
                v = c[0] if c else est[l]
                if v:
                    pts.append((l, v))
        else:
            pts = [(l, c[0]) for l, c in zip(Ls, res[a][0]) if c]
        if not pts:
            continue
        ax.plot([p[0] for p in pts], [p[1] for p in pts], color=col, marker=mk, ms=8, lw=2, label=lab,
                mec=SURF, mew=1.5, ls="--" if a == "ctl" else "-")
        ends.append((pts[-1][1], pts[-1][0], a))
    ends.sort()
    ly = None
    for v, x, a in ends:          # end labels, pushed apart so they do not collide
        ly = math.log10(v) if ly is None else max(math.log10(v), ly + 0.14)
        ax.annotate(fmt(v), (x, v), xytext=(x + 0.12, 10 ** ly), textcoords="data", color=INK, fontsize=9, va="center")
    ax.axhline(1.0, color=INK, lw=1.2)
    ax.text(Ls[0], 1.0, "pair scan, 2^(2l)/2 leaf solves = 1", color=INK, fontsize=9, va="bottom")
    ax.axhline(0.7, color=MUTE, lw=1, ls=":")
    ax.text(Ls[0], 0.7, "pre-registered 'alive' threshold 0.7", color=MUTE, fontsize=9, va="top")
    ax.set_yscale("log")
    ax.set_xticks(Ls)
    ax.set_xlim(Ls[0] - 0.2, Ls[-1] + 0.6)
    ax.set_xlabel("l (dimension of V; n = 4l + 1)", color=INK)
    ax.set_ylabel("(leaf calls + conflicts) / (2^(2l)/2), mean of 8 targets", color=INK)
    ax.set_title("m = 4 dual-rail encoding: search cost against the pair scan count\n(non-decomposable targets, CryptoMiniSat; pilot, unverified)",
                 color=INK, fontsize=11, loc="left")
    ax.grid(True, which="major", color="#e4e3df", lw=0.6)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    for s in ("left", "bottom"):
        ax.spines[s].set_color(MUTE)
    ax.tick_params(colors=MUTE)
    ax.legend(frameon=False, fontsize=9, handlelength=3.2, loc="upper left", bbox_to_anchor=(1.0, 1.0), labelcolor=INK)
    fig.tight_layout()
    fig.savefig(os.path.join(HERE, "ratio_vs_l.svg"), facecolor=SURF)
    fig.savefig(os.path.join(HERE, "ratio_vs_l.png"), dpi=150, facecolor=SURF)
