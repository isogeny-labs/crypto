#!/usr/bin/env python3
"""Append the field-degree and elliptic-cover window to the three-page report."""
from pathlib import Path
import subprocess
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle

P = Path(__file__).resolve().parent
pdf = P / 'REPORT.pdf'
tmp = P / 'tmp_pdfs'
tmp.mkdir(exist_ok=True)
addendum = tmp / 'field_gate_addendum.pdf'
merged = tmp / 'field_gate_merged.pdf'
styles = getSampleStyleSheet()
styles.add(ParagraphStyle(name='GateTitle', parent=styles['Heading1'], fontName='Helvetica-Bold', fontSize=15, leading=18, spaceAfter=12))
styles.add(ParagraphStyle(name='GateBody', parent=styles['Normal'], fontName='Helvetica', fontSize=9, leading=12.3, spaceAfter=8))
styles.add(ParagraphStyle(name='GateSmall', parent=styles['Normal'], fontName='Helvetica', fontSize=8, leading=10, spaceAfter=6))
story = [Paragraph('Field-degree gate and finite cover windows', styles['GateTitle'])]
def body(s): story.append(Paragraph(s, styles['GateBody']))
body('<b>Exact field-degree gate.</b> Let Y/F3 have genus five and Weil polynomial X^10-tX^5+243 for t in the eight traces on page 1. For m &gt;= 1 and d=gcd(5,m), its Jacobian over F_(3^m) is isogenous to the d-th power of a simple (5/d)-fold. If 5 does not divide m, no map over F_(3^m) from Y to a positive-genus curve of genus below five exists. If 5 divides m, an elliptic quotient and a nonconstant elliptic map exist. This is the powered-root consequence of standard finite-field isogeny theory; it does not supply an evaluation formula. [pcc:unverified]')
body('<b>Proof key.</b> Roots are fifth roots of alpha and beta, where alpha and beta solve Z^2-tZ+243. Since 3 does not divide t, their 3-adic valuations are 0 and 5. Raising roots to m-th powers merges exactly d roots within each quintet and none across quintets. The irreducible powered-root factor has degree 10/d. A map to a positive-genus curve would induce a nonzero Jacobian homomorphism. [pcc:unverified]')

data = [['|trace|','source order','prime r','gcd(r,disc P)','elliptic degree over F243'],
        ['10','254 / 234','127 / 13','1 / 1','4 to 35'],
        ['14','258 / 230','43 / 23','1 / 1','4 to 33'],
        ['22','266 / 222','19 / 37','1 / 1','4 to 26'],
        ['26','270 / 218','none / 109','-- / 1','4 to 20']]
t = Table(data, colWidths=[53,93,83,100,144], hAlign='LEFT')
t.setStyle(TableStyle([('BACKGROUND',(0,0),(-1,0),colors.HexColor('#233b57')),
                       ('TEXTCOLOR',(0,0),(-1,0),colors.white),
                       ('FONTNAME',(0,0),(-1,0),'Helvetica-Bold'),
                       ('FONTSIZE',(0,0),(-1,-1),8),
                       ('BOTTOMPADDING',(0,0),(-1,-1),6),
                       ('TOPPADDING',(0,0),(-1,-1),6),
                       ('ROWBACKGROUNDS',(0,1),(-1,-1),[colors.white,colors.HexColor('#edf2f7')]),
                       ('LINEBELOW',(0,-1),(-1,-1),0.5,colors.HexColor('#cbd5e1'))]))
story += [t,Spacer(1,12)]
body('<b>Subgroup-preserving existence.</b> disc(X^10-tX^5+243)=5^10 3^20 (t^2-972)^5. For each prime r with gcd(r,disc)=1, the two equal-Weil-polynomial Tate modules are free rank-one over the same finite-etale order. Integral Tate yields an F3-isogeny from the restriction to J(Y) of degree prime to r. This proves an injective transfer exists on the listed r-subgroups for seven traces; no computable isogeny is supplied. The criterion is inconclusive for trace -26. [pcc:unverified]')
body('<b>Cover-degree bounds and four injective pullbacks.</b> Howe Theorem 4.17 applies over F243: the four imaginary quadratic discriminants -872, -776, -488 and -296 are fundamental, so the source elliptic endomorphism ring is generated by Frobenius. His Hermite bound gives the displayed upper limits; the geometric exclusion on page 3 gives the lower limit four. For traces -14, -10, +22 and +26, the selected primes 43, 127, 37 and 109 exceed those limits. Push-pull makes the cover pullback injective on the selected prime subgroup over F243. This does not by itself place the image in J(Y)(F3); the separate integral Tate argument gives an abstract F3-isogeny in seven traces. No rational-function formula is yet available. Eleven axiom-free Lean arithmetic declarations check the prime, gcd and integer bound inputs; geometry remains paper-level. [pcc:unverified]')
story.append(Paragraph('Sources: Diem, Weil-restrictions of abelian varieties; Tate 1966, Endomorphisms of abelian varieties over finite fields; Waterhouse-Milne 1971; Poonen-Rybakov, Lattices in Tate modules; Howe, arxiv.org/pdf/2110.04221, Theorem 4.17. Full equations, proof and exact receipts: THEOREM.md. Practical attack costs for this stratum are not established.', styles['GateSmall']))

def footer(canvas, doc):
    canvas.saveState()
    canvas.setFont('Helvetica',8)
    canvas.setFillColor(colors.HexColor('#64748b'))
    canvas.drawString(36,26,'15 November 2026  |  Odd-degree-five carrier study')
    canvas.drawRightString(576,26,'4')
    canvas.restoreState()

SimpleDocTemplate(str(addendum), pagesize=(612,792), leftMargin=36, rightMargin=36,
                  topMargin=40, bottomMargin=44).build(story, onFirstPage=footer)
subprocess.run(['pdfseparate','-f','1','-l','3',str(pdf),str(tmp/'base-%d.pdf')], check=True,
               stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
subprocess.run(['pdfunite',str(tmp/'base-1.pdf'),str(tmp/'base-2.pdf'),str(tmp/'base-3.pdf'),
                str(addendum),str(merged)], check=True)
merged.replace(pdf)
print(pdf)
