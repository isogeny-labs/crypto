#!/usr/bin/env python3
"""Tables and one figure for the Smith transfer cost study.

Reads runs.jsonl (driver) and analysis.json (genus_ladder_analyze). Cell means,
their intervals and the exponent fits are read from analysis.json. The
between-arm ratios are computed here (the analyzer has none for these arm
names): ratio of cell means with a paired hierarchical bootstrap (curves, then
seeds within a curve; the same resample in numerator and denominator).
"""
import json, math, random, sys

runs_path = sys.argv[1] if len(sys.argv) > 1 else "runs.jsonl"
an_path = sys.argv[2] if len(sys.argv) > 2 else "analysis.json"
R = [json.loads(l) for l in open(runs_path)]
A = json.load(open(an_path))
SURF, INK, INK2, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df"
ARMS = ["H_C_double_lp+pre", "H_rho_neg", "C_transfer_diem_2lp", "C_rho_neg"]
COL = {"H_C_double_lp+pre": "#2a78d6", "H_rho_neg": "#1baf7a",
       "C_transfer_diem_2lp": "#eb6834", "C_rho_neg": "#eda100"}
LABEL = {"H_C_double_lp+pre": "index calculus on H (2LP)", "H_rho_neg": "rho on H",
         "C_transfer_diem_2lp": "C route: transfer + Diem on C (2LP)", "C_rho_neg": "rho on C"}
READ = ["fpm_low", "fpm_mid", "fpm_high"]
INV = {"fpm_low": 1.0, "fpm_mid": 10.0, "fpm_high": 30.0}
LA = {"fpm_low": 1.0, "fpm_mid": 9.0, "fpm_high": 9.0}
BOOT = 2000


def g(v, k):
    return float(v.get(k, 0) or 0)


def cost(v, rd):
    return g(v, "cantor_mul") + g(v, "rel_mul") + INV[rd] * g(v, "cantor_inv") + LA[rd] * g(v, "la_mul")


def tcost(v, rd):
    return g(v, "transfer_mul") + INV[rd] * g(v, "transfer_inv")


def sci(x):
    if x is None or (isinstance(x, float) and (math.isnan(x) or math.isinf(x))):
        return "-"
    if x == 0:
        return "0"
    if abs(x) >= 1e5 or abs(x) < 1e-2:
        return f"{x:.2e}"
    if abs(x) >= 100:
        return f"{x:,.0f}"
    return f"{x:.3g}"


runs = [v for v in R if v.get("kind") == "run"]
primes = sorted({v["p"] for v in runs})
# p -> arm -> curve -> seed -> record
T = {}
for v in runs:
    T.setdefault(v["p"], {}).setdefault(v["arm"], {}).setdefault(v["curve_seed"], {})[v["seed"]] = v


def ratio(p, num, den, fn, fd, seed=1):
    """Ratio of means over the (curve, seed) pairs present in both arms, with interval."""
    a, b = T[p].get(num, {}), T[p].get(den, {})
    curves = sorted(c for c in a if c in b and set(a[c]) & set(b[c]))
    if not curves:
        return None
    pairs = {c: sorted(set(a[c]) & set(b[c])) for c in curves}

    def val(pick):
        n = sum(fn(a[c][s]) for c, ss in pick for s in ss)
        d = sum(fd(b[c][s]) for c, ss in pick for s in ss)
        return n / d if d else float("nan")

    point = val([(c, pairs[c]) for c in curves])
    rng = random.Random(1000003 * p + seed)
    bs = []
    for _ in range(BOOT):
        pick = []
        for _ in curves:
            c = rng.choice(curves)
            pick.append((c, [rng.choice(pairs[c]) for _ in pairs[c]]))
        bs.append(val(pick))
    bs = sorted(x for x in bs if not math.isnan(x))
    return point, bs[int(0.025 * (len(bs) - 1))], bs[int(0.975 * (len(bs) - 1))], sum(len(s) for s in pairs.values())


def fmt_ratio(r):
    return "-" if r is None else f"{sci(r[0])} [{sci(r[1])}, {sci(r[2])}]"


def band(rs):
    if any(r is None for r in rs):
        return "-"
    if all(r[2] < 1 for r in rs):
        return "below"
    if all(r[1] > 1 for r in rs):
        return "above"
    return "unresolved"


cells = {(c["p"], c["arm"]): c for c in A["cells"] if c["family"] == "smith_transfer"}
out = []
w = out.append
w("# Smith transfer cost: tables\n")
w(f"Generated by `render.py` from `{runs_path}` and `{an_path}`; every figure is `[pcc:unverified]`.\n")
bad = [v for v in runs if not (v.get("certified") and v.get("ok"))]
fails = [v for v in R if v.get("kind") == "transfer_failed"]
skips = [v for v in R if v.get("kind") == "skip"]
w(f"Runs: {len(runs)}; not certified or wrong: {len(bad)}; transfer failures: {len(fails)}; "
  f"skipped (rho cap): {len(skips)}; zeta mismatches: {sum(1 for v in R if v.get('kind') == 'zeta_mismatch')}. "
  f"`ord_ratio` values seen: {sorted({v['ord_ratio'] for v in runs if 'ord_ratio' in v})}.\n")

w("## S1. Instance search\n")
w("| p | seeds tried | admitted (h r, h <= 8) | Smith-positive | accepted | rejects | search wall s |")
w("|--:|--:|--:|--:|--:|---|--:|")
tot_adm = tot_pos = 0
for c in sorted((v for v in R if v.get("kind") == "cell"), key=lambda v: v["p"]):
    tot_adm += c["admitted"]
    tot_pos += c["smith_positive"]
    rej = ", ".join(f"{k}: {n}" for k, n in sorted(c["rejects"].items()))
    w(f"| {c['p']} | {c['tried']} | {c['admitted']} | {c['smith_positive']} | {c['accepted']} | {rej} | {c['search_wall_s']:.1f} |")
if tot_adm:
    z = 1.96
    ph = tot_pos / tot_adm
    d = 1 + z * z / tot_adm
    ctr = ph + z * z / (2 * tot_adm)
    hw = z * math.sqrt(ph * (1 - ph) / tot_adm + z * z / (4 * tot_adm ** 2))
    w(f"\nPooled: Smith-positive / admitted = {tot_pos}/{tot_adm} = {ph:.3f} (Wilson 95% [{(ctr - hw) / d:.3f}, {(ctr + hw) / d:.3f}]).\n")

w("## S2. Instances\n")
w("| p | curve seed | #J | h | r | N = x^3 + n1 x + n0 | D = x^2 + d1 x + d0 | #C(F_p) = #H(F_p) |")
w("|--:|--:|--:|--:|--:|---|---|--:|")
for v in sorted((v for v in R if v.get("kind") == "instance"), key=lambda v: (v["p"], v["curve_seed"])):
    w(f"| {v['p']} | {v['curve_seed']} | {v['order']} | {v['h']} | {v['r']} | {v['N']} | {v['D']} | {v['n_points']} |")

w("\n## S3. Mean counts per cell\n")
w("FPM mid = cantor_mul + 10 inv + rel_mul + 9 la_mul; for the C arms cantor = Pic. In `C_transfer_diem_2lp` the transfer is inside rel_mul and inv.\n")
w("| p | arm | curves | runs | group ops | cantor_mul | inv | rel_mul | la_mul | relations | FPM mid [95%] |")
w("|--:|---|--:|--:|--:|--:|--:|--:|--:|--:|---|")


def mean(p, arm, k):
    v = [g(r, k) for c in T[p].get(arm, {}).values() for r in c.values()]
    return sum(v) / len(v) if v else float("nan")


for p in primes:
    for arm in ARMS:
        c = cells.get((p, arm))
        if not c:
            continue
        fm = c["fpm_mid"]
        w(f"| {p} | {arm} | {c['curves']} | {c['runs']} | {sci(mean(p, arm, 'group_ops'))} | {sci(mean(p, arm, 'cantor_mul'))} | "
          f"{sci(mean(p, arm, 'cantor_inv'))} | {sci(mean(p, arm, 'rel_mul'))} | {sci(mean(p, arm, 'la_mul'))} | "
          f"{sci(mean(p, arm, 'relations'))} | {sci(fm['mean'])} [{sci(fm['lo'])}, {sci(fm['hi'])}] |")

w("\n## S4. Transfer + Diem on C against index calculus on H\n")
w("Ratio of means, `C_transfer_diem_2lp / H_C_double_lp+pre` (below 1: the transfer route costs less), paired bootstrap 95%.\n")
w("| p | pairs | FPM low | FPM mid | FPM high | FPM band |")
w("|--:|--:|---|---|---|---|")
RAT = {}
for p in primes:
    rs = [ratio(p, "C_transfer_diem_2lp", "H_C_double_lp+pre", lambda v, rd=rd: cost(v, rd), lambda v, rd=rd: cost(v, rd)) for rd in READ]
    RAT[p] = rs
    w(f"| {p} | {rs[1][3] if rs[1] else 0} | {fmt_ratio(rs[0])} | {fmt_ratio(rs[1])} | {fmt_ratio(rs[2])} | {band(rs)} |")

w("\n## S5. Each arm against rho on H (the matched rho), and Diem against rho on C\n")
w("| p | ratio | FPM low | FPM mid | FPM high | FPM band |")
w("|--:|---|---|---|---|---|")
RHO = {}
for p in primes:
    for num, den in [("H_C_double_lp+pre", "H_rho_neg"), ("C_transfer_diem_2lp", "H_rho_neg"),
                     ("C_rho_neg", "H_rho_neg"), ("C_transfer_diem_2lp", "C_rho_neg")]:
        rs = [ratio(p, num, den, lambda v, rd=rd: cost(v, rd), lambda v, rd=rd: cost(v, rd)) for rd in READ]
        RHO[(p, num, den)] = rs
        w(f"| {p} | {num} / {den} | {fmt_ratio(rs[0])} | {fmt_ratio(rs[1])} | {fmt_ratio(rs[2])} | {band(rs)} |")

w("\n## S6. The transfer's own cost\n")
w("Share = (transfer_mul + I transfer_inv) / FPM of `C_transfer_diem_2lp`; parts are mean multiplications per run.\n")
w("| p | transfer_mul | transfer_inv | share low | share mid | share high | map | fit | Pic set-up | images | Pic classes and sums | Cantor | roots | Pic ops | Cantor ops | tries |")
w("|--:|--:|--:|---|---|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|")
SHARE = {}
for p in primes:
    recs = [r for c in T[p].get("C_transfer_diem_2lp", {}).values() for r in c.values()]
    if not recs:
        continue
    sh = [ratio(p, "C_transfer_diem_2lp", "C_transfer_diem_2lp", lambda v, rd=rd: tcost(v, rd), lambda v, rd=rd: cost(v, rd)) for rd in READ]
    SHARE[p] = sh
    pm = lambda k: sum(r["transfer_parts"][k] for r in recs) / len(recs)
    w(f"| {p} | {sci(mean(p, 'C_transfer_diem_2lp', 'transfer_mul'))} | {sci(mean(p, 'C_transfer_diem_2lp', 'transfer_inv'))} | "
      f"{fmt_ratio(sh[0])} | {fmt_ratio(sh[1])} | {fmt_ratio(sh[2])} | {sci(pm('map_mul'))} | {sci(pm('fit_mul'))} | {sci(pm('setup_mul'))} | "
      f"{sci(pm('image_mul'))} | {sci(pm('pic_mul'))} | {sci(pm('cantor_mul'))} | {sci(pm('root_mul'))} | {sci(pm('pic_ops'))} | {sci(pm('cantor_ops'))} | {sci(pm('tries'))} |")

w("\n## S7. Growth exponents in p (analyzer fits, ln mean cost on ln p)\n")
w("| arm | primes | FPM low | FPM mid | FPM high | group ops (GAE w = 0) |")
w("|---|--:|---|---|---|---|")
FIT = {(f["arm"], f["reading"]): f for f in A["fits"] if f["family"] == "smith_transfer"}
for arm in ARMS:
    def e(rd):
        f = FIT.get((arm, rd))
        return "-" if not f else f"{f['exponent']:.3f} [{f['lo']:.3f}, {f['hi']:.3f}]"
    f0 = FIT.get((arm, "fpm_mid"))
    w(f"| {arm} | {f0['primes'] if f0 else 0} | {e('fpm_low')} | {e('fpm_mid')} | {e('fpm_high')} | {e('gae_w0')} |")

w("\n## S8. Wall time (informational; shared host)\n")
w("| p | arm | mean wall s |")
w("|--:|---|--:|")
for p in primes:
    for arm in ARMS:
        if arm in T[p]:
            w(f"| {p} | {arm} | {mean(p, arm, 'wall_ns') / 1e9:.2f} |")
open("tables.md", "w").write("\n".join(out) + "\n")

# ── figure ──────────────────────────────────────────────────────────────


def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;")


def panel(x0, y0, pw, ph, title, ylab, ymin, ymax, draw):
    lx0, lx1 = math.log10(primes[0]) - 0.08, math.log10(primes[-1]) + 0.08
    ly0, ly1 = math.log10(ymin), math.log10(ymax)
    X = lambda p: x0 + 62 + (math.log10(p) - lx0) / (lx1 - lx0) * (pw - 82)
    Y = lambda v: y0 + ph - 44 - (math.log10(v) - ly0) / (ly1 - ly0) * (ph - 84)
    b = [f'<text x="{x0 + 62}" y="{y0 + 24}" font-size="13" font-weight="600" fill="{INK}">{esc(title)}</text>']
    for k in range(math.ceil(ly0), math.floor(ly1) + 1):
        yy = Y(10 ** k)
        b.append(f'<line x1="{x0 + 62}" x2="{x0 + pw - 20}" y1="{yy:.1f}" y2="{yy:.1f}" stroke="{GRID}"/>')
        lab = f"1e{k}" if abs(k) > 2 else f"{10 ** k:g}"
        b.append(f'<text x="{x0 + 56}" y="{yy + 4:.1f}" font-size="11" text-anchor="end" fill="{INK2}">{lab}</text>')
    for p in primes:
        b.append(f'<text x="{X(p):.1f}" y="{y0 + ph - 26}" font-size="11" text-anchor="middle" fill="{INK2}">{p}</text>')
    b.append(f'<text x="{x0 + pw / 2 + 20}" y="{y0 + ph - 8}" font-size="11" text-anchor="middle" fill="{INK2}">p</text>')
    b.append(f'<text x="{x0 + 14}" y="{y0 + ph / 2}" font-size="11" text-anchor="middle" fill="{INK2}" transform="rotate(-90 {x0 + 14} {y0 + ph / 2})">{esc(ylab)}</text>')
    b.extend(draw(X, Y))
    return b


def series(X, Y, pts, col, dash=""):
    b = []
    pts = [q for q in pts if q[1] and q[1] > 0]
    if len(pts) > 1:
        d = " ".join(f"{X(p):.1f},{Y(v):.1f}" for p, v, _, _ in pts)
        b.append(f'<polyline points="{d}" fill="none" stroke="{col}" stroke-width="2" {dash}/>')
    for p, v, lo, hi in pts:
        if lo and hi and lo > 0:
            b.append(f'<line x1="{X(p):.1f}" x2="{X(p):.1f}" y1="{Y(lo):.1f}" y2="{Y(hi):.1f}" stroke="{col}" stroke-width="1.5"/>')
        b.append(f'<circle cx="{X(p):.1f}" cy="{Y(v):.1f}" r="3.5" fill="{col}" stroke="{SURF}" stroke-width="1"/>')
    return b


if primes:
    allv = [cells[(p, a)]["fpm_mid"]["mean"] for p in primes for a in ARMS if (p, a) in cells]
    lo_all = [cells[(p, a)]["fpm_mid"]["lo"] for p in primes for a in ARMS if (p, a) in cells]
    ymin = 10 ** math.floor(math.log10(min(lo_all + allv)))
    ymax = 10 ** math.ceil(math.log10(max(allv)) + 0.05)

    def left(X, Y):
        b = []
        for a in ARMS:
            pts = [(p, cells[(p, a)]["fpm_mid"]["mean"], cells[(p, a)]["fpm_mid"]["lo"], cells[(p, a)]["fpm_mid"]["hi"]) for p in primes if (p, a) in cells]
            b += series(X, Y, pts, COL[a])
        return b

    rvals = [r[1] for p in primes for r in [RAT[p]] if r[1]]
    svals = [SHARE[p][1] for p in primes if p in SHARE and SHARE[p][1]]
    hv = [RHO[(p, "C_transfer_diem_2lp", "H_rho_neg")][1] for p in primes]
    hv = [x for x in hv if x]
    every = [x[1] for x in rvals + svals + hv] + [x[2] for x in rvals + svals + hv] + [1.0]
    rmin = 10 ** math.floor(math.log10(min(every)))
    rmax = 10 ** math.ceil(math.log10(max(every)) + 0.05)

    def right(X, Y):
        b = [f'<line x1="{X(primes[0]) - 20:.1f}" x2="{X(primes[-1]) + 20:.1f}" y1="{Y(1):.1f}" y2="{Y(1):.1f}" stroke="{INK2}" stroke-dasharray="4 3"/>']
        b += series(X, Y, [(p, *RAT[p][1][:3]) for p in primes if RAT[p][1]], "#eb6834")
        b += series(X, Y, [(p, *RHO[(p, "C_transfer_diem_2lp", "H_rho_neg")][1][:3]) for p in primes if RHO[(p, "C_transfer_diem_2lp", "H_rho_neg")][1]], "#1baf7a")
        b += series(X, Y, [(p, *SHARE[p][1][:3]) for p in primes if p in SHARE and SHARE[p][1]], "#eda100")
        return b

    W, Hh = 980, 496
    body = panel(0, 40, 500, 380, "Cost per solve, FPM mid (mean, 95% interval)", "F_p multiplication equivalents", ymin, ymax, left)
    body += panel(500, 40, 480, 380, "Ratios, FPM mid (paired bootstrap 95%)", "ratio", rmin, rmax, right)
    body.append(f'<text x="20" y="24" font-size="15" font-weight="700" fill="{INK}">Smith&#39;s reduction, counted end to end: genus-3 hyperelliptic DLP, Smith-positive curves</text>')
    body.append(f'<text x="20" y="{Hh - 56}" font-size="11" fill="{INK2}">left:</text>')
    lx = 62
    for a in ARMS:
        body.append(f'<rect x="{lx}" y="{Hh - 66}" width="12" height="12" fill="{COL[a]}"/><text x="{lx + 17}" y="{Hh - 56}" font-size="11" fill="{INK}">{esc(LABEL[a])}</text>')
        lx += 27 + 6.2 * len(LABEL[a])
    lx = 62
    body.append(f'<text x="20" y="{Hh - 36}" font-size="11" fill="{INK2}">right:</text>')
    for col, lab in [("#eb6834", "C route / IC on H"), ("#1baf7a", "C route / rho on H"), ("#eda100", "transfer share of C route")]:
        body.append(f'<rect x="{lx}" y="{Hh - 46}" width="12" height="12" fill="{col}"/><text x="{lx + 17}" y="{Hh - 36}" font-size="11" fill="{INK}">{esc(lab)}</text>')
        lx += 27 + 6.2 * len(lab)
    body.append(f'<text x="{W - 20}" y="{Hh - 10}" font-size="10" text-anchor="end" fill="{INK2}">[pcc:unverified]; toy primes; 3 curves x 2 seeds per point</text>')
    open("fig_cost.svg", "w").write(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {Hh}" width="{W}" height="{Hh}" font-family="system-ui, -apple-system, Segoe UI, sans-serif" role="img" aria-label="Smith transfer cost against p">'
        f'<rect width="{W}" height="{Hh}" fill="{SURF}"/>' + "\n".join(body) + "</svg>\n")
print("wrote tables.md, fig_cost.svg")
