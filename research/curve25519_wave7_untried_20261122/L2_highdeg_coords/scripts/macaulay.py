#!/usr/bin/env python3
"""L2 part (b2): counted Macaulay proxy for the m = 2 decomposition, same code for
x and for every f, on the same targets.

System (the engine's `bits` formulation, research src pkm_semaev.rs Membership::Bits):
  unknowns: n = 2T Boolean variables, z^2 = z (multilinear quotient ring);
  even f (x, ye, jac6): a = sum_{j<T} 2^j alpha_j          (V = [0, 2^T))
  odd  f (v, q, uv, xeye, xe): a = (1 - 2 sigma) sum_{j<T-1} 2^j alpha_j   (+-[0, 2^(T-1)))
  (same Boolean count; both give ~2^(T-1) +- classes per summand), b likewise;
  equation  Shat_R(z) = S^f(a, b, f(-R)) reduced mod z^2 = z.
Shat_R is computed exactly from its values on the cube (S^f evaluated on the grid,
then the Moebius transform), so every coefficient is exact.

Reported per (k, f, T, target):
  e = deg Shat_R, terms, |Z| = Boolean roots, true (rational, re-added) decompositions,
  census agreement (R covered by the signed base  <=>  true decompositions > 0);
  M1 (plain Macaulay): rows m*Shat, deg m + e <= D. 1 is in the span iff some g of
     degree <= D - e has g*Shat = 1 on the cube, i.e. iff deg(1/Shat) <= D - e
     (evaluation isomorphism), so d1 = deg_ml(1/Shat) exactly, rows = sum_{i<=d1} C(n,i);
  M2 (degree-D Macaulay closure, MutantXL rule, the counted proxy): V_D = span of
     m*Shat (deg m <= D - e), closed under z_i * h for h in V_D of degree <= D - 1
     (degree falls); at D = n the ring is closed, V_n = the ideal. D_ref = first D with
     1 in V_D (refutation); for a target with a unique Boolean root D_root = first D
     with n independent polynomials of degree <= 1 in V_D (they pin the root).
     Recorded per D: active columns sum_{i<=D} C(n,i), rank V_D, counted mul-adds
     (rows x pivots x active columns per reduction, rows x active columns per pivot in
     each RREF). Check: rank V_n = 2^n - |Z|.
"""
import argparse, itertools, json, math, sys, time
import numpy as np
import common as C_
from linalg import mmod, rref


def popcount(x):
    return bin(x).count('1')


class Ring:
    def __init__(self, n):
        self.n = n
        N = 1 << n
        self.N = N
        self.order = sorted(range(N), key=lambda m: (-popcount(m), m))
        self.pos = np.empty(N, dtype=np.int64)
        self.pos[self.order] = np.arange(N)
        self.deg = np.array([popcount(m) for m in self.order])
        self.cnt = [sum(math.comb(n, i) for i in range(D + 1)) for D in range(n + 1)]
        self.zmaps = []
        for i in range(n):
            bit = 1 << i
            T = np.array([m for m in range(N) if m & bit], dtype=np.int64)
            self.zmaps.append((self.pos[T], self.pos[T ^ bit]))

    def mulz(self, H, i, p):
        G = np.zeros_like(H)
        a, b = self.zmaps[i]
        G[:, a] = (H[:, a] + H[:, b]) % p
        return G


def moebius(vals, n, p):
    """values on the cube (index = mask) -> multilinear coefficients."""
    h = vals.astype(np.int64).copy() % p
    for i in range(n):
        h = h.reshape(-1, 2, 1 << i)
        h[:, 1, :] = (h[:, 1, :] - h[:, 0, :]) % p
        h = h.reshape(-1)
    return h


def closure(ring, shat_perm, e, p, mode, Dmax):
    """M2. shat_perm: coefficients in the degree-descending column order."""
    n, N = ring.n, ring.N
    B = np.zeros((0, N), dtype=np.int64); piv = []
    processed = set()
    counter = {'muladds': 0}
    hist = []
    mult_rows = {0: shat_perm[None, :] % p}  # rows m*Shat by |m| (generated by z_i, i increasing)
    mult_last = {0: [-1]}
    D0 = max(e, 0)
    res = dict(D_ref=None, D_root=None)
    for D in range(D0, Dmax + 1):
        lo = N - ring.cnt[D]
        j = D - e
        if j > 0:
            prev, last = mult_rows[j - 1], mult_last[j - 1]
            newr, newl = [], []
            for row, li in zip(prev, last):
                for i in range(li + 1, n):
                    newr.append(ring.mulz(row[None, :], i, p)[0]); newl.append(i)
            mult_rows[j] = np.array(newr, dtype=np.int64).reshape(-1, N); mult_last[j] = newl
            X = mult_rows[j]
        else:
            X = mult_rows[0]
        def absorb(X):
            nonlocal B, piv
            if X.shape[0] == 0:
                return 0
            Xa = X[:, lo:]
            if piv:
                pa = [c - lo for c in piv]
                Xa = (Xa - mmod(Xa[:, pa], B[:, lo:], p)) % p
                counter['muladds'] += Xa.shape[0] * len(piv) * Xa.shape[1]
            Xa = Xa[np.any(Xa != 0, axis=1)]
            if Xa.shape[0] == 0:
                return 0
            Rn, pn = rref(Xa, p, counter=counter)
            Rfull = np.zeros((Rn.shape[0], N), dtype=np.int64); Rfull[:, lo:] = Rn
            pn = [c + lo for c in pn]
            if piv:
                B = (B - mmod(B[:, pn], Rfull, p)) % p
                counter['muladds'] += B.shape[0] * len(pn) * (N - lo)
            B = np.vstack([B, Rfull]); piv = piv + pn
            o = np.argsort(piv); B = B[o]; piv = [piv[i] for i in o]
            return len(pn)
        absorb(X)
        while True:
            low = [ii for ii, c in enumerate(piv) if (D == n or ring.deg[c] <= D - 1) and c not in processed]
            if not low:
                break
            for ii in low:
                processed.add(piv[ii])
            H = B[low]
            cand = np.vstack([ring.mulz(H, i, p) for i in range(n)])
            absorb(cand)
        refuted = (N - 1) in piv
        lin = sum(1 for c in piv if ring.deg[c] <= 1)
        hist.append(dict(D=D, cols=ring.cnt[D], rank=len(piv), muladds=counter['muladds'], refuted=refuted, lin=lin))
        if refuted and res['D_ref'] is None:
            res['D_ref'] = D
        if lin >= n and res['D_root'] is None:
            res['D_root'] = D
        if (mode == 'ref' and refuted) or (mode == 'root' and lin >= n) or D == Dmax:
            break
    res['hist'] = hist
    return res


def run(a):
    sp = json.load(open(a.sumpoly))
    out = []
    t0 = time.time()
    for k in a.k:
        C = C_.Curve(k); p, n, r = C.p, C.n, C.r
        rngT = np.random.default_rng(C_.dseed(k, 'targets'))
        common_targets = []
        while len(common_targets) < a.targets:
            s = int(rngT.integers(1, r)); common_targets.append((8 * s) % n)
        for f in a.funcs:
            S = sp[str(k)][f]['S']
            if S is None:
                print(f'k={k} f={f}: no S', file=sys.stderr); continue
            Dp = S['pervar_degree']
            coef = np.zeros((Dp + 1, Dp + 1, Dp + 1), dtype=np.int64)
            for i, j, kk, c in S['coeffs']:
                for perm in set(itertools.permutations((i, j, kk))):
                    coef[perm] = c
            val, ok = C.fvals(f)
            fullval = np.full(n, -1, dtype=np.int64); fullval[1:] = np.where(ok, val, -1)
            odd = C_.DESK[f]['parity'] == 'odd'
            FT = C_.FTable(C, f)
            for T in a.T:
                nb = T; nn = 2 * T
                t = T - 1 if odd else T
                idx = np.arange(1 << nb)
                if odd:
                    m = idx & ((1 << t) - 1); sg = idx >> t
                    avals = np.where(sg == 0, m, (p - m) % p)
                else:
                    avals = idx % p
                Apow = np.ones((1 << nb, Dp + 1), dtype=np.int64)
                for e_ in range(1, Dp + 1):
                    Apow[:, e_] = Apow[:, e_ - 1] * avals % p
                # base (census) for this encoding: f in [0, 2^t)
                base_logs = FT.interval(0, 1 << t)
                cls = C_.fold(base_logs, n)
                Ssig = np.concatenate([cls, (-cls) % n])
                sums = (Ssig[:, None] + Ssig[None, :]) % n
                covered_set = np.unique(sums[(sums % 8 == 0) & (sums != 0)])
                rngc = np.random.default_rng(C_.dseed(k, f, T, 'covered'))
                cov_targets = list(rngc.choice(covered_set, size=min(a.covered, covered_set.size), replace=False)) if covered_set.size else []
                ring = Ring(nn) if T in a.m2T else None
                # value -> logs for lifting
                vdict = {}
                for l in base_logs:
                    vdict.setdefault(int(fullval[l]), []).append(int(l))
                    vdict.setdefault(int((-fullval[l]) % p), []).append(int((n - l) % n))
                for kind, tl in (('common', common_targets), ('covered', cov_targets)):
                    for lR in tl:
                        lR = int(lR)
                        cR = fullval[(n - lR) % n]
                        rec = dict(k=k, f=f, T=T, n=nn, kind=kind, target_log=lR, base_cols=int(cls.size), base_cov=float(covered_set.size / r))
                        if cR < 0:
                            rec['skip'] = 'f(-R) at a pole'; out.append(rec); continue
                        cp = np.array([pow(int(cR), e_, p) for e_ in range(Dp + 1)], dtype=np.int64)
                        Cm = (coef * cp[None, None, :]).sum(axis=2) % p  # exact: < (Dp+1) p^2
                        G = mmod(mmod(Apow, Cm, p), Apow.T.copy(), p)  # G[ia, ib]
                        vals = G.T.reshape(-1)  # index = ia + (ib << nb)
                        h = moebius(vals, nn, p)
                        nzm = np.nonzero(h)[0]
                        e = max(popcount(int(x)) for x in nzm) if nzm.size else 0
                        Z = np.nonzero(vals == 0)[0]
                        true = 0
                        for z in Z:
                            av, bv = int(avals[z & ((1 << nb) - 1)]), int(avals[z >> nb])
                            for l1 in vdict.get(av, []):
                                for l2 in vdict.get(bv, []):
                                    if (l1 + l2) % n == lR:
                                        true += 1
                        covered = bool(np.isin(lR, covered_set))
                        rec.update(e=e, terms=int(nzm.size), roots=int(Z.size), true_decomp=true,
                                   census_covered=covered, census_agrees=(covered == (true > 0)))
                        if Z.size == 0:
                            inv = np.array([pow(int(x), p - 2, p) for x in vals], dtype=np.int64)
                            hi = moebius(inv, nn, p)
                            d1 = max(popcount(int(x)) for x in np.nonzero(hi)[0])
                            rec['M1'] = dict(d_mult=d1, D=e + d1, rows=sum(math.comb(nn, i) for i in range(d1 + 1)),
                                             cols=sum(math.comb(nn, i) for i in range(min(nn, e + d1) + 1)))
                        if ring is not None and (Z.size == 0 or Z.size == 1):
                            sp_perm = np.zeros(ring.N, dtype=np.int64); sp_perm[ring.pos] = h
                            mode = 'ref' if Z.size == 0 else 'root'
                            cl = closure(ring, sp_perm, e, p, mode, nn)
                            last = cl['hist'][-1]
                            rec['M2'] = dict(mode=mode, D_ref=cl['D_ref'], D_root=cl['D_root'], hist=cl['hist'],
                                             rank_at_n_check=(last['rank'] == ring.N - Z.size) if last['D'] == nn else None)
                        out.append(rec)
                        print(f"k={k} f={f} T={T} {kind} e={rec.get('e')} terms={rec.get('terms')} roots={rec.get('roots')} true={rec.get('true_decomp')} "
                              f"M1={rec.get('M1',{}).get('D')} M2={rec.get('M2',{}).get('D_ref')}/{rec.get('M2',{}).get('D_root')} "
                              f"{time.time()-t0:.0f}s", file=sys.stderr)
                        if time.time() - t0 > a.budget:
                            print('BUDGET EXCEEDED, stopping', file=sys.stderr)
                            json.dump(out, open(a.out, 'w'), default=int); return
    json.dump(out, open(a.out, 'w'), default=int)
    import resource
    print(f'maxrss_MB {resource.getrusage(resource.RUSAGE_SELF).ru_maxrss/1024:.0f} wall {time.time()-t0:.0f}s', file=sys.stderr)


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--sumpoly', required=True)
    ap.add_argument('--k', type=int, nargs='+', default=[16, 18, 20])
    ap.add_argument('--funcs', nargs='+', default=['x', 'ye', 'xe', 'v', 'q', 'xeye', 'jac6', 'uv'])
    ap.add_argument('--T', type=int, nargs='+', default=[4, 5, 6])
    ap.add_argument('--m2T', type=int, nargs='+', default=[4, 5])
    ap.add_argument('--targets', type=int, default=10)
    ap.add_argument('--covered', type=int, default=3)
    ap.add_argument('--budget', type=float, default=7200)
    ap.add_argument('--out', required=True)
    run(ap.parse_args())
