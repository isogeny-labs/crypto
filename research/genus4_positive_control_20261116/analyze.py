#!/usr/bin/env python3
"""Gates, tables, figure and PDF for the genus-4 study (PROTOCOL sections 4-7)."""
import json
import math
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))
OLD = os.path.join(HERE, "..", "genus_ladder_bound_r_20261114", "bound_r.jsonl")
B = 2000
W = [("0", 0.0), ("0.1", 0.1), ("1", 1.0)]
ARMS = {"c": "C_double_lp+pre", "v": "C_double_lp+pre+coord", "w": "C_double_lp+pre+coord+unitT",
        "R": "R_rho_neg"}

new = [json.loads(l) for l in open(os.path.join(HERE, "run.jsonl"))]
old = [json.loads(l) for l in open(OLD)]


def runs(rows, arm):
    return {(r["p"], r["curve_seed"], r["seed"]): r for r in rows
            if r.get("kind") == "run" and r.get("family", "hyperelliptic") == "hyperelliptic"
            and r.get("g") == 4 and r["arm"] == arm}


X = {k: runs(new, a) for k, a in ARMS.items()}
O = {k: runs(old, a) for k, a in ARMS.items()}

# ── gates ──
gates = {"G1": [], "G2": []}
inst_new = {(r["p"], r["curve_seed"]): r for r in new if r.get("kind") == "instance"}
inst_old = {(r["p"], r["curve_seed"]): r for r in old if r.get("kind") == "instance" and r["family"] == "hyperelliptic"}
for k, o in inst_old.items():
    n = inst_new.get(k)
    if n is None or any(n[f] != o[f] for f in ("order", "h", "r")):
        gates["G1"].append(f"instance {k} differs or missing")
for arm, fields in [("c", ["group_ops", "rel_mul", "la_mul", "trials", "relations"]), ("R", ["group_ops", "native"])]:
    for k, o in O[arm].items():
        n = X[arm].get(k)
        if n is None:
            gates["G1"].append(f"{arm} {k} missing")
            continue
        for f in fields:
            if n[f] != o[f]:
                gates["G1"].append(f"{arm} {k} {f}: {n[f]} != {o[f]}")
for arm in ARMS:
    for k, r in X[arm].items():
        if not r.get("certified") or not r.get("ok"):
            gates["G2"].append(f"{arm} {k} not certified/ok")
gate_ok = {g: not v for g, v in gates.items()}


def total(r, w):
    if "rel_mul" in r:
        return r["group_ops"] + w * (r["rel_mul"] + r["la_mul"])
    return r["group_ops"] + w * r["native"]


def fpm(r):
    if "rel_mul" in r:
        return r["cantor_mul"] + 10 * r["cantor_inv"] + r["rel_mul"] + 16 * r["la_mul"]
    return r["cantor_mul"] + 10 * r["cantor_inv"]


def mean(v):
    return sum(v) / len(v)


def boot(num, den, p, fn, seed=20261119):
    rnd = random.Random(seed)
    gn, gd = {}, {}
    for k, r in num.items():
        if k[0] == p:
            gn.setdefault(k[1], []).append(fn(r))
    for k, r in den.items():
        if k[0] == p:
            gd.setdefault(k[1], []).append(fn(r))
    curves = sorted(gn)
    est = mean(sum(gn.values(), [])) / mean(sum(gd.values(), []))
    bs = []
    for _ in range(B):
        cs = [rnd.choice(curves) for _ in curves]
        n, d = [], []
        for c in cs:
            n += [rnd.choice(gn[c]) for _ in gn[c]]
            d += [rnd.choice(gd[c]) for _ in gd[c]]
        bs.append(mean(n) / mean(d))
    bs.sort()
    return est, bs[int(0.025 * B)], bs[int(0.975 * B) - 1]


ps = sorted({k[0] for k in X["w"]})
out = {"gates": gate_ok, "gate_failures": {g: v[:20] for g, v in gates.items()}, "per_p": [],
       "claims": "[pcc:unverified]"}
for p in ps:
    e = {"p": p, "runs": sum(1 for k in X["w"] if k[0] == p),
         "fallbacks": {a: sum(r.get("la_fallbacks", 0) for k, r in X[a].items() if k[0] == p) for a in "vw"},
         "v_over_c_la": boot(X["v"], X["c"], p, lambda r: r["la_mul"]),
         "w_over_c_la": boot(X["w"], X["c"], p, lambda r: r["la_mul"]),
         "w_over_c_rel": boot(X["w"], X["c"], p, lambda r: r["rel_mul"]),
         "w_rel_share": mean([r["rel_mul"] / (r["rel_mul"] + r["la_mul"]) for k, r in X["w"].items() if k[0] == p])}
    for arm in "cvw":
        for name, w in W:
            e[f"{arm}_over_R_w{name}"] = boot(X[arm], X["R"], p, lambda r, w=w: total(r, w))
        e[f"{arm}_over_R_fpm"] = boot(X[arm], X["R"], p, fpm)
    for arm in "vw":
        for name, w in W[1:]:
            e[f"{arm}_over_c_w{name}"] = boot(X[arm], X["c"], p, lambda r, w=w: total(r, w))
    e["w_below_R_all_prices"] = all(e[f"w_over_R_w{n}"][2] < 1 for n, _ in W)
    out["per_p"].append(e)
json.dump(out, open(os.path.join(HERE, "analysis.json"), "w"), indent=1)

f3 = lambda t: f"{t[0]:.3f} [{t[1]:.3f}, {t[2]:.3f}]"
L = ["# Tables (generated by analyze.py; every number [pcc:unverified])", "",
     "Gates: " + ", ".join(f"{g} {'pass' if ok else 'FAIL'}" for g, ok in gate_ok.items()), "",
     "## Components (paired on curve, seed)", "",
     "| p | runs/arm | fallbacks v, w | LA v/c | LA w/c | relation w/c | relation share of w's native mult. |",
     "|--:|--:|--|--|--|--|--:|"]
for e in out["per_p"]:
    L.append(f"| {e['p']} | {e['runs']} | {e['fallbacks']['v']}, {e['fallbacks']['w']} | {f3(e['v_over_c_la'])} | "
             f"{f3(e['w_over_c_la'])} | {f3(e['w_over_c_rel'])} | {e['w_rel_share']:.2f} |")
L += ["", "## Arm total / rho total (§5a band) and FPM", "",
      "| p | arm | w = 0 | w = 0.1 | w = 1 | FPM | arm/c at w = 0.1 | arm/c at w = 1 |", "|--:|--|--|--|--|--|--|--|"]
for e in out["per_p"]:
    for arm in "cvw":
        rc = ("–", "–") if arm == "c" else (f3(e[f"{arm}_over_c_w0.1"]), f3(e[f"{arm}_over_c_w1"]))
        L.append(f"| {e['p']} | {arm} | {f3(e[f'{arm}_over_R_w0'])} | {f3(e[f'{arm}_over_R_w0.1'])} | "
                 f"{f3(e[f'{arm}_over_R_w1'])} | {f3(e[f'{arm}_over_R_fpm'])} | {rc[0]} | {rc[1]} |")
L += ["", "w below rho at all three prices (upper bounds < 1): "
      + ", ".join(f"p = {e['p']}: {e['w_below_R_all_prices']}" for e in out["per_p"])]
open(os.path.join(HERE, "tables.md"), "w").write("\n".join(L) + "\n")

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.backends.backend_pdf import PdfPages

fig, ax = plt.subplots(1, 3, figsize=(15, 4.6))
x = [e["p"] for e in out["per_p"]]
cols = {"c": "#6b6b6b", "v": "#1f77b4", "w": "#d62728"}
for k, (name, _) in enumerate(W):
    for arm in "cvw":
        v = [e[f"{arm}_over_R_w{name}"] for e in out["per_p"]]
        ax[k].errorbar(x, [t[0] for t in v], yerr=[[t[0] - t[1] for t in v], [t[2] - t[0] for t in v]],
                       fmt="o-", color=cols[arm], label=arm, capsize=2)
    ax[k].axhline(1, color="k", lw=0.8, ls="--")
    ax[k].set(xscale="log", yscale="log", xlabel="p", ylabel="arm / matched rho", title=f"w = {name}")
    ax[k].legend()
fig.suptitle("Genus 4 (h <= 2): c, v (coordinate Wiedemann), w (+ unit-T walk) against negation rho  [pcc:unverified]")
fig.tight_layout()
fig.savefig(os.path.join(HERE, "figure.svg"))
fig.savefig(os.path.join(HERE, "figure.png"), dpi=150)
with PdfPages(os.path.join(HERE, "REPORT.pdf")) as pdf:
    pdf.savefig(fig)
    for src in ["RESULTS.md", "tables.md"]:
        pth = os.path.join(HERE, src)
        if os.path.exists(pth):
            t = plt.figure(figsize=(11, 8.5))
            t.text(0.03, 0.97, open(pth).read()[:7000], va="top", family="monospace", fontsize=5.6)
            pdf.savefig(t)
print("\n".join(L))
