#!/usr/bin/env python3
"""Join rerun.json (new) with the recorded old values; write tables.md, summary.json, rerun.svg.

Reads, never edits: rerun.json, the v3, tower_large and small_de records.
Standard library only.  Every number is [pcc:unverified].
"""
import json
import math
import os
import sys
from statistics import median

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "rerun.json")
OLD = os.path.join(HERE, "..", "chained_prime_transfer_20261111")
R = json.load(open(SRC))
W = (0.0, 0.1, 1.0)
WS = ("0", "0.1", "1")
md = ["<!-- generated by render_rerun.py from rerun.json and the recorded old files; do not edit -->\n"]
summary = {}


def f(x, n=3):
    if x is None or x != x:
        return "-"
    if abs(x) >= 1e5 or (0 < abs(x) < 0.01):
        return f"{x:.{n}g}"
    if abs(x) >= 100:
        return f"{x:.0f}"
    return f"{x:.{n}g}"


def r3(xs):
    return " / ".join(f(x) for x in xs)


# ------------------------------------------------------------------ v3
if "v3" in R:
    old = json.load(open(os.path.join(OLD, "results_v3.json")))["rows"]
    md.append("## v3 (genus-2 Jacobian of the bielliptic pull-back)\n")
    md.append("### Linear-algebra counter, recorded versus counted (arm L: the old relations, the counted elimination)\n")
    md.append("| p | rows | columns (fb) | recorded `la_field_ops` | `(fb+2) x rows` | recorded = it + 1? | counted mulmods | counted adds | counted / recorded | free path same answer |")
    md.append("|--:|--:|--:|--:|--:|:-:|--:|--:|--:|:-:|")
    for v in R["v3"]:
        lc, L = v["legacy_counter"], v["L"]
        md.append(
            f"| {v['p']} | {lc['rows']} | {lc['fb_size']} | {lc['la_field_ops']} | {lc['matrix_size_fb_plus_2_times_rows']} | "
            f"{'yes' if lc['equal'] else 'no'} | {L['la_mul']} | {L['la_add']} | {f(L['la_mul_over_recorded'])} | {lc['free_path_same_answer']} |"
        )
    md.append("")
    md.append("### Gate: the rerun reproduces the record")
    md.append("")
    md.append("| p | candidate | rho on E1 (recorded 428/357/370/847) | IC group ops | IC trials | LA mulmods | reproduces | word-Jacobian cross-check |")
    md.append("|--:|--:|--:|--:|--:|--:|:-:|:-:|")
    for v in R["v3"]:
        o = v["old"]
        md.append(
            f"| {v['p']} | {v['candidate']} | {o['rho_src_ops']} | {o['ic_group_ops']} | {o['ic_trials']} | {o['ic_la_mulmods']} | "
            f"{v['gate_reproduces_record']} | {v['word_jacobian_crosscheck']} |"
        )
    md.append("")
    md.append("### Matched rho on E1 (mean over seeds)\n")
    md.append("| p | recorded rho (1 seed) | plain total | negation total | negation walk ops | negation set-up and other | canonicalisations | walk share |")
    md.append("|--:|--:|--:|--:|--:|--:|--:|--:|")
    for v in R["v3"]:
        n, pl = v["rho_negation"], v["rho_plain"]
        md.append(
            f"| {v['p']} | {v['old']['rho_src_ops']} | {f(pl['total_ops'])} | {f(n['total_ops'])} | {f(n['walk_ops'])} | {f(n['other_ops'])} | {f(n['native'])} | {f(n['walk_share'])} |"
        )
    md.append("")
    md.append("### IC cost composition (mean over 8 seeds; old = recorded, 1 seed)\n")
    md.append("| p | arm | group ops | set-up | walk | trials | relations | columns | rel mulmods | LA mulmods | LA adds |")
    md.append("|--:|--|--:|--:|--:|--:|--:|--:|--:|--:|--:|")
    for v in R["v3"]:
        o = v["old"]
        md.append(f"| {v['p']} | old | {o['ic_group_ops']} | - | - | {o['ic_trials']} | {o['ic_relations']} | {o['ic_fb']} | - | {o['ic_la_mulmods']} | - |")
        L = v["L"]
        md.append(f"| {v['p']} | L | {L['group_ops']} | - | - | {L['trials']} | {L['relations']} | {v['legacy_counter']['fb_size']} | - | {L['la_mul']} | {L['la_add']} |")
        for a in "ABC":
            g = v["arms"][a]
            md.append(
                f"| {v['p']} | {a} | {f(g['group_ops'])} | {f(g['setup_ops'])} | {f(g['walk_ops'])} | {f(g['trials'])} | {f(g['relations'])} | {f(g['columns'])} | {f(g['rel_mul'])} | {f(g['la_mul'])} | {f(g['la_add'])} |"
            )
    md.append("")
    md.append("### Distance to the matched rho (IC total over negation-map rho total; recorded = IC total over recorded plain rho)\n")
    md.append("| p | arm | w=0 | w=0.1 | w=1 | calibrated (info) | class vs negation | order at 0 GAE | vs plain (0 / 0.1 / 1) | vs negation walk only (0 / 0.1 / 1) |")
    md.append("|--:|--|--:|--:|--:|--:|--|--|--|--|")
    for v in R["v3"]:
        o = v["old"]["ratio_vs_recorded_rho"]
        md.append(f"| {v['p']} | recorded | {f(o[0])} | {f(o[1])} | {f(o[2])} | - | above | above | - | - |")
        for a in ("old", "L", "A", "B", "C"):
            c = v["compare"][a]
            nm = {"old": "recorded IC, new rho", "L": "L (accounting only)"}.get(a, a)
            md.append(
                f"| {v['p']} | {nm} | {f(c['ratio_neg'][0])} | {f(c['ratio_neg'][1])} | {f(c['ratio_neg'][2])} | {f(c['ratio_neg_cal'])} | "
                f"{c['class_neg']} | {c['order_at_0_vs_neg']} | {r3(c['ratio_plain'])} | {r3(c['ratio_neg_walk'])} |"
            )
    md.append("")
    summary["v3"] = {
        str(v["p"]): {
            "recorded_ratio": v["old"]["ratio_vs_recorded_rho"],
            **{a: {"ratio_neg": v["compare"][a]["ratio_neg"], "cal": v["compare"][a]["ratio_neg_cal"], "class": v["compare"][a]["class_neg"]} for a in ("old", "L", "A", "B", "C")},
        }
        for v in R["v3"]
    }

# ------------------------------------------------------------------ tower
if "tower" in R:
    old = {r["p"]: r for r in json.load(open(os.path.join(OLD, "tower_large", "tower_large.json")))["rows"]}
    md.append("## tower_large (genus-2 and genus-3 rungs over an elliptic curve, p up to 16001)\n")
    md.append("### Matched rho on E (mean over instances and seeds)\n")
    md.append("| p | recorded rho_E (plain, old walk) | recorded walk steps | plain total | negation total | negation walk ops | negation set-up and other | walk share | canon. |")
    md.append("|--:|--:|--:|--:|--:|--:|--:|--:|--:|")
    for t in R["tower"]:
        o = old.get(t["p"], {})
        n, pl = t["rho_negation"], t["rho_plain"]
        md.append(
            f"| {t['p']} | {f(o.get('rho_ops'))} | {f(o.get('rho_steps'))} | {f(pl['total_ops'])} | {f(n['total_ops'])} | {f(n['walk_ops'])} | {f(n['other_ops'])} | {f(n['walk_share'])} | {f(n['native'])} |"
        )
    md.append("")
    for gi, g in ((0, 2), (1, 3)):
        md.append(f"### Genus {g}: distance to the negation-map rho (recorded: `ratio_la`, IC with full base over plain rho)\n")
        md.append("| p | recorded w=0 / 0.1 / 1 | recorded class | A w=0 / 0.1 / 1 | B w=0 / 0.1 / 1 | C w=0 / 0.1 / 1 | C calibrated | class A | class B | class C | C vs neg walk only (0 / 0.1 / 1) |")
        md.append("|--:|--|--|--|--|--|--:|--|--|--|--|")
        for t in R["tower"]:
            o = old.get(t["p"], {})
            rr = o.get("ratio_la", [[None] * 3] * 2)[gi]
            vc = o.get("verdict_la", ["-", "-"])[gi]
            vc = "above" if vc.startswith("above") else ("below" if vc.startswith("below") else "unresolved")
            cm = t["compare"]
            if f"g{g}_C" not in cm:
                md.append(f"| {t['p']} | {r3(rr)} | {vc} | skipped |||||||")
                continue
            def cell(a):
                return r3(cm[f"g{g}_{a}"]["ratio_neg"])
            md.append(
                f"| {t['p']} | {r3(rr)} | {vc} | {cell('A')} | {cell('B')} | {cell('C')} | {f(cm[f'g{g}_C']['ratio_neg_cal'])} | "
                f"{cm[f'g{g}_A']['class_neg']} | {cm[f'g{g}_B']['class_neg']} | {cm[f'g{g}_C']['class_neg']} | {r3(cm[f'g{g}_C']['ratio_neg_walk'])} |"
            )
        md.append("")
    md.append("### IC composition (mean over instances x seeds)\n")
    md.append("| p | genus | arm | group ops | trials | relations | columns | rel mulmods | LA mulmods | LA adds | certified |")
    md.append("|--:|--:|--|--:|--:|--:|--:|--:|--:|--:|--|")
    for t in R["tower"]:
        for g in (2, 3):
            for a in "ABC":
                x = t["arms"].get(f"g{g}_{a}")
                if x:
                    md.append(
                        f"| {t['p']} | {g} | {a} | {f(x['group_ops'])} | {f(x['trials'])} | {f(x['relations'])} | {f(x['columns'])} | {f(x['rel_mul'])} | {f(x['la_mul'])} | {f(x['la_add'])} | {x['certified']}/{x['runs']} |"
                    )
    md.append("")
    md.append("### Cost of genus 3 over genus 2 (ratio of IC totals; recorded = full base, LA mulmods priced)\n")
    md.append("| p | recorded IC3/IC2 (w=0) | A: w=0 / 0.1 / 1 | C: w=0 / 0.1 / 1 | best arm per price (g=3 over g=2) |")
    md.append("|--:|--:|--|--|--|")
    for t in R["tower"]:
        a = t["arms"]
        if "g2_A" not in a or "g3_A" not in a:
            continue
        def q(arm, w):
            return a[f"g3_{arm}"]["total"][w] / a[f"g2_{arm}"]["total"][w]
        best = []
        for w in range(3):
            b3 = min(a[f"g3_{x}"]["total"][w] for x in "ABC")
            b2 = min(a[f"g2_{x}"]["total"][w] for x in "ABC")
            best.append(b3 / b2)
        md.append(f"| {t['p']} | {f(old.get(t['p'], {}).get('ic3_over_ic2'))} | {r3([q('A', w) for w in range(3)])} | {r3([q('C', w) for w in range(3)])} | {r3(best)} |")
    md.append("")
    summary["tower"] = {
        str(t["p"]): {k: {"ratio_neg": v["ratio_neg"], "class": v["class_neg"]} for k, v in t["compare"].items()}
        for t in R["tower"]
    }

# ------------------------------------------------------------------ small_de
if "smallde" in R:
    od = json.load(open(os.path.join(HERE, "..", "small_de_endo_fb_20261112", "small_de_derived.json")))["cells"]
    oldmap = {(c["bits"], c["m"], c["d"], c["arm"]): c for c in od}
    md.append("## small_de (24- and 28-bit cells)\n")
    rows = []
    for c in R["smallde"]:
        rho = {r["kind"]: r for r in c["rho"]}
        for a in c["arms"]:
            k = (c["bits"], c["m"], c["d"], a["arm"])
            o = oldmap.get(k)
            if not o:
                continue
            rec = {"key": k}
            rec["ic_same"] = max(abs(a["single"][i] / o["single"][str(W[i]) if str(W[i]) in o["single"] else WS[i]][0] - 1) for i in range(3)) if o else None
            best_old = [o["rho_best"][w][0] for w in ("0.0", "0.1", "1.0")]
            rec["old_ratio"] = [a["single"][i] / best_old[i] for i in range(3)]
            rec["old_ref"] = o["rho_best"]["0.1"][2]
            n = rho["negation"]
            rec["neg_ratio"] = [a["single"][i] / n["total"][i] for i in range(3)]
            rec["neg_walk_ratio"] = [a["single"][i] / n["walk_only"][i] for i in range(3)]
            rec["plain_ratio"] = [a["single"][i] / rho["plain"]["total"][i] for i in range(3)]
            best_new = [min(r["total"][i] for r in c["rho"]) for i in range(3)]
            rec["best_new_ratio"] = [a["single"][i] / best_new[i] for i in range(3)]
            rec["amort_ratio_neg"] = a["amortised"][1] / n["total"][1]
            rec["amort_ratio_old"] = o["amortised"]["0.1"] / best_old[1]
            rec["walk_share_neg"] = n["walk_ops"] / n["total_gae"]
            rec["aut_ratio"] = [a["single"][i] / rho["aut"]["total"][i] for i in range(3)] if "aut" in rho else None
            rows.append(rec)
    md.append("IC arms are deterministic in their seeds, so the rerun reproduces the recorded single-instance totals; column `IC drift` is the largest relative difference over the three prices.\n")
    md.append("| bits | m | D | arm | IC drift | recorded dist. (best rho) w=0 / 0.1 / 1 | recorded ref | negation total: w=0 / 0.1 / 1 | negation walk only | plain total | best of the rerun | automorphism | amortised w=0.1 recorded -> over negation | neg. walk share |")
    md.append("|--:|--:|--:|--|--:|--|--|--|--|--|--|--|--|--:|")
    for r in rows:
        b, m_, d, arm = r["key"]
        md.append(
            f"| {b} | {m_} | {d} | {arm} | {f(r['ic_same'], 2)} | {r3(r['old_ratio'])} | {r['old_ref']} | {r3(r['neg_ratio'])} | {r3(r['neg_walk_ratio'])} | {r3(r['plain_ratio'])} | {r3(r['best_new_ratio'])} | "
            f"{r3(r['aut_ratio']) if r['aut_ratio'] else '-'} | {f(r['amort_ratio_old'])} -> {f(r['amort_ratio_neg'])} | {f(r['walk_share_neg'])} |"
        )
    md.append("")
    s = {}
    s["ic_max_drift"] = max(r["ic_same"] for r in rows)
    s["n_arm_cells"] = len(rows)
    s["min_ratio_old"] = [min(r["old_ratio"][i] for r in rows) for i in range(3)]
    s["min_ratio_neg"] = [min(r["neg_ratio"][i] for r in rows) for i in range(3)]
    s["min_ratio_neg_walk"] = [min(r["neg_walk_ratio"][i] for r in rows) for i in range(3)]
    s["min_ratio_best_new"] = [min(r["best_new_ratio"][i] for r in rows) for i in range(3)]
    s["below_at_all_prices_neg_total"] = sum(1 for r in rows if all(x < 1 for x in r["neg_ratio"]))
    s["below_at_all_prices_neg_walk"] = sum(1 for r in rows if all(x < 1 for x in r["neg_walk_ratio"]))
    s["below_at_all_prices_best_new"] = sum(1 for r in rows if all(x < 1 for x in r["best_new_ratio"]))
    s["new_vs_old_ratio_best_new_over_old_max_dev"] = max(abs(r["best_new_ratio"][i] / r["old_ratio"][i] - 1) for r in rows for i in range(3))
    s["neg_over_old_ratio_median"] = [median(r["neg_ratio"][i] / r["old_ratio"][i] for r in rows) for i in range(3)]
    s["neg_over_old_ratio_range"] = [[min(r["neg_ratio"][i] / r["old_ratio"][i] for r in rows), max(r["neg_ratio"][i] / r["old_ratio"][i] for r in rows)] for i in range(3)]
    s["walk_share_range"] = [min(r["walk_share_neg"] for r in rows), max(r["walk_share_neg"] for r in rows)]
    s["walk_share_by_bits"] = {b: [min(r["walk_share_neg"] for r in rows if r["key"][0] == b), max(r["walk_share_neg"] for r in rows if r["key"][0] == b)] for b in (24, 28)}
    summary["smallde"] = s
    md.append("Summary over all arm-cells: `" + json.dumps(s) + "`\n")

open(os.path.join(HERE, "tables.md"), "w").write("\n".join(md) + "\n")
json.dump(summary, open(os.path.join(HERE, "summary.json"), "w"), indent=1)

# ------------------------------------------------------------------ svg
def svg():
    W_, H_ = 900, 330
    panels = []
    if "v3" in R:
        pts = {"recorded w=1": [], "C w=1": [], "recorded w=0": [], "C w=0": []}
        xs = []
        for v in R["v3"]:
            o = v["old"]["ratio_vs_recorded_rho"]
            c = v["compare"]["C"]["ratio_neg"]
            xs.append(v["p"])
            pts["recorded w=0"].append(o[0]); pts["C w=0"].append(c[0])
            pts["recorded w=1"].append(o[2]); pts["C w=1"].append(c[2])
        panels.append(("v3: genus-2 IC over rho on E1", xs, pts))
    if "tower" in R:
        pts = {"g3 recorded w=0": [], "g3 C w=0": [], "g3 recorded w=1": [], "g3 C w=1": []}
        xs = []
        for t in R["tower"]:
            if "g3_C" not in t["compare"]:
                continue
            o = old_tw[t["p"]]["ratio_la"][1]
            c = t["compare"]["g3_C"]["ratio_neg"]
            xs.append(t["p"])
            pts["g3 recorded w=0"].append(o[0]); pts["g3 C w=0"].append(c[0])
            pts["g3 recorded w=1"].append(o[2]); pts["g3 C w=1"].append(c[2])
        panels.append(("tower: genus-3 IC over rho on E", xs, pts))
    cols = ["#9ca3af", "#2563eb", "#d1d5db", "#d97706"]
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W_}" height="{H_}" viewBox="0 0 {W_} {H_}" font-family="Helvetica,Arial,sans-serif" font-size="11">',
           f'<rect width="{W_}" height="{H_}" fill="#fff"/>',
           f'<text x="{W_/2}" y="18" text-anchor="middle" font-size="14" font-weight="bold">Distance to the matched rho, recorded versus fixed instrument (log-log); [pcc:unverified]</text>']
    for pi, (title, xs, pts) in enumerate(panels):
        x0 = 50 + pi * 440
        allv = [v for s in pts.values() for v in s if v and v > 0]
        if not allv or not xs:
            continue
        lo, hi = math.log10(min(allv) * 0.8), math.log10(max(allv) * 1.25)
        lx0, lx1 = math.log10(min(xs)), math.log10(max(xs))
        X = lambda p: x0 + 30 + (math.log10(p) - lx0) / max(lx1 - lx0, 1e-9) * 330
        Y = lambda v: 270 - (math.log10(v) - lo) / max(hi - lo, 1e-9) * 210
        out.append(f'<text x="{x0+195}" y="40" text-anchor="middle" font-weight="bold">{title}</text>')
        out.append(f'<line x1="{x0+30}" y1="270" x2="{x0+360}" y2="270" stroke="#999"/><line x1="{x0+30}" y1="60" x2="{x0+30}" y2="270" stroke="#999"/>')
        if lo < 0 < hi:
            out.append(f'<line x1="{x0+30}" y1="{Y(1)}" x2="{x0+360}" y2="{Y(1)}" stroke="#16a34a" stroke-dasharray="4,3"/><text x="{x0+362}" y="{Y(1)+4}" fill="#16a34a">= rho</text>')
        for e in range(math.ceil(lo), math.floor(hi) + 1):
            out.append(f'<text x="{x0+26}" y="{Y(10**e)+4}" text-anchor="end" fill="#444">{10**e:g}</text>')
        for p in xs:
            out.append(f'<text x="{X(p)}" y="286" text-anchor="middle" fill="#444">{p}</text>')
        for k, (name, ser) in enumerate(pts.items()):
            col = cols[k]
            ps = " ".join(f"{X(p):.1f},{Y(v):.1f}" for p, v in zip(xs, ser) if v and v > 0)
            dash = "" if "C" in name else ' stroke-dasharray="5,3"'
            out.append(f'<polyline fill="none" stroke="{col}" stroke-width="2"{dash} points="{ps}"/>')
            out.append(f'<text x="{x0+40}" y="{74+13*k}" fill="{col}">{name}</text>')
        out.append(f'<text x="{x0+195}" y="304" text-anchor="middle">field size p</text>')
    out.append("</svg>")
    return "\n".join(out)

if "tower" in R:
    old_tw = {r["p"]: r for r in json.load(open(os.path.join(OLD, "tower_large", "tower_large.json")))["rows"]}
open(os.path.join(HERE, "rerun.svg"), "w").write(svg() + "\n")
print("wrote tables.md, summary.json, rerun.svg")
