#!/usr/bin/env python3
"""Lay out paired.json (written by paired.py) as tables.md and fig_ratio.svg.

Layout only: every number is read from paired.json. All figures [pcc:unverified].
"""
import json
import math
import sys

src = sys.argv[1] if len(sys.argv) > 1 else "paired.json"
P = json.load(open(src))
cells = P["cells"]
SURF, INK, INK2, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df"
COL = {"trials": "#2a78d6", "group_ops": "#eb6834", "fpm_mid": "#1baf7a", "gae_w01": "#eda100"}
LAB = {"trials": "trials", "group_ops": "group operations", "fpm_mid": "FPM mid",
       "gae_w01": "GAE w=0.1"}

out = []
w = out.append
w("# Genus ladder harvest: paired tables\n")
w(f"Generated by `render.py` from `{src}`; every figure is `[pcc:unverified]`.\n")
w("Ratio = harvest / off, per pair (instance, seed); geometric mean with 95% hierarchical "
  "bootstrap interval (curves, then seeds). Below 1: harvesting costs less.\n")
w("## P1. Paired ratios\n")
w("| g | p | arm | pairs | certified | trials | trials/relation | group ops | GAE w=0.1 | GAE w=1 | FPM mid | rel_mul | la_mul |")
w("|--:|--:|---|--:|---|---|---|---|---|---|---|---|---|")


def f(c, k):
    x = c[k]
    return f"{x['gm']:.3f} [{x['lo']:.3f}, {x['hi']:.3f}]"


for c in sorted(cells, key=lambda c: (c["g"], c["arm"], c["p"])):
    w(f"| {c['g']} | {c['p']} | {c['arm']} | {c['pairs']} | {c['all_certified']} | {f(c,'trials')} | "
      f"{f(c,'trials_per_relation')} | {f(c,'group_ops')} | {f(c,'gae_w01')} | {f(c,'gae_w1')} | "
      f"{f(c,'fpm_mid')} | {f(c,'rel_mul')} | {f(c,'la_mul')} |")
w("\n## P2. Event rates (harvest arm; main split rate from the off arm)\n")
w("| g | p | arm | intermediates / trial | prefilter pass | harvest split rate (x24) | main split rate (x g!) | harvested share of relations | overflow |")
w("|--:|--:|---|--:|--:|--:|--:|--:|--:|")
for c in sorted(cells, key=lambda c: (c["g"], c["arm"], c["p"])):
    gf = math.factorial(c["g"])
    hf = math.factorial(2 * c["g"] - 2) if c["g"] >= 3 else 0
    w(f"| {c['g']} | {c['p']} | {c['arm']} | {c['intermediates_per_trial']:.4f} | "
      f"{c['harvest_prefilter_pass']:.3f} | {c['harvest_split_rate']:.5f} ({c['harvest_split_rate']*hf:.3f}) | "
      f"{c['main_split_rate_off']:.4f} ({c['main_split_rate_off']*gf:.3f}) | "
      f"{c['harvest_share_of_relations']:.3f} | {c['harvest_overflow']} |")
open("tables.md", "w").write("\n".join(out) + "\n")

# ── figure: paired ratios per cell, one panel per arm ──
arms = sorted({c["arm"] for c in cells})
rows = {a: sorted([c for c in cells if c["arm"] == a], key=lambda c: (c["g"], c["p"])) for a in arms}
keys = ["trials", "group_ops", "gae_w01", "fpm_mid"]
W, PH, top, left = 900, 300, 60, 70
H = top + len(arms) * (PH + 50) + 40
lo_v, hi_v = 0.6, 1.6


def ymap(v, y0):
    v = min(max(v, lo_v), hi_v)
    return y0 + PH - (math.log(v) - math.log(lo_v)) / (math.log(hi_v) - math.log(lo_v)) * PH


s = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" '
     f'font-family="Helvetica, Arial, sans-serif">',
     f'<rect width="{W}" height="{H}" fill="{SURF}"/>',
     f'<text x="{left}" y="28" font-size="16" fill="{INK}">Harvesting the intermediate divisor: paired ratio harvest / off (log scale, 95% intervals)</text>',
     f'<text x="{left}" y="46" font-size="11" fill="{INK2}">[pcc:unverified] - one session, synthetic curves; below 1 = harvesting cheaper</text>']
for ai, a in enumerate(arms):
    y0 = top + ai * (PH + 50) + 20
    rs = rows[a]
    pw = W - left - 30
    s.append(f'<text x="{left}" y="{y0 - 6}" font-size="13" fill="{INK}">{a}</text>')
    for t in (0.6, 0.8, 1.0, 1.25, 1.6):
        y = ymap(t, y0)
        s.append(f'<line x1="{left}" x2="{left + pw}" y1="{y:.1f}" y2="{y:.1f}" stroke="{INK2 if t == 1.0 else GRID}" stroke-width="1"/>')
        s.append(f'<text x="{left - 8}" y="{y + 4:.1f}" font-size="10" text-anchor="end" fill="{INK2}">{t}</text>')
    n = max(len(rs), 1)
    cw = pw / n
    for i, c in enumerate(rs):
        cx0 = left + i * cw
        s.append(f'<text x="{cx0 + cw / 2:.1f}" y="{y0 + PH + 16}" font-size="11" text-anchor="middle" fill="{INK}">g={c["g"]}, p={c["p"]}</text>')
        for k_i, k in enumerate(keys):
            x = cx0 + cw * (0.2 + 0.6 * k_i / (len(keys) - 1))
            v = c[k]
            s.append(f'<line x1="{x:.1f}" x2="{x:.1f}" y1="{ymap(v["lo"], y0):.1f}" y2="{ymap(v["hi"], y0):.1f}" stroke="{COL[k]}" stroke-width="2"/>')
            s.append(f'<circle cx="{x:.1f}" cy="{ymap(v["gm"], y0):.1f}" r="4" fill="{COL[k]}"/>')
lx = left
ly = H - 16
for k in keys:
    s.append(f'<circle cx="{lx}" cy="{ly - 4}" r="4" fill="{COL[k]}"/>')
    s.append(f'<text x="{lx + 8}" y="{ly}" font-size="11" fill="{INK}">{LAB[k]}</text>')
    lx += 150
s.append("</svg>")
open("fig_ratio.svg", "w").write("\n".join(s) + "\n")
print("wrote tables.md, fig_ratio.svg")
