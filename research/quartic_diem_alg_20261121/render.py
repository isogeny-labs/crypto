#!/usr/bin/env python3
"""Layout of analysis.json as tables.md and fig_quartic_alg.svg (no statistic computed here)."""
import json, math
A = json.load(open("analysis.json"))
P = A["primes"]
SURF, INK, INK2, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df"
COL = {"Q_diem_2lp": "#eb6834", "Q_diem_2lp+alg": "#2a78d6", "Q_diem_2lp+alg+sge(8,3)": "#1baf7a", "Q_rho_neg": "#eda100"}
LAB = {"Q_diem_2lp": "2LP, scan", "Q_diem_2lp+alg": "2LP, algebraic", "Q_diem_2lp+alg+sge(8,3)": "2LP, algebraic + SGE(8,3)", "Q_rho_neg": "rho, negation map"}

def sci(x):
    return "-" if x is None else (f"{x:.3g}" if abs(x) < 1e5 else f"{x:.2e}")
def rc(r):
    return f"{r['ratio']:.3f} [{r['lo']:.3f}, {r['hi']:.3f}]"

o = []; w = o.append
w("# Quartic Diem, algebraic decomposition and SGE: tables\n")
w("Generated by `render.py` from `analysis.json`; every figure `[pcc:unverified]`. 6 runs per cell (3 curves x 2 seeds), bootstrap 95% intervals (2000 resamples over runs).\n")
w("## T1. Cost per arm, FPM_mid = pic_mul + 10 pic_inv + rel_mul + 9 la_mul (means)\n")
w("| q | arm | pic (mul+10 inv) | rel_mul | of which enum | of which decomposition | 9 la_mul | FPM_mid |")
w("|--:|---|--:|--:|--:|--:|--:|--:|")
fm = {(c["arm"], c["p"]): c["fpm_mid"] for c in A["cells"]}
for q in P:
    for arm in COL:
        c = next(c for c in A["composition"] if c["arm"] == arm and c["p"] == q)
        w(f"| {q} | {LAB[arm]} | {sci(c['pic'])} | {sci(c['rel'])} | {sci(c.get('rel_enum'))} | {sci(c.get('rel_decomp'))} | {sci(c['la9'])} | {sci(fm[(arm, q)])} |")
w("\n## T2. Ratios (arm / reference)\n")
w("| q | Q2 rel_mul alg/scan | decomposition share alg/scan | Q3 FPM alg+sge / scan | FPM alg / scan | la_mul +sge / alg | Q5 FPM alg+sge / rho | FPM scan / rho |")
w("|--:|---|---|---|---|---|---|---|")
for i, q in enumerate(P):
    w(f"| {q} | {rc(A['Q2_rel_mul_alg_over_scan'][i])} | {rc(A['Q2_rel_decomp_alg_over_scan'][i])} | {rc(A['Q3_fpm_algsge_over_scan'][i])} | {rc(A['fpm_alg_over_scan'][i])} | {rc(A['la_mul_algsge_over_alg'][i])} | {rc(A['Q5_fpm_algsge_over_rho'][i])} | {rc(A['fpm_scan_over_rho'][i])} |")
w("\n## T3. Exponents in q, FPM_mid, least squares on ln mean (q = 2053, 4099, 8209)\n")
w("| arm | exponent [95%] |")
w("|---|---|")
for e in A["Q4_exponents"]:
    w(f"| {LAB[e['arm']]} | {e['exponent']:.3f} [{e['lo']:.3f}, {e['hi']:.3f}] |")
w("\n## T4. Identity of the relation phase\n")
w("| arm vs scan | pairs | relation phase identical | group_ops, pic_mul, pic_inv identical |")
w("|---|--:|--:|--:|")
for k, v in A["Q1"]["scan_vs"].items():
    w(f"| {k} | {v['pairs']} | {v['relation_phase_identical']} | {v['group_ops_and_cantor_identical']} |")
if A["Q1"]["cert_phase_diffs"]:
    w("\nCertificate-phase differences of the merged arm (scan, merged): group_ops / pic_mul\n")
    w("| q | curve | seed | group_ops | pic_mul |")
    w("|--:|--:|--:|---|---|")
    for d in A["Q1"]["cert_phase_diffs"]:
        w(f"| {d['key'][0]} | {d['key'][1]} | {d['key'][2]} | {d['group_ops'][0]} / {d['group_ops'][1]} | {d['cantor_mul'][0]} / {d['cantor_mul'][1]} |")
b = A.get("boundr_crosscheck")
if b:
    w(f"\n## T5. Cross-check with the bound-r study\n\nInstances identical: {b['instances_identical']} ({b['instances']}); default-arm rows compared (Q_diem_full, Q_diem_2lp, Q_rho_neg): {b['rows_compared']}, identical on every counted field: {b['rows_identical']}. Rho rows at q = 8209 taken from that study (AMENDMENT1.md): {len(A['rho_rows_from_boundr'])}.")
w("\n## T6. Scorecard\n")
r8 = lambda L: L[-1]
ex = {e["arm"]: e for e in A["Q4_exponents"]}["Q_diem_2lp+alg+sge(8,3)"]
q2, q3, q5 = r8(A["Q2_rel_mul_alg_over_scan"]), r8(A["Q3_fpm_algsge_over_scan"]), r8(A["Q5_fpm_algsge_over_rho"])
fall = [x["ratio"] for x in A["Q2_rel_mul_alg_over_scan"]]
ok1 = not A["Q1"]["diffs"] and all(v["relation_phase_identical"] == v["pairs"] for v in A["Q1"]["scan_vs"].values())
w("| id | prediction | measured | verdict |")
w("|---|---|---|---|")
w(f"| Q1 | identical relation phase | {'all pairs identical' if ok1 else 'DIFFERENCES'} | {'holds' if ok1 else 'FALSIFIED'} |")
w(f"| Q2 | rel_mul alg/scan <= 0.4 at 8209, falling | {fall[0]:.3f}, {fall[1]:.3f}, {fall[2]:.3f} | {'holds' if q2['ratio'] <= 0.4 and fall[0] > fall[1] > fall[2] else 'FALSIFIED'} |")
w(f"| Q3 | FPM alg+sge / scan <= 0.5 at 8209 | {rc(q3)} | {'holds' if q3['ratio'] <= 0.5 else 'FALSIFIED'} |")
w(f"| Q4 | exponent <= 1.2 | {ex['exponent']:.3f} [{ex['lo']:.3f}, {ex['hi']:.3f}] | {'holds' if ex['exponent'] <= 1.2 else 'FALSIFIED'} |")
w(f"| Q5 | alg+sge / rho <= 0.005 at 8209 | {rc(q5)} | {'holds' if q5['ratio'] <= 0.005 else 'FALSIFIED'} |")
open("tables.md", "w").write("\n".join(o) + "\n")

# figure
W, H = 980, 440
svg = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" font-family="system-ui,sans-serif" font-size="12">',
       f'<rect width="{W}" height="{H}" fill="{SURF}"/>',
       f'<text x="20" y="26" font-size="15" font-weight="600" fill="{INK}">Plane-quartic Diem: algebraic decomposition and SGE (random quartics, h &lt;= 2)</text>',
       f'<text x="20" y="44" fill="{INK2}">[pcc:unverified] means of 6 runs per q; FPM_mid = pic_mul + 10 pic_inv + rel_mul + 9 la_mul</text>']
def panel(x0, y0, w_, h_, title):
    svg.append(f'<text x="{x0}" y="{y0-10}" font-weight="600" fill="{INK}">{title}</text>')
    svg.append(f'<rect x="{x0}" y="{y0}" width="{w_}" height="{h_}" fill="none" stroke="{GRID}"/>')
# left: FPM vs q, log-log
x0, y0, pw, ph = 70, 90, 400, 280
panel(x0, y0, pw, ph, "FPM_mid against q (log-log)")
vals = [v for v in fm.values()]
lo, hi = math.log10(min(vals)) - 0.2, math.log10(max(vals)) + 0.2
qx = lambda q: x0 + 30 + (math.log(q) - math.log(P[0])) / (math.log(P[-1]) - math.log(P[0])) * (pw - 60)
qy = lambda v: y0 + ph - (math.log10(v) - lo) / (hi - lo) * ph
for d in range(math.ceil(lo), math.floor(hi) + 1):
    yy = qy(10 ** d)
    svg.append(f'<line x1="{x0}" x2="{x0+pw}" y1="{yy:.1f}" y2="{yy:.1f}" stroke="{GRID}"/><text x="{x0-6}" y="{yy+4:.1f}" text-anchor="end" fill="{INK2}">1e{d}</text>')
for q in P:
    svg.append(f'<text x="{qx(q):.1f}" y="{y0+ph+16}" text-anchor="middle" fill="{INK2}">{q}</text>')
for arm, c in COL.items():
    pts = [(qx(q), qy(fm[(arm, q)])) for q in P]
    svg.append(f'<polyline fill="none" stroke="{c}" stroke-width="2" points="{" ".join(f"{a:.1f},{b:.1f}" for a, b in pts)}"/>')
    for a, b in pts:
        svg.append(f'<circle cx="{a:.1f}" cy="{b:.1f}" r="3.5" fill="{c}"/>')
for i, (arm, c) in enumerate(COL.items()):
    yy = y0 + 20 + i * 18
    svg.append(f'<rect x="{x0+12}" y="{yy-9}" width="12" height="12" fill="{c}"/><text x="{x0+30}" y="{yy+2}" fill="{INK}">{LAB[arm]}</text>')
# right: ratio bars
x1 = 540
panel(x1, y0, 400, ph, "Ratios to the scan arm, per q")
series = [("rel_mul, algebraic", A["Q2_rel_mul_alg_over_scan"], "#2a78d6"),
          ("FPM_mid, algebraic", A["fpm_alg_over_scan"], "#eb6834"),
          ("FPM_mid, algebraic + SGE", A["Q3_fpm_algsge_over_scan"], "#1baf7a")]
gw = (400 - 40) / len(P); bw = gw / 4.2
ry = lambda v: y0 + ph - v / 1.0 * (ph - 10)
for t in (0, 0.25, 0.5, 0.75, 1.0):
    yy = ry(t)
    svg.append(f'<line x1="{x1}" x2="{x1+400}" y1="{yy:.1f}" y2="{yy:.1f}" stroke="{GRID}"/><text x="{x1-6}" y="{yy+4:.1f}" text-anchor="end" fill="{INK2}">{t:g}</text>')
for gi, q in enumerate(P):
    gx = x1 + 20 + gi * gw
    for si, (nm, L, c) in enumerate(series):
        r = L[gi]
        bx = gx + si * (bw + 4) + 6
        svg.append(f'<rect x="{bx:.1f}" y="{ry(r["ratio"]):.1f}" width="{bw:.1f}" height="{ry(0)-ry(r["ratio"]):.1f}" fill="{c}"/>')
        svg.append(f'<line x1="{bx+bw/2:.1f}" x2="{bx+bw/2:.1f}" y1="{ry(r["lo"]):.1f}" y2="{ry(r["hi"]):.1f}" stroke="{INK}"/>')
        svg.append(f'<text x="{bx+bw/2:.1f}" y="{ry(r["hi"])-4:.1f}" text-anchor="middle" font-size="10" fill="{INK2}">{r["ratio"]:.2f}</text>')
    svg.append(f'<text x="{gx+gw/2-6:.1f}" y="{y0+ph+16}" text-anchor="middle" fill="{INK2}">{q}</text>')
for i, (nm, L, c) in enumerate(series):
    yy = y0 + ph + 38 + i * 0
    svg.append(f'<rect x="{x1+ i*135}" y="{y0+ph+30}" width="12" height="12" fill="{c}"/><text x="{x1+i*135+16}" y="{y0+ph+40}" fill="{INK}" font-size="11">{nm}</text>')
svg.append(f'<line x1="{x1}" x2="{x1+400}" y1="{ry(0.5):.1f}" y2="{ry(0.5):.1f}" stroke="{INK2}" stroke-dasharray="4 3"/>')
svg.append(f'<text x="{x1+398}" y="{ry(0.5)-4:.1f}" text-anchor="end" fill="{INK2}" font-size="10">Q3 threshold 0.5</text>')
svg.append("</svg>")
open("fig_quartic_alg.svg", "w").write("\n".join(svg))
