#!/usr/bin/env python3
"""Independent re-implementation of the degree-c PC closure in F_p[y]/T [u].
Different representation from closure.py: y-part kept as a 0/1 vector over (i,j),
reduction by explicit carry y_{i,j}^2 -> y_{i,j+1}, y_{i,t-1}^2 -> 1; sparse dict rows,
pure-Python modular elimination (no floats).  Usage: SYS.ms m t c"""
import sys, re, itertools
path, m, t, c = sys.argv[1], int(sys.argv[2]), int(sys.argv[3]), int(sys.argv[4])
lines = open(path).read().split("\n")
names = lines[0].split(","); p = int(lines[1])
body = "\n".join(lines[2:]).replace("\n", "")
polys = [s for s in body.split(",") if s.strip()]
nv = len(names); k = m - 2
def norm(ybits, uex):
    # ybits: dict (i,j)->exponent (any int); reduce via carries
    b = [[0]*t for _ in range(m)]
    for (i, j), e in ybits.items():
        b[i][j] += e
    for i in range(m):
        for j in range(t):
            while b[i][j] >= 2:
                b[i][j] -= 2
                if j + 1 < t: b[i][j+1] += 1
    return (tuple(tuple(r) for r in b), tuple(uex))
def deg(mon):
    return sum(sum(r) for r in mon[0]) + sum(mon[1])
def parse(s):
    P = {}
    s = s.replace("-", "+-")
    for term in s.split("+"):
        term = term.strip()
        if not term: continue
        fac = term.split("*")
        coef = 1; yb = {}; ue = [0]*k
        for f in fac:
            if re.fullmatch(r"-?\d+", f): coef = coef * int(f); continue
            neg = f.startswith("-")
            if neg: coef = -coef; f = f[1:]
            if "^" in f: v, e = f.split("^"); e = int(e)
            else: v, e = f, 1
            if v.startswith("y"):
                i, j = map(int, v[1:].split("_")); yb[(i, j)] = yb.get((i, j), 0) + e
            else:
                ue[int(v[1:])] += e
        mon = norm(yb, ue)
        P[mon] = (P.get(mon, 0) + coef) % p
    return {a: b for a, b in P.items() if b}
gens = [g for g in (parse(s) for s in polys) if g]
gens = [g for g in gens if max(deg(x) for x in g) <= c]
# column order: by degree descending then lexicographic
def key(mon): return (-deg(mon), mon)
basis = {}  # pivot monomial -> row (dict), rows fully reduced w.r.t. other pivots? keep echelon only
def lead(r): return min(r, key=key)
def reduce(r):
    r = dict(r)
    while r:
        L = lead(r)
        if L in basis:
            f = r[L]; br = basis[L]
            for mon, v in br.items():
                r[mon] = (r.get(mon, 0) - f*v) % p
                if r[mon] == 0: del r[mon]
        else:
            return r, L
    return r, None
def insert(r):
    r, L = reduce(r)
    if L is None: return None
    inv = pow(r[L], p-2, p)
    r = {a: b*inv % p for a, b in r.items()}
    basis[L] = r
    return L
for g in gens: insert(g)
one = (tuple(tuple([0]*t) for _ in range(m)), tuple([0]*k))
processed = set()
def mulvar(r, var):
    out = {}
    for mon, v in r.items():
        yb = {(i, j): mon[0][i][j] for i in range(m) for j in range(t) if mon[0][i][j]}
        ue = list(mon[1])
        if var[0] == 'y': yb[var[1]] = yb.get(var[1], 0) + 1
        else: ue[var[1]] += 1
        nm = norm(yb, ue)
        out[nm] = (out.get(nm, 0) + v) % p
    return {a: b for a, b in out.items() if b}
vars_ = [('y', (i, j)) for i in range(m) for j in range(t)] + [('u', q) for q in range(k)]
changed = True
while changed and one not in basis:
    changed = False
    for L in list(basis.keys()):
        if L in processed or deg(L) > c-1: continue
        processed.add(L)
        r = basis[L]  # echelon row; its degree = deg(L) since L is max-degree monomial
        for v in vars_:
            if insert(mulvar(r, v)) is not None:
                changed = True
            if one in basis: break
        if one in basis: break
    # rows already processed may have been fine: closure of span is generated by products of a spanning set
print(dict(system=path.split('/')[-1], c=c, dimV=len(basis), one_in_closure=one in basis))
