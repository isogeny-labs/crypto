def arm_metrics(c, a):
    reps = a["reps"]
    n = len(reps)
    mean = lambda k: sum(r[k] for r in reps) / n
    rel = {w: ms(rel_costs(a, w)) for w in W}
    tg = {w: ms(tgt_costs(a, w)) for w in W}
    single = {w: (rel[w][0] + tg[w][0], math.hypot(rel[w][1], tg[w][1])) for w in W}
    amort = {w: rel[w][0] / len(a["targets"]) + tg[w][0] for w in W}
    m = {
        "arm": a["arm"],
        "fb_points": a["fb_points"],
        "columns": a["columns"],
        "dropped": a["dropped"],
        "decomp_prob": ms([r["decomp_prob"] for r in reps]),
        "trials_per_relation": mean("trials_per_relation"),
        "hits_per_trial": mean("hits_per_trial"),
        "sweep_field_ops_per_trial": mean("sweep_field_ops_per_trial"),
        "trials": mean("trials"),
        "relations": mean("relations"),
        "la_total_ops": mean("la_total_ops"),
        "la_final_ops": mean("la_final_ops"),
        "la_rows": mean("la_rows"),
        "la_cols": mean("la_cols"),
        "la_max_row": max(r["la_max_row"] for r in reps),
        "la_attempts": mean("la_attempts"),
        "determined_frac": mean("determined_frac"),
        "rule_met": sum(1 for r in reps if r["rule_met"]),
        "reps": n,
        "native_split": {
            k: sum(r["native"][k] for r in reps) / n for k in ("muls", "invs", "tests", "la_ops")
        },
        "build_gae": a["build_gae"],
        "rel": rel,
        "tgt": tg,
        "single": single,
        "amortised": amort,
        "field_ops_rel": ms(fo_rel(a)),
        "certified": sum(1 for t in a["targets"] if t["certified"]),
        "targets": len(a["targets"]),
        "target_trials": sum(t["trials"] for t in a["targets"]) / max(1, len(a["targets"])),
    }
    return m


