W = (0.0, 0.1, 1.0)
doc = json.load(open(SRC))


def nat(d):
    return sum(d.values())


def ms(xs):
    n = len(xs)
    if n == 0:
        return (float("nan"), 0.0, 0)
    m = sum(xs) / n
    if n < 2:
        return (m, 0.0, n)
    v = sum((x - m) ** 2 for x in xs) / (n - 1)
    return (m, math.sqrt(v / n), n)


def fmt(x):
    if x != x:
        return "-"
    if abs(x) >= 1e5 or (0 < abs(x) < 0.01):
        return f"{x:.3g}"
    if abs(x) >= 100:
        return f"{x:.0f}"
    return f"{x:.3g}"


def rel_costs(a, w):
    return [
        r["gae"] + a["build_gae"] + w * (nat(r["native"]) + nat(a["build_native"]))
        for r in a["reps"]
    ]


def tgt_costs(a, w):
    return [t["gae"] + w * nat(t["native"]) for t in a["targets"] if t["certified"]]


def fo_rel(a):
    out = []
    for r in a["reps"]:
        n = r["native"]
        b = a["build_native"]
        out.append(
            n["muls"] + n["invs"] + n["la_ops"] + b["muls"] + b["invs"] + 4 * (r["gae"] + a["build_gae"])
        )
    return out


def best_rho(cell, w):
    """Mean per-target cost of each rho variant; returns dict kind -> (mean, se)."""
    res = {}
    for r in cell["rho"]:
        xs = [x["gae"] + w * x["native"] for x in r["runs"]]
        if xs:
            res[r["kind"]] = ms(xs)
    return res


