def best(c, w):
    r = c["_rho"][w]
    if not r:
        return (float("nan"), 0.0, "-")
    k = min(r, key=lambda k: r[k][0])
    return (r[k][0], r[k][1], k)


def classify(a, b, w, key="rel"):
    """a lower than b? returns 'win'/'tie'/'loss' for a vs b using 2 pooled SE."""
    ma, sa = armmap_get(a)[key][w][:2]
    mb, sb = armmap_get(b)[key][w][:2]
    se = math.hypot(sa, sb)
    if mb - ma > 2 * se:
        return "win"
    if ma - mb > 2 * se:
        return "loss"
    return "tie"


