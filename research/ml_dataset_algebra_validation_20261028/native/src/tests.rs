#[test]
fn hand_constant_and_all_censored_prefixes() {
    let events = constant();
    let report = check(&events).unwrap();
    assert_eq!(report.independent_rank, Some(1));
    assert_eq!(report.named_admission_model_checked, Some(10));
    assert!(
        !report.input_encoding_checked
            && !report.unsat_verified
            && !report.producer_execution_attested
    );
    for n in 0..events.len() {
        let report = check(&events[..n]).unwrap();
        assert!(!report.matrix_trace_complete);
        assert_eq!(report.independent_rank, None);
        assert_eq!(report.named_admission_model_checked, None);
    }
}

