#[test]
fn combination_order_is_variable_lexicographic_and_boolean_products_cancel() {
    assert_eq!(multipliers(4, 2), vec![0, 1, 2, 4, 8, 3, 5, 9, 6, 10, 12]);
    assert_eq!(multipliers(8, 4).len(), 163);
    // x+1 times x is x+x=0 in the Boolean quotient.
    let prefix = vec![
        begin(1, 2, &[vec![1, 0]]),
        Event::Input {
            index: 0,
            terms: vec![1, 0],
        },
        Event::Candidate {
            index: 0,
            generator: 0,
            multiplier: 0,
            terms: vec![0, 1],
            matrix_row: Some(0),
        },
        Event::Candidate {
            index: 1,
            generator: 0,
            multiplier: 1,
            terms: vec![],
            matrix_row: None,
        },
    ];
    assert!(!check(&prefix).unwrap().matrix_trace_complete);
    let mut corrupt = prefix;
    if let Event::Candidate { terms, .. } = &mut corrupt[3] {
        terms.push(1);
    }
    assert!(check(&corrupt).is_err());
}

