use super::*;
use std::io::Cursor;

fn binding() -> Binding {
    Binding {
        source_commit: "a".repeat(40),
        producer_sha256: "b".repeat(64),
        configuration_sha256: "c".repeat(64),
        context_sha256: "d".repeat(64),
        call_id: "e".repeat(64),
    }
}

fn limits() -> Limits {
    Limits {
        max_candidates: 4096,
        max_events: EVENT_CAP,
        max_stream_bytes: STREAM_CAP as u64,
        max_event_bytes: RECORD_CAP as u64,
        max_workspace_bytes: 2 * 1024 * 1024,
        max_memory_bytes: 32 * 1024 * 1024,
        max_admission_units: 16 * 1024 * 1024,
    }
}

fn begin(q: u8, d: u8, inputs: &[Vec<u8>]) -> Event {
    Event::Begin {
        profile: PROFILE.into(),
        binding: Box::new(binding()),
        n_vars: q,
        degree: d,
        input_count: inputs.len() as u64,
        input_sha256: digest(&serde_json::to_vec(&(q, d, inputs)).unwrap()),
        limits: limits(),
        native_row_cap: 20_000,
        native_column_cap: 40_000,
        kernel: "native-suffix-rref".into(),
        ring: "F2[v]/(vi^2+vi)".into(),
        order: "degrevlex:v0>v1>...".into(),
    }
}

fn stream(events: &[Event]) -> Vec<u8> {
    let mut previous = "0".repeat(64);
    let mut out = Vec::new();
    for (i, event) in events.iter().enumerate() {
        let record = Record {
            schema: SCHEMA.into(),
            sequence: i as u64 + 1,
            previous_sha256: previous,
            event: event.clone(),
        };
        let bytes = serde_json::to_vec(&record).unwrap();
        previous = digest(&bytes);
        out.extend(bytes);
        out.push(b'\n');
    }
    out
}

fn check(events: &[Event]) -> Result<Report> {
    verify(Cursor::new(stream(events)), &binding())
}

