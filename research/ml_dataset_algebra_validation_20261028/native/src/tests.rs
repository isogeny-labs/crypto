#[test]
fn scalar_oracle_matches_exhaustive_span_cardinality() {
    // All 4x3 matrices, with rank independently inferred from enumerated row span.
    for encoded in 0..4096u64 {
        let raw: Vec<u64> = (0..4).map(|r| (encoded >> (3 * r)) & 7).collect();
        let mut span = std::collections::BTreeSet::new();
        for choice in 0..16 {
            let mut v = 0;
            for (i, row) in raw.iter().enumerate() {
                if choice & (1 << i) != 0 {
                    v ^= row;
                }
            }
            span.insert(v);
        }
        let packed: Vec<Vec<u64>> = raw.into_iter().map(|v| vec![v]).collect();
        assert_eq!(
            scalar_rank(&packed, 3, &mut 0).unwrap(),
            span.len().ilog2() as usize
        );
    }
    let packed = vec![vec![1, 0, 0], vec![0, 1, 0], vec![1, 1, 0], vec![0, 0, 1]];
    assert_eq!(scalar_rank(&packed, 129, &mut 0).unwrap(), 3);
    let mut exhausted = WORK_CAP;
    assert!(scalar_rank(&packed, 129, &mut exhausted).is_err());
}

#[test]
fn rehashed_semantic_tampering_is_rejected() {
    let original = constant();
    let mut wrong = original.clone();
    if let Event::Begin { input_sha256, .. } = &mut wrong[0] {
        *input_sha256 = "0".repeat(64);
    }
    assert!(check(&wrong).is_err());
    let mut wrong = original.clone();
    if let Event::MatrixRow { words, .. } = &mut wrong[4] {
        words[0] = "8000000000000001".into();
    }
    assert!(check(&wrong).is_err());
    let mut wrong = original.clone();
    if let Event::Swap {
        left_after_version, ..
    } = &mut wrong[7]
    {
        *left_after_version = 2;
    }
    assert!(check(&wrong).is_err());
    for field in 0..4 {
        let mut wrong = original.clone();
        if let Event::End {
            rank_native,
            word_xors_native,
            admission_units,
            claims,
            ..
        } = &mut wrong[9]
        {
            match field {
                0 => *rank_native = 0,
                1 => *word_xors_native = 1,
                2 => *admission_units = 11,
                _ => claims.unsat_verified = true,
            }
        }
        assert!(check(&wrong).is_err());
    }
    let mut missing = original.clone();
    missing.remove(7);
    assert!(check(&missing).is_err());
    let mut duplicate = original.clone();
    duplicate.insert(3, original[2].clone());
    assert!(check(&duplicate).is_err());
    let mut expected = binding();
    expected.call_id = "f".repeat(64);
    assert!(verify(Cursor::new(stream(&original)), &expected).is_err());
}

#[test]
fn strict_json_rejects_aliases_unknowns_duplicates_and_broken_chain() {
    let valid = String::from_utf8(stream(&constant())).unwrap();
    for mutated in [
        valid.replacen("\"sequence\":1", "\"sequence\":1.0", 1),
        valid.replacen("\"sequence\":1", "\"sequence\":1,\"sequence\":1", 1),
        valid.replacen("\"sequence\":1", "\"sequence\":1,\"unknown\":0", 1),
        valid.replacen("\"n_vars\":0", "\"n_vars\":-0", 1),
        valid.replacen(
            "\"source_commit\":",
            "\"source_commit\":\"0000\",\"source_commit\":",
            1,
        ),
        valid.replacen("\"sequence\":2", "\"sequence\":3", 1),
        valid.replacen("{", "{ ", 1),
    ] {
        assert!(verify(Cursor::new(mutated), &binding()).is_err());
    }
}

#[test]
fn censored_tail_is_not_parsed_and_no_data_follows_terminal() {
    let events = constant();
    let mut prefix = stream(&events[..3]);
    prefix.extend(b"{nonsense");
    let report = verify(Cursor::new(prefix.clone()), &binding()).unwrap();
    assert_eq!(report.acknowledged_records, 3);
    assert_eq!(report.trailing_unacknowledged_bytes, 9);
    assert!(!report.matrix_trace_complete);
    prefix.push(b'\n');
    assert!(verify(Cursor::new(prefix), &binding()).is_err());
    let mut complete = stream(&events);
    complete.push(b'x');
    assert!(verify(Cursor::new(complete), &binding()).is_err());
    let mut stopped = events[..3].to_vec();
    stopped.push(Event::Stopped {
        reason: StopReason::Deadline,
        acknowledged_before_stop: 3,
    });
    let report = check(&stopped).unwrap();
    assert!(!report.matrix_trace_complete && !report.stop_reason_independently_verified);
    stopped.push(events[3].clone());
    assert!(check(&stopped).is_err());
}

#[test]
fn producer_and_parser_resource_limits_fail_closed() {
    let mut events = constant();
    if let Event::Begin { limits, .. } = &mut events[0] {
        limits.max_candidates = 4097;
    }
    assert!(check(&events).is_err());
    let mut events = constant();
    if let Event::Begin { limits, .. } = &mut events[0] {
        limits.max_admission_units = 9;
    }
    assert!(check(&events).is_err());
    let mut events = constant();
    if let Event::Begin { native_row_cap, .. } = &mut events[0] {
        *native_row_cap = 0;
    }
    assert!(check(&events).is_err());
    let mut events = constant();
    if let Event::Begin { limits, .. } = &mut events[0] {
        limits.max_memory_bytes = 1;
    }
    assert!(check(&events).is_err());
    let oversized = vec![b'x'; RECORD_CAP + 1];
    assert!(verify(Cursor::new(oversized), &binding()).is_err());
    let mut bytes = 0;
    let mut reader = Cursor::new(vec![b'x'; RECORD_CAP]);
    assert_eq!(
        line(&mut reader, &mut bytes).unwrap().unwrap().0.len(),
        RECORD_CAP
    );
    let mut bytes = STREAM_CAP;
    let mut reader = Cursor::new(b"x\n");
    assert!(line(&mut reader, &mut bytes).is_err());
}

#[test]
fn native_row_cap_crossing_is_a_valid_last_candidate_but_cannot_continue() {
    let mut events = vec![
        begin(2, 1, &[vec![0]]),
        Event::Input {
            index: 0,
            terms: vec![0],
        },
        Event::Candidate {
            index: 0,
            generator: 0,
            multiplier: 0,
            terms: vec![0],
            matrix_row: Some(0),
        },
        Event::Candidate {
            index: 1,
            generator: 0,
            multiplier: 1,
            terms: vec![1],
            matrix_row: Some(1),
        },
    ];
    if let Event::Begin { native_row_cap, .. } = &mut events[0] {
        *native_row_cap = 1;
    }
    let prefix = check(&events).unwrap();
    assert!(!prefix.matrix_trace_complete && prefix.independent_rank.is_none());
    let mut stopped = events.clone();
    stopped.push(Event::Stopped {
        reason: StopReason::NativeSizeLimit,
        acknowledged_before_stop: 4,
    });
    let report = check(&stopped).unwrap();
    assert_eq!(report.acknowledged_records, 5);
    assert!(!report.stop_reason_independently_verified);
    events.push(Event::Candidate {
        index: 2,
        generator: 0,
        multiplier: 2,
        terms: vec![2],
        matrix_row: Some(2),
    });
    assert!(check(&events).unwrap_err().contains("after native row cap"));
    for (stream_bytes, event_bytes) in [(1024, 65536), (4194304, 1023)] {
        let mut invalid = constant();
        if let Event::Begin { limits, .. } = &mut invalid[0] {
            limits.max_stream_bytes = stream_bytes;
            limits.max_event_bytes = event_bytes;
        }
        assert!(check(&invalid).is_err());
    }
}
