// Operational fresh-only GP transport and strict byte/process admission.
import fs from 'node:fs';
import crypto from 'node:crypto';
import {spawn} from 'node:child_process';
const d=process.argv[2];
if(!d)throw Error('audit directory required');
const sha=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const pins=JSON.parse(fs.readFileSync(d+'/REFERENCE_PINS.json'));
for(const [p,h]of Object.entries(pins.files))if(sha(p)!==h)throw Error('reference pin mismatch '+p);
if(sha(pins.gp.path)!==pins.gp.sha256)throw Error('GP binary changed');
const prefix=d+'/reference-v1/RECEIPT';
if(fs.existsSync(d+'/reference-v1'))throw Error('fresh reference required');
fs.mkdirSync(d+'/reference-v1');
const argv=['/usr/bin/prlimit','--as=4294967296','--','/usr/bin/taskset','-c','0','/usr/bin/timeout','--signal=TERM','--kill-after=1s',String(pins.timeout_s)+'s',pins.gp.path,'-f','-q','-s','64000000',d+'/verify.gp'];
const started=new Date().toISOString();
const child=spawn(argv[0],argv.slice(1),{env:{...process.env,LD_LIBRARY_PATH:'/workspace/shared/twist-tools-20261023/cas/root/usr/lib/x86_64-linux-gnu'},stdio:['ignore',fs.openSync(prefix+'.stdout','wx'),fs.openSync(prefix+'.stderr','wx')]});
const [exit_code,signal]=await new Promise((r,j)=>{child.on('error',j);child.on('close',(x,y)=>r([x,y]));});
const receipt={schema:'twist.cold-reference-transport/v1',started,finished:new Date().toISOString(),argv,exit_code,signal,script_sha256:sha(d+'/verify.gp'),stdout_sha256:sha(prefix+'.stdout'),stderr_sha256:sha(prefix+'.stderr'),gp_binary_sha256:pins.gp.sha256,wall_time_admitted:false};
fs.writeFileSync(prefix+'.json',JSON.stringify(receipt,null,2)+'\n',{flag:'wx'});
const expected='ALL_COLD_PIPELINE_REPLAY_OK '+pins.expected_cases;
const stdout=fs.readFileSync(prefix+'.stdout','utf8').trim();
const stderr=fs.readFileSync(prefix+'.stderr','utf8').trim();
const allowed='***   Warning: new maximum stack size = 4000002048 (3814.699 Mbytes).';
const issues=[];
if(exit_code!==0||signal)issues.push('reference process failed');
if(stdout!==expected)issues.push('sole expected marker absent or extra stdout');
if(stderr!==''&&stderr!==allowed)issues.push('undeclared GP stderr');
for(const [p,h]of Object.entries(pins.files))if(sha(p)!==h)issues.push('changed reference pin '+p);
const admission={schema:'twist.cold-reference-admission/v1',status:issues.length?'rejected-reference':'native-counters-and-independent-GP-verified',issues,expected_cases:pins.expected_cases,reference_receipt:prefix+'.json',reference_receipt_sha256:sha(prefix+'.json'),audit_sha256:sha(d+'/AUDIT.json'),script_sha256:receipt.script_sha256,full_formal_concrete_bridge:false};
fs.writeFileSync(d+'/ADMISSION.json',JSON.stringify(admission,null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify({status:admission.status,cases:pins.expected_cases,issues}));
process.exitCode=issues.length?1:0;
