w("| family | g | p | seeds tried | admitted | rejects | search wall s |")
w("|---|--:|--:|--:|--:|---|--:|")
for c in sorted(A["admission"], key=lambda c: (c["family"], c["g"], c["p"])):
    rej = ", ".join(f"{k}: {v}" for k, v in sorted(c["rejects"].items()))
    w(f"| {c['family']} | {c['g']} | {c['p']} | {c['tried']} | {c['admitted']} | {rej} | {c['search_wall_s']:.1f} |")

w("\n## T2. Mean counts per cell\n")
w("`grp` group operations; `cantor_mul`/`inv` field work inside them; `rel_mul` relation-phase native multiplications; `la_mul` linear algebra mod r; FPM mid = cantor_mul + 10 inv + rel_mul + g^2 la_mul.\n")
w("| family | g | p | arm | curves | runs | grp | cantor_mul | inv | rel_mul | la_mul | FPM mid [95%] | split x g! |")
w("|---|--:|--:|---|--:|--:|--:|--:|--:|--:|--:|---|--:|")
for c in sorted(cells, key=lambda c: (c["family"], c["g"], c["p"], c["arm"])):
    m = c["fpm_mid"]
    sf = c.get("split_fraction_times_g_factorial")
    w(f"| {c['family']} | {c['g']} | {c['p']} | {c['arm']} | {c['curves']} | {c['runs']} | {sci(c['mean_group_ops'])} | {sci(c['mean_cantor_mul'])} | {sci(c['mean_cantor_inv'])} | {sci(c['mean_rel_mul'])} | {sci(c['mean_la_mul'])} | {sci(m['mean'])} [{sci(m['lo'])}, {sci(m['hi'])}] | {'-' if sf is None else f'{sf:.3f}'} |")

w("\n## T3. Ratio to the cell's rho, across both bands\n")
w("Ratio = arm mean / rho mean (below 1: the arm costs less). Verdict `below` or `above` only if the 95% interval is on that side of 1 at every price of the band.\n")
w("| family | g | p | arm | GAE w=0 | GAE w=0.1 | GAE w=1 | GAE band | FPM low | FPM mid | FPM high | FPM band |")
w("|---|--:|--:|---|---|---|---|---|---|---|---|---|")
for c in sorted(cells, key=lambda c: (c["family"], c["g"], c["p"], c["arm"])):
    if "gae_w0_over_rho" not in c:
        continue
    def r(k):
        x = c[k + "_over_rho"]
        return f"{sci(x['ratio'])} [{sci(x['lo'])}, {sci(x['hi'])}]"
    w(f"| {c['family']} | {c['g']} | {c['p']} | {c['arm']} | {r('gae_w0')} | {r('gae_w01')} | {r('gae_w1')} | {c.get('band_gae','-')} | {r('fpm_low')} | {r('fpm_mid')} | {r('fpm_high')} | {c.get('band_fpm','-')} |")

w("\n## T4. Growth exponents in p (least squares on ln mean against ln p)\n")
w("| family | g | arm | reading | primes | p range | exponent [95%] |")
w("|---|--:|---|---|--:|---|---|")
for ft in sorted(A["fits"], key=lambda f: (f["family"], f["g"], f["arm"], f["reading"])):
    if ft["reading"] not in ("gae_w0", "fpm_mid", "trials"):
        continue
    w(f"| {ft['family']} | {ft['g']} | {ft['arm']} | {ft['reading']} | {ft['primes']} | {int(ft['p_min'])}..{int(ft['p_max'])} | {ft['exponent']:.3f} [{ft['lo']:.3f}, {ft['hi']:.3f}] |")

w("\n## T5. Parity prefilter, paired runs (same instance, same seed)\n")
w("| g | p | arm | pairs | identical counts | rel_mul on/off (min..max) | FPM mid on/off | GAE w=0.1 on/off |")
w("|--:|--:|---|--:|--:|---|---|---|")
for q in sorted(A["prefilter"], key=lambda q: (q["g"], q["p"], q["arm"])):
    a, b, c_ = q["rel_mul_ratio"], q["fpm_mid_ratio"], q["gae_w01_ratio"]
    w(f"| {q['g']} | {q['p']} | {q['arm']} | {q['pairs']} | {q['identical_counts']} | {a['mean']:.3f} ({a['min']:.3f}..{a['max']:.3f}) | {b['mean']:.3f} ({b['min']:.3f}..{b['max']:.3f}) | {c_['mean']:.3f} ({c_['min']:.3f}..{c_['max']:.3f}) |")

w("\n## T6. Smith's Propositions 2 and 4 on genus-3 hyperelliptic curves\n")
w("Interval: Wilson 95% of the recorded count (computed here from the two recorded integers).\n")
w("| population | p | curves | with a rational tractable subgroup | full_success | share [95%] |")
w("|---|--:|--:|--:|--:|---|")
for label, rows in (("census (random, no admission filter)", A["smith_census"]), ("admitted ladder instances", A["smith_admitted"])):
    for s in sorted(rows, key=lambda s: s["p"]):
        lo, hi = wilson(s["full_success"], s["curves"])
        sh = s["full_success"] / s["curves"] if s["curves"] else float("nan")
        w(f"| {label} | {s['p']} | {s['curves']} | {s['with_tractable_subgroup']} | {s['full_success']} | {sh:.3f} [{lo:.3f}, {hi:.3f}] |")

w("\n## T6b. Split rate against the point-count model, per instance (arm A)\n")
w("Model: a random class splits with probability C(n_x, g) 2^g / #J, n_x the number of abscissae carrying two points. `model x g!` is the instance's predicted split rate relative to the naive 1/g!.\n")
w("| g | p | curve_seed | n_x | candidates | splits | observed x g! | model x g! | observed / model |")
w("|--:|--:|--:|--:|--:|--:|--:|--:|--:|")
for s_ in sorted(A.get("smooth_model", []), key=lambda s: (s["g"], s["p"], s["curve_seed"])):
    gf = math.factorial(s_["g"])
    w(f"| {s_['g']} | {s_['p']} | {s_['curve_seed']} | {int(s_['fb'])} | {int(s_['candidates'])} | {int(s_['splits'])} | {s_['observed']*gf:.3f} | {s_['predicted_times_g_factorial']:.3f} | {s_['observed_over_predicted']:.3f} |")

if A["skipped"]:
    w("\n## T7. Skipped by the frozen cap\n")
    sk = {}
    for s in A["skipped"]:
        sk.setdefault((s["family"], s["g"], s["p"], s["arm"], s["reason"]), 0)
        sk[(s["family"], s["g"], s["p"], s["arm"], s["reason"])] += 1
    w("| family | g | p | arm | reason | runs |")
    w("|---|--:|--:|---|---|--:|")
    for k, v in sorted(sk.items()):
        w(f"| {k[0]} | {k[1]} | {k[2]} | {k[3]} | {k[4]} | {v} |")
if A["not_certified"]:
    w("\n## T8. Runs that did not certify\n")
    w("| family | g | p | arm | curve_seed | seed | exhausted |")
    w("|---|--:|--:|---|--:|--:|---|")
    for b in A["not_certified"]:
        w(f"| {b['family']} | {b['g']} | {b['p']} | {b['arm']} | {b['curve_seed']} | {b['seed']} | {b.get('exhausted')} |")
