# ── figures ─────────────────────────────────────────────────────────────
def esc(s):
    return str(s).replace("&", "&amp;").replace("<", "&lt;")


def nice_p(p):
    return f"{p:,}"


def panel(x0, y0, pw, ph, title, series, ylab, ymin, ymax, xs):
    """One log-log panel. series: list of (label, colour, [(p, mean, lo, hi)])."""
    s = []
    lx = lambda p: x0 + 46 + (math.log(p) - math.log(xs[0])) / max(1e-9, math.log(xs[-1]) - math.log(xs[0])) * (pw - 66)
    ly = lambda v: y0 + ph - 30 - (math.log10(v) - ymin) / (ymax - ymin) * (ph - 62)
    s.append(f'<text x="{x0+46}" y="{y0+16}" font-size="13" font-weight="600" fill="{INK}">{esc(title)}</text>')
    for e in range(math.ceil(ymin), math.floor(ymax) + 1):
        y = ly(10 ** e)
        s.append(f'<line x1="{x0+46}" y1="{y:.1f}" x2="{x0+pw-20}" y2="{y:.1f}" stroke="{GRID}" stroke-width="1"/>')
        if (math.floor(ymax) - math.ceil(ymin)) <= 8 or e % 2 == 0:
            s.append(f'<text x="{x0+40}" y="{y+4:.1f}" font-size="10" text-anchor="end" fill="{INK2}">1e{e}</text>')
    for p in xs:
        s.append(f'<text x="{lx(p):.1f}" y="{y0+ph-14}" font-size="10" text-anchor="middle" fill="{INK2}">{nice_p(p)}</text>')
    s.append(f'<text x="{x0+pw-20}" y="{y0+ph-2}" font-size="10" text-anchor="end" fill="{INK2}">p</text>')
    s.append(f'<text x="{x0+46}" y="{y0+30}" font-size="10" fill="{INK2}">{esc(ylab)}</text>')
    for label, col, pts in series:
        if not pts:
            continue
        pts = sorted(pts)
        d = " ".join(f"{'M' if i == 0 else 'L'}{lx(p):.1f},{ly(m):.1f}" for i, (p, m, lo, hi) in enumerate(pts))
        s.append(f'<path d="{d}" fill="none" stroke="{col}" stroke-width="2"/>')
        for p, m, lo, hi in pts:
            if lo and hi and lo > 0:
                s.append(f'<line x1="{lx(p):.1f}" y1="{ly(lo):.1f}" x2="{lx(p):.1f}" y2="{ly(hi):.1f}" stroke="{col}" stroke-width="1.5"/>')
            s.append(f'<circle cx="{lx(p):.1f}" cy="{ly(m):.1f}" r="4" fill="{col}" stroke="{SURF}" stroke-width="2"><title>{esc(label)}, p = {p}: {sci(m)} [{sci(lo)}, {sci(hi)}]</title></circle>')
    return "\n".join(s)


def legend(x, y, items):
    s = []
    for label, col in items:
        s.append(f'<line x1="{x}" y1="{y-4}" x2="{x+18}" y2="{y-4}" stroke="{col}" stroke-width="2"/><circle cx="{x+9}" cy="{y-4}" r="4" fill="{col}"/>')
        s.append(f'<text x="{x+24}" y="{y}" font-size="11" fill="{INK}">{esc(label)}</text>')
        x += 34 + 6.4 * len(label)
    return "\n".join(s)


def svg(wd, ht, body, title):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {wd} {ht}" width="{wd}" height="{ht}" font-family="system-ui, -apple-system, Segoe UI, sans-serif" role="img" aria-label="{esc(title)}">'
            f'<rect width="{wd}" height="{ht}" fill="{SURF}"/>{body}</svg>\n')


fams = [f for f in ("h2", "h3", "h4", "h5", "q3") if any(fam(c) == f for c in cells)]
primes = sorted({c["p"] for c in cells})
if fams and len(primes) >= 1:
    xs = primes if len(primes) > 1 else [primes[0], primes[0] * 2]
    # Figure 1: cost against p, one panel per curve kind, one shared y scale.
    allv = [c["fpm_mid"]["mean"] for c in cells if arm_class(c["arm"]) and c["fpm_mid"]["mean"] > 0]
    ymin, ymax = math.floor(math.log10(min(allv))), math.ceil(math.log10(max(allv)))
    pw, ph = 300, 250
    body = [f'<text x="16" y="22" font-size="15" font-weight="600" fill="{INK}">Cost of one discrete logarithm against p, by genus (F_p-multiplication equivalents, primary reading)</text>']
    body.append(legend(16, 44, [(ARM_LABEL[k], ARM_COL[k]) for k in "ACR"]))
    for i, fm in enumerate(fams):
        ser = []
        for k in "ACR":
            pts = [(c["p"], c["fpm_mid"]["mean"], c["fpm_mid"]["lo"], c["fpm_mid"]["hi"]) for c in cells if fam(c) == fm and arm_class(c["arm"]) == k]
            ser.append((ARM_LABEL[k], ARM_COL[k], pts))
        ttl = ("Hyperelliptic, " + GENUS_LABEL[fm]) if fm != "q3" else "Smooth plane quartic (g = 3)"
        body.append(panel(8 + (i % 3) * pw, 56 + (i // 3) * ph, pw, ph, ttl, ser, "FPM per logarithm", ymin, ymax, xs))
    rows = (len(fams) + 2) // 3
    open("fig_cost.svg", "w").write(svg(16 + 3 * pw, 64 + rows * ph, "\n".join(body), "cost against p by genus"))

    # Figure 2: best index calculus over rho, against p, one line per curve kind.
    ser = []
    lo_all, hi_all = [], []
    for fm in fams:
        pts = []
        for p in primes:
            cand = [c for c in cells if fam(c) == fm and c["p"] == p and arm_class(c["arm"]) in ("A", "C") and "fpm_mid_over_rho" in c]
            if not cand:
                continue
            b = min(cand, key=lambda c: c["fpm_mid_over_rho"]["ratio"])["fpm_mid_over_rho"]
            pts.append((p, b["ratio"], b["lo"], b["hi"]))
            lo_all.append(b["ratio"]); hi_all.append(b["ratio"])
        ser.append((GENUS_LABEL[fm], GENUS_COL[fm], pts))
    if lo_all:
        ymin, ymax = math.floor(math.log10(min(lo_all))), max(1, math.ceil(math.log10(max(hi_all))))
        body = [f'<text x="16" y="22" font-size="15" font-weight="600" fill="{INK}">Index calculus over rho on the same instances (cheaper IC arm; below 1e0 = IC costs less)</text>']
        body.append(legend(16, 44, [(GENUS_LABEL[f], GENUS_COL[f]) for f in fams]))
        body.append(panel(8, 56, 720, 330, "FPM(IC) / FPM(rho), primary reading, 95% bootstrap bars", ser, "ratio", ymin, ymax, xs))
        open("fig_ratio.svg", "w").write(svg(740, 400, "\n".join(body), "IC over rho by genus"))
print("wrote tables.md, fig_cost.svg, fig_ratio.svg")
