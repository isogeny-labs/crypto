w(f"Generated by `render.py` from `{src}`; every figure is `[pcc:unverified]`.\n")
w(f"Runs: {A['runs_total']}, not certified: {A['runs_not_certified']}. Bootstrap: {A['bootstrap']['resamples']} resamples, {A['bootstrap']['scheme']}.\n")

