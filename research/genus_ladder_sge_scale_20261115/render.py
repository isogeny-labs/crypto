#!/usr/bin/env python3
"""Lay out analysis.json (written by genus_ladder_analyze) as tables.md and SVG figures.

Layout only: every number printed here is read from analysis.json. No statistic is
computed in this file apart from formatting and the binomial interval of a recorded
count (Wilson), which is labelled where it appears.
"""
import json, math, sys

src = sys.argv[1] if len(sys.argv) > 1 else "analysis.json"
A = json.load(open(src))
cells = A["cells"]
SURF, INK, INK2, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df"
ARM_COL = {"A": "#2a78d6", "C": "#eb6834", "R": "#1baf7a"}
ARM_LABEL = {"A": "IC, full base", "C": "IC, double large prime", "R": "rho, negation map"}
GENUS_COL = {"h2": "#2a78d6", "h3": "#eb6834", "h4": "#1baf7a", "h5": "#eda100", "q3": "#e87ba4"}
GENUS_LABEL = {"h2": "g = 2", "h3": "g = 3", "h4": "g = 4", "h5": "g = 5", "q3": "plane quartic"}


def arm_class(arm):
    """Plot class of an arm name; the prefiltered hyperelliptic arms are the ones drawn."""
    if "rho" in arm:
        return "R"
    if arm in ("A_full+pre", "Q_diem_full"):
        return "A"
    if arm in ("C_double_lp+pre", "Q_diem_2lp"):
        return "C"
    return None


def fam(c):
    return ("q" if c["family"] == "quartic" else "h") + str(c["g"])


def sci(x):
    if x is None or (isinstance(x, float) and (math.isnan(x) or math.isinf(x))):
        return "-"
    if x == 0:
        return "0"
    if abs(x) >= 1e5 or abs(x) < 1e-2:
        return f"{x:.2e}"
    if abs(x) >= 100:
        return f"{x:,.0f}"
    return f"{x:.3g}"


def wilson(k, n):
    if n == 0:
        return (float("nan"), float("nan"))
    z = 1.96
    ph = k / n
    d = 1 + z * z / n
    c = ph + z * z / (2 * n)
    h = z * math.sqrt(ph * (1 - ph) / n + z * z / (4 * n * n))
    return ((c - h) / d, (c + h) / d)


