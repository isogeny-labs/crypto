//! # Tables for research/volcano_koblitz_layers_20261018
//!
//! Reads the study's committed `ecbench` sessions (`nXX-crater`, `nXX-neighbors`) and
//! prints the layer comparison and a JSON twin.  Native; no result is computed anywhere else.
//!
//! The unit of replication is a **workload** (one curve, one target): its value is the mean
//! of `cost.total_gae` over the measured (non-warm-up), verified rounds of one arm.  ecbench's
//! counts are deterministic given the seeds, so repeated rounds of a workload are identical
//! and the rounds are not counted as extra samples.
//!
//! Intervals are 95% percentile intervals from a hierarchical bootstrap (curve, then target
//! within curve, for the neighbours; target for the crater), 4000 resamples, fixed seed.
//! A ratio of means compares neighbours to the crater, or two arms on the crater's identical
//! targets (paired: the same resampled targets feed both arms).
//!
//! ```bash
//! cargo run --release --example volcano_layers_analyze -- \
//!   --study research/volcano_koblitz_layers_20261018 \
//!   --out research/volcano_koblitz_layers_20261018/TABLES.md \
//!   --json research/volcano_koblitz_layers_20261018/tables.json
//! ```

use std::collections::BTreeMap;
use std::fmt::Write as _;

use serde_json::{json, Value};

type Series = BTreeMap<String, BTreeMap<String, Vec<f64>>>; // arm -> curve slug -> per-target values

struct Rng(u64);
impl Rng {
    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9E37_79B9_7F4A_7C15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        z ^ (z >> 31)
    }
    fn below(&mut self, n: usize) -> usize {
        (self.next() % n as u64) as usize
    }
}

fn mean(v: &[f64]) -> f64 {
    v.iter().sum::<f64>() / v.len() as f64
}

fn sd(v: &[f64]) -> f64 {
    let m = mean(v);
    (v.iter().map(|x| (x - m) * (x - m)).sum::<f64>() / (v.len() as f64 - 1.0).max(1.0)).sqrt()
}

/// Per-workload values of one arm, grouped by curve, from a session's records.
fn load(dir: &str, value: &str) -> Series {
    let text = std::fs::read_to_string(format!("{dir}/records.jsonl"))
        .unwrap_or_else(|e| panic!("{dir}: {e}"));
    // (arm, curve, workload) -> rounds
    let mut raw: BTreeMap<(String, String, String), Vec<f64>> = BTreeMap::new();
    for line in text.lines() {
        let r: Value = serde_json::from_str(line).unwrap();
        if r["warmup"].as_bool().unwrap_or(false) || r["outcome"]["status"] != "verified" {
            continue;
        }
        let arm = r["arm"].as_str().unwrap().to_string();
        let curve = r["workload"]["curve"]["slug"].as_str().unwrap().to_string();
        let wl = r["workload"]["workload_id"].as_str().unwrap().to_string();
        let v = r["cost"][value].as_f64().unwrap();
        raw.entry((arm, curve, wl)).or_default().push(v);
    }
    let mut out: Series = BTreeMap::new();
    for ((arm, curve, _), rounds) in raw {
        out.entry(arm)
            .or_default()
            .entry(curve)
            .or_default()
            .push(mean(&rounds));
    }
    out
}

fn boot_pool(curves: &[&Vec<f64>], rng: &mut Rng) -> f64 {
    // resample curves, then targets within each sampled curve
    let mut tot = 0.0;
    let mut cnt = 0usize;
    for _ in 0..curves.len() {
        let c = curves[rng.below(curves.len())];
        for _ in 0..c.len() {
            tot += c[rng.below(c.len())];
            cnt += 1;
        }
    }
    tot / cnt as f64
}

fn pct(v: &mut [f64], q: f64) -> f64 {
    v.sort_by(|a, b| a.partial_cmp(b).unwrap());
    v[((v.len() as f64 - 1.0) * q).round() as usize]
}

const B: usize = 4000;

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let get = |k: &str| {
        args.iter()
            .position(|a| a == k)
            .map(|i| args[i + 1].clone())
    };
    let study = get("--study").expect("--study DIR");
    let mut sizes: Vec<u32> = Vec::new();
    for e in std::fs::read_dir(format!("{study}/sessions")).unwrap() {
        let name = e.unwrap().file_name().to_string_lossy().to_string();
        if let Some(rest) = name.strip_suffix("-crater") {
            if let Some(n) = rest.strip_prefix('n').and_then(|x| x.parse::<u32>().ok()) {
                if std::path::Path::new(&format!("{study}/sessions/n{n}-neighbors/records.jsonl"))
                    .exists()
                {
                    sizes.push(n);
                }
            }
        }
    }
    sizes.sort();
    let mut md = String::new();
    let mut js = Vec::new();
    writeln!(
        md,
        "# Layer comparison tables (generated by `examples/volcano_layers_analyze.rs`)\n"
    )
    .unwrap();
    writeln!(md, "Unit: `ecbench.gae`, group-addition equivalents (`cost.total_gae`). Replication unit: a workload (curve, target). Intervals: 95% hierarchical bootstrap, {B} resamples.\n").unwrap();
    writeln!(md, "| n | log2 r | layer | arm | curves | targets | mean GAE | sd of per-target GAE | mean S |").unwrap();
    writeln!(md, "|--:|--:|---|---|--:|--:|--:|--:|--:|").unwrap();
    let mut ratios = String::new();
    writeln!(
        ratios,
        "\n| n | comparison | ratio of mean GAE | 95% interval | reading |"
    )
    .unwrap();
    writeln!(ratios, "|--:|---|--:|---|---|").unwrap();
    for n in &sizes {
        let cdir = format!("{study}/sessions/n{n}-crater");
        let ndir = format!("{study}/sessions/n{n}-neighbors");
        let cg = load(&cdir, "total_gae");
        let ng = load(&ndir, "total_gae");
        let cs = load(&cdir, "s");
        let ns = load(&ndir, "s");
        let plan: Value =
            serde_json::from_str(&std::fs::read_to_string(format!("{cdir}/plan.json")).unwrap())
                .unwrap();
        let log2r = plan["workloads"][0]["curve"]["r"]
            .as_f64()
            .map(|r| r.log2());
        let r_bits = match log2r {
            Some(b) => format!("{b:.1}"),
            None => "-".into(),
        };
        let mut entry = json!({"n": n, "arms": {}, "ratios": []});
        for (layer, g, s) in [("crater", &cg, &cs), ("level 1", &ng, &ns)] {
            for (arm, by_curve) in g.iter() {
                let all: Vec<f64> = by_curve.values().flatten().copied().collect();
                let sall: Vec<f64> = s[arm].values().flatten().copied().collect();
                writeln!(
                    md,
                    "| {n} | {r_bits} | {layer} | {arm} | {} | {} | {:.1} | {:.1} | {:.3} |",
                    by_curve.len(),
                    all.len(),
                    mean(&all),
                    sd(&all),
                    mean(&sall)
                )
                .unwrap();
                entry["arms"][format!("{layer}/{arm}")] = json!({"curves": by_curve.len(), "targets": all.len(), "mean_gae": mean(&all), "sd_gae": sd(&all), "mean_s": mean(&sall)});
            }
        }
        // ratios
        let mut rng = Rng(0x5EED_0000 + *n as u64);
        for arm in ["rho-neg", "rho-plain"] {
            let (Some(cc), Some(nn)) = (cg.get(arm), ng.get(arm)) else {
                continue;
            };
            let cvals: Vec<f64> = cc.values().flatten().copied().collect();
            let ncurves: Vec<&Vec<f64>> = nn.values().collect();
            let point = mean(
                &ncurves
                    .iter()
                    .flat_map(|v| v.iter().copied())
                    .collect::<Vec<_>>(),
            ) / mean(&cvals);
            let mut rs: Vec<f64> = (0..B)
                .map(|_| {
                    let num = boot_pool(&ncurves, &mut rng);
                    let den = (0..cvals.len())
                        .map(|_| cvals[rng.below(cvals.len())])
                        .sum::<f64>()
                        / cvals.len() as f64;
                    num / den
                })
                .collect();
            let (lo, hi) = (pct(&mut rs.clone(), 0.025), pct(&mut rs, 0.975));
            let reading = if lo <= 1.0 && 1.0 <= hi {
                "interval contains 1"
            } else {
                "interval excludes 1"
            };
            writeln!(
                ratios,
                "| {n} | level 1 / crater, {arm} | {point:.3} | [{lo:.3}, {hi:.3}] | {reading} |"
            )
            .unwrap();
            entry["ratios"].as_array_mut().unwrap().push(json!({"comparison": format!("level1/crater {arm}"), "ratio": point, "lo": lo, "hi": hi}));
        }
        // crater, paired on identical targets: frob-strong / neg
        if let (Some(f), Some(g)) = (cg.get("rho-frob-strong"), cg.get("rho-neg")) {
            let fv: Vec<f64> = f.values().next().unwrap().clone();
            let gv: Vec<f64> = g.values().next().unwrap().clone();
            let m = fv.len().min(gv.len());
            let point = mean(&fv) / mean(&gv);
            let mut rs: Vec<f64> = (0..B)
                .map(|_| {
                    let (mut a, mut b) = (0.0, 0.0);
                    for _ in 0..m {
                        let i = rng.below(m);
                        a += fv[i];
                        b += gv[i];
                    }
                    a / b
                })
                .collect();
            let (lo, hi) = (pct(&mut rs.clone(), 0.025), pct(&mut rs, 0.975));
            let ideal = 1.0 / (*n as f64).sqrt();
            let reading = format!("ideal 1/√n = {ideal:.3}");
            writeln!(ratios, "| {n} | crater, rho-frob-strong / rho-neg (paired targets) | {point:.3} | [{lo:.3}, {hi:.3}] | {reading} |").unwrap();
            entry["ratios"].as_array_mut().unwrap().push(json!({"comparison": "crater frob-strong/neg", "ratio": point, "lo": lo, "hi": hi, "ideal": ideal}));
        }
        js.push(entry);
    }
    md.push_str(&ratios);
    writeln!(md, "\nrho-neg-aa repeats rho-neg with the same seeds; ecbench's counts are deterministic, so the control is bit-identical and carries no sampling information.").unwrap();
    print!("{md}");
    if let Some(p) = get("--out") {
        std::fs::write(&p, &md).unwrap();
    }
    if let Some(p) = get("--json") {
        std::fs::write(
            &p,
            serde_json::to_string_pretty(&json!({"sizes": js})).unwrap() + "\n",
        )
        .unwrap();
    }
}
