//! # Tables for research/volcano_prime_layers_20261018
//!
//! Reads the study's committed `ecbench` sessions (`m0`, `m5`, ...) and the vertex tables
//! `specs/<id>/vertices.json` written by `crypto volcano explore`, and prints the level
//! comparison and a JSON twin.  Native; no result is computed anywhere else.
//!
//! The unit of replication is a workload (curve, target); its value is the mean of
//! `cost.total_gae` over the measured, verified rounds (ecbench's counts are deterministic,
//! so rounds are not extra samples).  Level groups: crater = level 0, middle = levels 1..k-1,
//! floor = level k.  Intervals are 95% percentile intervals from a hierarchical bootstrap
//! (curve, then target within curve), 4000 resamples, fixed seed.  The slope is the least-squares
//! slope of per-curve mean GAE on level, as a percentage of the grand mean per level, with the
//! same bootstrap over curves.
//!
//! ```bash
//! cargo run --release --example volcano_levels_analyze -- \
//!   --study research/volcano_prime_layers_20261018 \
//!   --out research/volcano_prime_layers_20261018/TABLES.md \
//!   --json research/volcano_prime_layers_20261018/tables.json
//! ```

use std::collections::BTreeMap;
use std::fmt::Write as _;

use serde_json::{json, Value};

struct Rng(u64);
impl Rng {
    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9E37_79B9_7F4A_7C15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        z ^ (z >> 31)
    }
    fn below(&mut self, n: usize) -> usize {
        (self.next() % n as u64) as usize
    }
}

fn mean(v: &[f64]) -> f64 {
    v.iter().sum::<f64>() / v.len() as f64
}
fn pct(v: &mut [f64], q: f64) -> f64 {
    v.sort_by(|a, b| a.partial_cmp(b).unwrap());
    v[((v.len() as f64 - 1.0) * q).round() as usize]
}

/// A curve's per-target values and its level.
#[derive(Clone)]
struct CurveVals {
    level: u32,
    vals: Vec<f64>,
}

const B: usize = 4000;

fn boot_group(curves: &[&CurveVals], rng: &mut Rng) -> f64 {
    let (mut tot, mut cnt) = (0.0, 0usize);
    for _ in 0..curves.len() {
        let c = curves[rng.below(curves.len())];
        for _ in 0..c.vals.len() {
            tot += c.vals[rng.below(c.vals.len())];
            cnt += 1;
        }
    }
    tot / cnt as f64
}

fn group_mean(curves: &[&CurveVals]) -> f64 {
    mean(
        &curves
            .iter()
            .flat_map(|c| c.vals.iter().copied())
            .collect::<Vec<_>>(),
    )
}

fn slope(points: &[(f64, f64)]) -> f64 {
    let n = points.len() as f64;
    let (sx, sy) = points
        .iter()
        .fold((0.0, 0.0), |a, p| (a.0 + p.0, a.1 + p.1));
    let (mx, my) = (sx / n, sy / n);
    let sxx: f64 = points.iter().map(|p| (p.0 - mx) * (p.0 - mx)).sum();
    let sxy: f64 = points.iter().map(|p| (p.0 - mx) * (p.1 - my)).sum();
    sxy / sxx
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let get = |k: &str| {
        args.iter()
            .position(|a| a == k)
            .map(|i| args[i + 1].clone())
    };
    let study = get("--study").expect("--study DIR");
    let mut ids: Vec<String> = std::fs::read_dir(format!("{study}/specs"))
        .unwrap()
        .filter_map(|e| e.ok())
        .map(|e| e.file_name().to_string_lossy().to_string())
        .filter(|n| std::path::Path::new(&format!("{study}/sessions/{n}/records.jsonl")).exists())
        .collect();
    ids.sort();
    let mut md = String::from("# Level comparison tables (generated by `examples/volcano_levels_analyze.rs`)\n\nUnit: `ecbench.gae` (`cost.total_gae`). Replication unit: a workload (curve, target). Intervals: 95% hierarchical bootstrap (curve, then target), 4000 resamples.\n\n");
    let mut out_json = Vec::new();
    for id in &ids {
        let meta: Value = serde_json::from_str(
            &std::fs::read_to_string(format!("{study}/specs/{id}/vertices.json")).unwrap(),
        )
        .unwrap();
        let depth = meta["depth"].as_u64().unwrap() as u32;
        let mut level_of: BTreeMap<(u64, u64), (u32, u64)> = BTreeMap::new(); // (a,b) -> (level, n1)
        for v in meta["vertices"].as_array().unwrap() {
            level_of.insert(
                (v["a"].as_u64().unwrap(), v["b"].as_u64().unwrap()),
                (
                    v["level"].as_u64().unwrap() as u32,
                    v["n1"].as_u64().unwrap(),
                ),
            );
        }
        let text = std::fs::read_to_string(format!("{study}/sessions/{id}/records.jsonl")).unwrap();
        // (arm, (a,b), workload) -> rounds
        let mut raw: BTreeMap<(String, (u64, u64), String), Vec<f64>> = BTreeMap::new();
        for line in text.lines() {
            let r: Value = serde_json::from_str(line).unwrap();
            if r["warmup"].as_bool().unwrap_or(false) || r["outcome"]["status"] != "verified" {
                continue;
            }
            let cs = &r["workload"]["curve_spec"];
            let ab = (cs["a"].as_u64().unwrap(), cs["b"].as_u64().unwrap());
            raw.entry((
                r["arm"].as_str().unwrap().to_string(),
                ab,
                r["workload"]["workload_id"].as_str().unwrap().to_string(),
            ))
            .or_default()
            .push(r["cost"]["total_gae"].as_f64().unwrap());
        }
        let mut per_arm: BTreeMap<String, BTreeMap<(u64, u64), Vec<f64>>> = BTreeMap::new();
        for ((arm, ab, _), rounds) in raw {
            per_arm
                .entry(arm)
                .or_default()
                .entry(ab)
                .or_default()
                .push(mean(&rounds));
        }
        writeln!(md, "## `{id}`: p = {}, depth {depth}\n", meta["p"]).unwrap();
        writeln!(
            md,
            "| arm | level | curves | targets | n1 | mean GAE |\n|---|--:|--:|--:|--:|--:|"
        )
        .unwrap();
        let mut rng =
            Rng(0x1E7E15 + id.len() as u64 * 31 + id.bytes().map(|b| b as u64).sum::<u64>());
        let mut ratio_md = String::from("\n| solver | comparison | ratio of mean GAE | 95% interval | reading |\n|---|---|--:|---|---|\n");
        let mut entry = json!({"id": id, "p": meta["p"], "depth": depth, "levels": [], "ratios": [], "slopes": []});
        for arm in ["rho-neg", "rho-plain"] {
            let Some(curves_map) = per_arm.get(arm) else {
                continue;
            };
            let curves: Vec<CurveVals> = curves_map
                .iter()
                .map(|(ab, vals)| CurveVals {
                    level: level_of[ab].0,
                    vals: vals.clone(),
                })
                .collect();
            let mut by_level: BTreeMap<u32, Vec<&CurveVals>> = BTreeMap::new();
            for c in &curves {
                by_level.entry(c.level).or_default().push(c);
            }
            for (l, cs) in &by_level {
                let n1 = level_of
                    .values()
                    .find(|v| v.0 == *l)
                    .map(|v| v.1)
                    .unwrap_or(0);
                let ntg: usize = cs.iter().map(|c| c.vals.len()).sum();
                let gm = group_mean(cs);
                writeln!(
                    md,
                    "| {arm} | {l} | {} | {ntg} | {n1} | {gm:.0} |",
                    cs.len()
                )
                .unwrap();
                entry["levels"].as_array_mut().unwrap().push(json!({"arm": arm, "level": l, "curves": cs.len(), "targets": ntg, "n1": n1, "mean_gae": gm}));
            }
            let crater: Vec<&CurveVals> = curves.iter().filter(|c| c.level == 0).collect();
            let middle: Vec<&CurveVals> = curves
                .iter()
                .filter(|c| c.level > 0 && c.level < depth)
                .collect();
            let floor: Vec<&CurveVals> = curves.iter().filter(|c| c.level == depth).collect();
            for (name, num, den) in [
                ("middle / crater", &middle, &crater),
                ("floor / crater", &floor, &crater),
                ("floor / middle", &floor, &middle),
            ] {
                let point = group_mean(num) / group_mean(den);
                let mut rs: Vec<f64> = (0..B)
                    .map(|_| boot_group(num, &mut rng) / boot_group(den, &mut rng))
                    .collect();
                let (lo, hi) = (pct(&mut rs.clone(), 0.025), pct(&mut rs, 0.975));
                let reading = if lo <= 1.0 && 1.0 <= hi {
                    "interval contains 1"
                } else {
                    "interval excludes 1"
                };
                writeln!(
                    ratio_md,
                    "| {arm} | {name} | {point:.3} | [{lo:.3}, {hi:.3}] | {reading} |"
                )
                .unwrap();
                entry["ratios"].as_array_mut().unwrap().push(
                    json!({"solver": arm, "comparison": name, "ratio": point, "lo": lo, "hi": hi}),
                );
            }
            // slope of per-curve mean on level, % of grand mean per level
            let pts: Vec<(f64, f64)> = curves
                .iter()
                .map(|c| (c.level as f64, mean(&c.vals)))
                .collect();
            let grand = mean(&pts.iter().map(|p| p.1).collect::<Vec<_>>());
            let point = 100.0 * slope(&pts) / grand;
            let mut ss: Vec<f64> = (0..B)
                .map(|_| {
                    let s: Vec<(f64, f64)> =
                        (0..pts.len()).map(|_| pts[rng.below(pts.len())]).collect();
                    let g = mean(&s.iter().map(|p| p.1).collect::<Vec<_>>());
                    let lv: std::collections::BTreeSet<u64> =
                        s.iter().map(|p| p.0 as u64).collect();
                    if lv.len() < 2 {
                        f64::NAN
                    } else {
                        100.0 * slope(&s) / g
                    }
                })
                .filter(|x| x.is_finite())
                .collect();
            let (lo, hi) = (pct(&mut ss.clone(), 0.025), pct(&mut ss, 0.975));
            writeln!(ratio_md, "| {arm} | slope per level, % of grand mean | {point:.2} | [{lo:.2}, {hi:.2}] | {} |", if lo <= 0.0 && 0.0 <= hi { "interval contains 0" } else { "interval excludes 0" }).unwrap();
            entry["slopes"]
                .as_array_mut()
                .unwrap()
                .push(json!({"solver": arm, "percent_per_level": point, "lo": lo, "hi": hi}));
        }
        md.push_str(&ratio_md);
        md.push('\n');
        out_json.push(entry);
    }
    writeln!(md, "`rho-neg-aa` repeats `rho-neg` with the same seeds; ecbench's counts are deterministic, so the control is bit-identical and carries no sampling information.").unwrap();
    print!("{md}");
    if let Some(p) = get("--out") {
        std::fs::write(&p, &md).unwrap();
    }
    if let Some(p) = get("--json") {
        std::fs::write(
            &p,
            serde_json::to_string_pretty(&json!({"volcanoes": out_json})).unwrap() + "\n",
        )
        .unwrap();
    }
}
