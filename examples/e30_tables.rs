//! **E30 (§9.28) tables**: the trivial-product audit against E27's records.
//! `S_audited = S_K − ic_trivial_product_savings`; the walk (iii) less the
//! walk audit's mean saving.  Distances at `0`, `0.1`, `1` GAE (`97` per
//! Macaulay entry and per walk step), before and after.
//!
//! ```text
//! cargo run --release --example e30_tables -- experiments/35_invariants_lite experiments/32_walk_karatsuba
//! ```

use std::env;
use std::fmt::Write as _;
use std::fs;

use serde_json::{json, Value};

const GAE: f64 = 97.0;

fn load(path: &str) -> Value {
    serde_json::from_str(&fs::read_to_string(path).unwrap_or_else(|e| panic!("{path}: {e}")))
        .unwrap()
}

fn main() {
    let args: Vec<String> = env::args().skip(1).collect();
    let dir = args
        .first()
        .cloned()
        .unwrap_or("experiments/35_invariants_lite".into());
    let e27 = args
        .get(1)
        .cloned()
        .unwrap_or("experiments/32_walk_karatsuba".into());
    let walk_audit = load(&format!("{dir}/walk_audit.json"));
    let e27_summary = load(&format!("{e27}/summary.json"));
    let mut md = String::from("# E30 tables (generated by `examples/e30_tables.rs`)\n\n| p | seed | arm | `S_K` (E27) | saving (IC) | saving / `S_K` | other fields equal | walk (iii) | walk saving | `S/rho` change 0 / 0.1 / 1 GAE |\n|--:|--:|:--|--:|--:|--:|:--|--:|--:|:--|\n");
    let mut rows = Vec::new();
    let mut max_change = 0f64;
    for p in [101u64, 149, 197, 269, 397] {
        for seed in [1u64, 2] {
            let Ok(t) = fs::read_to_string(format!("{dir}/e2e_audit_p{p}s{seed}.json")) else {
                writeln!(md, "| {p} | {seed} | missing |").unwrap();
                continue;
            };
            let au: Value = serde_json::from_str(&t).unwrap();
            let k = load(&format!("{e27}/e2e_chain_karatsuba_p{p}s{seed}.json"));
            let ws = walk_audit["rows"]
                .as_array()
                .unwrap()
                .iter()
                .find(|r| {
                    r["p"].as_u64() == Some(p)
                        && r["seed"].as_u64() == Some(seed)
                        && r["fold"] == "Gls"
                })
                .unwrap()["mean_saved"]
                .as_f64()
                .unwrap();
            for (ra, rk) in au.as_array().unwrap().iter().zip(k.as_array().unwrap()) {
                let arm = ra["arm"].as_str().unwrap();
                let mut equal = true;
                for (key, vk) in rk.as_object().unwrap() {
                    if key.ends_with("_ms")
                        || key == "rho"
                        || key.starts_with("rho_")
                        || key == "ratio"
                    {
                        continue; // wall times; walks re-run (same counts expected).
                    }
                    if &ra[key] != vk {
                        equal = false;
                        eprintln!("p={p} seed={seed} arm {arm}: field {key} differs");
                    }
                }
                let sk = rk["total_muls"].as_f64().unwrap();
                let saved = ra["ic_trivial_product_savings"]
                    .as_f64()
                    .unwrap_or(f64::NAN);
                let srow = e27_summary["rows"]
                    .as_array()
                    .unwrap()
                    .iter()
                    .find(|r| {
                        r["p"].as_u64() == Some(p)
                            && r["seed"].as_u64() == Some(seed)
                            && r["arm"].as_str() == Some(arm)
                    })
                    .unwrap();
                let rho = srow["rho_e27"].as_f64().unwrap();
                let steps = srow["walk_steps"].as_f64().unwrap();
                let entries = srow["macaulay_entries"].as_f64().unwrap();
                let mut ch = [0f64; 3];
                for (wi, &w) in [0.0, 0.1, 1.0].iter().enumerate() {
                    let before = (sk + w * GAE * entries) / (rho + w * GAE * steps);
                    let after = (sk - saved + w * GAE * entries) / (rho - ws + w * GAE * steps);
                    ch[wi] = after / before - 1.0;
                    max_change = max_change.max(ch[wi].abs());
                }
                writeln!(
                    md,
                    "| {p} | {seed} | {arm} | {sk:.4e} | {saved:.4e} | {:.4} % | {equal} | {rho:.4e} | {ws:.1} | {:+.4} % / {:+.4} % / {:+.4} % |",
                    100.0 * saved / sk, 100.0 * ch[0], 100.0 * ch[1], 100.0 * ch[2]
                )
                .unwrap();
                rows.push(
                    json!({"p": p, "seed": seed, "arm": arm, "S_K": sk, "saving": saved,
                    "saving_share": saved / sk, "other_fields_equal": equal, "walk_saving": ws,
                    "distance_change": ch}),
                );
            }
        }
    }
    writeln!(
        md,
        "\nLargest |distance change| over rows and weights: `{:.4} %`.",
        100.0 * max_change
    )
    .unwrap();
    fs::write(format!("{dir}/tables.md"), &md).unwrap();
    fs::write(
        format!("{dir}/summary.json"),
        serde_json::to_string_pretty(
            &json!({"experiment": "e30", "rows": rows, "max_abs_change": max_change}),
        )
        .unwrap(),
    )
    .unwrap();
    print!("{md}");
}
