//! **E37 (§9.44) tables**: E36's pivot rules F, S, H re-tested on fresh
//! streams — Stage A per call, the controls (G2.165), and end to end on
//! E25's 20 rows and E24's 12 curves against A, E25 (the Macaulay solver),
//! B″ and the matched rho (walk (iii)), at `0`, `0.1` and `1` GAE, with
//! σ1–σ3.  Reads recorded JSON only; writes `tables.md` and `summary.json`
//! (the values the report plots).
//!
//! ```text
//! ./e37_tables experiments/44_pivot_rules_confirm
//! ```

use std::env;
use std::fmt::Write as _;
use std::fs;

use serde_json::{json, Map, Value};

const GAE: f64 = 97.0;
const GS: [f64; 3] = [0.0, 0.1, 1.0];
const GLS: [(u64, u64); 10] = [
    (101, 1),
    (101, 2),
    (149, 1),
    (149, 2),
    (197, 1),
    (197, 2),
    (269, 1),
    (269, 2),
    (397, 1),
    (397, 2),
];
const E24: [(u64, u64); 12] = [
    (101, 1),
    (101, 2),
    (149, 1),
    (149, 2),
    (197, 1),
    (197, 2),
    (269, 1),
    (269, 2),
    (397, 1),
    (397, 2),
    (521, 1),
    (521, 2),
];
const RULES: [&str; 3] = ["chain-fifo", "chain-static", "chain-fifo-static"];
/// End-to-end arms: A (run as `chain-counted`), E25 (`macaulay`), the
/// rules, B″.
const ARMS: [&str; 6] = [
    "chain-counted",
    "macaulay",
    "chain-fifo",
    "chain-static",
    "chain-fifo-static",
    "chain-sparsest-est",
];

fn load(path: &str) -> Value {
    serde_json::from_str(&fs::read_to_string(path).unwrap_or_else(|e| panic!("{path}: {e}")))
        .unwrap()
}

fn f(v: &Value, k: &str) -> f64 {
    v[k].as_f64().unwrap_or_else(|| panic!("field {k}"))
}

fn short(s: &str) -> &'static str {
    match s {
        "chain-fifo" => "F",
        "chain-static" => "S",
        "chain-fifo-static" => "H",
        "chain-lifo" => "L",
        "chain-sparsest-est" => "B″",
        "chain-counted" | "chain" => "A",
        "macaulay" | "existing" => "E25",
        _ => "?",
    }
}

fn sci(v: f64) -> String {
    if v == 0.0 {
        return "0".into();
    }
    let e = v.abs().log10().floor() as i32;
    format!("{:.2}·10^{}", v / 10f64.powi(e), e)
}

fn range(v: &[f64]) -> (f64, f64) {
    v.iter()
        .fold((f64::INFINITY, f64::NEG_INFINITY), |(lo, hi), &x| {
            (lo.min(x), hi.max(x))
        })
}

fn arm_of(recs: &Value, a: Option<&str>) -> Value {
    let arr = recs.as_array().unwrap();
    match a {
        Some(a) => arr
            .iter()
            .find(|r| r["arm"] == a)
            .unwrap_or_else(|| panic!("arm {a}"))
            .clone(),
        None => arr[0].clone(),
    }
}

/// Fields a rule's (or B″'s) record may change against A's on the same
/// stream: the solve's multiplications and what derives from them, the
/// selection and lead-scan fields, wall times and the tag.
fn may_differ(k: &str) -> bool {
    k.ends_with("_ms")
        || matches!(
            k,
            "solve_muls"
                | "total_muls"
                | "call"
                | "ratio"
                | "solver"
                | "pivot_selection"
                | "pivot_selection_ops"
                | "lead_scan_reads"
        )
}

fn diff_fields(a: &Value, b: &Value, allow: fn(&str) -> bool) -> Vec<String> {
    let (ao, bo) = (a.as_object().unwrap(), b.as_object().unwrap());
    let mut keys: Vec<&String> = ao.keys().chain(bo.keys()).collect();
    keys.sort();
    keys.dedup();
    keys.into_iter()
        .filter(|k| !allow(k) && ao.get(*k) != bo.get(*k))
        .cloned()
        .collect()
}

fn within(v: f64, lo: f64, hi: f64) -> bool {
    (lo..=hi).contains(&v)
}

fn main() {
    let args: Vec<String> = env::args().skip(1).collect();
    let dir = args
        .first()
        .cloned()
        .unwrap_or("experiments/44_pivot_rules_confirm".into());
    let e27 = "experiments/32_walk_karatsuba";
    let e36 = "experiments/40_pivot_rules";
    let mut md = String::new();
    let mut verdict = Map::new();
    writeln!(md, "# E37 tables (generated by `examples/e37_tables.rs`)\n").unwrap();

    // ── Stage A ──────────────────────────────────────────────────────────
    let sa = load(&format!("{dir}/stage_a.json"));
    writeln!(md, "## Stage A (fresh calls: salt `0xE37A_0001`; per call, means over all calls, fallbacks charged)\n").unwrap();
    writeln!(md, "| p | seed | calls | agree (existing, A, A counted, B″, A-rule, F, S, H, L) | A-rule = A counted | digest ≠ A | contested calls |").unwrap();
    writeln!(md, "|--:|--:|--:|:--|--:|:--|--:|").unwrap();
    let mut stage = Vec::new();
    let mut sa_identity = true;
    // Pooled σ2/σ3 tallies (for E24's rows, which have no Stage A).
    let mut pooled: Map<String, Value> = Map::new();
    let mut pool_acc: std::collections::BTreeMap<String, (f64, f64, f64)> = Default::default();
    for c in sa.as_array().unwrap() {
        let calls = c["calls"].as_u64().unwrap() as usize;
        let agree: Vec<usize> = c["agree"]
            .as_array()
            .unwrap()
            .iter()
            .map(|v| v.as_u64().unwrap() as usize)
            .collect();
        let low = c["lowest_equals_a"].as_u64().unwrap() as usize;
        if agree.iter().any(|&a| a != calls) || low != calls {
            sa_identity = false;
        }
        writeln!(
            md,
            "| {} | {} | {calls} | {:?} | {low} | {} | {} |",
            c["p"], c["seed"], agree, c["digest_differs_from_a"], c["calls_contested"]
        )
        .unwrap();
        let sums = c["summaries"].as_array().unwrap();
        let by = |n: &str| sums.iter().find(|s| s["solver"] == n).unwrap().clone();
        let sv = |n: &str, g: usize| by(n)["s_mean"][g].as_f64().unwrap();
        let a_lead = f(&by("chain-counted"), "lead_scan_mean");
        let a_ord = f(&by("chain-lowest-e36"), "ordered_candidates_mean");
        // σ1 lead scans for every arm (existing and A take A counted's);
        // σ2 ordered candidates for A (the positive control's tally), S,
        // H; σ3 contested columns for the E36 rules.
        let sens = |n: &str, g: usize, which: usize| -> f64 {
            let w = GAE * GS[g];
            let extra = match (which, n) {
                (1, "existing" | "chain") => a_lead,
                (1, _) => f(&by(n), "lead_scan_mean"),
                (2, "existing" | "chain") => a_ord,
                (2, "chain-sparsest-est") => 0.0,
                (2, _) => f(&by(n), "ordered_candidates_mean"),
                (3, "chain-fifo" | "chain-static" | "chain-fifo-static" | "chain-lifo") => {
                    f(&by(n), "contested_mean")
                }
                _ => 0.0,
            };
            sv(n, g) + w * extra
        };
        for n in ["chain-lowest-e36", "chain-fifo", "chain-static", "chain-fifo-static"] {
            let e = pool_acc.entry(n.to_string()).or_default();
            e.0 += f(&by(n), "ordered_candidates_mean");
            e.1 += f(&by(n), "contested_mean");
            e.2 += 1.0;
        }
        let mut per = Map::new();
        for n in [
            "existing",
            "chain",
            "chain-lowest-e36",
            "chain-sparsest-est",
            "chain-fifo",
            "chain-static",
            "chain-fifo-static",
            "chain-lifo",
        ] {
            let b = by(n);
            per.insert(
                n.into(),
                json!({
                    "c_mean": f(&b, "call_mean"), "c_median": b["call_median"].clone(),
                    "echelon_mean": f(&b, "echelon_mean"), "entries_mean": f(&b, "entries_mean"),
                    "sel_mean": f(&b, "sel_mean"), "lead_scan_mean": f(&b, "lead_scan_mean"),
                    "contested_mean": f(&b, "contested_mean"),
                    "ordered_candidates_mean": f(&b, "ordered_candidates_mean"),
                    "fallbacks": b["fallbacks"].clone(),
                    "s": [sens(n, 0, 0), sens(n, 1, 0), sens(n, 2, 0)],
                    "s_sigma1": [sens(n, 0, 1), sens(n, 1, 1), sens(n, 2, 1)],
                    "s_sigma2": [sens(n, 0, 2), sens(n, 1, 2), sens(n, 2, 2)],
                    "s_sigma3": [sens(n, 0, 3), sens(n, 1, 3), sens(n, 2, 3)],
                }),
            );
        }
        stage.push(json!({"p": c["p"], "seed": c["seed"], "calls": calls, "per": per}));
    }
    for (n, (o, ct, k)) in &pool_acc {
        pooled.insert(n.clone(), json!({"ordered_candidates_mean": o / k, "contested_mean": ct / k}));
    }
    writeln!(md, "\nStage A identity (every solver agrees with the existing solver on every call; A's rule through E36's echelon = A counted on every call): **{sa_identity}**\n").unwrap();

    writeln!(md, "| p | seed | X | C mean | sel / call | C_A/C_X | S_A/S_X 0 | 0.1 | 1 | σ1 1 | σ2 1 | σ3 1 | S_E25/S_X 1 | S_B″/S_X 0 | 0.1 | 1 |").unwrap();
    writeln!(md, "|--:|--:|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|").unwrap();
    let mut g166 = true;
    let mut g167 = true;
    let mut g168 = true;
    let mut sa_ranges: std::collections::BTreeMap<String, Vec<Vec<f64>>> = Default::default();
    for r in &stage {
        let per = &r["per"];
        let s = |n: &str, k: &str, g: usize| per[n][k][g].as_f64().unwrap();
        let ca = f(&per["chain"], "c_mean");
        let sel_s = f(&per["chain-static"], "sel_mean");
        let sel_h = f(&per["chain-fifo-static"], "sel_mean");
        g166 &= f(&per["chain-fifo"], "sel_mean") == 0.0
            && f(&per["chain-lifo"], "sel_mean") == 0.0
            && within(sel_s, 500.0, 525.0)
            && within(sel_h - sel_s, 325.0, 345.0);
        let cf = f(&per["chain-fifo"], "c_mean");
        let cb = f(&per["chain-sparsest-est"], "c_mean");
        g167 &= within(ca / cf, 1.44, 1.58)
            && within(ca / f(&per["chain-static"], "c_mean"), 1.38, 1.49)
            && within(ca / f(&per["chain-fifo-static"], "c_mean"), 1.48, 1.59)
            && within(f(&per["chain-lifo"], "c_mean") / ca, 1.36, 1.44)
            && within(cf / cb, 1.00, 1.08);
        for x in ["chain-fifo", "chain-static", "chain-fifo-static", "chain-lifo", "chain-sparsest-est"] {
            let rat = |k: &str, g: usize| s("chain", k, g) / s(x, k, g);
            let v = vec![
                ca / f(&per[x], "c_mean"),
                rat("s", 0),
                rat("s", 1),
                rat("s", 2),
                rat("s_sigma1", 2),
                rat("s_sigma2", 2),
                rat("s_sigma3", 2),
                s("existing", "s", 2) / s(x, "s", 2),
                s("chain-sparsest-est", "s", 0) / s(x, "s", 0),
                s("chain-sparsest-est", "s", 1) / s(x, "s", 1),
                s("chain-sparsest-est", "s", 2) / s(x, "s", 2),
            ];
            if RULES.contains(&x) {
                let all_ahead = ["s", "s_sigma1", "s_sigma2", "s_sigma3"]
                    .iter()
                    .all(|k| (0..3).all(|g| rat(k, g) > 1.0));
                let band = match x {
                    "chain-fifo" => within(v[3], 1.009, 1.016),
                    _ => within(v[3], 1.006, 1.011),
                };
                g168 &= all_ahead && band;
            }
            writeln!(
                md,
                "| {} | {} | {} | {:.0} | {:.1} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} |",
                r["p"], r["seed"], short(x), f(&per[x], "c_mean"), f(&per[x], "sel_mean"),
                v[0], v[1], v[2], v[3], v[4], v[5], v[6], v[7], v[8], v[9], v[10]
            )
            .unwrap();
            sa_ranges.entry(x.to_string()).or_default().push(v);
        }
    }
    writeln!(md, "\nStage A ranges over the ten curves (`[min, max]`):\n").unwrap();
    writeln!(md, "| X | C_A/C_X | S_A/S_X 0 | 0.1 | 1 | σ1 1 | σ2 1 | σ3 1 | S_E25/S_X 1 | S_B″/S_X 0 | 0.1 | 1 |").unwrap();
    writeln!(md, "|:--|:--|:--|:--|:--|:--|:--|:--|:--|:--|:--|:--|").unwrap();
    let mut sa_range_json = Map::new();
    for (x, rows) in &sa_ranges {
        let cols: Vec<(f64, f64)> = (0..rows[0].len())
            .map(|i| range(&rows.iter().map(|r| r[i]).collect::<Vec<_>>()))
            .collect();
        let cells: Vec<String> = cols.iter().map(|(a, b)| format!("{a:.4}–{b:.4}")).collect();
        writeln!(md, "| {} | {} |", short(x), cells.join(" | ")).unwrap();
        sa_range_json.insert(
            x.clone(),
            json!(cols.iter().map(|(a, b)| json!([a, b])).collect::<Vec<_>>()),
        );
    }
    verdict.insert("G2.166_selection".into(), json!(g166));
    verdict.insert("G2.167_quality_bands".into(), json!(g167));
    verdict.insert("G2.168_stage_a_band".into(), json!(g168));
    verdict.insert("G2.164_stage_a_identity".into(), json!(sa_identity));

    // ── Controls ────────────────────────────────────────────────────────
    let ck = load(&format!("{dir}/checks.json"));
    writeln!(md, "\n## Controls (G2.165; {} calls, {} with a non-empty clean set)\n", ck["calls"], ck["nonempty"]).unwrap();
    writeln!(md, "Positive check: the control's read log first differs from the clean run's at the same phase and column with a different row hash.  Detected: solutions, degree, decomposition set or fallback flag differ (a call without a positive check counts as not detected).\n").unwrap();
    writeln!(md, "| control | rule | aimed | effective | positive | structural | unread | detected (positive) | rate | non-empty detected | rate | via fallback only | thresholds met |").unwrap();
    writeln!(md, "|:--|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|:--|").unwrap();
    let mut g165 = true;
    let mut controls = Vec::new();
    for (ctl, rules, gating) in [
        ("c_sh", vec!["S", "H"], true),
        ("c_f", vec!["F"], true),
        ("c_0", vec!["F", "S", "H", "L"], false),
    ] {
        for rule in rules {
            let t = &ck[ctl][rule];
            let n = t["calls"].as_f64().unwrap();
            let pos = t["positive"].as_f64().unwrap();
            let det = t["detected_positive"].as_f64().unwrap();
            let ne = t["nonempty"].as_f64().unwrap();
            let ned = t["nonempty_detected_positive"].as_f64().unwrap();
            let ok = pos / n >= 0.95 && det / n >= 0.75 && ned / ne.max(1.0) >= 0.95;
            if gating {
                g165 &= ok;
            }
            writeln!(
                md,
                "| {} | {rule} | {} | {} | {} | {} | {} | {} | {:.3} | {}/{} | {:.3} | {} | {ok}{} |",
                ctl.to_uppercase(), t["aimed"], t["effective"], t["positive"], t["structural"], t["unread"],
                t["detected_positive"], det / n, t["nonempty_detected_positive"], t["nonempty"], ned / ne.max(1.0),
                t["via_fallback"], if gating { "" } else { " (calibration)" }
            )
            .unwrap();
            controls.push(json!({"control": ctl, "rule": rule, "gating": gating, "calls": n,
                "positive_rate": pos / n, "detection_rate": det / n,
                "nonempty_detection_rate": ned / ne.max(1.0), "thresholds_met": ok, "tally": t}));
        }
    }
    let nonempty = ck["nonempty"].as_u64().unwrap();
    let pert_ok = ["F", "S", "H", "L"]
        .iter()
        .all(|r| ck["perturbed_detected"][r].as_u64() == Some(nonempty));
    let dig_ok = ["F", "L"].iter().all(|r| {
        ck["digest_differs_from_a"][r].as_u64() == ck["contested_calls_f"].as_u64()
    });
    g165 &= pert_ok && dig_ok && ck["identity_failures"].as_u64() == Some(0);
    writeln!(md, "\nPerturbed coefficient detected (non-empty calls {nonempty}): {}; digests ≠ A: {} (contested calls {}); clean-run identity failures: {}.  **G2.165 thresholds met: {g165}**\n",
        ck["perturbed_detected"], ck["digest_differs_from_a"], ck["contested_calls_f"], ck["identity_failures"]).unwrap();
    verdict.insert("G2.165_controls".into(), json!(g165));

    // ── End to end ───────────────────────────────────────────────────────
    let s27 = load(&format!("{e27}/summary.json"));
    let w24 = load(&format!("{dir}/walk_e24.json"));
    let mut walk_ok = true;
    let mut walk_ratio = Vec::new();
    for c in w24["curves"].as_array().unwrap() {
        walk_ok &= c["replay_matches_e24"] == true
            && c["karatsuba_identical"] == true
            && c["batched_identical"] == true
            && c["all_correct"] == true
            && c["e24_records"].as_u64() == Some(16);
        walk_ratio.push(f(&c["mean_fp_muls"], "schoolbook") / f(&c["mean_fp_muls"], "batched"));
    }
    let (wr0, wr1) = range(&walk_ratio);
    let g174 = walk_ok && wr0 >= 1.40 && wr1 <= 1.50;
    verdict.insert("G2.174_walk_e24".into(), json!(g174));
    writeln!(md, "## E24 walk (iii) (G2.174)\n\nAll 192 walks replay E24's records and are identical across (i), (ii), (iii), all correct: **{walk_ok}**; (i)/(iii) cost `{wr0:.4}`–`{wr1:.4}`.\n").unwrap();

    let stage_by = |p: u64, seed: u64| -> Option<&Value> {
        stage
            .iter()
            .find(|r| r["p"].as_u64() == Some(p) && r["seed"].as_u64() == Some(seed))
    };
    // Per-call σ2/σ3 tallies of an arm on a curve (Stage A means of the
    // curve; for E24's rows, which have no Stage A, the ten curves' mean).
    // A and E25 take A's ordered candidates (the positive control's tally).
    let tally = |set: &str, p: u64, seed: u64, arm: &str| -> (f64, f64) {
        let ordered = matches!(arm, "chain-counted" | "macaulay" | "chain-static" | "chain-fifo-static");
        let contested = matches!(arm, "chain-fifo" | "chain-static" | "chain-fifo-static");
        if !ordered && !contested {
            return (0.0, 0.0);
        }
        let key = match arm {
            "chain-counted" | "macaulay" => "chain-lowest-e36",
            x => x,
        };
        let src = if set == "gls" {
            stage_by(p, seed).unwrap()["per"][key].clone()
        } else {
            pooled[key].clone()
        };
        (
            if ordered { f(&src, "ordered_candidates_mean") } else { 0.0 },
            if contested { f(&src, "contested_mean") } else { 0.0 },
        )
    };
    let mut rows: Vec<Value> = Vec::new();
    let mut identity = Vec::new();
    let mut health = Vec::new();
    for (set, curves) in [("gls", &GLS[..]), ("e24", &E24[..])] {
        for &(p, seed) in curves {
            let recs: Vec<(&str, Value)> = ARMS
                .iter()
                .map(|s| (*s, load(&format!("{dir}/e2e/{set}_{s}_p{p}s{seed}.json"))))
                .collect();
            let arms: Vec<Option<&str>> = if set == "gls" {
                vec![Some("A"), Some("B")]
            } else {
                vec![None]
            };
            for a in arms {
                let (rho, steps) = if set == "gls" {
                    let r = s27["rows"]
                        .as_array()
                        .unwrap()
                        .iter()
                        .find(|r| r["p"] == p && r["seed"] == seed && r["arm"] == a.unwrap())
                        .unwrap();
                    (f(r, "rho_e27"), f(r, "walk_steps"))
                } else {
                    let c = w24["curves"]
                        .as_array()
                        .unwrap()
                        .iter()
                        .find(|c| c["p"] == p && c["seed"] == seed)
                        .unwrap();
                    (f(&c["mean_fp_muls"], "batched"), f(c, "mean_steps"))
                };
                let rho_g: Vec<f64> = GS.iter().map(|g| rho + GAE * g * steps).collect();
                let xa = arm_of(&recs[0].1, a);
                let a_lead = xa["lead_scan_reads"].as_f64().unwrap_or(0.0);
                let mut row = json!({"set": set, "p": p, "seed": seed, "arm": a.unwrap_or("—"),
                    "rho": rho, "walk_steps": steps, "rho_g": rho_g});
                for (s, rec) in &recs {
                    let x = arm_of(rec, a);
                    let calls = f(&x, "residuals");
                    let sel = x["pivot_selection_ops"].as_f64().unwrap_or(0.0);
                    let lead = if *s == "macaulay" {
                        a_lead
                    } else {
                        x["lead_scan_reads"].as_f64().unwrap_or(0.0)
                    };
                    let (ord, cont) = tally(set, p, seed, s);
                    let base: Vec<f64> = GS
                        .iter()
                        .map(|g| f(&x, "total_muls") + GAE * g * (f(&x, "macaulay_entries") + sel))
                        .collect();
                    let plus = |extra: f64| -> Vec<f64> {
                        (0..3).map(|g| base[g] + GAE * GS[g] * extra).collect()
                    };
                    row[*s] = json!({
                        "S": base, "S_sigma1": plus(lead), "S_sigma2": plus(ord * calls),
                        "S_sigma3": plus(cont * calls), "calls": calls,
                        "selection_per_call": sel / calls, "c_mean": x["call"]["mean"].clone(),
                        "over_rho": (0..3).map(|g| base[g] / rho_g[g]).collect::<Vec<_>>(),
                    });
                    let unsolved = f(&x, "unsolved");
                    let fb = x["solver_fallbacks"].as_f64().unwrap_or(0.0);
                    let rho_ok = x["rho"].as_array().is_some_and(|w| w.iter().all(|w| w["correct"] == true));
                    health.push(json!({"set": set, "p": p, "seed": seed, "arm": a.unwrap_or("—"), "solver": s,
                        "log_recovered": x["folded"]["correct"] == true, "rho_walks_correct": rho_ok,
                        "unsolved_share": unsolved / calls, "fallback_share": fb / calls,
                        "stream_salt": x["stream_salt"].clone()}));
                    if *s != "chain-counted" && *s != "macaulay" {
                        let d = diff_fields(&xa, &x, may_differ);
                        identity.push(json!({"set": set, "p": p, "seed": seed, "arm": a.unwrap_or("—"),
                            "solver": s, "fields_differing_from_a": d}));
                    } else if *s == "macaulay" {
                        identity.push(json!({"set": set, "p": p, "seed": seed, "arm": a.unwrap_or("—"),
                            "solver": s, "informational": true,
                            "fields_differing_from_a": diff_fields(&xa, &x, may_differ)}));
                    }
                }
                rows.push(row);
            }
        }
    }
    let ident_ok = identity
        .iter()
        .filter(|i| i["informational"] != true)
        .all(|i| i["fields_differing_from_a"].as_array().unwrap().is_empty());
    verdict.insert("G2.164_e2e_identity".into(), json!(ident_ok));
    let health_ok_e24 = health.iter().filter(|h| h["set"] == "e24").all(|h| {
        h["log_recovered"] == true
            && h["rho_walks_correct"] == true
            && f(h, "unsolved_share") <= 0.01
            && f(h, "fallback_share") <= 0.01
    });
    let health_ok_all = health
        .iter()
        .all(|h| h["log_recovered"] == true && h["rho_walks_correct"] == true);

    // Ratios and ranks.
    let refs = [
        ("chain-counted", "S_A / S_X"),
        ("macaulay", "S_E25 / S_X"),
        ("chain-sparsest-est", "S_B″ / S_X"),
    ];
    writeln!(md, "## End to end (paired on the fresh stream `0xE37E_0001`; Karatsuba products for every arm)\n").unwrap();
    writeln!(md, "Per row: `S_ref / S_X` at `0 / 0.1 / 1` GAE (`>1`: X cheaper) and `S_X / rho` (walk (iii)).\n").unwrap();
    for x in RULES {
        writeln!(md, "### {} (`{x}`)\n", short(x)).unwrap();
        writeln!(md, "| set | p | seed | arm | sel/call | A/X 0 | 0.1 | 1 | E25/X 0 | 0.1 | 1 | B″/X 0 | 0.1 | 1 | X/rho 0 | 0.1 | 1 |").unwrap();
        writeln!(md, "|:--|--:|--:|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|").unwrap();
        for r in &rows {
            let v = |n: &str, g: usize| r[n]["S"][g].as_f64().unwrap() / r[x]["S"][g].as_f64().unwrap();
            let o = |g: usize| r[x]["over_rho"][g].as_f64().unwrap();
            writeln!(
                md,
                "| {} | {} | {} | {} | {:.1} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {} | {} | {} |",
                r["set"].as_str().unwrap(), r["p"], r["seed"], r["arm"].as_str().unwrap(),
                f(&r[x], "selection_per_call"),
                v("chain-counted", 0), v("chain-counted", 1), v("chain-counted", 2),
                v("macaulay", 0), v("macaulay", 1), v("macaulay", 2),
                v("chain-sparsest-est", 0), v("chain-sparsest-est", 1), v("chain-sparsest-est", 2),
                sci(o(0)), sci(o(1)), sci(o(2))
            )
            .unwrap();
        }
        writeln!(md).unwrap();
    }
    writeln!(md, "### Ranges and orders (an order is stated only where it holds at every weight on every row of the set)\n").unwrap();
    writeln!(md, "| X | reference | rows | 0 GAE | 0.1 GAE | 1 GAE | rows X ahead (0/0.1/1) | primary order | σ1 | σ2 | σ3 |").unwrap();
    writeln!(md, "|:--|:--|:--|:--|:--|:--|:--|:--|:--|:--|:--|").unwrap();
    let mut ranks = Vec::new();
    let order_of = |ahead: &[usize], n: usize| -> &'static str {
        if ahead.iter().all(|&a| a == n) {
            "X ahead across the band"
        } else if ahead.iter().all(|&a| a == 0) {
            "X behind across the band"
        } else {
            "unresolved"
        }
    };
    let mut band_checks = Map::new();
    for x in RULES.iter().copied().chain(["chain-sparsest-est"]) {
        for (rf, what) in refs {
            if rf == x {
                continue;
            }
            for set in ["gls", "e24", "all"] {
                let sel: Vec<&Value> = rows
                    .iter()
                    .filter(|r| set == "all" || r["set"] == set)
                    .collect();
                let n = sel.len();
                let mut cells = Vec::new();
                let mut ahead = Vec::new();
                let mut rr = Vec::new();
                for g in 0..3 {
                    let v: Vec<f64> = sel
                        .iter()
                        .map(|r| r[rf]["S"][g].as_f64().unwrap() / r[x]["S"][g].as_f64().unwrap())
                        .collect();
                    let (lo, hi) = range(&v);
                    rr.push(json!([lo, hi]));
                    cells.push(format!("{lo:.4}–{hi:.4}"));
                    ahead.push(v.iter().filter(|&&q| q > 1.0).count());
                }
                let mut sig = Vec::new();
                for k in ["S_sigma1", "S_sigma2", "S_sigma3"] {
                    let ah: Vec<usize> = (0..3)
                        .map(|g| {
                            sel.iter()
                                .filter(|r| r[rf][k][g].as_f64().unwrap() / r[x][k][g].as_f64().unwrap() > 1.0)
                                .count()
                        })
                        .collect();
                    sig.push(order_of(&ah, n));
                }
                let prim = order_of(&ahead, n);
                writeln!(
                    md,
                    "| {} | {what} | {set} ({n}) | {} | {} | {} | {}/{}/{} | {prim} | {} | {} | {} |",
                    short(x), cells[0], cells[1], cells[2], ahead[0], ahead[1], ahead[2], sig[0], sig[1], sig[2]
                )
                .unwrap();
                ranks.push(json!({"x": x, "reference": rf, "set": set, "rows": n, "ranges": rr,
                    "rows_x_ahead": ahead, "order": prim, "order_sigma": sig}));
                if rf == "chain-counted" && set != "all" {
                    band_checks.insert(format!("{x}_{set}"), json!(rr));
                }
            }
        }
    }
    // Distance to rho.
    writeln!(md, "\n### Distance to the matched rho (`S_X / rho`, walk (iii))\n").unwrap();
    writeln!(md, "| X | rows | 0 GAE | 0.1 GAE | 1 GAE | rows below rho |").unwrap();
    writeln!(md, "|:--|:--|:--|:--|:--|--:|").unwrap();
    let mut rho_ranges = Vec::new();
    let mut any_below = false;
    for x in ARMS {
        for set in ["gls", "e24"] {
            let sel: Vec<&Value> = rows.iter().filter(|r| r["set"] == set).collect();
            let mut cells = Vec::new();
            let mut rr = Vec::new();
            let mut below = 0;
            for g in 0..3 {
                let v: Vec<f64> = sel.iter().map(|r| r[x]["over_rho"][g].as_f64().unwrap()).collect();
                below += v.iter().filter(|&&q| q < 1.0).count();
                let (lo, hi) = range(&v);
                rr.push(json!([lo, hi]));
                cells.push(format!("{}–{}", sci(lo), sci(hi)));
            }
            any_below |= below > 0;
            writeln!(md, "| {} | {set} ({}) | {} | {} | {} | {below} |", short(x), sel.len(), cells[0], cells[1], cells[2]).unwrap();
            rho_ranges.push(json!({"x": x, "set": set, "ranges": rr, "rows_below_rho": below}));
        }
    }

    // A/A across streams: S_A / S_F on E36's stream (E27 A, E36 F) vs here.
    writeln!(md, "\n### A/A across streams (GLS rows): `S_A / S_F` on E25's stream (E27's A, E36's F) and on the fresh stream\n").unwrap();
    writeln!(md, "| p | seed | arm | E36 0 | 0.1 | 1 | E37 0 | 0.1 | 1 | Δ 0 | Δ 0.1 | Δ 1 |").unwrap();
    writeln!(md, "|--:|--:|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|").unwrap();
    let mut aa = Vec::new();
    let mut g173 = true;
    for &(p, seed) in &GLS {
        let ra = load(&format!("{e27}/e2e_chain_karatsuba_p{p}s{seed}.json"));
        let rf = load(&format!("{e36}/e2e_chain-fifo_karatsuba_p{p}s{seed}.json"));
        for a in ["A", "B"] {
            let (xa, xf) = (arm_of(&ra, Some(a)), arm_of(&rf, Some(a)));
            let old: Vec<f64> = GS
                .iter()
                .map(|g| {
                    (f(&xa, "total_muls") + GAE * g * f(&xa, "macaulay_entries"))
                        / (f(&xf, "total_muls") + GAE * g * (f(&xf, "macaulay_entries") + f(&xf, "pivot_selection_ops")))
                })
                .collect();
            let r = rows
                .iter()
                .find(|r| r["set"] == "gls" && r["p"] == p && r["seed"] == seed && r["arm"] == a)
                .unwrap();
            let new: Vec<f64> = (0..3)
                .map(|g| r["chain-counted"]["S"][g].as_f64().unwrap() / r["chain-fifo"]["S"][g].as_f64().unwrap())
                .collect();
            let d: Vec<f64> = (0..3).map(|g| new[g] - old[g]).collect();
            g173 &= d[0].abs() <= 0.05 && d[1].abs() <= 0.01 && d[2].abs() <= 0.002;
            writeln!(md, "| {p} | {seed} | {a} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {:+.4} | {:+.4} | {:+.4} |",
                old[0], old[1], old[2], new[0], new[1], new[2], d[0], d[1], d[2]).unwrap();
            aa.push(json!({"p": p, "seed": seed, "arm": a, "e36": old, "e37": new, "delta": d}));
        }
    }
    verdict.insert("G2.173_aa".into(), json!(g173));

    // Pre-registered bands, end to end.
    let rng_of = |x: &str, set: &str, g: usize| -> (f64, f64) {
        let r = &band_checks[&format!("{x}_{set}")][g];
        (r[0].as_f64().unwrap(), r[1].as_f64().unwrap())
    };
    let inside = |x: &str, set: &str, g: usize, lo: f64, hi: f64| {
        let (a, b) = rng_of(x, set, g);
        a >= lo && b <= hi
    };
    let rank_of = |x: &str, rf: &str, set: &str| -> String {
        ranks
            .iter()
            .find(|r| r["x"] == x && r["reference"] == rf && r["set"] == set)
            .map(|r| r["order"].as_str().unwrap().to_string())
            .unwrap()
    };
    let ahead = |x: &str, set: &str| {
        rank_of(x, "chain-counted", set) == "X ahead across the band"
            && rank_of(x, "macaulay", set) == "X ahead across the band"
    };
    let e25f0 = {
        let v: Vec<f64> = rows
            .iter()
            .filter(|r| r["set"] == "gls")
            .map(|r| r["macaulay"]["S"][0].as_f64().unwrap() / r["chain-fifo"]["S"][0].as_f64().unwrap())
            .collect();
        range(&v)
    };
    let g169_bands = inside("chain-fifo", "gls", 0, 1.43, 1.56)
        && inside("chain-fifo", "gls", 1, 1.085, 1.115)
        && inside("chain-fifo", "gls", 2, 1.010, 1.015)
        && inside("chain-static", "gls", 0, 1.38, 1.47)
        && inside("chain-static", "gls", 1, 1.075, 1.100)
        && inside("chain-static", "gls", 2, 1.006, 1.011)
        && inside("chain-fifo-static", "gls", 0, 1.47, 1.57)
        && inside("chain-fifo-static", "gls", 1, 1.087, 1.110)
        && inside("chain-fifo-static", "gls", 2, 1.006, 1.011)
        && e25f0.0 >= 3.3
        && e25f0.1 <= 4.1;
    let g169_order = RULES.iter().all(|x| ahead(x, "gls"));
    let g170 = health_ok_e24
        && RULES.iter().all(|x| ahead(x, "e24"))
        && inside("chain-fifo", "e24", 0, 1.30, 1.70)
        && inside("chain-fifo", "e24", 1, 1.05, 1.15)
        && inside("chain-fifo", "e24", 2, 1.005, 1.020);
    let g171 = RULES.iter().all(|x| rank_of(x, "chain-sparsest-est", "all") == "unresolved")
        && {
            let b: Vec<f64> = rows
                .iter()
                .map(|r| r["chain-sparsest-est"]["S"][0].as_f64().unwrap() / r["chain-fifo"]["S"][0].as_f64().unwrap())
                .collect();
            let (lo, hi) = range(&b);
            lo >= 0.92 && hi < 1.0
        };
    let g172: Vec<(String, bool)> = RULES
        .iter()
        .map(|x| (short(x).to_string(), ahead(x, "all")))
        .collect();
    let f_rho = |set: &str, g: usize| -> (f64, f64) {
        let v: Vec<f64> = rows
            .iter()
            .filter(|r| r["set"] == set)
            .map(|r| r["chain-fifo"]["over_rho"][g].as_f64().unwrap())
            .collect();
        range(&v)
    };
    let (a0, b0) = f_rho("gls", 0);
    let (c0, d0) = f_rho("e24", 0);
    let (a1, b1) = f_rho("gls", 2);
    let (c1, d1) = f_rho("e24", 2);
    let g175 = !any_below
        && a0 >= 3e3
        && b0 <= 4e5
        && c0 >= 2e3
        && d0 <= 2e5
        && a1.min(c1) >= 6e4
        && b1.max(d1) <= 1e7;
    verdict.insert("G2.169_bands".into(), json!(g169_bands));
    verdict.insert("G2.169_order_gls".into(), json!(g169_order));
    verdict.insert("G2.170_e24".into(), json!(g170));
    verdict.insert("G2.170_health".into(), json!(health_ok_e24));
    verdict.insert("G2.171_b2_unresolved".into(), json!(g171));
    verdict.insert("G2.172_rank_all_rows".into(), json!(g172));
    verdict.insert("G2.175_rho".into(), json!(g175));
    verdict.insert("e2e_logs_and_walks_all_arms".into(), json!(health_ok_all));
    writeln!(md, "\n## Automatic checks against the registered numbers (the verdicts are written in §9.45)\n").unwrap();
    for (k, v) in &verdict {
        writeln!(md, "- `{k}`: {v}").unwrap();
    }
    writeln!(md, "\nE25/F at 0 GAE (GLS rows): `{:.3}`–`{:.3}`; F/rho 0 GAE GLS `{}`–`{}`, E24 `{}`–`{}`; 1 GAE GLS `{}`–`{}`, E24 `{}`–`{}`.",
        e25f0.0, e25f0.1, sci(a0), sci(b0), sci(c0), sci(d0), sci(a1), sci(b1), sci(c1), sci(d1)).unwrap();
    writeln!(md, "\nEnd-to-end identity (F, S, H, B″ records equal A's on the same row and stream apart from the solve's multiplications, selection, lead scans, wall times, tag): **{ident_ok}**").unwrap();
    fs::write(format!("{dir}/tables.md"), &md).unwrap();
    let summary = json!({
        "experiment": "e37",
        "gae": GAE,
        "stage_a": stage,
        "stage_a_ranges": sa_range_json,
        "stage_a_pooled_tallies": pooled,
        "controls": controls,
        "walk_e24_ratio_range": [wr0, wr1],
        "e2e": rows,
        "ranks": ranks,
        "rho_ranges": rho_ranges,
        "aa": aa,
        "e2e_identity": identity,
        "e2e_identity_ok": ident_ok,
        "health": health,
        "verdict_checks": verdict,
    });
    fs::write(format!("{dir}/summary.json"), serde_json::to_string_pretty(&summary).unwrap()).unwrap();
    print!("{md}");
}
