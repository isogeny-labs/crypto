//! **E29 (§9.27) tables.**  Reads the kill test, Stage R and Stage A records;
//! writes `tables.md` and `summary.json`.  Walk costs exclude the `[d]G`
//! check (E25's convention).  The handover is §11.16's model:
//! `p* = y·(cols/p)·C₄·√h / (S_rho·(1 − r))`, `S_rho` the walk's `F_p`
//! multiplications per `√n`, `r = 16·LA / rho`, `C₄ = 1.213·10¹²`,
//! `n* = p*⁴ / h` (`h = 1`).
//!
//! ```text
//! cargo run --release --example e29_tables -- experiments/34_twist24_stage_r
//! ```

use std::env;
use std::fmt::Write as _;
use std::fs;

use serde_json::{json, Value};

const C4: f64 = 1.213e12;

fn load(path: &str) -> Value {
    serde_json::from_str(&fs::read_to_string(path).unwrap_or_else(|e| panic!("{path}: {e}")))
        .unwrap()
}

/// (mean walk F_p mults, mean steps, all correct) over walks of one fold.
fn walks(ws: &[Value], fold: Option<&str>) -> (f64, f64, bool) {
    let w: Vec<&Value> = ws
        .iter()
        .filter(|r| fold.is_none_or(|f| r["fold"].as_str() == Some(f)))
        .collect();
    let k = w.len().max(1) as f64;
    (
        w.iter()
            .map(|r| {
                (r["fp_muls"].as_u64().unwrap() - r["verify_fp_muls"].as_u64().unwrap_or(0)) as f64
            })
            .sum::<f64>()
            / k,
        w.iter().map(|r| r["steps"].as_f64().unwrap()).sum::<f64>() / k,
        w.iter().all(|r| r["correct"].as_bool() == Some(true)),
    )
}

fn main() {
    let dir = env::args()
        .nth(1)
        .unwrap_or("experiments/34_twist24_stage_r".into());
    let mut md = String::from("# E29 tables (generated by `examples/e29_tables.rs`)\n\n## Kill test (E18's eight curves, E18's model)\n\n| p | log₂ n | n mod 24 / 96 | ψ_p on E | ord λ_p | ord χ₆(b) | ord λ_ω | |⟨λ_p, λ_ω, −1⟩| | u² ∈ F_p | canonical b₀ |\n|--:|--:|:--|:--|--:|--:|--:|--:|:--|--:|\n");
    let kill = load(&format!("{dir}/kill.json"));
    for k in kill.as_array().unwrap() {
        writeln!(
            md,
            "| {} | {:.1} | {} / {} | {} | {} | {} | {} | {} | {} | {} |",
            k["p"],
            k["bits"].as_f64().unwrap(),
            k["n_mod_24"],
            k["n_mod_96"],
            k["psi_p_on_curve"],
            k["order_lambda_p"],
            k["order_chi6_b"],
            k["order_lambda_omega"],
            k["group_order"],
            k["u2_in_fp"],
            k["canonical_b0"]
        )
        .unwrap();
    }

    // Stage R.
    writeln!(md, "\n## Stage R (canonical models; 16 walks per order and arithmetic)\n\n| p | b₀ | log₂ n | arithmetic | steps order 6 | order 24 | steps ratio | F_p mults order 6 | order 24 | mults ratio | per step 6 / 24 | S_rho/√n 6 / 24 | all correct |\n|--:|--:|--:|:--|--:|--:|--:|--:|--:|--:|:--|:--|:--|").unwrap();
    let mut r_rows = Vec::new();
    let mut pooled = [[0f64; 2]; 2]; // [arith][order] of steps/√n
    let mut pooled_m = [[0f64; 2]; 2];
    let mut cnt = [0f64; 2];
    for f in ["stage_r_p241.json", "stage_r_rest.json"] {
        for row in load(&format!("{dir}/{f}")).as_array().unwrap() {
            for (ai, run) in row["runs"].as_array().unwrap().iter().enumerate() {
                let n = run["n"].as_f64().unwrap();
                let (m6, s6, ok6) = walks(run["order6"].as_array().unwrap(), None);
                let (m24, s24, ok24) = walks(run["order24"].as_array().unwrap(), None);
                let sq = n.sqrt();
                pooled[ai][0] += s6 / sq;
                pooled[ai][1] += s24 / sq;
                pooled_m[ai][0] += m6 / sq;
                pooled_m[ai][1] += m24 / sq;
                cnt[ai] += 1.0;
                writeln!(
                    md,
                    "| {} | {} | {:.1} | {} | {:.0} | {:.0} | {:.3} | {:.4e} | {:.4e} | {:.3} | {:.1} / {:.1} | {:.1} / {:.1} | {} |",
                    run["p"], run["b0"], run["bits"].as_f64().unwrap(),
                    if run["karatsuba"].as_bool() == Some(true) { "Karatsuba" } else { "schoolbook" },
                    s6, s24, s6 / s24, m6, m24, m6 / m24, m6 / s6, m24 / s24, m6 / sq, m24 / sq, ok6 && ok24
                )
                .unwrap();
                r_rows.push(
                    json!({"p": run["p"], "karatsuba": run["karatsuba"], "steps_ratio": s6 / s24,
                    "muls_ratio": m6 / m24, "srho6": m6 / sq, "srho24": m24 / sq}),
                );
            }
        }
    }
    let mut pooled_out = Vec::new();
    for (ai, name) in ["schoolbook", "Karatsuba"].iter().enumerate() {
        let st = pooled[ai][0] / pooled[ai][1];
        let mu = pooled_m[ai][0] / pooled_m[ai][1];
        writeln!(md, "\nPooled over the eight curves ({name}): steps per √n order 6 / order 24 = `{st:.3}`; F_p mults per √n `{:.1}` / `{:.1}` → ratio `{mu:.3}`.", pooled_m[ai][0] / cnt[ai], pooled_m[ai][1] / cnt[ai]).unwrap();
        pooled_out.push(json!({"arith": name, "steps_ratio": st, "muls_ratio": mu,
            "srho6": pooled_m[ai][0] / cnt[ai], "srho24": pooled_m[ai][1] / cnt[ai]}));
    }

    // Stage A.
    writeln!(md, "\n## Stage A (the lane's run_k4_twist24; E18's exact oracle; one stream, three arms)\n\n| p | b₀ | log₂ n | arm | cols | relations | residuals to the log | y | 16·LA | r vs order-6 walk | r vs order-24 walk | log | n* vs order-6 walk | n* vs order-24 walk |\n|--:|--:|--:|:--|--:|--:|--:|--:|--:|--:|--:|:--|:--|:--|").unwrap();
    let mut a_rows = Vec::new();
    for p in [241u64, 337, 541] {
        let Ok(t) = fs::read_to_string(format!("{dir}/stage_a_p{p}.json")) else {
            continue;
        };
        let row: Value = serde_json::from_str::<Value>(&t).unwrap()[0].clone();
        let r = &row["report"];
        let n = r["n"].as_f64().unwrap();
        let sq = n.sqrt();
        let rho = r["rho"].as_array().unwrap();
        let (m6, _, ok6) = walks(rho, Some("Psi"));
        let (m24, _, ok24) = walks(rho, Some("Twist24"));
        for arm in ["flat", "cubic", "twist24"] {
            let a = &r[arm];
            let la = 16.0 * a["la_ops"].as_f64().unwrap();
            let rel = a["relations"].as_f64().unwrap();
            let res = a["residuals_at_solve"].as_f64().unwrap();
            let y = res / rel;
            let cols = a["columns"].as_f64().unwrap();
            let nstar = |rho_m: f64| {
                let r_ = la / rho_m;
                if r_ >= 1.0 {
                    return f64::NAN;
                }
                let pstar = y * (cols / p as f64) * C4 / ((rho_m / sq) * (1.0 - r_));
                4.0 * pstar.log2()
            };
            writeln!(
                md,
                "| {p} | {} | {:.1} | {arm} | {cols} | {rel} | {res} | {y:.1} | {la:.3e} | {:.4} | {:.4} | {} | 2^{:.1} | 2^{:.1} |",
                row["b0"], n.log2(), la / m6, la / m24, a["correct"], nstar(m6), nstar(m24)
            )
            .unwrap();
            a_rows.push(json!({"p": p, "arm": arm, "cols": cols, "y": y, "la": la, "r6": la / m6, "r24": la / m24,
                "nstar6_log2": nstar(m6), "nstar24_log2": nstar(m24), "correct": a["correct"], "walks_correct": ok6 && ok24}));
        }
    }
    fs::write(format!("{dir}/tables.md"), &md).unwrap();
    fs::write(
        format!("{dir}/summary.json"),
        serde_json::to_string_pretty(
            &json!({"experiment": "e29", "kill": kill, "stage_r": r_rows,
            "stage_r_pooled": pooled_out, "stage_a": a_rows}),
        )
        .unwrap(),
    )
    .unwrap();
    print!("{md}");
}
