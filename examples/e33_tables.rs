//! **E33 (§9.35) tables**: solver B's pivot selection counted (and B′, B″),
//! per call (Stage A) and end to end, against E25, E31 A (E27's Karatsuba
//! records) and the matched rho (walk (iii) of E27, without the `[d]G`
//! check), at `0`, `0.1` and `1` GAE.  Reads the recorded JSON only; writes
//! `tables.md` and `summary.json` (the values the report's graphs plot).
//!
//! ```text
//! ./target/release/examples/e33_tables experiments/37_solver_b_pivot_count
//! ```

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use serde_json::{json, Value};

/// E25/E31's GAE: the measured cost of an affine addition (§9.19).
const GAE: f64 = 97.0;
const GS: [f64; 3] = [0.0, 0.1, 1.0];
const CURVES: [(u64, u64); 10] = [
    (101, 1),
    (101, 2),
    (149, 1),
    (149, 2),
    (197, 1),
    (197, 2),
    (269, 1),
    (269, 2),
    (397, 1),
    (397, 2),
];

fn load(path: &str) -> Value {
    serde_json::from_str(&fs::read_to_string(path).unwrap_or_else(|e| panic!("{path}: {e}")))
        .unwrap()
}

fn f(v: &Value, k: &str) -> f64 {
    v[k].as_f64().unwrap_or_else(|| panic!("field {k}"))
}

fn sci(v: f64) -> String {
    if v == 0.0 {
        return "0".into();
    }
    let e = v.abs().log10().floor() as i32;
    format!("`{:.2}·10^{}`", v / 10f64.powi(e), e)
}

fn arm(recs: &Value, a: &str) -> Value {
    recs.as_array()
        .unwrap()
        .iter()
        .find(|r| r["arm"] == a)
        .unwrap_or_else(|| panic!("arm {a}"))
        .clone()
}

/// Fields a Karatsuba rerun of E31 B may change (E27's list) plus E33's new
/// fields and tags.
fn may_differ_vs_e31(k: &str) -> bool {
    k.ends_with("_muls")
        || k.ends_with("_ms")
        || matches!(
            k,
            "ratio"
                | "rho"
                | "fp_muls_per_add"
                | "fp4_product"
                | "ic_fp_inversions"
                | "call"
                | "solver"
                | "pivot_selection"
                | "pivot_selection_ops"
                | "lead_scan_reads"
        )
}

/// Fields B′ (or B″) may change against B counted on the same arithmetic.
fn may_differ_vs_bc(k: &str) -> bool {
    k.ends_with("_ms")
        || matches!(
            k,
            "solver" | "pivot_selection" | "pivot_selection_ops" | "lead_scan_reads"
        )
}

fn diff_fields(a: &Value, b: &Value, allow: fn(&str) -> bool) -> Vec<String> {
    let (ao, bo) = (a.as_object().unwrap(), b.as_object().unwrap());
    let mut keys: Vec<&String> = ao.keys().chain(bo.keys()).collect();
    keys.sort();
    keys.dedup();
    keys.into_iter()
        .filter(|k| !allow(k) && ao.get(*k) != bo.get(*k))
        .cloned()
        .collect()
}

fn range(v: &[f64]) -> (f64, f64) {
    v.iter()
        .fold((f64::INFINITY, f64::NEG_INFINITY), |(lo, hi), &x| {
            (lo.min(x), hi.max(x))
        })
}

fn main() {
    let args: Vec<String> = env::args().skip(1).collect();
    let dir = args
        .first()
        .cloned()
        .unwrap_or("experiments/37_solver_b_pivot_count".into());
    let e25 = "experiments/30_gls_v4";
    let e31 = "experiments/31_solve_cost";
    let e27 = "experiments/32_walk_karatsuba";
    let mut md = String::new();
    writeln!(md, "# E33 tables (generated by `examples/e33_tables.rs`)\n").unwrap();

    // ── Stage A ──────────────────────────────────────────────────────────
    let sa = load(&format!("{dir}/stage_a.json"));
    let mut stage_rows = Vec::new();
    writeln!(
        md,
        "## Stage A (per call; means over all calls, fallbacks charged)\n"
    )
    .unwrap();
    writeln!(md, "Agreement with the existing solver (solutions, degree, outcome, decomposition set), per solver in the order of `solvers`; phase counts equal (A counted = A, B counted = B, B′ = B); pivot digests equal to B counted's (B counted present, B′, B″).\n").unwrap();
    writeln!(md, "| p | seed | calls | agree | phases equal | digest = B | B′ count mismatches | B″ fallbacks |").unwrap();
    writeln!(md, "|--:|--:|--:|:--|:--|:--|--:|--:|").unwrap();
    for c in sa.as_array().unwrap() {
        let fb = c["summaries"][6]["fallbacks"].as_u64().unwrap();
        writeln!(
            md,
            "| {} | {} | {} | {} | {} | {} | {} | {} |",
            c["p"],
            c["seed"],
            c["calls"],
            c["agree"],
            c["phases_equal"],
            c["digest_equal_b"],
            c["inc_count_mismatches"],
            fb
        )
        .unwrap();
    }
    writeln!(md, "\n| p | seed | solver | C median | C mean | echelon | entries | sel. initial | comparisons | updates | selection | lead scan | S(0) | S(0.1) | S(1) |").unwrap();
    writeln!(
        md,
        "|--:|--:|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|"
    )
    .unwrap();
    for c in sa.as_array().unwrap() {
        let (p, seed) = (c["p"].as_u64().unwrap(), c["seed"].as_u64().unwrap());
        let sums = c["summaries"].as_array().unwrap();
        let by = |name: &str| sums.iter().find(|s| s["solver"] == name).unwrap().clone();
        for s in sums {
            let name = s["solver"].as_str().unwrap();
            if name == "chain-counted" || name == "chain-sparsest" {
                continue;
            }
            let sm: Vec<f64> = s["s_mean"]
                .as_array()
                .unwrap()
                .iter()
                .map(|x| x.as_f64().unwrap())
                .collect();
            writeln!(
                md,
                "| {p} | {seed} | {name} | {} | {:.0} | {:.0} | {:.0} | {:.0} | {:.0} | {:.0} | {:.0} | {:.0} | {} | {} | {} |",
                s["call_median"], f(s, "call_mean"), f(s, "echelon_mean"), f(s, "entries_mean"),
                f(s, "sel_init_mean"), f(s, "sel_compare_mean"), f(s, "sel_update_mean"),
                f(s, "sel_mean"), f(s, "lead_scan_mean"), sci(sm[0]), sci(sm[1]), sci(sm[2])
            )
            .unwrap();
        }
        let sv = |n: &str, g: usize| by(n)["s_mean"][g].as_f64().unwrap();
        // Sensitivity G2.133: every arm's lead-scan reads priced too.
        let sens = |n: &str, g: usize| {
            // The existing solver's echelon is A's (same rows, same code).
            let lead = if n == "existing" || n == "chain" {
                f(&by("chain-counted"), "lead_scan_mean")
            } else {
                f(&by(n), "lead_scan_mean")
            };
            sv(n, g) + GAE * GS[g] * lead
        };
        let arms = [
            "existing",
            "chain",
            "chain-sparsest-counted",
            "chain-sparsest-inc",
            "chain-sparsest-est",
        ];
        type M = serde_json::Map<String, Value>;
        let sparse = [
            "chain-sparsest-counted",
            "chain-sparsest-inc",
            "chain-sparsest-est",
        ];
        let s_mean: M = arms
            .iter()
            .map(|n| {
                (
                    n.to_string(),
                    json!((0..3).map(|g| sv(n, g)).collect::<Vec<_>>()),
                )
            })
            .collect();
        let s_lead: M = arms
            .iter()
            .map(|n| {
                (
                    n.to_string(),
                    json!((0..3).map(|g| sens(n, g)).collect::<Vec<_>>()),
                )
            })
            .collect();
        let selection: M = sparse
            .iter()
            .map(|n| {
                let b = by(n);
                (
                    n.to_string(),
                    json!([
                        f(&b, "sel_init_mean"),
                        f(&b, "sel_compare_mean"),
                        f(&b, "sel_update_mean"),
                        f(&b, "sel_mean")
                    ]),
                )
            })
            .collect();
        let lead_scan: M = arms
            .iter()
            .skip(1)
            .map(|n| {
                let src = if *n == "chain" { "chain-counted" } else { n };
                (n.to_string(), json!(f(&by(src), "lead_scan_mean")))
            })
            .collect();
        let c_median: M = arms
            .iter()
            .map(|n| (n.to_string(), by(n)["call_median"].clone()))
            .collect();
        let c_mean: M = arms
            .iter()
            .map(|n| (n.to_string(), by(n)["call_mean"].clone()))
            .collect();
        stage_rows.push(json!({
            "p": p, "seed": seed, "s_mean": s_mean, "s_mean_with_lead_scan": s_lead,
            "selection": selection, "lead_scan": lead_scan, "c_median": c_median, "c_mean": c_mean,
        }));
    }
    writeln!(
        md,
        "\nPer-call `S(g)` ratios (Stage A means; `>1`: the second arm is cheaper):\n"
    )
    .unwrap();
    writeln!(md, "| p | seed | g | A / B | A / B′ | A / B″ | E25 / B | E25 / B′ | E25 / B″ | A / B (lead scans priced) | A / B′ (lead) | A / B″ (lead) | E25 / B″ (lead) |").unwrap();
    writeln!(md, "|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|").unwrap();
    for r in &stage_rows {
        for g in 0..3 {
            let s = |n: &str| r["s_mean"][n][g].as_f64().unwrap();
            let l = |n: &str| r["s_mean_with_lead_scan"][n][g].as_f64().unwrap();
            writeln!(
                md,
                "| {} | {} | {} | {:.3} | {:.3} | {:.3} | {:.3} | {:.3} | {:.3} | {:.3} | {:.3} | {:.3} | {:.3} |",
                r["p"], r["seed"], GS[g],
                s("chain") / s("chain-sparsest-counted"), s("chain") / s("chain-sparsest-inc"), s("chain") / s("chain-sparsest-est"),
                s("existing") / s("chain-sparsest-counted"), s("existing") / s("chain-sparsest-inc"), s("existing") / s("chain-sparsest-est"),
                l("chain") / l("chain-sparsest-counted"), l("chain") / l("chain-sparsest-inc"), l("chain") / l("chain-sparsest-est"),
                l("existing") / l("chain-sparsest-est"),
            )
            .unwrap();
        }
    }
    let est_carried = stage_rows.iter().all(|r| {
        r["s_mean"]["chain-sparsest-est"][1].as_f64().unwrap()
            < r["s_mean"]["chain"][1].as_f64().unwrap()
    });
    writeln!(md, "\nB″ carried to end to end (its Stage A `S(0.1)` below A's on every curve): **{est_carried}**\n").unwrap();

    // ── End to end ───────────────────────────────────────────────────────
    let summary27 = load(&format!("{e27}/summary.json"));
    let mut e2e_rows = Vec::new();
    let solvers: Vec<&str> = [
        "chain-sparsest-counted",
        "chain-sparsest-inc",
        "chain-sparsest-est",
    ]
    .into_iter()
    .filter(|s| Path::new(&format!("{dir}/e2e_{s}_karatsuba_p101s1.json")).exists())
    .collect();
    let mut identity = Vec::new();
    for (p, seed) in CURVES {
        let r25 = load(&format!("{e25}/p{p}s{seed}.json"));
        let r31 = load(&format!("{e31}/e2e_chain-sparsest_p{p}s{seed}.json"));
        let r27 = load(&format!("{e27}/e2e_chain_karatsuba_p{p}s{seed}.json"));
        let recs: Vec<(String, Value)> = solvers
            .iter()
            .map(|s| {
                (
                    s.to_string(),
                    load(&format!("{dir}/e2e_{s}_karatsuba_p{p}s{seed}.json")),
                )
            })
            .collect();
        for a in ["A", "B"] {
            let (x25, x31, x27) = (arm(&r25, a), arm(&r31, a), arm(&r27, a));
            let s27 = summary27["rows"]
                .as_array()
                .unwrap()
                .iter()
                .find(|r| r["p"] == p && r["seed"] == seed && r["arm"] == a)
                .unwrap()
                .clone();
            let (rho, steps) = (f(&s27, "rho_e27"), f(&s27, "walk_steps"));
            let rho_g: Vec<f64> = GS.iter().map(|g| rho + GAE * g * steps).collect();
            let s_e25: Vec<f64> = GS
                .iter()
                .map(|g| f(&x25, "total_muls") + GAE * g * f(&x25, "macaulay_entries"))
                .collect();
            let s_ak: Vec<f64> = GS
                .iter()
                .map(|g| f(&x27, "total_muls") + GAE * g * f(&x27, "macaulay_entries"))
                .collect();
            let mut row = json!({"p": p, "seed": seed, "arm": a, "rho_e27": rho, "walk_steps": steps,
                "S_E25": s_e25, "S_AK": s_ak, "rho_g": rho_g});
            let bc = recs
                .iter()
                .find(|(s, _)| s == "chain-sparsest-counted")
                .map(|(_, r)| arm(r, a));
            for (s, rec) in &recs {
                let x = arm(rec, a);
                let sel = f(&x, "pivot_selection_ops");
                let d31 = diff_fields(&x31, &x, may_differ_vs_e31);
                let solve_eq = x["solve_muls"] == x31["solve_muls"]
                    && x["macaulay_entries"] == x31["macaulay_entries"];
                let dbc = bc
                    .as_ref()
                    .map(|b| diff_fields(b, &x, may_differ_vs_bc))
                    .unwrap_or_default();
                identity.push(json!({"p": p, "seed": seed, "arm": a, "solver": s,
                    "fields_differing_from_e31_b": d31, "solve_and_entries_equal_e31_b": solve_eq,
                    "fields_differing_from_b_counted": dbc}));
                // Schoolbook B (E31's record) with this run's selection work.
                let s_b_school: Vec<f64> = GS
                    .iter()
                    .map(|g| f(&x31, "total_muls") + GAE * g * (f(&x31, "macaulay_entries") + sel))
                    .collect();
                let s_bk: Vec<f64> = GS
                    .iter()
                    .map(|g| f(&x, "total_muls") + GAE * g * (f(&x, "macaulay_entries") + sel))
                    .collect();
                row[s.as_str()] = json!({
                    "selection_ops": sel,
                    "selection_parts": x["pivot_selection"].clone(),
                    "lead_scan_reads": x["lead_scan_reads"].clone(),
                    "residuals": x["residuals"].clone(),
                    "selection_per_call": sel / f(&x, "residuals"),
                    "S_school": s_b_school,
                    "S_K": s_bk,
                    "E25_over": (0..3).map(|g| s_e25[g] / s_b_school[g]).collect::<Vec<_>>(),
                    "A_over": (0..3).map(|g| s_ak[g] / s_bk[g]).collect::<Vec<_>>(),
                    "over_rho": (0..3).map(|g| s_bk[g] / rho_g[g]).collect::<Vec<_>>(),
                });
            }
            e2e_rows.push(row);
        }
    }
    writeln!(
        md,
        "## End to end (E25's ten curves, both arms; Karatsuba products)\n"
    )
    .unwrap();
    writeln!(md, "`S_E25/S_X`: schoolbook (E25's records against E31 B's records plus the selection work measured here); `S_A/S_X`: Karatsuba (E27's solver-A records against this run); `S_X/rho`: this run against walk (iii) of E27 without the `[d]G` check.  Band: one GAE (`97`) per Macaulay entry, per selection operation and per walk step.\n").unwrap();
    for s in &solvers {
        writeln!(md, "### {s}\n").unwrap();
        writeln!(md, "| p | seed | arm | selection ops | per call | E25/X 0 | 0.1 | 1 | A/X 0 | 0.1 | 1 | X/rho 0 | 0.1 | 1 |").unwrap();
        writeln!(
            md,
            "|--:|--:|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|"
        )
        .unwrap();
        for r in &e2e_rows {
            let x = &r[*s];
            let v = |k: &str, g: usize| x[k][g].as_f64().unwrap();
            writeln!(
                md,
                "| {} | {} | {} | {} | {:.0} | {:.3} | {:.3} | {:.3} | {:.3} | {:.3} | {:.3} | {} | {} | {} |",
                r["p"], r["seed"], r["arm"].as_str().unwrap(), sci(f(x, "selection_ops")), f(x, "selection_per_call"),
                v("E25_over", 0), v("E25_over", 1), v("E25_over", 2),
                v("A_over", 0), v("A_over", 1), v("A_over", 2),
                sci(v("over_rho", 0)), sci(v("over_rho", 1)), sci(v("over_rho", 2))
            )
            .unwrap();
        }
        writeln!(md).unwrap();
    }
    // Ranks: an order is stated only where it holds at every weight on every row.
    let mut ranks = Vec::new();
    writeln!(md, "### Ranges and ranks\n").unwrap();
    writeln!(
        md,
        "| X | quantity | 0 GAE | 0.1 GAE | 1 GAE | rows X ahead (0 / 0.1 / 1) | rank |"
    )
    .unwrap();
    writeln!(md, "|:--|:--|:--|:--|:--|:--|:--|").unwrap();
    for s in &solvers {
        for (k, what) in [
            ("E25_over", "S_E25 / S_X"),
            ("A_over", "S_A / S_X"),
            ("over_rho", "S_X / rho"),
        ] {
            let mut cells = Vec::new();
            let mut ahead = Vec::new();
            let mut rr = Vec::new();
            for g in 0..3 {
                let v: Vec<f64> = e2e_rows
                    .iter()
                    .map(|r| r[*s][k][g].as_f64().unwrap())
                    .collect();
                let (lo, hi) = range(&v);
                rr.push(json!([lo, hi]));
                cells.push(if k == "over_rho" {
                    format!("{}–{}", sci(lo), sci(hi))
                } else {
                    format!("{lo:.4}–{hi:.4}")
                });
                // X ahead: ratio > 1 for the comparisons, < 1 against rho.
                ahead.push(
                    v.iter()
                        .filter(|&&x| if k == "over_rho" { x < 1.0 } else { x > 1.0 })
                        .count(),
                );
            }
            let n = e2e_rows.len();
            let rank = if ahead.iter().all(|&a| a == n) {
                "X ahead across the band".to_string()
            } else if ahead.iter().all(|&a| a == 0) {
                "X behind across the band".to_string()
            } else {
                "unresolved (order changes inside the band or across rows)".to_string()
            };
            writeln!(
                md,
                "| {s} | {what} | {} | {} | {} | {}/{}/{} of {n} | {rank} |",
                cells[0], cells[1], cells[2], ahead[0], ahead[1], ahead[2]
            )
            .unwrap();
            ranks.push(json!({"solver": s, "quantity": what, "ranges": rr, "rows_x_ahead": ahead, "rows": n, "rank": rank}));
        }
    }
    let ident_ok = identity.iter().all(|i| {
        i["fields_differing_from_e31_b"]
            .as_array()
            .unwrap()
            .is_empty()
            && i["solve_and_entries_equal_e31_b"] == true
            && i["fields_differing_from_b_counted"]
                .as_array()
                .unwrap()
                .is_empty()
    });
    writeln!(md, "\nEnd-to-end identity (every non-product field of E31 B's records; every field of B counted's apart from the selection fields and the tag): **{ident_ok}**\n").unwrap();
    fs::write(format!("{dir}/tables.md"), &md).unwrap();
    let summary = json!({
        "experiment": "e33",
        "gae": GAE,
        "stage_a": stage_rows,
        "est_carried": est_carried,
        "e2e_solvers": solvers,
        "e2e": e2e_rows,
        "ranks": ranks,
        "e2e_identity_ok": ident_ok,
        "e2e_identity": identity,
    });
    fs::write(
        format!("{dir}/summary.json"),
        serde_json::to_string_pretty(&summary).unwrap(),
    )
    .unwrap();
    print!("{md}");
}
