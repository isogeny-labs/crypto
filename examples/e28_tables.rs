//! **E28 (§9.26) tables and Stage A2 (a model).**  Reads Stage 0, Stage A,
//! the supplementary control and E19's records; writes `tables.md` and
//! `summary.json`.
//!
//! Stage A2: `S_model = R × C + R × g + 16·LA`, with `R` an arm's residuals to
//! its verified logarithm, `C` the control's median weighted-`D₄` call on that
//! curve, `g` the measured generation cost per target and `LA` the arm's
//! mod-`n` multiplications; against the matched walk's mean (`⟨±ψ⟩` for τψ,
//! negation for τ).  The band prices one GAE (`97`) per Macaulay entry (E19's
//! entries per target at the same `p`) and per walk step.
//!
//! ```text
//! cargo run --release --example e28_tables -- experiments/33_tau_stage_a experiments/27_quartic_pipeline_d4
//! ```

use std::env;
use std::fmt::Write as _;
use std::fs;

use serde_json::{json, Value};

const GAE: f64 = 97.0;

fn load(path: &str) -> Value {
    serde_json::from_str(&fs::read_to_string(path).unwrap_or_else(|e| panic!("{path}: {e}")))
        .unwrap()
}

fn sci(v: f64) -> String {
    let e = v.abs().log10().floor() as i32;
    format!("`{:.2}·10^{}`", v / 10f64.powi(e), e)
}

fn median(mut v: Vec<f64>) -> f64 {
    v.sort_by(|a, b| a.partial_cmp(b).unwrap());
    if v.is_empty() {
        return f64::NAN;
    }
    let m = v.len() / 2;
    if v.len() % 2 == 1 {
        v[m]
    } else {
        (v[m - 1] + v[m]) / 2.0
    }
}

/// Mean walk cost (E25's convention: the `[d]G` check excluded) and steps.
fn walk(rows: &Value, fold: &str) -> (f64, f64, bool) {
    let w: Vec<&Value> = rows
        .as_array()
        .unwrap()
        .iter()
        .filter(|r| r["fold"].as_str() == Some(fold))
        .collect();
    let k = w.len().max(1) as f64;
    let m = w
        .iter()
        .map(|r| {
            (r["fp_muls"].as_u64().unwrap() - r["verify_fp_muls"].as_u64().unwrap_or(0)) as f64
        })
        .sum::<f64>()
        / k;
    let s = w.iter().map(|r| r["steps"].as_f64().unwrap()).sum::<f64>() / k;
    (m, s, w.iter().all(|r| r["correct"].as_bool() == Some(true)))
}

fn main() {
    let args: Vec<String> = env::args().skip(1).collect();
    let dir = args
        .first()
        .cloned()
        .unwrap_or("experiments/33_tau_stage_a".into());
    let e19 = args
        .get(1)
        .cloned()
        .unwrap_or("experiments/27_quartic_pipeline_d4".into());
    let mut md = String::from("# E28 tables (generated by `examples/e28_tables.rs`)\n\n");

    // Stage 0.
    let s0 = load(&format!("{dir}/stage0.json"));
    writeln!(md, "## Stage 0 (gate)\n\n| p | seeds | curves | all ψ / line checks | `h` histogram | density pooled | pts/col τ / τψ (abscissae; ×2 with ±) |\n|--:|--:|--:|:--|:--|--:|:--|").unwrap();
    let mut s0_rows = Vec::new();
    for p in [53u64, 101, 149, 197, 269] {
        let rs: Vec<&Value> = s0
            .as_array()
            .unwrap()
            .iter()
            .filter(|r| r["p"].as_u64() == Some(p))
            .collect();
        let ok: Vec<&&Value> = rs.iter().filter(|r| r.get("error").is_none()).collect();
        let checks = ok.iter().all(|r| {
            [
                "psi_squared_is_minus_one",
                "psi_g_is_lambda_g",
                "lambda_squared_is_minus_one",
                "psi_fixes_t",
                "line_checks",
            ]
            .iter()
            .all(|k| r[*k].as_bool() == Some(true))
        });
        let mut hist = std::collections::BTreeMap::new();
        for r in &ok {
            *hist.entry(r["cofactor"].as_u64().unwrap()).or_insert(0) += 1;
        }
        let (pts, base): (f64, f64) = ok.iter().fold((0.0, 0.0), |a, r| {
            (
                a.0 + r["base_points"].as_f64().unwrap(),
                a.1 + (p - 5) as f64,
            )
        });
        let ppc: Vec<String> = ok
            .iter()
            .map(|r| {
                format!(
                    "{:.2}/{:.2}",
                    r["points_per_column_tau"].as_f64().unwrap(),
                    r["points_per_column_tau_psi"].as_f64().unwrap()
                )
            })
            .collect::<std::collections::BTreeSet<_>>()
            .into_iter()
            .collect();
        writeln!(
            md,
            "| {p} | {} | {} | {checks} | {hist:?} | {:.3} | {} |",
            rs.len(),
            ok.len(),
            pts / base,
            ppc.join(", ")
        )
        .unwrap();
        s0_rows.push(json!({"p": p, "curves": ok.len(), "checks": checks, "h": format!("{hist:?}"), "density": pts / base}));
    }

    // Stage A, the control and A2.
    writeln!(
        md,
        "\n## Stage A (fold, exact oracle) and the solve-cost control\n"
    )
    .unwrap();
    writeln!(md, "| p | seed | h | base | cols τ / τψ | decs/target (median of decomposed) | R τ | R τψ | y τ | y τψ | R τ / R τψ | logs | control C median (3 uniform) | control agreement | supp. control (decomposed): C median, agree | walks ⟨±ψ⟩ / neg (E25 arith.) |").unwrap();
    writeln!(
        md,
        "|--:|--:|--:|--:|:--|--:|--:|--:|--:|--:|--:|:--|--:|:--|:--|:--|"
    )
    .unwrap();
    let supp = fs::read_to_string(format!("{dir}/control_decomposed.json"))
        .ok()
        .map(|s| serde_json::from_str::<Value>(&s).unwrap());
    let mut a2 = String::from("\n## Stage A2 (model, extrapolation from measured constants)\n\n| p | seed | `S_model` τψ | rho ⟨±ψ⟩ (i) | `S/rho` τψ 0 / 0.1 / 1 GAE | `S_model` τ | rho neg (i) | `S/rho` τ 0 GAE | E19 measured `S/rho` (same p, mean of seeds) | E19 / E28 (0 GAE) | E28 against walk (iii) 0 GAE |\n|--:|--:|--:|--:|:--|--:|--:|--:|--:|--:|--:|\n");
    let mut rows_out = Vec::new();
    for p in [53u64, 101, 149, 197, 269] {
        let e19_rows: Vec<Value> = (1..=2)
            .filter_map(|s| fs::read_to_string(format!("{e19}/p{p}s{s}.json")).ok())
            .map(|t| {
                let v: Value = serde_json::from_str(&t).unwrap();
                if v.is_array() {
                    v[0].clone()
                } else {
                    v
                }
            })
            .collect();
        let e19_ratio = e19_rows
            .iter()
            .map(|r| r["ratio"].as_f64().unwrap())
            .sum::<f64>()
            / e19_rows.len().max(1) as f64;
        let e19_entries_per_target = e19_rows
            .iter()
            .map(|r| r["macaulay_entries"].as_f64().unwrap() / r["residuals"].as_f64().unwrap())
            .sum::<f64>()
            / e19_rows.len().max(1) as f64;
        for seed in [1u64, 2] {
            let path = format!("{dir}/stage_a_p{p}s{seed}.json");
            let Ok(t) = fs::read_to_string(&path) else {
                continue;
            };
            let r: Value = serde_json::from_str::<Value>(&t).unwrap()[0].clone();
            if r.get("error").is_some() {
                writeln!(md, "| {p} | {seed} | error: {} |", r["error"]).unwrap();
                continue;
            }
            let (tau, tp) = (&r["tau"], &r["tau_psi"]);
            let rt = tau["residuals_at_solve"].as_f64().unwrap();
            let rp = tp["residuals_at_solve"].as_f64().unwrap();
            let yt = rt / tau["relations"].as_f64().unwrap();
            let yp = rp / tp["relations"].as_f64().unwrap();
            let dpt = r["decompositions_per_target"].as_array().unwrap();
            let mut dvec = Vec::new();
            for (k, c) in dpt.iter().enumerate().skip(1) {
                for _ in 0..c.as_u64().unwrap() {
                    dvec.push(k as f64);
                }
            }
            let calls = r["control_calls"].as_array().unwrap();
            let c_med = median(
                calls
                    .iter()
                    .map(|c| c["call_muls"].as_f64().unwrap())
                    .collect(),
            );
            let agree = calls.iter().all(|c| c["agrees"].as_bool() == Some(true));
            let supp_s = supp
                .as_ref()
                .and_then(|s| {
                    s.as_array()
                        .unwrap()
                        .iter()
                        .find(|x| x["p"].as_u64() == Some(p) && x["seed"].as_u64() == Some(seed))
                        .cloned()
                })
                .map(|x| {
                    let cs = x["calls"].as_array().cloned().unwrap_or_default();
                    format!(
                        "{} ({} calls), {}",
                        sci(median(
                            cs.iter()
                                .map(|c| c["call_muls"].as_f64().unwrap())
                                .collect()
                        )),
                        cs.len(),
                        cs.iter().all(|c| c["agrees"].as_bool() == Some(true))
                    )
                })
                .unwrap_or("—".into());
            let (rho_g, steps_g, ok_g) = walk(&r["rho_schoolbook"], "Gls");
            let (rho_n, _steps_n, ok_n) = walk(&r["rho_schoolbook"], "Negation");
            let (rho_g3, _, ok_g3) = walk(&r["rho_e27"], "Gls");
            let g = r["generation_muls_per_target"].as_f64().unwrap();
            let s_model = |rr: f64, la: f64, w: f64| {
                rr * c_med + rr * g + 16.0 * la + w * GAE * rr * e19_entries_per_target
            };
            let lap = tp["la_ops"].as_f64().unwrap();
            let lat = tau["la_ops"].as_f64().unwrap();
            let d: Vec<f64> = [0.0, 0.1, 1.0]
                .iter()
                .map(|&w| s_model(rp, lap, w) / (rho_g + w * GAE * steps_g))
                .collect();
            let dt = s_model(rt, lat, 0.0) / rho_n;
            let d3 = s_model(rp, lap, 0.0) / rho_g3;
            writeln!(
                md,
                "| {p} | {seed} | {} | {} | {} / {} | {} | {} | {} | {:.1} | {:.1} | {:.3} | {} {} | {} | {agree} | {supp_s} | {} {} |",
                r["cofactor"], r["base_points"], tau["columns"], tp["columns"], median(dvec),
                rt, rp, yt, yp, rt / rp, tau["correct"], tp["correct"], sci(c_med), ok_g, ok_n
            )
            .unwrap();
            writeln!(
                a2,
                "| {p} | {seed} | {} | {} | {} / {} / {} | {} | {} | {} | {} | {:.2} | {} |",
                sci(s_model(rp, lap, 0.0)),
                sci(rho_g),
                sci(d[0]),
                sci(d[1]),
                sci(d[2]),
                sci(s_model(rt, lat, 0.0)),
                sci(rho_n),
                sci(dt),
                sci(e19_ratio),
                e19_ratio / d[0],
                sci(d3)
            )
            .unwrap();
            rows_out.push(json!({
                "p": p, "seed": seed, "cofactor": r["cofactor"], "cols_tau": tau["columns"], "cols_tau_psi": tp["columns"],
                "residuals_tau": rt, "residuals_tau_psi": rp, "y_tau": yt, "y_tau_psi": yp,
                "logs_correct": tau["correct"].as_bool() == Some(true) && tp["correct"].as_bool() == Some(true),
                "walks_correct": ok_g && ok_n && ok_g3,
                "control_c_median": c_med, "control_agree": agree,
                "s_model_tau_psi": s_model(rp, lap, 0.0), "rho_psi_i": rho_g, "rho_psi_iii": rho_g3, "rho_neg_i": rho_n,
                "dist_tau_psi": d, "dist_tau": dt, "dist_tau_psi_iii": d3, "e19_ratio_same_p": e19_ratio,
                "e19_over_e28": e19_ratio / d[0],
            }));
        }
    }
    md.push_str(&a2);
    fs::write(format!("{dir}/tables.md"), &md).unwrap();
    fs::write(
        format!("{dir}/summary.json"),
        serde_json::to_string_pretty(
            &json!({"experiment": "e28", "stage0": s0_rows, "rows": rows_out}),
        )
        .unwrap(),
    )
    .unwrap();
    print!("{md}");
}
