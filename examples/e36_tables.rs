//! **E36 (§9.41) tables**: pivot rules whose selection work fits the §5a
//! band, per call (Stage A) and end to end, against E25, A (E27's Karatsuba
//! solver-A records) and the matched rho (walk (iii) of E27, without the
//! `[d]G` check), at `0`, `0.1` and `1` GAE.  Reads recorded JSON only;
//! writes `tables.md` and `summary.json` (the values the report plots).
//!
//! ```text
//! ./e36_tables experiments/40_pivot_rules
//! ```

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use serde_json::{json, Value};

const GAE: f64 = 97.0;
const GS: [f64; 3] = [0.0, 0.1, 1.0];
const CURVES: [(u64, u64); 10] = [
    (101, 1),
    (101, 2),
    (149, 1),
    (149, 2),
    (197, 1),
    (197, 2),
    (269, 1),
    (269, 2),
    (397, 1),
    (397, 2),
];
/// The E36 rules (L is the negative control) and the arms they are compared with.
const RULES: [&str; 5] = [
    "chain-fifo",
    "chain-static",
    "chain-fifo-static",
    "chain-est-k2",
    "chain-lifo",
];
const ARMS: [&str; 7] = [
    "existing",
    "chain",
    "chain-fifo",
    "chain-static",
    "chain-fifo-static",
    "chain-est-k2",
    "chain-lifo",
];

fn load(path: &str) -> Value {
    serde_json::from_str(&fs::read_to_string(path).unwrap_or_else(|e| panic!("{path}: {e}")))
        .unwrap()
}

fn f(v: &Value, k: &str) -> f64 {
    v[k].as_f64().unwrap_or_else(|| panic!("field {k}"))
}

fn sci(v: f64) -> String {
    if v == 0.0 {
        return "0".into();
    }
    let e = v.abs().log10().floor() as i32;
    format!("`{:.2}·10^{}`", v / 10f64.powi(e), e)
}

fn arm(recs: &Value, a: &str) -> Value {
    recs.as_array()
        .unwrap()
        .iter()
        .find(|r| r["arm"] == a)
        .unwrap_or_else(|| panic!("arm {a}"))
        .clone()
}

/// Fields an E36 record may change against E27's solver-A record: the
/// solve's multiplications and what derives from them, the selection
/// fields, wall times and the tag.
fn may_differ_vs_a(k: &str) -> bool {
    k.ends_with("_ms")
        || matches!(
            k,
            "solve_muls"
                | "total_muls"
                | "call"
                | "ratio"
                | "solver"
                | "pivot_selection"
                | "pivot_selection_ops"
                | "lead_scan_reads"
        )
}

fn diff_fields(a: &Value, b: &Value, allow: fn(&str) -> bool) -> Vec<String> {
    let (ao, bo) = (a.as_object().unwrap(), b.as_object().unwrap());
    let mut keys: Vec<&String> = ao.keys().chain(bo.keys()).collect();
    keys.sort();
    keys.dedup();
    keys.into_iter()
        .filter(|k| !allow(k) && ao.get(*k) != bo.get(*k))
        .cloned()
        .collect()
}

fn range(v: &[f64]) -> (f64, f64) {
    v.iter()
        .fold((f64::INFINITY, f64::NEG_INFINITY), |(lo, hi), &x| {
            (lo.min(x), hi.max(x))
        })
}

fn main() {
    let args: Vec<String> = env::args().skip(1).collect();
    let dir = args
        .first()
        .cloned()
        .unwrap_or("experiments/40_pivot_rules".into());
    let e25 = "experiments/30_gls_v4";
    let e31 = "experiments/31_solve_cost";
    let e27 = "experiments/32_walk_karatsuba";
    let e33 = "experiments/37_solver_b_pivot_count";
    let mut md = String::new();
    writeln!(md, "# E36 tables (generated by `examples/e36_tables.rs`)\n").unwrap();

    // ── Stage A ──────────────────────────────────────────────────────────
    let sa = load(&format!("{dir}/stage_a.json"));
    let sa33 = load(&format!("{e33}/stage_a.json"));
    writeln!(md, "## Stage A (per call; means over all calls, fallbacks charged)\n").unwrap();
    writeln!(md, "Agreement with the existing solver per solver (order of `solvers`); A's rule through E36's echelon equal to A counted (phases, digest, lead scans); calls whose pivot digest differs from A's; E33 reproduction: calls where `C`, echelon, entries and selection of existing / A / A counted / B″ equal E33's records.\n").unwrap();
    writeln!(md, "| p | seed | calls | agree | lowest = A | digest ≠ A | contested calls | E33 reproduced (existing, A, A counted, B″) |").unwrap();
    writeln!(md, "|--:|--:|--:|:--|--:|:--|--:|:--|").unwrap();
    let mut stage_rows = Vec::new();
    let mut e33_ok = true;
    for (ci, c) in sa.as_array().unwrap().iter().enumerate() {
        let c33 = &sa33.as_array().unwrap()[ci];
        assert_eq!((c["p"].clone(), c["seed"].clone()), (c33["p"].clone(), c33["seed"].clone()));
        let arm_of = |cv: &Value, name: &str| -> Value {
            cv["arms"]
                .as_array()
                .unwrap()
                .iter()
                .find(|a| a["solver"] == name)
                .unwrap()
                .clone()
        };
        let mut repro = Vec::new();
        for name in ["existing", "chain", "chain-counted", "chain-sparsest-est"] {
            let (a, b) = (arm_of(c, name), arm_of(c33, name));
            let n = a["call"].as_array().unwrap().len();
            let same = (0..n)
                .filter(|&i| {
                    ["call", "echelon", "entries", "sel", "lead_scan"]
                        .iter()
                        .all(|k| a[k][i] == b[k][i])
                })
                .count();
            if same != n {
                e33_ok = false;
            }
            repro.push(same);
        }
        writeln!(
            md,
            "| {} | {} | {} | {} | {} | {} | {} | {:?} |",
            c["p"], c["seed"], c["calls"], c["agree"], c["lowest_equals_a"],
            c["digest_differs_from_a"], c["calls_contested"], repro
        )
        .unwrap();
        let sums = c["summaries"].as_array().unwrap();
        let by = |name: &str| sums.iter().find(|s| s["solver"] == name).unwrap().clone();
        let sv = |n: &str, g: usize| by(n)["s_mean"][g].as_f64().unwrap();
        // Sensitivities.  σ1: lead scans priced (existing takes A counted's);
        // σ2: ordered candidates priced for A (via the positive control), S, H
        // (existing takes A's); σ3: contested columns priced for every E36 rule.
        let a_lead = f(&by("chain-counted"), "lead_scan_mean");
        let a_ord = f(&by("chain-lowest-e36"), "ordered_candidates_mean");
        let sens = |n: &str, g: usize, which: usize| -> f64 {
            let base = sv(n, g);
            let w = GAE * GS[g];
            let extra = match (which, n) {
                (1, "existing" | "chain") => a_lead,
                (1, _) => f(&by(n), "lead_scan_mean"),
                (2, "existing" | "chain") => a_ord,
                (2, _) => f(&by(n), "ordered_candidates_mean"),
                (3, "existing" | "chain") => 0.0,
                (3, _) => f(&by(n), "contested_mean"),
                _ => 0.0,
            };
            base + w * extra
        };
        type M = serde_json::Map<String, Value>;
        let mk = |which: usize| -> M {
            ARMS.iter()
                .map(|n| {
                    (
                        n.to_string(),
                        json!((0..3).map(|g| sens(n, g, which)).collect::<Vec<_>>()),
                    )
                })
                .collect()
        };
        let mut per: M = M::new();
        for n in ARMS.iter().chain(["chain-sparsest-est"].iter()) {
            let b = by(n);
            per.insert(
                n.to_string(),
                json!({
                    "c_mean": f(&b, "call_mean"), "c_median": b["call_median"].clone(),
                    "echelon_mean": f(&b, "echelon_mean"), "entries_mean": f(&b, "entries_mean"),
                    "sel": [f(&b, "sel_init_mean"), f(&b, "sel_compare_mean"), f(&b, "sel_update_mean"), f(&b, "sel_mean")],
                    "lead_scan_mean": f(&b, "lead_scan_mean"),
                    "contested_mean": f(&b, "contested_mean"),
                    "ordered_candidates_mean": f(&b, "ordered_candidates_mean"),
                    "row_updates_mean": f(&b, "row_updates_mean"),
                    "fallbacks": b["fallbacks"].clone(),
                }),
            );
        }
        let b2 = by("chain-sparsest-est");
        stage_rows.push(json!({
            "p": c["p"], "seed": c["seed"], "per": per,
            "s_mean": mk(0), "s_sigma1": mk(1), "s_sigma2": mk(2), "s_sigma3": mk(3),
            "s_mean_est": b2["s_mean"].clone(),
        }));
    }
    writeln!(md, "\nE33 per-call reproduction on every call: **{e33_ok}**\n").unwrap();
    writeln!(md, "| p | seed | solver | C median | C mean | echelon | entries | sel init | cmp | upd | selection | lead scan | contested | ordered cand. | row updates | fallbacks |").unwrap();
    writeln!(md, "|--:|--:|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|").unwrap();
    for r in &stage_rows {
        for n in ARMS.iter().chain(["chain-sparsest-est"].iter()) {
            let x = &r["per"][*n];
            let s = |i: usize| x["sel"][i].as_f64().unwrap();
            writeln!(
                md,
                "| {} | {} | {n} | {} | {:.0} | {:.0} | {:.0} | {:.1} | {:.1} | {:.1} | {:.1} | {:.0} | {:.1} | {:.1} | {:.1} | {} |",
                r["p"], r["seed"], x["c_median"], f(x, "c_mean"), f(x, "echelon_mean"), f(x, "entries_mean"),
                s(0), s(1), s(2), s(3), f(x, "lead_scan_mean"), f(x, "contested_mean"),
                f(x, "ordered_candidates_mean"), f(x, "row_updates_mean"), x["fallbacks"]
            )
            .unwrap();
        }
    }
    writeln!(md, "\nPer-call `S(g)` ratios `S_A / S_X` (Stage A means; `>1`: X cheaper), primary and under σ1–σ3; and `C_A / C_X`:\n").unwrap();
    writeln!(md, "| p | seed | X | C_A/C_X | 0 | 0.1 | 1 | σ1 0.1 | σ1 1 | σ2 0.1 | σ2 1 | σ3 0.1 | σ3 1 | E25/X 0 | 0.1 | 1 |").unwrap();
    writeln!(md, "|--:|--:|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|").unwrap();
    let mut carried: Vec<&str> = Vec::new();
    let mut stage_ranks = Vec::new();
    for x in RULES.iter().chain(["chain-sparsest-est"].iter()) {
        let mut ahead = [[0usize; 3]; 4]; // [primary, σ1, σ2, σ3][g]
        let mut ahead_e25 = [0usize; 3];
        for r in &stage_rows {
            let key = |k: &str, n: &str, g: usize| -> f64 {
                if *x == "chain-sparsest-est" && k != "s_mean" {
                    // B″ is not part of the sensitivities here.
                    r["s_mean_est"][g].as_f64().unwrap()
                } else if *x == "chain-sparsest-est" {
                    if n == "chain-sparsest-est" {
                        r["s_mean_est"][g].as_f64().unwrap()
                    } else {
                        r["s_mean"][n][g].as_f64().unwrap()
                    }
                } else {
                    r[k][n][g].as_f64().unwrap()
                }
            };
            let rat = |k: &str, g: usize| key(k, "chain", g) / key(k, x, g);
            let e25 = |g: usize| key("s_mean", "existing", g) / key("s_mean", x, g);
            for (i, k) in ["s_mean", "s_sigma1", "s_sigma2", "s_sigma3"].iter().enumerate() {
                for g in 0..3 {
                    if rat(k, g) > 1.0 {
                        ahead[i][g] += 1;
                    }
                }
            }
            for (g, a) in ahead_e25.iter_mut().enumerate() {
                if e25(g) > 1.0 {
                    *a += 1;
                }
            }
            let ca = f(&r["per"]["chain"], "c_mean") / f(&r["per"][*x], "c_mean");
            writeln!(
                md,
                "| {} | {} | {x} | {ca:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} |",
                r["p"], r["seed"], rat("s_mean", 0), rat("s_mean", 1), rat("s_mean", 2),
                rat("s_sigma1", 1), rat("s_sigma1", 2), rat("s_sigma2", 1), rat("s_sigma2", 2),
                rat("s_sigma3", 1), rat("s_sigma3", 2), e25(0), e25(1), e25(2)
            )
            .unwrap();
        }
        let n = stage_rows.len();
        if RULES.contains(x) && *x != "chain-lifo" && ahead[0][1] == n {
            carried.push(x);
        }
        stage_ranks.push(json!({"solver": x, "curves_ahead_of_a": ahead, "curves_ahead_of_e25": ahead_e25, "curves": n}));
    }
    writeln!(md, "\nCurves (of 10) where X is ahead of A, `[0, 0.1, 1]` GAE, primary / σ1 / σ2 / σ3, and of E25 (primary):\n").unwrap();
    for s in &stage_ranks {
        writeln!(md, "- `{}`: A {} ; E25 {}", s["solver"].as_str().unwrap(), s["curves_ahead_of_a"], s["curves_ahead_of_e25"]).unwrap();
    }
    writeln!(md, "\nCarried end to end (Stage A `S(0.1)` below A's on every curve; L never): **{carried:?}**\n").unwrap();

    // ── End to end ───────────────────────────────────────────────────────
    let summary27 = load(&format!("{e27}/summary.json"));
    let solvers: Vec<&str> = RULES
        .iter()
        .copied()
        .filter(|s| Path::new(&format!("{dir}/e2e_{s}_karatsuba_p101s1.json")).exists())
        .collect();
    let mut e2e_rows = Vec::new();
    let mut identity = Vec::new();
    for (p, seed) in CURVES {
        if solvers.is_empty() {
            break;
        }
        let r25 = load(&format!("{e25}/p{p}s{seed}.json"));
        let r31 = load(&format!("{e31}/e2e_chain_p{p}s{seed}.json"));
        let r27 = load(&format!("{e27}/e2e_chain_karatsuba_p{p}s{seed}.json"));
        let recs: Vec<(String, Value)> = solvers
            .iter()
            .map(|s| (s.to_string(), load(&format!("{dir}/e2e_{s}_karatsuba_p{p}s{seed}.json"))))
            .collect();
        for a in ["A", "B"] {
            let (x25, x31, x27) = (arm(&r25, a), arm(&r31, a), arm(&r27, a));
            let s27 = summary27["rows"]
                .as_array()
                .unwrap()
                .iter()
                .find(|r| r["p"] == p && r["seed"] == seed && r["arm"] == a)
                .unwrap()
                .clone();
            let (rho, steps) = (f(&s27, "rho_e27"), f(&s27, "walk_steps"));
            let rho_g: Vec<f64> = GS.iter().map(|g| rho + GAE * g * steps).collect();
            let s_e25: Vec<f64> = GS
                .iter()
                .map(|g| f(&x25, "total_muls") + GAE * g * f(&x25, "macaulay_entries"))
                .collect();
            let s_ak: Vec<f64> = GS
                .iter()
                .map(|g| f(&x27, "total_muls") + GAE * g * f(&x27, "macaulay_entries"))
                .collect();
            // Schoolbook re-pricing of the non-solve F_{p⁴} work, measured on A
            // (E31 A's schoolbook total − E27 A's Karatsuba total, same calls).
            let shift = f(&x31, "total_muls") - f(&x27, "total_muls");
            let mut row = json!({"p": p, "seed": seed, "arm": a, "rho_e27": rho, "walk_steps": steps,
                "S_E25": s_e25, "S_AK": s_ak, "rho_g": rho_g, "school_shift": shift,
                "A_over_rho": (0..3).map(|g| s_ak[g] / rho_g[g]).collect::<Vec<_>>()});
            for (s, rec) in &recs {
                let x = arm(rec, a);
                let sel = f(&x, "pivot_selection_ops");
                let d = diff_fields(&x27, &x, may_differ_vs_a);
                identity.push(json!({"p": p, "seed": seed, "arm": a, "solver": s,
                    "fields_differing_from_e27_a": d,
                    "solve_muls_differs": x["solve_muls"] != x27["solve_muls"]}));
                let s_x: Vec<f64> = GS
                    .iter()
                    .map(|g| f(&x, "total_muls") + GAE * g * (f(&x, "macaulay_entries") + sel))
                    .collect();
                let s_xs: Vec<f64> = (0..3)
                    .map(|g| s_x[g] + shift)
                    .collect();
                row[s.as_str()] = json!({
                    "selection_ops": sel,
                    "selection_parts": x["pivot_selection"].clone(),
                    "residuals": x["residuals"].clone(),
                    "selection_per_call": sel / f(&x, "residuals"),
                    "c_mean": x["call"]["mean"].clone(),
                    "S_K": s_x, "S_school": s_xs,
                    "A_over": (0..3).map(|g| s_ak[g] / s_x[g]).collect::<Vec<_>>(),
                    "E25_over": (0..3).map(|g| s_e25[g] / s_xs[g]).collect::<Vec<_>>(),
                    "over_rho": (0..3).map(|g| s_x[g] / rho_g[g]).collect::<Vec<_>>(),
                });
            }
            e2e_rows.push(row);
        }
    }
    let mut ranks = Vec::new();
    if !solvers.is_empty() {
        writeln!(md, "## End to end (E25's ten curves, both arms; Karatsuba products)\n").unwrap();
        writeln!(md, "`S_A/S_X`: E27's solver-A records against this run (Karatsuba); `S_E25/S_X`: schoolbook (E25's records against X re-priced by E31 A − E27 A); `S_X/rho`: against walk (iii) of E27 without the `[d]G` check.  One GAE (`97`) per Macaulay entry, per selection operation and per walk step.\n").unwrap();
        for s in &solvers {
            writeln!(md, "### {s}\n").unwrap();
            writeln!(md, "| p | seed | arm | selection / call | A/X 0 | 0.1 | 1 | E25/X 0 | 0.1 | 1 | X/rho 0 | 0.1 | 1 |").unwrap();
            writeln!(md, "|--:|--:|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|").unwrap();
            for r in &e2e_rows {
                let x = &r[*s];
                let v = |k: &str, g: usize| x[k][g].as_f64().unwrap();
                writeln!(
                    md,
                    "| {} | {} | {} | {:.1} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {} | {} | {} |",
                    r["p"], r["seed"], r["arm"].as_str().unwrap(), f(x, "selection_per_call"),
                    v("A_over", 0), v("A_over", 1), v("A_over", 2),
                    v("E25_over", 0), v("E25_over", 1), v("E25_over", 2),
                    sci(v("over_rho", 0)), sci(v("over_rho", 1)), sci(v("over_rho", 2))
                )
                .unwrap();
            }
            writeln!(md).unwrap();
        }
        writeln!(md, "### Ranges and ranks (an order is stated only where it holds at every weight on every row)\n").unwrap();
        writeln!(md, "| X | quantity | 0 GAE | 0.1 GAE | 1 GAE | rows X ahead (0 / 0.1 / 1) | rank |").unwrap();
        writeln!(md, "|:--|:--|:--|:--|:--|:--|:--|").unwrap();
        for s in &solvers {
            for (k, what) in [
                ("A_over", "S_A / S_X"),
                ("E25_over", "S_E25 / S_X"),
                ("over_rho", "S_X / rho"),
            ] {
                let mut cells = Vec::new();
                let mut ahead = Vec::new();
                let mut rr = Vec::new();
                for g in 0..3 {
                    let v: Vec<f64> = e2e_rows.iter().map(|r| r[*s][k][g].as_f64().unwrap()).collect();
                    let (lo, hi) = range(&v);
                    rr.push(json!([lo, hi]));
                    cells.push(if k == "over_rho" {
                        format!("{}–{}", sci(lo), sci(hi))
                    } else {
                        format!("{lo:.4}–{hi:.4}")
                    });
                    ahead.push(
                        v.iter()
                            .filter(|&&x| if k == "over_rho" { x < 1.0 } else { x > 1.0 })
                            .count(),
                    );
                }
                let n = e2e_rows.len();
                let rank = if ahead.iter().all(|&a| a == n) {
                    "X ahead across the band"
                } else if ahead.iter().all(|&a| a == 0) {
                    "X behind across the band"
                } else {
                    "unresolved (order changes inside the band or across rows)"
                };
                writeln!(md, "| {s} | {what} | {} | {} | {} | {}/{}/{} of {n} | {rank} |", cells[0], cells[1], cells[2], ahead[0], ahead[1], ahead[2]).unwrap();
                ranks.push(json!({"solver": s, "quantity": what, "ranges": rr, "rows_x_ahead": ahead, "rows": n, "rank": rank}));
            }
        }
        // A's own distance to rho, for comparison.
        let mut cells = Vec::new();
        for g in 0..3 {
            let v: Vec<f64> = e2e_rows.iter().map(|r| r["A_over_rho"][g].as_f64().unwrap()).collect();
            let (lo, hi) = range(&v);
            cells.push(format!("{}–{}", sci(lo), sci(hi)));
        }
        writeln!(md, "| A (E27) | S_A / rho | {} | {} | {} | — | rho ahead |", cells[0], cells[1], cells[2]).unwrap();
    }
    let ident_ok = identity.iter().all(|i| i["fields_differing_from_e27_a"].as_array().unwrap().is_empty());
    writeln!(md, "\nEnd-to-end identity (every field of E27's solver-A record apart from the solve's multiplications and what derives from them, the selection fields, wall times and the tag): **{ident_ok}**\n").unwrap();
    fs::write(format!("{dir}/tables.md"), &md).unwrap();
    let summary = json!({
        "experiment": "e36",
        "gae": GAE,
        "stage_a": stage_rows,
        "stage_a_e33_reproduced": e33_ok,
        "stage_a_ranks": stage_ranks,
        "carried": carried,
        "e2e_solvers": solvers,
        "e2e": e2e_rows,
        "ranks": ranks,
        "e2e_identity_ok": ident_ok,
        "e2e_identity": identity,
    });
    fs::write(format!("{dir}/summary.json"), serde_json::to_string_pretty(&summary).unwrap()).unwrap();
    print!("{md}");
}
