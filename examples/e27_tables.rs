//! **E27 (§9.25) tables**: the matched walk under the three arithmetics,
//! E31 solver A's `S` with and without Karatsuba products, and the
//! distances to rho at `0`, `0.1` and `1` GAE.  Reads the recorded JSON
//! only; writes `tables.md` and `summary.json` (the values the report's
//! graphs plot).
//!
//! ```text
//! cargo run --release --example e27_tables -- experiments/32_walk_karatsuba experiments/31_solve_cost
//! ```

use std::collections::BTreeSet;
use std::env;
use std::fmt::Write as _;
use std::fs;

use serde_json::{json, Value};

/// E25/E31's GAE: the measured cost of an affine addition (§9.19).
const GAE: f64 = 97.0;

fn load(path: &str) -> Value {
    serde_json::from_str(&fs::read_to_string(path).unwrap_or_else(|e| panic!("{path}: {e}")))
        .unwrap()
}

fn sci(v: f64) -> String {
    if v == 0.0 {
        return "0".into();
    }
    let e = v.abs().log10().floor() as i32;
    format!("`{:.2}·10^{}`", v / 10f64.powi(e), e)
}

/// The fields a Karatsuba rerun may change: every multiplication count and
/// what is derived from it, wall times, the new tags, and the walks (which
/// now charge the [d]G check, §9.25 note).
fn may_differ(k: &str) -> bool {
    k.ends_with("_muls")
        || k.ends_with("_ms")
        || matches!(
            k,
            "ratio" | "rho" | "fp_muls_per_add" | "fp4_product" | "ic_fp_inversions" | "call"
        )
}

fn main() {
    let args: Vec<String> = env::args().skip(1).collect();
    let dir = args
        .first()
        .cloned()
        .unwrap_or("experiments/32_walk_karatsuba".into());
    let e31 = args
        .get(1)
        .cloned()
        .unwrap_or("experiments/31_solve_cost".into());
    let w = load(&format!("{dir}/stage_w.json"));
    let ops = &w["per_op_costs"];
    let mut md = String::new();
    let mut summary_rows = Vec::new();

    // Stage W.
    writeln!(md, "# E27 tables (generated by `examples/e27_tables.rs`)\n").unwrap();
    writeln!(
        md,
        "Per-operation costs (`F_p` multiplications, unbatched): {ops}\n"
    )
    .unwrap();
    writeln!(md, "## Stage W: the walks\n").unwrap();
    writeln!(md, "| p | seed | log₂ n | fold | walks | replay (i) = E25 | (ii) = (i) | (iii) = (i) | mean steps | (i) | (ii) | (iii) | (i)/(ii) | (i)/(iii) | muls/group op (i) | (iii) | inversion share | fillers |").unwrap();
    writeln!(
        md,
        "|--:|--:|--:|:--|--:|:--|:--|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|"
    )
    .unwrap();
    let mut walk = std::collections::HashMap::new();
    let mut all_identical = true;
    let mut ratios = Vec::new();
    for c in w["curves"].as_array().unwrap() {
        let (p, seed) = (c["p"].as_u64().unwrap(), c["seed"].as_u64().unwrap());
        for fold in ["Gls", "Negation"] {
            let f = &c["folds"][fold];
            let m = &f["mean_fp_muls"];
            let (i, ii, iii) = (
                m["schoolbook"].as_f64().unwrap(),
                m["karatsuba"].as_f64().unwrap(),
                m["batched"].as_f64().unwrap(),
            );
            let ok = [
                f["replay_matches_e25"].as_bool().unwrap(),
                f["karatsuba_identical"].as_bool().unwrap(),
                f["batched_identical"].as_bool().unwrap(),
            ];
            all_identical &= ok.iter().all(|&b| b);
            let gops = f["mean_group_ops"].as_f64().unwrap();
            ratios.push(i / iii);
            writeln!(
                md,
                "| {p} | {seed} | {:.1} | {fold} | {} | {} | {} | {} | {:.0} | {} | {} | {} | {:.4} | {:.4} | {:.1} | {:.1} | {:.3} | {} |",
                c["bits"].as_f64().unwrap(),
                f["walks"]["schoolbook"].as_array().unwrap().len(),
                ok[0], ok[1], ok[2],
                f["mean_steps"].as_f64().unwrap(),
                sci(i), sci(ii), sci(iii), i / ii, i / iii,
                i / gops, iii / gops,
                f["inversion_share"].as_f64().unwrap(),
                f["batch"]["filler_walks"].as_u64().unwrap()
            )
            .unwrap();
            walk.insert(
                (p, seed, fold),
                (
                    i,
                    iii,
                    f["mean_steps"].as_f64().unwrap(),
                    f["inversion_share"].as_f64().unwrap(),
                ),
            );
        }
    }
    let rmin = ratios.iter().cloned().fold(f64::MAX, f64::min);
    let rmax = ratios.iter().cloned().fold(0.0, f64::max);
    writeln!(
        md,
        "\nAll walks identical: **{all_identical}**; (i)/(iii) `{rmin:.4}`–`{rmax:.4}`.\n"
    )
    .unwrap();

    // IC side and distances.
    writeln!(
        md,
        "## IC side (E31 solver A) and the distance to the matched `⟨±ψ⟩` walk\n"
    )
    .unwrap();
    writeln!(md, "`S` in `F_p` multiplications; rho = mean `F_p` multiplications of the 16 `⟨±ψ⟩` walks, E25's convention (the `[d]G` check excluded). Band: one GAE (`97`) per Macaulay entry and per walk step.\n").unwrap();
    writeln!(md, "| p | seed | arm | `S_A` (E31) | `S_A,K` (E27) | `S_A/S_A,K` | non-solve share of `S_A` | `F_p` inversions (IC) | batching bound | other fields equal | rho E25 | rho E27 | `S/rho` 0 GAE, E31 → E27 | growth 0 | growth 0.1 | growth 1 |").unwrap();
    writeln!(
        md,
        "|--:|--:|:--|--:|--:|--:|--:|--:|--:|:--|--:|--:|:--|--:|--:|--:|"
    )
    .unwrap();
    let mut differing_fields: BTreeSet<String> = BTreeSet::new();
    let mut s_ratio = Vec::new();
    let mut growth = [Vec::new(), Vec::new(), Vec::new()];
    let mut dist_new = [Vec::new(), Vec::new(), Vec::new()];
    let mut dist_old = [Vec::new(), Vec::new(), Vec::new()];
    let mut growth_sens = Vec::new();
    for p in [101u64, 149, 197, 269, 397] {
        for seed in [1u64, 2] {
            let a_path = format!("{e31}/e2e_chain_p{p}s{seed}.json");
            let k_path = format!("{dir}/e2e_chain_karatsuba_p{p}s{seed}.json");
            if fs::metadata(&k_path).is_err() {
                writeln!(md, "| {p} | {seed} | — | missing `{k_path}` |").unwrap();
                continue;
            }
            let (a_rows, k_rows) = (load(&a_path), load(&k_path));
            for (ra, rk) in a_rows
                .as_array()
                .unwrap()
                .iter()
                .zip(k_rows.as_array().unwrap())
            {
                let arm = ra["arm"].as_str().unwrap();
                assert_eq!(arm, rk["arm"].as_str().unwrap());
                // Every field other than counts must be reproduced.
                let mut equal = true;
                for (key, va) in ra.as_object().unwrap() {
                    if may_differ(key) {
                        if va != &rk[key] {
                            differing_fields.insert(key.clone());
                        }
                        continue;
                    }
                    // A field the older record lacks (`recovered`, added to
                    // ArmReport after E31) is not a disagreement.
                    let same = match (va, &rk[key]) {
                        (Value::Object(oa), Value::Object(ok)) => {
                            oa.iter().all(|(k2, v2)| &ok[k2] == v2)
                        }
                        (a, b) => a == b,
                    };
                    if !same {
                        equal = false;
                        differing_fields.insert(format!("{key} (UNEXPECTED)"));
                    }
                }
                let f = |r: &Value, k: &str| r[k].as_f64().unwrap_or(0.0);
                let (sa, sk) = (f(ra, "total_muls"), f(rk, "total_muls"));
                let nonsolve = sa - f(ra, "solve_muls");
                let inv = rk["ic_fp_inversions"].as_f64().unwrap_or(0.0);
                let (rho_old, rho_new, steps, share) = walk[&(p, seed, "Gls")];
                // What batching the IC side's inversions could still save.
                let bound = inv * (16.0 - share);
                let entries = f(ra, "macaulay_entries");
                assert_eq!(entries, f(rk, "macaulay_entries"));
                let mut g = [0.0; 3];
                for (wi, &wt) in [0.0, 0.1, 1.0].iter().enumerate() {
                    let old = (sa + wt * GAE * entries) / (rho_old + wt * GAE * steps);
                    let new = (sk + wt * GAE * entries) / (rho_new + wt * GAE * steps);
                    g[wi] = new / old;
                    growth[wi].push(new / old);
                    dist_new[wi].push(new);
                    dist_old[wi].push(old);
                }
                // Sensitivity: the GAE re-measured under (iii) on the new side.
                let gae_new = 24.0 + 3.0 * 13.0 + share;
                let old1 = (sa + GAE * entries) / (rho_old + GAE * steps);
                let new1 = (sk + gae_new * entries) / (rho_new + gae_new * steps);
                growth_sens.push(new1 / old1);
                s_ratio.push(sa / sk);
                writeln!(
                    md,
                    "| {p} | {seed} | {arm} | {} | {} | {:.5} | {:.2} % | {:.3e} | {:.3} % | {equal} | {} | {} | {} → {} | {:.4} | {:.4} | {:.4} |",
                    sci(sa), sci(sk), sa / sk, 100.0 * nonsolve / sa, inv, 100.0 * bound / sk,
                    sci(rho_old), sci(rho_new), sci(sa / rho_old), sci(sk / rho_new), g[0], g[1], g[2]
                )
                .unwrap();
                summary_rows.push(json!({
                    "p": p, "seed": seed, "arm": arm,
                    "S_A": sa, "S_AK": sk, "rho_e25": rho_old, "rho_e27": rho_new,
                    "walk_steps": steps, "macaulay_entries": entries,
                    "dist_old": [dist_old[0].last(), dist_old[1].last(), dist_old[2].last()],
                    "dist_new": [dist_new[0].last(), dist_new[1].last(), dist_new[2].last()],
                    "growth": g, "growth_gae_remeasured_1": new1 / old1,
                    "nonsolve_share": nonsolve / sa, "ic_fp_inversions": inv, "batch_bound_share": bound / sk,
                    "other_fields_equal": equal,
                }));
            }
        }
    }
    let range = |v: &[f64]| {
        (
            v.iter().cloned().fold(f64::MAX, f64::min),
            v.iter().cloned().fold(0.0, f64::max),
        )
    };
    let (a, b) = range(&s_ratio);
    writeln!(md, "\n`S_A / S_A,K` `{a:.5}`–`{b:.5}`.  Fields that differ between E31 A and E27 (expected: counts and what derives from them): {differing_fields:?}\n").unwrap();
    for (wi, wt) in ["0", "0.1", "1"].iter().enumerate() {
        let (a, b) = range(&growth[wi]);
        let (c, d) = range(&dist_old[wi]);
        let (e, f) = range(&dist_new[wi]);
        writeln!(
            md,
            "- {wt} GAE: `S/rho` E31 A {}–{}, E27 {}–{}; growth `{a:.4}`–`{b:.4}`",
            sci(c),
            sci(d),
            sci(e),
            sci(f)
        )
        .unwrap();
    }
    let (a, b) = range(&growth_sens);
    writeln!(
        md,
        "- 1 GAE with the GAE re-measured under (iii) on the E27 side: growth `{a:.4}`–`{b:.4}`"
    )
    .unwrap();
    fs::write(format!("{dir}/tables.md"), &md).unwrap();
    fs::write(
        format!("{dir}/summary.json"),
        serde_json::to_string_pretty(&json!({
            "experiment": "e27",
            "walk_ratio_range": [rmin, rmax],
            "all_walks_identical": all_identical,
            "per_op_costs": ops,
            "rows": summary_rows,
            "walks": w["curves"].as_array().unwrap().iter().map(|c| json!({
                "p": c["p"], "seed": c["seed"], "bits": c["bits"],
                "gls": c["folds"]["Gls"]["mean_fp_muls"], "negation": c["folds"]["Negation"]["mean_fp_muls"],
            })).collect::<Vec<_>>(),
        }))
        .unwrap(),
    )
    .unwrap();
    print!("{md}");
}
