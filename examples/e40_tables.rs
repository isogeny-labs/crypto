const E37: &str = "experiments/44_pivot_rules_confirm/e2e";

fn load(path: &str) -> Value {
    serde_json::from_str(&fs::read_to_string(path).unwrap_or_else(|e| panic!("{path}: {e}")))
        .unwrap()
}

fn f(v: &Value, k: &str) -> f64 {
    v[k].as_f64().unwrap_or_else(|| panic!("field {k}"))
}

fn sci(v: f64) -> String {
    if v == 0.0 {
        return "0".into();
    }
    let e = v.abs().log10().floor() as i32;
    format!("{:.2}·10^{}", v / 10f64.powi(e), e)
}

fn range(v: &[f64]) -> (f64, f64) {
    v.iter()
        .fold((f64::INFINITY, f64::NEG_INFINITY), |(lo, hi), &x| {
            (lo.min(x), hi.max(x))
        })
}

fn arm_of(recs: &Value, a: Option<&str>) -> Value {
    let arr = recs.as_array().unwrap();
    match a {
        Some(a) => arr
            .iter()
            .find(|r| r["arm"] == a)
            .unwrap_or_else(|| panic!("arm {a}"))
            .clone(),
        None => arr[0].clone(),
    }
}

/// Fields a V record may change against A's on the same row and stream.
fn may_differ(k: &str) -> bool {
    k.ends_with("_ms")
        || k == "ms"
        || k.contains("wall")
        || matches!(
            k,
            "solver" | "lead_scan_reads" | "macaulay_stored_entries" | "profile_offset_ops"
        )
}

fn diff_fields(a: &Value, b: &Value) -> Vec<String> {
    let (ao, bo) = (a.as_object().unwrap(), b.as_object().unwrap());
    let mut keys: Vec<&String> = ao.keys().chain(bo.keys()).collect();
    keys.sort();
    keys.dedup();
    keys.into_iter()
        .filter(|k| !may_differ(k) && strip(ao.get(*k)) != strip(bo.get(*k)))
        .cloned()
        .collect()
}

/// Nested objects compared without their timing fields.
fn strip(v: Option<&Value>) -> Option<Value> {
    fn go(v: &Value) -> Value {
        match v {
            Value::Object(m) => Value::Object(
                m.iter()
                    .filter(|(k, _)| !may_differ(k))
                    .map(|(k, x)| (k.clone(), go(x)))
                    .collect(),
            ),
            Value::Array(a) => Value::Array(a.iter().map(go).collect()),
            x => x.clone(),
        }
    }
    v.map(go)
}

/// `S(g)` of a record: `total_muls + 97 g (cells + extra)`; cells are the
/// stored cells plus offset operations for V, `macaulay_entries` (+ any
/// selection) otherwise.
fn s_of(x: &Value, extra: f64) -> Vec<f64> {
    let cells = match x.get("macaulay_stored_entries").and_then(Value::as_f64) {
        Some(st) => st + f(x, "profile_offset_ops"),
        None => f(x, "macaulay_entries") + x["pivot_selection_ops"].as_f64().unwrap_or(0.0),
    };
    GS.iter()
        .map(|g| f(x, "total_muls") + GAE * g * (cells + extra))
        .collect()
}

fn order(a: &[f64], x: &[f64]) -> &'static str {
    // a = reference, x = arm.  ">" : x cheaper.
    let ahead = (0..3).all(|g| x[g] < a[g]);
    let behind = (0..3).all(|g| x[g] > a[g]);
    let weak = x[0] == a[0] && x[1] < a[1] && x[2] < a[2];
    if ahead {
        "ahead"
    } else if weak {
        "equal at 0, ahead at 0.1 and 1"
    } else if behind {
        "behind"
    } else {
        "unresolved"
    }
}

fn main() {
    let dir = env::args()
        .nth(1)
        .unwrap_or("experiments/47_macaulay_entries".into());
    let mut md = String::new();
    let mut verdict = Map::new();
    writeln!(md, "# E40 tables (§9.51)\n\nGenerated by `examples/e40_tables.rs` from recorded JSON. `S(g) = total_muls + 97 g · cells`; cells = `macaulay_entries` for A and E25, `macaulay_stored_entries + profile_offset_ops` for V; rho(g) = rho + 97 g · steps (walk (iii)).\n").unwrap();

    // ── Stage 0 ──
    let s0 = load(&format!("{dir}/stage0.json"));
    let s0r = |k: &str| -> (f64, f64) {
        range(
            &s0.as_array()
                .unwrap()
                .iter()
                .map(|c| f(&c["fields"][k], "mean"))
                .collect::<Vec<_>>(),
        )
    };
    writeln!(md, "## Stage 0 (per call, means over curves; 22 curves × 200 calls)\n\n| count | min | max |\n|:--|--:|--:|").unwrap();
    for k in [
        "rows",
        "cols",
        "dense_entries",
        "prefix_entries",
        "tail_entries",
        "term_writes",
        "enumerated_monomials",
        "selection_tests",
        "initial_lead_scan",
        "lead_scan",
        "zero_rows",
        "zero_row_tail_entries",
        "duplicate_rows",
        "untouched_columns",
        "dependency_rows",
        "outside_dependency_tail_entries",
        "dim",
        "chains",
        "reached",
    ] {
        let (lo, hi) = s0r(k);
        writeln!(md, "| `{k}` | {lo:.1} | {hi:.1} |").unwrap();
    }
    // Per-call structural work (σ4), per set and curve.
    let struct_of = |set: &str, p: u64, seed: u64| -> f64 {
        let c = s0
            .as_array()
            .unwrap()
            .iter()
            .find(|c| c["set"] == set && c["p"] == p && c["seed"] == seed)
            .unwrap();
        [
            "enumerated_monomials",
            "cols",
            "selection_tests",
            "term_writes",
        ]
        .iter()
        .map(|k| f(&c["fields"][k], "mean"))
        .sum()
    };

    // ── Identity of existing configurations ──
    let ide = load(&format!("{dir}/identity_existing_solvers.json"));
    let ide_ok = ide["runs"]
        .as_array()
        .unwrap()
        .iter()
        .all(|r| r["identical"] == true);
    writeln!(md, "\n## Existing configurations under the E40 binary\n\n| config | reference | identical |\n|:--|:--|:--|").unwrap();
    for r in ide["runs"].as_array().unwrap() {
        writeln!(
            md,
            "| `{}` | {} | {} |",
            r["config"].as_str().unwrap(),
            r["reference"].as_str().unwrap(),
            r["identical"]
        )
        .unwrap();
    }

    // ── Controls ──
    let ck = load(&format!("{dir}/checks.json"));
    let ck_ok = ck["g2_205_holds"] == true;
    writeln!(md, "\n## Controls (G2.205)\n\n{} calls: V = A counted on {}; P1 detected {}; P2 detected {}; perturbed coefficient changed {}/{} non-empty sets.\n",
        ck["calls"], ck["v_equals_a_counted"], ck["p1_detected"], ck["p2_detected"], ck["perturbed_changed"], ck["nonempty"]).unwrap();

    // ── Stage A ──
    let sa = load(&format!("{dir}/stage_a.json"));
    let mut sa_ok = true;
    let mut sa_rows = Vec::new();
    writeln!(md, "## Stage A (10 curves × 1,000 calls, stream `seed ^ 0xE40A_0001`)\n\n| p | seed | agree (ex, A, A cnt, V) | V = A cnt | stored ok | lead rel. | A cells clean | V cells clean [min, max] | E_A/E_V clean | V ops | V lead | fb A / V | S_A/S_V 0 | 0.1 | 1 | σ1 0.1 | σ1 1 |\n|--:|--:|:--|--:|--:|--:|--:|:--|--:|--:|--:|:--|--:|--:|--:|--:|--:|").unwrap();
    for c in sa.as_array().unwrap() {
        let calls = c["calls"].as_u64().unwrap();
        let agree: Vec<u64> = c["agree"]
            .as_array()
            .unwrap()
            .iter()
            .map(|x| x.as_u64().unwrap())
            .collect();
        let ok = agree.iter().all(|&a| a == calls)
            && c["v_equals_a_counted"].as_u64() == Some(calls)
            && c["stored_counter_ok"].as_u64() == Some(calls)
            && c["lead_scan_relation_ok"].as_u64() == Some(calls)
            && c["a_clean_cells_all_176064"] == true;
        sa_ok &= ok;
        let s = &c["summaries"];
        let (a, v) = (&s[2], &s[3]);
        let r = &c["ratio_a_over_v"];
        let r1 = &c["ratio_a_over_v_sigma1"];
        let ecl = f(a, "cells_clean_mean") / f(v, "cells_clean_mean");
        writeln!(md, "| {} | {} | {:?} | {} | {} | {} | {:.0} | {:.0} [{}, {}] | {:.4} | {:.0} | {:.0} | {} / {} | {:.6} | {:.4} | {:.4} | {:.4} | {:.4} |",
            c["p"], c["seed"], agree, c["v_equals_a_counted"], c["stored_counter_ok"], c["lead_scan_relation_ok"],
            f(a, "cells_clean_mean"), f(v, "cells_clean_mean"), v["cells_clean_min"], v["cells_clean_max"], ecl,
            f(v, "offset_ops_mean"), f(v, "lead_scan_mean"), a["fallbacks"], v["fallbacks"],
            r[0].as_f64().unwrap(), r[1].as_f64().unwrap(), r[2].as_f64().unwrap(),
            r1[1].as_f64().unwrap(), r1[2].as_f64().unwrap()).unwrap();
        sa_rows.push(json!({"p": c["p"], "seed": c["seed"], "e_ratio_clean": ecl,
            "v_cells_clean": f(v, "cells_clean_mean"), "v_cells_clean_min": v["cells_clean_min"], "v_cells_clean_max": v["cells_clean_max"],
            "v_ops": f(v, "offset_ops_mean"), "v_lead": f(v, "lead_scan_mean"), "a_lead": f(a, "lead_scan_mean"),
            "a_c": f(a, "call_mean"), "ratio": r, "ratio_sigma1": r1,
            "fb_a": a["fallbacks"], "fb_v": v["fallbacks"], "identity_ok": ok}));
    }
    let col = |k: &str, i: Option<usize>| -> (f64, f64) {
        range(
            &sa_rows
                .iter()
                .map(|r| match i {
                    Some(i) => r[k][i].as_f64().unwrap(),
                    None => f(r, k),
                })
                .collect::<Vec<_>>(),
        )
    };
    let (vc0, vc1) = col("v_cells_clean", None);
    let (er0, er1) = col("e_ratio_clean", None);
    let (op0, op1) = col("v_ops", None);
    let (r00, r01) = col("ratio", Some(0));
    let (r10, r11) = col("ratio", Some(1));
    let (r20, r21) = col("ratio", Some(2));
    let (vl0, vl1) = col("v_lead", None);
    let fb_same = sa_rows.iter().all(|r| r["fb_a"] == r["fb_v"]);
    let r0_exact = sa_rows
        .iter()
        .all(|r| r["ratio"][0].as_f64().unwrap() == 1.0);
    writeln!(md, "\nRanges over curves: V clean cells `{vc0:.0}`–`{vc1:.0}`, E_A/E_V clean `{er0:.4}`–`{er1:.4}`, offset ops `{op0:.0}`–`{op1:.0}`, V lead scans `{vl0:.0}`–`{vl1:.0}`; S_A/S_V `{r00:.6}`–`{r01:.6}` / `{r10:.4}`–`{r11:.4}` / `{r20:.4}`–`{r21:.4}`.").unwrap();

    // ── End to end ──
    let s27 = load("experiments/32_walk_karatsuba/summary.json");
    let w24 = load("experiments/44_pivot_rules_confirm/walk_e24.json");
    let mut rows: Vec<Value> = Vec::new();
    let mut identity = Vec::new();
    let mut health_ok = true;
    for (set, curves) in [("gls", &GLS[..]), ("e24", &E24[..])] {
        for &(p, seed) in curves {
            let ra = load(&format!("{E37}/{set}_chain-counted_p{p}s{seed}.json"));
            let re = load(&format!("{E37}/{set}_macaulay_p{p}s{seed}.json"));
            let rv = load(&format!("{dir}/e2e/{set}_chain-profile_p{p}s{seed}.json"));
            let arms: Vec<Option<&str>> = if set == "gls" {
                vec![Some("A"), Some("B")]
            } else {
                vec![None]
            };
            for a in arms {
                let (rho, steps) = if set == "gls" {
                    let r = s27["rows"]
                        .as_array()
                        .unwrap()
                        .iter()
                        .find(|r| r["p"] == p && r["seed"] == seed && r["arm"] == a.unwrap())
                        .unwrap();
                    (f(r, "rho_e27"), f(r, "walk_steps"))
                } else {
                    let c = w24["curves"]
                        .as_array()
                        .unwrap()
                        .iter()
                        .find(|c| c["p"] == p && c["seed"] == seed)
                        .unwrap();
                    (f(&c["mean_fp_muls"], "batched"), f(c, "mean_steps"))
                };
                let rho_g: Vec<f64> = GS.iter().map(|g| rho + GAE * g * steps).collect();
                let (xa, xe, xv) = (arm_of(&ra, a), arm_of(&re, a), arm_of(&rv, a));
                let calls = f(&xa, "residuals");
                let st = struct_of(set, p, seed) * calls;
                let (la, lv) = (f(&xa, "lead_scan_reads"), f(&xv, "lead_scan_reads"));
                let (sa_, se, sv) = (s_of(&xa, 0.0), s_of(&xe, 0.0), s_of(&xv, 0.0));
                let (sa1, se1, sv1) = (s_of(&xa, la), s_of(&xe, la), s_of(&xv, lv));
                let (sa4, se4, sv4) = (s_of(&xa, st), s_of(&xe, st), s_of(&xv, st));
                let d = diff_fields(&xa, &xv);
                identity.push(json!({"set": set, "p": p, "seed": seed, "arm": a.unwrap_or("—"), "fields_differing_from_a": d}));
                for x in [&xa, &xe, &xv] {
                    health_ok &= x["folded"]["correct"] == true
                        && x["rho"]
                            .as_array()
                            .is_some_and(|w| w.iter().all(|w| w["correct"] == true));
                }
                let rat =
                    |r: &[f64], x: &[f64]| -> Vec<f64> { (0..3).map(|g| r[g] / x[g]).collect() };
                rows.push(json!({"set": set, "p": p, "seed": seed, "arm": a.unwrap_or("—"),
                    "calls": calls, "fallbacks": xv["solver_fallbacks"].clone(),
                    "fallbacks_a": xa["solver_fallbacks"].clone(),
                    "rho": rho, "walk_steps": steps, "rho_g": rho_g,
                    "S_A": sa_, "S_E25": se, "S_V": sv,
                    "a_over_v": rat(&sa_, &sv), "e25_over_v": rat(&se, &sv), "e25_over_a": rat(&se, &sa_),
                    "a_over_v_sigma1": rat(&sa1, &sv1), "e25_over_v_sigma1": rat(&se1, &sv1),
                    "a_over_v_sigma4": rat(&sa4, &sv4), "e25_over_v_sigma4": rat(&se4, &sv4),
                    "v_over_rho": rat(&sv, &rho_g), "a_over_rho": rat(&sa_, &rho_g), "e25_over_rho": rat(&se, &rho_g),
                    "order_v_vs_a": order(&sa_, &sv), "order_v_vs_e25": order(&se, &sv),
                    "order_v_vs_a_sigma1": order(&sa1, &sv1), "order_v_vs_e25_sigma1": order(&se1, &sv1),
                    "order_v_vs_a_sigma4": order(&sa4, &sv4), "order_v_vs_e25_sigma4": order(&se4, &sv4),
                    "v_cells_per_call": (f(&xv, "macaulay_stored_entries")) / calls,
                    "v_ops_per_call": f(&xv, "profile_offset_ops") / calls,
                    "a_cells_per_call": f(&xa, "macaulay_entries") / calls,
                    "v_lead_per_call": lv / calls, "a_lead_per_call": la / calls}));
            }
        }
    }
    let ident_ok = identity
        .iter()
        .all(|i| i["fields_differing_from_a"].as_array().unwrap().is_empty());
    let rr = |k: &str, g: usize| -> (f64, f64) {
        range(
            &rows
                .iter()
                .map(|r| r[k][g].as_f64().unwrap())
                .collect::<Vec<_>>(),
        )
    };
    let all_order = |k: &str, want: &str| rows.iter().all(|r| r[k] == want);
    writeln!(md, "\n## End to end (32 rows, E37's stream `E37E0001`, Karatsuba)\n\nIdentity (V record = E37's A record on every field except tag, timing, lead scans and the two E40 fields): **{ident_ok}**; every log recovered and every walk correct (A, E25, V): **{health_ok}**.\n").unwrap();
    writeln!(md, "| set | p | seed | arm | calls | fb | V cells/call | V ops/call | A/V 0 | 0.1 | 1 | E25/V 0 | 0.1 | 1 | V/rho 0 | 0.1 | 1 | A/rho 0 | 0.1 | 1 |\n|:--|--:|--:|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|").unwrap();
    for r in &rows {
        let g = |k: &str, i: usize| r[k][i].as_f64().unwrap();
        writeln!(md, "| {} | {} | {} | {} | {} | {} | {:.0} | {:.0} | {:.6} | {:.4} | {:.4} | {:.3} | {:.3} | {:.4} | {} | {} | {} | {} | {} | {} |",
            r["set"].as_str().unwrap(), r["p"], r["seed"], r["arm"].as_str().unwrap(), r["calls"], r["fallbacks"],
            f(r, "v_cells_per_call"), f(r, "v_ops_per_call"),
            g("a_over_v", 0), g("a_over_v", 1), g("a_over_v", 2),
            g("e25_over_v", 0), g("e25_over_v", 1), g("e25_over_v", 2),
            sci(g("v_over_rho", 0)), sci(g("v_over_rho", 1)), sci(g("v_over_rho", 2)),
            sci(g("a_over_rho", 0)), sci(g("a_over_rho", 1)), sci(g("a_over_rho", 2))).unwrap();
    }
    let band = |k: &str| -> Vec<(f64, f64)> { (0..3).map(|g| rr(k, g)).collect() };
    let b_av = band("a_over_v");
    let b_ev = band("e25_over_v");
    let b_av1 = band("a_over_v_sigma1");
    let b_av4 = band("a_over_v_sigma4");
    let b_ev1 = band("e25_over_v_sigma1");
    let b_ev4 = band("e25_over_v_sigma4");
    let b_vr = band("v_over_rho");
    let b_ar = band("a_over_rho");
    let fmt3 = |b: &[(f64, f64)]| -> String {
        format!(
            "`{:.4}`–`{:.4}` / `{:.4}`–`{:.4}` / `{:.4}`–`{:.4}`",
            b[0].0, b[0].1, b[1].0, b[1].1, b[2].0, b[2].1
        )
    };
    let v_vs_a = all_order("order_v_vs_a", "equal at 0, ahead at 0.1 and 1");
    let v_vs_e25 = all_order("order_v_vs_e25", "ahead");
    let v_vs_a_s1 = all_order("order_v_vs_a_sigma1", "equal at 0, ahead at 0.1 and 1")
        || all_order("order_v_vs_a_sigma1", "ahead");
    let v_vs_a_s4 = all_order("order_v_vs_a_sigma4", "equal at 0, ahead at 0.1 and 1");
    let v_vs_e_s1 = all_order("order_v_vs_e25_sigma1", "ahead");
    let v_vs_e_s4 = all_order("order_v_vs_e25_sigma4", "ahead");
    let below_rho = rows
        .iter()
        .filter(|r| (0..3).any(|g| r["v_over_rho"][g].as_f64().unwrap() < 1.0))
        .count();
    writeln!(md, "\n### Band summary (0 / 0.1 / 1 GAE)\n\n| quantity | 0 / 0.1 / 1 GAE | order on all 32 rows |\n|:--|:--|:--|").unwrap();
    writeln!(
        md,
        "| `S_A / S_V` | {} | {} |",
        fmt3(&b_av),
        if v_vs_a {
            "V equal at 0, ahead at 0.1 and 1"
        } else {
            "not as registered"
        }
    )
    .unwrap();
    writeln!(
        md,
        "| `S_E25 / S_V` | {} | {} |",
        fmt3(&b_ev),
        if v_vs_e25 {
            "V ahead at every weight"
        } else {
            "not ahead on every row"
        }
    )
    .unwrap();
    writeln!(
        md,
        "| σ1 `S_A / S_V` | {} | {} |",
        fmt3(&b_av1),
        if v_vs_a_s1 { "same order" } else { "changes" }
    )
    .unwrap();
    writeln!(
        md,
        "| σ1 `S_E25 / S_V` | {} | {} |",
        fmt3(&b_ev1),
        if v_vs_e_s1 { "same order" } else { "changes" }
    )
    .unwrap();
    writeln!(
        md,
        "| σ4 `S_A / S_V` | {} | {} |",
        fmt3(&b_av4),
        if v_vs_a_s4 { "same order" } else { "changes" }
    )
    .unwrap();
    writeln!(
        md,
        "| σ4 `S_E25 / S_V` | {} | {} |",
        fmt3(&b_ev4),
        if v_vs_e_s4 { "same order" } else { "changes" }
    )
    .unwrap();
    writeln!(md, "| `S_V / rho` | `{}`–`{}` / `{}`–`{}` / `{}`–`{}` | rows with V below rho at any weight: {below_rho} |",
        sci(b_vr[0].0), sci(b_vr[0].1), sci(b_vr[1].0), sci(b_vr[1].1), sci(b_vr[2].0), sci(b_vr[2].1)).unwrap();
    writeln!(
        md,
        "| `S_A / rho` | `{}`–`{}` / `{}`–`{}` / `{}`–`{}` | — |",
        sci(b_ar[0].0),
        sci(b_ar[0].1),
        sci(b_ar[1].0),
        sci(b_ar[1].1),
        sci(b_ar[2].0),
        sci(b_ar[2].1)
    )
    .unwrap();
    let fb_e2e_same = rows.iter().all(|r| r["fallbacks"] == r["fallbacks_a"]);

    // ── Negative control: A′ and V′ on E40E0002 (GLS) ──
    let mut neg = Vec::new();
    for &(p, seed) in &GLS {
        let ra = load(&format!("{E37}/gls_chain-counted_p{p}s{seed}.json"));
        let ra2 = load(&format!(
            "{dir}/e2e/gls_chain-counted_E40E0002_p{p}s{seed}.json"
        ));
        let rv2 = load(&format!(
            "{dir}/e2e/gls_chain-profile_E40E0002_p{p}s{seed}.json"
        ));
        for a in ["A", "B"] {
            let (xa, xa2, xv2) = (
                arm_of(&ra, Some(a)),
                arm_of(&ra2, Some(a)),
                arm_of(&rv2, Some(a)),
            );
            let (sa_, sa2, sv2) = (s_of(&xa, 0.0), s_of(&xa2, 0.0), s_of(&xv2, 0.0));
            let d = diff_fields(&xa2, &xv2);
            neg.push(json!({"p": p, "seed": seed, "arm": a,
                "order_a2_vs_a": order(&sa_, &sa2),
                "a_over_a2": (0..3).map(|g| sa_[g] / sa2[g]).collect::<Vec<_>>(),
                "a2_over_v2": (0..3).map(|g| sa2[g] / sv2[g]).collect::<Vec<_>>(),
                "order_v2_vs_a2": order(&sa2, &sv2),
                "cells_per_call_a": f(&xa, "macaulay_entries") / f(&xa, "residuals"),
                "cells_per_call_a2": f(&xa2, "macaulay_entries") / f(&xa2, "residuals"),
                "v2_identity_fields": d}));
        }
    }
    let a2_ranked = neg.iter().all(|r| r["order_a2_vs_a"] == "ahead");
    let a2_orders: Vec<&str> = neg
        .iter()
        .map(|r| r["order_a2_vs_a"].as_str().unwrap())
        .collect();
    let nb = |k: &str, g: usize| -> (f64, f64) {
        range(
            &neg.iter()
                .map(|r| r[k][g].as_f64().unwrap())
                .collect::<Vec<_>>(),
        )
    };
    let v2_band: Vec<(f64, f64)> = (0..3).map(|g| nb("a2_over_v2", g)).collect();
    let v2_ident = neg
        .iter()
        .all(|r| r["v2_identity_fields"].as_array().unwrap().is_empty());
    let v2_order = neg
        .iter()
        .all(|r| r["order_v2_vs_a2"] == "equal at 0, ahead at 0.1 and 1");
    let aa: Vec<(f64, f64)> = (0..3).map(|g| nb("a_over_a2", g)).collect();
    writeln!(md, "\n## Negative control (stream `E40E0002`, 20 GLS rows)\n\nA′ against A (unpaired across streams): orders {:?}; A′ ranked ahead of A: **{a2_ranked}**; `S_A / S_A′` {}.\nV′ against A′ (paired): {}; order as registered on all rows: **{v2_order}**; V′ records = A′'s outside the allowed fields: **{v2_ident}**.\n",
        a2_orders, fmt3(&aa), fmt3(&v2_band)).unwrap();

    // ── Verdicts ──
    let inside = |b: (f64, f64), lo: f64, hi: f64| b.0 >= lo && b.1 <= hi;
    let g204 = sa_ok && ident_ok && ide_ok;
    let g206 = vc0 >= 1.02e5 && vc1 <= 1.04e5 && er0 >= 1.69 && er1 <= 1.73;
    let g207 = op0 >= 1.5e4 && op1 <= 3.0e4;
    let g208 = r0_exact && inside((r10, r11), 1.18, 1.34) && inside((r20, r21), 1.28, 1.48);
    let g208_kill = r20 < 1.15;
    let g209 = vl0 >= 5.0e3 && vl1 <= 7.0e3;
    let g210 = v_vs_a
        && b_av[0].0 == 1.0
        && b_av[0].1 == 1.0
        && inside(b_av[1], 1.18, 1.38)
        && inside(b_av[2], 1.28, 1.48);
    let g211 = v_vs_e25
        && inside(b_ev[0], 2.2, 2.9)
        && inside(b_ev[1], 1.6, 2.0)
        && inside(b_ev[2], 1.30, 1.58);
    let g212 = below_rho == 0;
    let g213 = v_vs_a_s1 && v_vs_a_s4 && v_vs_e_s1 && v_vs_e_s4 && inside(b_av1[2], 1.6, 2.0);
    let g214 = !a2_ranked
        && v2_order
        && v2_ident
        && inside(v2_band[1], 1.18, 1.38)
        && inside(v2_band[2], 1.28, 1.48);
    let g215 = fb_same && fb_e2e_same;
    for (k, v) in [
        ("G2.204_identity", g204),
        ("G2.205_controls", ck_ok),
        ("G2.206_stored_cells", g206),
        ("G2.207_offset_ops", g207),
        ("G2.208_stage_a_band", g208),
        ("G2.208_kill_fired", g208_kill),
        ("G2.209_lead_scans", g209),
        ("G2.210_e2e_vs_a", g210),
        ("G2.211_e2e_vs_e25", g211),
        ("G2.212_rho", g212),
        ("G2.213_sensitivities", g213),
        ("G2.214_negative", g214),
        ("G2.215_fallbacks", g215),
        ("stage_a_identity", sa_ok),
        ("e2e_identity", ident_ok),
        ("existing_configs_identical", ide_ok),
        ("e2e_logs_and_walks", health_ok),
    ] {
        verdict.insert(k.into(), json!(v));
    }
    let ranked = g204 && ck_ok && v_vs_a;
    verdict.insert("V_ranked_vs_A_registered_rule".into(), json!(ranked));
    verdict.insert("V_ranked_vs_E25".into(), json!(g204 && ck_ok && v_vs_e25));
    writeln!(
        md,
        "## Verdicts\n\n```\n{}\n```",
        serde_json::to_string_pretty(&verdict).unwrap()
    )
    .unwrap();
    let summary = json!({
        "verdict": verdict, "stage_a": sa_rows, "rows": rows, "negative": neg,
        "e2e_identity": identity,
        "bands": {"a_over_v": b_av, "e25_over_v": b_ev, "a_over_v_sigma1": b_av1, "e25_over_v_sigma1": b_ev1,
                  "a_over_v_sigma4": b_av4, "e25_over_v_sigma4": b_ev4, "v_over_rho": b_vr, "a_over_rho": b_ar,
                  "negative_a_over_a2": aa, "negative_a2_over_v2": v2_band},
    });
    fs::write(format!("{dir}/tables.md"), md).unwrap();
    fs::write(
        format!("{dir}/summary.json"),
        serde_json::to_string_pretty(&summary).unwrap(),
    )
    .unwrap();
    eprintln!("{}", serde_json::to_string_pretty(&verdict).unwrap());
}
