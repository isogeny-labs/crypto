//! **E40 tables** (`RESEARCH_GLV_INVARIANT_FACTOR_BASES.md` §9.50–§9.51):
//! Stage 0, controls, Stage A and end to end for V (`chain-profile`) against
//! A (`chain-counted`, E37's records on stream `E37E0001`), E25 (`macaulay`,
//! E37's records) and the matched rho (walk (iii)), at `0`, `0.1` and `1`
//! GAE, with σ1 (lead scans priced, every arm) and σ4 (per-call structural
//! work priced, every arm); the negative control A′/V′ on stream
//! `E40E0002`.  Reads recorded JSON only; writes `tables.md` and
//! `summary.json` (the values the report plots) and the verdicts.
//!
//! ```text
//! ./e40_tables experiments/47_macaulay_entries
//! ```

