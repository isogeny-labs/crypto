//! **E35 (§9.40) tables**: Stage 0 (does B's pivot sequence depend on the
//! target?), Stage A (per call) and end to end for the trace solver T
//! (`chain-sparsest-trace`) against E25, A (E27's Karatsuba records), B,
//! B′, B″ (E33's records) and the matched rho (walk (iii) of E27, without
//! the `[d]G` check), at `0`, `0.1` and `1` GAE.  Reads the recorded JSON
//! only; writes `tables.md` and `summary.json` (what the report plots).
//!
//! ```text
//! e35_tables experiments/39_chain_trace
//! ```

use std::env;
use std::fmt::Write as _;
use std::fs;

use serde_json::{json, Value};

const GAE: f64 = 97.0;
const GS: [f64; 3] = [0.0, 0.1, 1.0];
const CURVES: [(u64, u64); 10] = [
    (101, 1),
    (101, 2),
    (149, 1),
    (149, 2),
    (197, 1),
    (197, 2),
    (269, 1),
    (269, 2),
    (397, 1),
    (397, 2),
];
const T: &str = "chain-sparsest-trace";

fn load(path: &str) -> Value {
    serde_json::from_str(&fs::read_to_string(path).unwrap_or_else(|e| panic!("{path}: {e}")))
        .unwrap()
}

fn f(v: &Value, k: &str) -> f64 {
    v[k].as_f64().unwrap_or_else(|| panic!("field {k}"))
}

fn sci(v: f64) -> String {
    if v == 0.0 {
        return "0".into();
    }
    let e = v.abs().log10().floor() as i32;
    format!("`{:.2}·10^{}`", v / 10f64.powi(e), e)
}

fn arm(recs: &Value, a: &str) -> Value {
    recs.as_array()
        .unwrap()
        .iter()
        .find(|r| r["arm"] == a)
        .unwrap_or_else(|| panic!("arm {a}"))
        .clone()
}

/// Fields T may change against E33's B counted record of the same run:
/// its solve multiplications and what derives from them, the selection,
/// learning and lead-scan fields, the tag, and wall times.
fn may_differ_vs_bc(k: &str) -> bool {
    k.ends_with("_ms")
        || matches!(
            k,
            "solver"
                | "pivot_selection"
                | "pivot_selection_ops"
                | "lead_scan_reads"
                | "trace_learning"
                | "solve_muls"
                | "total_muls"
                | "call"
                | "ratio"
                | "macaulay_entries"
        )
}

fn diff_fields(a: &Value, b: &Value, allow: fn(&str) -> bool) -> Vec<String> {
    let (ao, bo) = (a.as_object().unwrap(), b.as_object().unwrap());
    let mut keys: Vec<&String> = ao.keys().chain(bo.keys()).collect();
    keys.sort();
    keys.dedup();
    keys.into_iter()
        .filter(|k| !allow(k) && ao.get(*k) != bo.get(*k))
        .cloned()
        .collect()
}

fn range(v: &[f64]) -> (f64, f64) {
    v.iter()
        .fold((f64::INFINITY, f64::NEG_INFINITY), |(lo, hi), &x| {
            (lo.min(x), hi.max(x))
        })
}

fn r3(v: &[f64]) -> String {
    let (lo, hi) = range(v);
    format!("`{lo:.4}`–`{hi:.4}`")
}

/// `S(g) = total_muls + 97 g (macaulay_entries + selection)` of a record.
fn s_rec(x: &Value) -> Vec<f64> {
    let sel = x["pivot_selection_ops"].as_f64().unwrap_or(0.0);
    GS.iter()
        .map(|g| f(x, "total_muls") + GAE * g * (f(x, "macaulay_entries") + sel))
        .collect()
}

fn median(v: &[u64]) -> f64 {
    let mut s = v.to_vec();
    s.sort_unstable();
    s[s.len() / 2] as f64
}

fn main() {
    let args: Vec<String> = env::args().skip(1).collect();
    let dir = args
        .first()
        .cloned()
        .unwrap_or("experiments/39_chain_trace".into());
    let e25 = "experiments/30_gls_v4";
    let e31 = "experiments/31_solve_cost";
    let e27 = "experiments/32_walk_karatsuba";
    let e33 = "experiments/37_solver_b_pivot_count";
    let mut md = String::new();
    let mut summary = json!({});
    writeln!(md, "# E35 tables (generated by `examples/e35_tables.rs`)\n").unwrap();

    // ── Stage 0 and Stage A ─────────────────────────────────────────────
    let sa = load(&format!("{dir}/stage_a.json"));
    let curves = sa["curves"].as_array().unwrap();
    writeln!(md, "## Stage 0: B's pivot sequence against the curve's learned trace\n").unwrap();
    writeln!(md, "Per curve, over the Stage A calls (B's sequence by B′'s elimination; its digest checked against B counted's). *Contested*: the call's columns with more than one candidate.\n").unwrap();
    writeln!(md, "| p | seed | calls | shape = trace | sequence = trace | distinct sequences | modal sequence calls (= trace) | contested: row = trace | contested: (row, position) = trace | all columns: row = trace | instrument = B | learned = mode |").unwrap();
    writeln!(md, "|--:|--:|--:|--:|--:|--:|:--|--:|--:|--:|--:|--:|").unwrap();
    let mut s0rows = Vec::new();
    for c in curves {
        let s = &c["stage0"];
        let calls = f(s, "calls");
        let cc = f(s, "contested_columns");
        let row = json!({
            "p": c["p"], "seed": c["seed"], "calls": calls,
            "shape_equal": f(s, "shape_equal") / calls,
            "sequence_equal": f(s, "sequence_equal") / calls,
            "distinct": s["distinct_sequences"],
            "modal_share": f(s, "modal_sequence_calls") / calls,
            "contested_row_agree": f(s, "contested_row_agree") / cc,
            "contested_choice_agree": f(s, "contested_choice_agree") / cc,
            "columns_row_agree": f(s, "columns_row_agree") / f(s, "columns"),
            "contested_per_call": cc / calls,
        });
        writeln!(
            md,
            "| {} | {} | {} | {:.1} % | {:.1} % | {} | {} ({}) | {:.2} % | {:.2} % | {:.2} % | {} | {}/3 |",
            c["p"], c["seed"], calls,
            100.0 * f(&row, "shape_equal"), 100.0 * f(&row, "sequence_equal"),
            s["distinct_sequences"], s["modal_sequence_calls"], s["modal_equals_trace"],
            100.0 * f(&row, "contested_row_agree"), 100.0 * f(&row, "contested_choice_agree"),
            100.0 * f(&row, "columns_row_agree"), s["instrument_digest_equal_b"],
            s["learning_sequences_equal_to_mode"]
        )
        .unwrap();
        s0rows.push(row);
    }
    if let Some(x) = sa["cross"].as_object() {
        let m = x["contested_agree"].as_array().unwrap();
        let se = x["sequence_equal"].as_array().unwrap();
        let (mut off, mut offs) = (Vec::new(), Vec::new());
        for i in 0..m.len() {
            for j in 0..m.len() {
                if i != j {
                    off.push(m[i][j].as_f64().unwrap());
                    offs.push(se[i][j].as_f64().unwrap());
                }
            }
        }
        writeln!(md, "\nAcross curves (calls of one curve against another curve's trace): contested-column agreement {}, whole-sequence equality {}.\n", r3(&off), r3(&offs)).unwrap();
        summary["stage0_cross"] = json!({"contested_agree": x["contested_agree"], "sequence_equal": x["sequence_equal"], "curves": x["curves"]});
    }
    summary["stage0"] = json!(s0rows);

    writeln!(md, "## Stage A: per call (means over all calls; fallbacks charged)\n").unwrap();
    writeln!(md, "Solvers: {}. Agreement with the existing solver (solutions, degree, outcome, decomposition set) per solver.\n", curves[0]["solvers"]).unwrap();
    writeln!(md, "| p | seed | calls | agree | T digest = B | contested / call | misses / call | calls with a miss | shape fallbacks | T selection / call | learning (muls; native) |").unwrap();
    writeln!(md, "|--:|--:|--:|:--|--:|--:|--:|--:|--:|--:|:--|").unwrap();
    let mut sarows = Vec::new();
    for c in curves {
        let calls = f(c, "calls");
        let l = &c["learning"];
        let st = &c["summaries"][4];
        writeln!(
            md,
            "| {} | {} | {} | {} | {} | {:.1} | {:.2} | {} | {} | {:.0} | {} ; {} |",
            c["p"], c["seed"], calls, c["agree"], c["trace_digest_equal_b"],
            f(c, "trace_contested") / calls, f(c, "trace_misses") / calls,
            c["trace_calls_with_miss"], c["trace_shape_fallbacks"], f(st, "sel_total_mean"),
            sci(f(l, "muls")), sci(f(l, "entries") + f(l, "selection_ops"))
        )
        .unwrap();
    }
    writeln!(md, "\n| p | seed | `C` median A | B | B″ | T | T / B | A / T | `S_A/S_T` 0 | 0.1 | 1 | `S_B/S_T` 0.1 | 1 | `S_B″/S_T` 0.1 | 1 | lead scans priced: `S_A/S_T` 0.1 | 1 |").unwrap();
    writeln!(md, "|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|").unwrap();
    for c in curves {
        let su = c["summaries"].as_array().unwrap();
        let (a, b, e, t) = (&su[1], &su[2], &su[3], &su[4]);
        let med = |k: usize| median(&c["arms"][k]["call"].as_array().unwrap().iter().map(|v| v.as_u64().unwrap()).collect::<Vec<_>>());
        let sm = |x: &Value, k: &str| -> Vec<f64> { x[k].as_array().unwrap().iter().map(|v| v.as_f64().unwrap()).collect() };
        let st_l = sm(t, "s_mean_learning");
        let ratio = |x: &Value| -> Vec<f64> { (0..3).map(|g| sm(x, "s_mean")[g] / st_l[g]).collect() };
        let (ra, rb, re) = (ratio(a), ratio(b), ratio(e));
        // Lead scans for every arm; the existing solver's taken as A's.
        let tl = sm(t, "s_mean_lead");
        let ral: Vec<f64> = (0..3).map(|g| sm(a, "s_mean_lead")[g] / tl[g]).collect();
        let (ma, mb, me, mt) = (med(1), med(2), med(3), med(4));
        writeln!(
            md,
            "| {} | {} | {:.0} | {:.0} | {:.0} | {:.0} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} |",
            c["p"], c["seed"], ma, mb, me, mt, mt / mb, ma / mt, ra[0], ra[1], ra[2], rb[1], rb[2], re[1], re[2], ral[1], ral[2]
        )
        .unwrap();
        sarows.push(json!({"p": c["p"], "seed": c["seed"],
            "c_median": {"A": ma, "B": mb, "Bpp": me, "T": mt},
            "t_over_b_median": mt / mb, "a_over_t_median": ma / mt,
            "A_over_T": ra, "B_over_T": rb, "Bpp_over_T": re, "A_over_T_lead": ral,
            "existing_over_T": ratio(&su[0]),
            "t_selection_per_call": f(t, "sel_total_mean"),
            "t_misses_per_call": f(c, "trace_misses") / f(c, "calls"),
            "t_contested_per_call": f(c, "trace_contested") / f(c, "calls"),
            "t_digest_equal_b": c["trace_digest_equal_b"],
            "learning": c["learning"],
            "agree": c["agree"]}));
    }
    summary["stage_a"] = json!(sarows);

    // ── Controls ─────────────────────────────────────────────────────────
    if let Ok(s) = fs::read_to_string(format!("{dir}/checks.json")) {
        let ck: Value = serde_json::from_str(&s).unwrap();
        writeln!(md, "\n## Controls (`e35_checks`)\n").unwrap();
        writeln!(md, "| p | seed | clean = existing | corruption | detected | outputs = existing | unchecked: abort | chain fallback | wrong | fine |").unwrap();
        writeln!(md, "|--:|--:|--:|:--|--:|--:|--:|--:|--:|--:|").unwrap();
        for c in ck.as_array().unwrap() {
            for k in c["controls"].as_array().unwrap() {
                writeln!(
                    md,
                    "| {} | {} | {} | {} | {}/{} | {}/{} | {} | {} | {} | {} |",
                    c["p"], c["seed"], c["clean_outputs_equal"], k["kind"].as_str().unwrap(),
                    k["detected"], k["calls"], k["outputs_equal"], k["calls"], k["unchecked_abort"],
                    k["unchecked_fallback"], k["unchecked_wrong"], k["unchecked_fine"]
                )
                .unwrap();
            }
        }
        summary["checks"] = ck;
    }

    // ── End to end ───────────────────────────────────────────────────────
    let summary27 = load(&format!("{e27}/summary.json"));
    let mut rows = Vec::new();
    let mut identity = Vec::new();
    let have = |p: u64, s: u64| {
        std::path::Path::new(&format!("{dir}/e2e_{T}_karatsuba_p{p}s{s}.json")).exists()
    };
    for (p, seed) in CURVES {
        if !have(p, seed) {
            continue;
        }
        let rt = load(&format!("{dir}/e2e_{T}_karatsuba_p{p}s{seed}.json"));
        let r25 = load(&format!("{e25}/p{p}s{seed}.json"));
        let r31 = load(&format!("{e31}/e2e_chain-sparsest_p{p}s{seed}.json"));
        let r27 = load(&format!("{e27}/e2e_chain_karatsuba_p{p}s{seed}.json"));
        let rb = load(&format!("{e33}/e2e_chain-sparsest-counted_karatsuba_p{p}s{seed}.json"));
        let rbi = load(&format!("{e33}/e2e_chain-sparsest-inc_karatsuba_p{p}s{seed}.json"));
        let rbe = load(&format!("{e33}/e2e_chain-sparsest-est_karatsuba_p{p}s{seed}.json"));
        for a in ["A", "B"] {
            let (x, x25, x31, x27) = (arm(&rt, a), arm(&r25, a), arm(&r31, a), arm(&r27, a));
            let (xb, xbi, xbe) = (arm(&rb, a), arm(&rbi, a), arm(&rbe, a));
            let s27 = summary27["rows"]
                .as_array()
                .unwrap()
                .iter()
                .find(|r| r["p"] == p && r["seed"] == seed && r["arm"] == a)
                .unwrap()
                .clone();
            let (rho, steps) = (f(&s27, "rho_e27"), f(&s27, "walk_steps"));
            let rho_g: Vec<f64> = GS.iter().map(|g| rho + GAE * g * steps).collect();
            let s_e25: Vec<f64> = GS
                .iter()
                .map(|g| f(&x25, "total_muls") + GAE * g * f(&x25, "macaulay_entries"))
                .collect();
            let (s_t, s_a, s_b, s_bi, s_be) = (s_rec(&x), s_rec(&x27), s_rec(&xb), s_rec(&xbi), s_rec(&xbe));
            // Schoolbook S of T: T's Karatsuba total shifted by the
            // schoolbook re-pricing measured on B (E31 B's total minus B
            // counted's Karatsuba total: the same calls), as E33 did.
            let shift = f(&x31, "total_muls") - f(&xb, "total_muls");
            let s_t_school: Vec<f64> = s_t.iter().map(|v| v + shift).collect();
            let over = |num: &[f64], den: &[f64]| -> Vec<f64> { (0..3).map(|g| num[g] / den[g]).collect() };
            let d = diff_fields(&xb, &x, may_differ_vs_bc);
            let l = &x["trace_learning"];
            identity.push(json!({"p": p, "seed": seed, "arm": a, "fields_differing_from_b_counted": d}));
            rows.push(json!({
                "p": p, "seed": seed, "arm": a, "residuals": x["residuals"],
                "selection_ops": x["pivot_selection_ops"], "selection_parts": x["pivot_selection"],
                "selection_per_call": (f(&x, "pivot_selection_ops") - f(l, "selection_ops")) / f(&x, "residuals"),
                "learning_muls": l["muls"], "learning_native": f(l, "selection_ops") + f(l, "entries"),
                "replay_misses_per_echelon": f(l, "replay_misses") / f(l, "replay_echelons"),
                "replay_contested_per_echelon": f(l, "replay_contested") / f(l, "replay_echelons"),
                "replay_shape_fallbacks": l["replay_shape_fallbacks"],
                "solve_T_over_B": f(&x, "solve_muls") / f(&xb, "solve_muls"),
                "S_T": s_t, "S_T_school": s_t_school,
                "E25_over_T": over(&s_e25, &s_t_school),
                "A_over_T": over(&s_a, &s_t),
                "B_over_T": over(&s_b, &s_t),
                "Bp_over_T": over(&s_bi, &s_t),
                "Bpp_over_T": over(&s_be, &s_t),
                "T_over_rho": over(&s_t, &rho_g),
                "A_over_rho": over(&s_a, &rho_g),
                "Bpp_over_rho": over(&s_be, &rho_g),
            }));
        }
    }
    writeln!(md, "\n## End to end (E25's ten curves, both arms; Karatsuba products)\n").unwrap();
    writeln!(md, "`S_E25/S_T`: schoolbook (E25's records against T's total shifted by the schoolbook re-pricing measured on B, as E33 did; T's learning stays Karatsuba-priced); `S_X/S_T` for X = A (E27), B, B′, B″ (E33): Karatsuba; `S_T/rho`: walk (iii) of E27 without the `[d]G` check.  Band: one GAE (`97`) per Macaulay entry, per selection operation and per walk step; T's learning is inside its record's totals.\n").unwrap();
    writeln!(md, "| p | seed | arm | calls | T sel / call | learning muls; native | misses / echelon | solve T/B | E25/T 0 | 0.1 | 1 | A/T 0 | 0.1 | 1 | B/T 0 | 0.1 | 1 | B″/T 0 | 0.1 | 1 | T/rho 0 | 0.1 | 1 |").unwrap();
    writeln!(md, "|--:|--:|:--|--:|--:|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|").unwrap();
    let g = |r: &Value, k: &str, i: usize| r[k][i].as_f64().unwrap();
    for r in &rows {
        writeln!(
            md,
            "| {} | {} | {} | {} | {:.0} | {} ; {} | {:.3} | {:.4} | {:.3} | {:.4} | {:.4} | {:.3} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {:.4} | {} | {} | {} |",
            r["p"], r["seed"], r["arm"].as_str().unwrap(), r["residuals"], f(r, "selection_per_call"),
            sci(f(r, "learning_muls")), sci(f(r, "learning_native")), f(r, "replay_misses_per_echelon"),
            f(r, "solve_T_over_B"),
            g(r, "E25_over_T", 0), g(r, "E25_over_T", 1), g(r, "E25_over_T", 2),
            g(r, "A_over_T", 0), g(r, "A_over_T", 1), g(r, "A_over_T", 2),
            g(r, "B_over_T", 0), g(r, "B_over_T", 1), g(r, "B_over_T", 2),
            g(r, "Bpp_over_T", 0), g(r, "Bpp_over_T", 1), g(r, "Bpp_over_T", 2),
            sci(g(r, "T_over_rho", 0)), sci(g(r, "T_over_rho", 1)), sci(g(r, "T_over_rho", 2))
        )
        .unwrap();
    }
    if !rows.is_empty() {
        writeln!(md, "\n### Ranges over the {} rows and ranks across the band\n", rows.len()).unwrap();
        writeln!(md, "| quantity | `0` GAE | `0.1` GAE | `1` GAE | T ahead at every weight on every row? |").unwrap();
        writeln!(md, "|:--|:--|:--|:--|:--|").unwrap();
        let mut ranks = json!({});
        for (k, label) in [
            ("E25_over_T", "`S_E25 / S_T`"),
            ("A_over_T", "`S_A / S_T`"),
            ("B_over_T", "`S_B / S_T`"),
            ("Bp_over_T", "`S_B′ / S_T`"),
            ("Bpp_over_T", "`S_B″ / S_T`"),
        ] {
            let per: Vec<Vec<f64>> = (0..3).map(|i| rows.iter().map(|r| g(r, k, i)).collect()).collect();
            let ahead = per.iter().all(|v| v.iter().all(|&x| x > 1.0));
            let at: Vec<bool> = per.iter().map(|v| v.iter().all(|&x| x > 1.0)).collect();
            let behind: Vec<bool> = per.iter().map(|v| v.iter().all(|&x| x < 1.0)).collect();
            writeln!(md, "| {label} | {} | {} | {} | {} |", r3(&per[0]), r3(&per[1]), r3(&per[2]),
                if ahead { "**yes: T ranked ahead**".to_string() } else { format!("no (T ahead on all rows at {at:?}; behind on all rows at {behind:?})") }).unwrap();
            ranks[k] = json!({"ahead_all": ahead, "ahead_at": at, "behind_at": behind,
                "ranges": per.iter().map(|v| { let (lo, hi) = range(v); json!([lo, hi]) }).collect::<Vec<_>>()});
        }
        for (k, label) in [("T_over_rho", "`S_T / rho`"), ("A_over_rho", "`S_A / rho`"), ("Bpp_over_rho", "`S_B″ / rho`")] {
            let per: Vec<(f64, f64)> = (0..3).map(|i| range(&rows.iter().map(|r| g(r, k, i)).collect::<Vec<_>>())).collect();
            writeln!(md, "| {label} | {}–{} | {}–{} | {}–{} | rho ahead on every row: {} |",
                sci(per[0].0), sci(per[0].1), sci(per[1].0), sci(per[1].1), sci(per[2].0), sci(per[2].1),
                per.iter().all(|x| x.0 > 1.0)).unwrap();
            ranks[k] = json!(per.iter().map(|x| json!([x.0, x.1])).collect::<Vec<_>>());
        }
        summary["ranks"] = ranks;
        let bad: Vec<&Value> = identity
            .iter()
            .filter(|r| !r["fields_differing_from_b_counted"].as_array().unwrap().is_empty())
            .collect();
        writeln!(md, "\nIdentity against E33's B counted records (fields other than the solve's multiplications and what derives from them, selection, learning, lead scans, entries, tag and wall times): {} of {} rows identical{}.\n",
            identity.len() - bad.len(), identity.len(),
            if bad.is_empty() { String::new() } else { format!("; differing: {}", serde_json::to_string(&bad).unwrap()) }).unwrap();
    }
    summary["e2e"] = json!(rows);
    summary["identity_vs_b_counted"] = json!(identity);
    fs::write(format!("{dir}/tables.md"), md).unwrap();
    fs::write(
        format!("{dir}/summary.json"),
        serde_json::to_string_pretty(&summary).unwrap(),
    )
    .unwrap();
    eprintln!("wrote {dir}/tables.md, {dir}/summary.json");
}
