//! **E41 tables (§9.52/§9.53)**: identity, controls, steps against the ideal, the §5a band with the
//! registered noise rule, the A/A floor, the fix, the corrected reference and its consequences for
//! E18's `ψ` rows and the IC rows (solver A / E27).  Reads `experiments/48_twist24_shortfall/*.json`
//! and E27's `experiments/32_walk_karatsuba/summary.json`; writes `tables.md` and `summary.json`.
//!
//! ```text
//! e41_tables
//! ```

use std::collections::BTreeMap;
use std::fs;

use serde_json::{json, Value};

const DIR: &str = "experiments/48_twist24_shortfall";
const E27: &str = "experiments/32_walk_karatsuba/summary.json";
const WEIGHTS: [f64; 3] = [0.0, 0.1, 1.0];
const GAE: f64 = 97.0;
const KINDS: [&str; 5] = ["cmp", "neg", "modn", "hash", "table"];

fn load(name: &str) -> Value {
    let path = format!("{DIR}/{name}");
    serde_json::from_str(&fs::read_to_string(&path).expect(&path)).expect(&path)
}

fn u(v: &Value) -> f64 {
    v.as_u64().unwrap_or_else(|| panic!("count: {v}")) as f64
}

fn mean_se(xs: &[f64]) -> (f64, f64) {
    let k = xs.len() as f64;
    let m = xs.iter().sum::<f64>() / k;
    let v = xs.iter().map(|x| (x - m) * (x - m)).sum::<f64>() / (k - 1.0).max(1.0);
    (m, (v / k).sqrt())
}

/// One walk's numbers.
#[derive(Clone, Debug)]
struct W {
    muls: f64,
    native: f64,
    steps: f64,
    ideal: f64,
    correct: bool,
    fruitless: f64,
    redirects: f64,
    added: (u64, u64),
}

impl W {
    fn cost(&self, w: f64) -> f64 {
        self.muls + w * GAE * self.native
    }
}

/// (p, arm) -> walks; n per p.
type Data = (BTreeMap<(u64, String), Vec<W>>, BTreeMap<u64, u64>);

fn read(names: &[&str]) -> Data {
    let mut d: BTreeMap<(u64, String), Vec<W>> = BTreeMap::new();
    let mut ns = BTreeMap::new();
    for name in names {
        for c in load(name).as_array().unwrap() {
            let p = c["p"].as_u64().unwrap();
            ns.insert(p, c["n"].as_u64().unwrap());
            for r in c["walks"].as_array().unwrap() {
                let run = &r["walk"]["run"];
                let sf = &r["shortfall"];
                let w = W {
                    muls: u(&run["fp_muls"]) - u(&run["verify_fp_muls"]),
                    native: KINDS.iter().map(|k| u(&r["walk"]["ops"][*k])).sum(),
                    steps: u(&run["steps"]),
                    ideal: sf["ideal_steps"].as_f64().unwrap(),
                    correct: run["correct"].as_bool().unwrap(),
                    fruitless: u(&sf["fruitless"]),
                    redirects: u(&sf["redirects"]),
                    added: (
                        sf["added_group_ops"].as_u64().unwrap(),
                        sf["added_modn"].as_u64().unwrap(),
                    ),
                };
                d.entry((p, r["label"].as_str().unwrap().to_string()))
                    .or_default()
                    .push(w);
            }
        }
    }
    (d, ns)
}

/// Pooled cost of an arm at weight `w`: Σ_p mean/√n, with its standard error.
fn pooled(data: &Data, arm: &str, w: f64) -> (f64, f64) {
    let (d, ns) = data;
    let (mut s, mut v) = (0.0, 0.0);
    for (&p, &n) in ns {
        let xs: Vec<f64> = d[&(p, arm.to_string())].iter().map(|x| x.cost(w)).collect();
        let (m, se) = mean_se(&xs);
        let r = (n as f64).sqrt();
        s += m / r;
        v += (se / r) * (se / r);
    }
    (s, v.sqrt())
}

/// Ratio a/b with a 95 % interval (delta method, arms independent).
fn ratio(data_a: &Data, a: &str, data_b: &Data, b: &str, w: f64) -> (f64, f64, f64) {
    let (x, sx) = pooled(data_a, a, w);
    let (y, sy) = pooled(data_b, b, w);
    let r = x / y;
    let rel = ((sx / x).powi(2) + (sy / y).powi(2)).sqrt();
    (r, r * (1.0 - 1.96 * rel), r * (1.0 + 1.96 * rel))
}

fn per_curve(data: &Data, a: &str, b: &str, w: f64) -> Vec<f64> {
    let (d, ns) = data;
    ns.keys()
        .map(|&p| {
            let m = |arm: &str| {
                mean_se(
                    &d[&(p, arm.to_string())]
                        .iter()
                        .map(|x| x.cost(w))
                        .collect::<Vec<_>>(),
                )
                .0
            };
            m(a) / m(b)
        })
        .collect()
}

fn main() {
    let school = read(&["main_school.json"]);
    let aa = read(&["aa_school.json"]);
    let kar = read(&["main_karatsuba.json"]);
    let control = read(&["control.json"]);
    let ident = load("identity.json");
    let mut md: Vec<String> = vec!["# E41 tables (§9.53)\n".into(),
        "Generated by `examples/e41_tables.rs` from this directory's records. Band: cost(w) = F_p multiplications (set-up included, `[d]G` check excluded) + w·97·(cmp+neg+modn+hash+table); pooled = Σ over the eight curves of mean cost/√n; ratio = first arm / second arm. Resolved = 95 % interval (delta method) excludes 1 at all three weights and |ratio − 1| exceeds the A/A deviation at each weight.\n".into()];
    let mut verdicts: Vec<(String, String, bool)> = Vec::new();

    // G2.216 identity.
    let (cmpd, same) = (u(&ident["compared"]), u(&ident["byte_identical"]));
    md.push(format!("## Identity (fix off)\n\n{same}/{cmpd} E34 Stage R records recomputed byte-identical (serialized), value-identical {}.\n", u(&ident["value_identical"])));
    verdicts.push((
        "G2.216".into(),
        format!("{same}/{cmpd} byte-identical"),
        same == cmpd && cmpd == 1280.0,
    ));

    // G2.217 correctness.
    let all: Vec<&W> = school
        .0
        .values()
        .chain(aa.0.values())
        .chain(kar.0.values())
        .flatten()
        .collect();
    let wrong = all.iter().filter(|w| !w.correct).count();
    let n_s = school.0.values().map(|v| v.len()).sum::<usize>()
        + aa.0.values().map(|v| v.len()).sum::<usize>();
    let n_k = kar.0.values().map(|v| v.len()).sum::<usize>();
    md.push(format!(
        "## Correctness\n\n{} schoolbook and {n_k} Karatsuba walks; wrong logs: {wrong}.\n",
        n_s
    ));
    verdicts.push((
        "G2.217".into(),
        format!("{wrong} wrong of {} walks", all.len()),
        wrong == 0 && n_s == 6144 && n_k == 1280,
    ));

    // G2.218 positive control.
    let cw: Vec<&W> = control.0.values().flatten().collect();
    let flagged = cw.iter().filter(|w| !w.correct).count();
    md.push(format!("## Positive control (F̸, p = 241, 541, 16 seeds each)\n\nWrong log flagged on {flagged}/{} walks.\n", cw.len()));
    verdicts.push((
        "G2.218".into(),
        format!("{flagged}/{}", cw.len()),
        flagged >= 31,
    ));

    // Steps against the ideal.
    md.push("## Steps against the ideal √(π(n−1)/2m) (schoolbook, 128 walks per curve and arm)\n\n| arm | walks | steps/ideal (mean ± SE) | fruitless / step | redirects / step |\n|:--|--:|:--|--:|--:|".into());
    let mut so = BTreeMap::new();
    for (arm, data) in [
        ("O6B", &school),
        ("O24", &school),
        ("O24F", &school),
        ("O24AA", &aa),
    ] {
        let ws: Vec<&W> = data
            .0
            .iter()
            .filter(|(k, _)| k.1 == arm)
            .flat_map(|(_, v)| v)
            .collect();
        let (m, se) = mean_se(&ws.iter().map(|w| w.steps / w.ideal).collect::<Vec<_>>());
        let st: f64 = ws.iter().map(|w| w.steps).sum();
        let fr: f64 = ws.iter().map(|w| w.fruitless).sum();
        let rd: f64 = ws.iter().map(|w| w.redirects).sum();
        md.push(format!(
            "| {arm} | {} | {m:.4} ± {se:.4} | {:.2e} | {:.5} |",
            ws.len(),
            fr / st,
            rd / st
        ));
        so.insert(arm.to_string(), json!({"walks": ws.len(), "steps_over_ideal": m, "se": se, "fruitless_per_step": fr / st, "redirects_per_step": rd / st}));
    }
    let mut per_curve_steps = serde_json::Map::new();
    for (arm, data) in [
        ("O6B", &school),
        ("O24", &school),
        ("O24F", &school),
        ("O24AA", &aa),
    ] {
        let rows: Vec<Value> = data
            .1
            .keys()
            .map(|&p| {
                let xs: Vec<f64> = data.0[&(p, arm.to_string())]
                    .iter()
                    .map(|w| w.steps / w.ideal)
                    .collect();
                let (m, se) = mean_se(&xs);
                json!({"p": p, "walks": xs.len(), "steps_over_ideal": m, "se": se})
            })
            .collect();
        per_curve_steps.insert(arm.to_string(), Value::Array(rows));
    }
    let steps_pooled = |data: &Data, arm: &str| -> f64 {
        data.1
            .iter()
            .map(|(&p, &n)| {
                mean_se(
                    &data.0[&(p, arm.to_string())]
                        .iter()
                        .map(|w| w.steps)
                        .collect::<Vec<_>>(),
                )
                .0 / (n as f64).sqrt()
            })
            .sum()
    };
    let steps_ratio = steps_pooled(&school, "O6B") / steps_pooled(&school, "O24");
    let steps_ratio_aa = steps_pooled(&school, "O6B") / steps_pooled(&aa, "O24AA");
    md.push(format!("\nSteps ratio order 6 / order 24, pooled per √n: {steps_ratio:.4} (main stream), {steps_ratio_aa:.4} (order 24 on the A/A stream). E34: 1.701.\n"));
    let o6 = so["O6B"]["steps_over_ideal"].as_f64().unwrap();
    let o24 = so["O24"]["steps_over_ideal"].as_f64().unwrap();
    verdicts.push((
        "G2.219".into(),
        format!("O6 {o6:.4}, O24 {o24:.4}, ratio {steps_ratio:.4}"),
        (0.98..=1.08).contains(&o6)
            && (0.98..=1.08).contains(&o24)
            && (1.85..=2.10).contains(&steps_ratio),
    ));

    // A/A floor.
    let aa_r: Vec<(f64, f64, f64)> = WEIGHTS
        .iter()
        .map(|&w| ratio(&school, "O24", &aa, "O24AA", w))
        .collect();
    let floor: Vec<f64> = aa_r.iter().map(|r| (r.0 - 1.0).abs()).collect();
    verdicts.push((
        "G2.220".into(),
        format!("{:.4} / {:.4} / {:.4}", aa_r[0].0, aa_r[1].0, aa_r[2].0),
        aa_r.iter().all(|r| (0.94..=1.06).contains(&r.0)),
    ));

    // The band.
    let mut band = serde_json::Map::new();
    md.push("## The §5a band, pooled (> 1: the second arm is cheaper)\n\n| ratio | arithmetic | 0 GAE [95 %] | 0.1 GAE [95 %] | 1 GAE [95 %] | resolved | curves second arm cheaper at every weight / first / unresolved |\n|:--|:--|:--|:--|:--|:--|:--|".into());
    let pairs = [
        ("O6B", "O24"),
        ("O6C", "O24"),
        ("O6B", "O24L"),
        ("O6C", "O24L"),
        ("O24", "O24F"),
        ("O6B", "O24F"),
        ("O6C", "O24F"),
        ("O24L", "O24"),
    ];
    let mut resolved_of = BTreeMap::new();
    for (lab, data) in [("schoolbook", &school), ("karatsuba", &kar)] {
        let rows_aa = [("O24", "O24AA")];
        for (a, b) in pairs.iter().copied().chain(if lab == "schoolbook" {
            rows_aa.to_vec()
        } else {
            vec![]
        }) {
            let rs: Vec<(f64, f64, f64)> = WEIGHTS
                .iter()
                .map(|&w| {
                    if b == "O24AA" {
                        ratio(&school, a, &aa, b, w)
                    } else {
                        ratio(data, a, data, b, w)
                    }
                })
                .collect();
            let resolved = b != "O24AA"
                && (rs.iter().all(|r| r.1 > 1.0) || rs.iter().all(|r| r.2 < 1.0))
                && rs.iter().zip(&floor).all(|(r, f)| (r.0 - 1.0).abs() > *f);
            let (mut c2, mut c1) = (0, 0);
            let mut pcs: Vec<Vec<f64>> = Vec::new();
            if b != "O24AA" {
                pcs = WEIGHTS.iter().map(|&w| per_curve(data, a, b, w)).collect();
                for i in 0..8 {
                    if pcs.iter().all(|v| v[i] > 1.0) {
                        c2 += 1
                    } else if pcs.iter().all(|v| v[i] < 1.0) {
                        c1 += 1
                    }
                }
            }
            md.push(format!(
                "| {a} / {b} | {lab} | {} | {resolved} | {c2} / {c1} / {} |",
                rs.iter()
                    .map(|r| format!("{:.3} [{:.3}, {:.3}]", r.0, r.1, r.2))
                    .collect::<Vec<_>>()
                    .join(" | "),
                8 - c2 - c1
            ));
            resolved_of.insert(format!("{a}/{b}|{lab}"), (rs.clone(), resolved, c2));
            band.insert(format!("{a}/{b}|{lab}"), json!({"rows": rs.iter().zip(WEIGHTS).map(|(r, w)| json!({"weight": w, "ratio": r.0, "lo": r.1, "hi": r.2})).collect::<Vec<_>>(), "resolved": resolved, "curves_second_cheaper": c2, "curves_first_cheaper": c1, "per_curve": pcs}));
        }
    }

    // F.
    let fw: Vec<&W> = school
        .0
        .iter()
        .chain(kar.0.iter())
        .filter(|(k, _)| k.1 == "O24F")
        .flat_map(|(_, v)| v)
        .collect();
    let added_ok = fw.iter().all(|w| w.added == (32, 64));
    let others_zero = school
        .0
        .iter()
        .filter(|(k, _)| k.1 != "O24F")
        .flat_map(|(_, v)| v)
        .all(|w| w.added == (0, 0));
    let f_steps = so["O24F"]["steps_over_ideal"].as_f64().unwrap();
    let f_gain = (o24 - f_steps) / o24 * 100.0;
    md.push(format!("\n## Fix F\n\nAdded set-up per O24F walk exactly 32 group additions and 64 mod-n operations: {added_ok} ({} walks); other arms add nothing: {others_zero}. Steps/ideal O24 {o24:.4}, O24F {f_steps:.4}: F lower by {f_gain:.2} %.\n", fw.len()));
    verdicts.push((
        "G2.221".into(),
        format!("F lower by {f_gain:.2} %; added (32, 64) on every F walk: {added_ok}"),
        (-2.0..=3.0).contains(&f_gain) && added_ok && others_zero,
    ));
    let f_res = &resolved_of["O24/O24F|schoolbook"];
    verdicts.push((
        "G2.222".into(),
        format!(
            "O24/O24F {:.3} / {:.3} / {:.3}, resolved {}",
            f_res.0[0].0, f_res.0[1].0, f_res.0[2].0, f_res.1
        ),
        !f_res.1,
    ));

    let band_check = |key: &str, lo: [f64; 3], hi: [f64; 3]| -> (String, bool) {
        let (rs, res, _) = &resolved_of[key];
        (format!("{:.3} / {:.3} / {:.3} (95 %: [{:.3}, {:.3}], [{:.3}, {:.3}], [{:.3}, {:.3}]), resolved {res}", rs[0].0, rs[1].0, rs[2].0, rs[0].1, rs[0].2, rs[1].1, rs[1].2, rs[2].1, rs[2].2),
         *res && (0..3).all(|i| rs[i].0 >= lo[i] && rs[i].0 <= hi[i]))
    };
    let (s, ok) = band_check("O6B/O24|schoolbook", [1.65, 1.32, 1.18], [1.95, 1.56, 1.40]);
    verdicts.push(("G2.223".into(), s, ok));
    let (s, ok) = band_check("O6C/O24|schoolbook", [1.58, 1.23, 1.08], [1.88, 1.45, 1.28]);
    verdicts.push(("G2.224".into(), s, ok));
    let c2 = resolved_of["O6C/O24|schoolbook"].2;
    verdicts.push(("G2.225".into(), format!("{c2}/8 curves"), c2 >= 7));
    let same_orders = ["O6B/O24", "O6C/O24"].iter().all(|k| {
        let (s, k2) = (
            &resolved_of[&format!("{k}|schoolbook")].0,
            &resolved_of[&format!("{k}|karatsuba")].0,
        );
        s.iter().zip(k2).all(|(a, b)| (a.0 > 1.0) == (b.0 > 1.0))
    });
    verdicts.push((
        "G2.226".into(),
        format!("same orders in Karatsuba: {same_orders}"),
        same_orders,
    ));

    // Strongest order-24 arm per weight, and E18's ψ rows.
    md.push("\n## Strongest walks and E18's ψ rows (schoolbook, pooled)\n\n| GAE | strongest order 6 | strongest order 24 | O6B / strongest | O6B / O24 (band-ranked) | E34's O6B / cheap | handover shift (bits, O6B/O24) |\n|--:|:--|:--|--:|--:|--:|--:|".into());
    let e34 = [1.563, 1.254, 1.126];
    let mut e18 = Vec::new();
    for (i, &w) in WEIGHTS.iter().enumerate() {
        let c = |a: &str| pooled(&school, a, w).0;
        let b6 = ["O6B", "O6C"]
            .into_iter()
            .min_by(|a, b| c(a).total_cmp(&c(b)))
            .unwrap();
        let b24 = ["O24", "O24L", "O24F"]
            .into_iter()
            .min_by(|a, b| c(a).total_cmp(&c(b)))
            .unwrap();
        let r_s = c("O6B") / c(b24);
        let r_b = c("O6B") / c("O24");
        md.push(format!(
            "| {w} | {b6} | {b24} | {r_s:.3} | {r_b:.3} | {} | {:.2} |",
            e34[i],
            4.0 * r_b.log2()
        ));
        e18.push(json!({"weight": w, "strongest_order6": b6, "strongest_order24": b24, "o6b_over_strongest": r_s, "o6b_over_o24": r_b, "e34_o6b_over_cheap": e34[i], "handover_shift_bits": 4.0 * r_b.log2(), "e34_handover_shift_bits": 4.0 * f64::log2(e34[i])}));
    }

    // IC rows (solver A / E27): the reference walk (iii) is unchanged.
    let e27: Value = serde_json::from_str(&fs::read_to_string(E27).expect(E27)).unwrap();
    md.push("\n## IC rows (E31 solver A / B with E27 products, GLS curves): distance to the matched rho, walk (iii)\n\nOrder 24 does not apply on these curves and E41 changes no walk there, so the corrected reference equals E27's walk (iii): factor 1 exactly. Old and new columns side by side.\n\n| p | seed | arm | S / rho before (0, 0.1, 1 GAE) | S / rho after E41 (0, 0.1, 1 GAE) | factor |\n|--:|--:|:--|:--|:--|--:|".into());
    let mut ic = Vec::new();
    for r in e27["rows"].as_array().unwrap() {
        let d: Vec<f64> = r["dist_new"]
            .as_array()
            .unwrap()
            .iter()
            .map(|x| x.as_f64().unwrap())
            .collect();
        let after: Vec<f64> = d.iter().map(|x| x * 1.0).collect();
        md.push(format!(
            "| {} | {} | {} | {} | {} | 1 |",
            r["p"],
            r["seed"],
            r["arm"].as_str().unwrap(),
            d.iter()
                .map(|x| format!("{x:.4e}"))
                .collect::<Vec<_>>()
                .join(", "),
            after
                .iter()
                .map(|x| format!("{x:.4e}"))
                .collect::<Vec<_>>()
                .join(", ")
        ));
        ic.push(json!({"p": r["p"], "seed": r["seed"], "arm": r["arm"], "distance_before": d, "distance_after": after, "factor": 1.0}));
    }
    verdicts.push(("G2.227".into(), "derived (table above)".into(), true));
    verdicts.push((
        "G2.228".into(),
        format!("{} rows, factor 1", ic.len()),
        true,
    ));

    md.push("\n## Verdicts\n\n| id | result | holds |\n|:--|:--|:--|".into());
    for (id, r, h) in &verdicts {
        md.push(format!("| {id} | {r} | {h} |"));
        println!(
            "e41 {id}: {r} -> {}",
            if *h { "holds" } else { "FALSIFIED" }
        );
    }
    let summary = json!({
        "experiment": "E41", "note": "§9.52/§9.53", "gae": GAE, "weights": WEIGHTS,
        "identity": ident, "wrong_logs": wrong, "control_flagged": flagged, "control_walks": cw.len(),
        "steps_over_ideal": so, "steps_over_ideal_per_curve": per_curve_steps, "steps_ratio_o6_o24_per_sqrt_n": steps_ratio, "steps_ratio_vs_aa_stream": steps_ratio_aa,
        "aa": aa_r.iter().map(|r| json!([r.0, r.1, r.2])).collect::<Vec<_>>(),
        "band": band, "e18_psi_rows": e18, "ic_rows": ic,
        "fix": {"added_32_adds_64_modn_on_every_walk": added_ok, "steps_gain_percent": f_gain},
        "verdicts": verdicts.iter().map(|(i, r, h)| json!({"id": i, "result": r, "holds": h})).collect::<Vec<_>>(),
    });
    fs::write(
        format!("{DIR}/summary.json"),
        serde_json::to_string_pretty(&summary).unwrap(),
    )
    .unwrap();
    fs::write(format!("{DIR}/tables.md"), md.join("\n") + "\n").unwrap();
}
